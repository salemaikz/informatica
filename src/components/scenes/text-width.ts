const EM = new Map<string, number>();
for (const [w, chars] of GROUPS) for (const ch of chars) EM.set(ch, w);

/** Для символа, которого нет в таблице (редкие знаки, эмодзи): ширина «средней» буквы с запасом. */
const UNKNOWN_EM = 0.65;
/** Запас на округление advance в браузере и погрешность таблицы: по 721 слову из уроков оценка не меньше замера Chromium (минимум +1%, в среднем +3%). */
export const TEXT_SAFETY = 1.02;

/** Ширина одного символа в em (для Nunito 700). */
export function charEm(ch: string): number {
  return EM.get(ch) ?? (ch.charCodeAt(0) < 0x2e0 ? UNKNOWN_EM : 0.8);
}

/**
 * Оценка ширины строки (px) в Nunito Bold при кегле fontPx: сумма продвижений глифов плюс небольшой запас.
 * Перенос строк не учитывается — это ширина «в одну строку».
 */
export function estimateTextWidth(text: string, fontPx: number): number {
  let em = 0;
  for (const ch of text) em += charEm(ch);
  return em * fontPx * TEXT_SAFETY;
}
