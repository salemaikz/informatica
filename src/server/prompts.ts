const MODE_RULE: Record<TutorMode, string> = {
  chat: `Режим: свободный диалог. Если ученик просит просто готовый ответ на учебную задачу — сначала дай наводящий вопрос или подсказку, а полное решение покажи, если он попросит ещё раз или уже попытался. Можешь предлагать короткие задачи для тренировки (с ответом — только после попытки ученика).`,
  hint: `Режим: ПОДСКАЗКА. Ученик прямо сейчас решает задание (оно ниже). Дай ОДНУ короткую подсказку (1–3 предложения), которая подтолкнёт к решению. НЕ называй ответ, не решай задание до конца, не перечисляй варианты, которые верны.`,
  ask: `Режим: ВОПРОС ПО УРОКУ. Ученик проходит урок и задал вопрос о текущем шаге (теория или задание — ниже). Считай, что ученик в теме НОВИЧОК: объясняй с нуля, через знакомое из жизни, коротким понятным языком, с маленьким примером. Если ученик просит проще — упрощай ещё. Если шаг — задание, на которое ученик ещё не ответил: НИКОГДА не называй ответ и не расписывай решение именно этого задания, даже если ученик прямо просит ответ или настаивает. Вместо этого покажи метод на ДРУГОМ похожем числе и подскажи только первый шаг для его задания. Если просят ответ — мягко скажи, что сначала нужно попробовать самому, а после ответа Бит всё разберёт.`,
  explain: `Режим: РАЗБОР ОШИБКИ. Ученик ответил на задание неверно (ниже его ответ и верный ответ). 1) Предположи, в чём именно ошибка рассуждения, исходя из его ответа. 2) Коротко покажи верное решение. 3) Закончи одним советом, как не ошибаться на ЕНТ. Без упрёков.`,
};

export function tutorSystemPrompt(ctx: StudentContext, mode: TutorMode, task?: TaskContext): string {
  const parts = [BASE, LANG_RULE[ctx.lang], MODE_RULE[mode], `ДАННЫЕ УЧЕНИКА (для персонализации, не пересказывай их дословно):\n${renderContext(ctx)}`];
  if (task?.theory) parts.push(`ТЕОРИЯ ТЕКУЩЕГО ШАГА УРОКА${task.prompt ? ` «${task.prompt}»` : ""}:\n${task.theory}`);
  if (task?.prompt && !task.theory) {
    const t = [`ЗАДАНИЕ: ${task.prompt}`];
    if (task.options?.length) t.push(`Варианты: ${task.options.join(" | ")}`);
    // В подсказке и в вопросе к ещё не решённому заданию ответ модели виден, но сообщать его нельзя.
    const hideAnswer = mode === "hint" || (mode === "ask" && !task.answered);
    if (!hideAnswer) {
      if (task.given) t.push(`Ответ ученика: ${task.given}`);
      if (task.correct) t.push(`Верный ответ: ${task.correct}`);
      if (task.explanation) t.push(`Объяснение из урока: ${task.explanation}`);
    } else if (task.correct) {
      t.push(`(Верный ответ для тебя, НЕ сообщай его: ${task.correct})`);
    }
    parts.push(t.join("\n"));
  }
  return parts.join("\n\n");
}

export function checkSolutionPrompt(ctx: StudentContext, lang: Lang, task: { prompt: string; reference: string; answer: string }, typed?: string): string {
  return `Ты проверяешь решение школьника по информатике (подготовка к ЕНТ). Решение прислано как фото тетради или рисунок на экране и/или как введённый ответ.

ЗАДАНИЕ: ${task.prompt}
ЭТАЛОННОЕ РЕШЕНИЕ: ${task.reference}
ВЕРНЫЙ ИТОГОВЫЙ ОТВЕТ: ${task.answer}
${typed ? `Ученик дополнительно ввёл итоговый ответ: ${typed}` : "Введённого ответа нет."}

Как оценивать:
- verdict "correct": итоговый ответ верный и ход решения в целом правильный (мелкие помарки допустимы).
- "partial": метод верный, но есть арифметическая ошибка, неверный порядок чтения остатков, или нет хода решения при верном ответе.
- "incorrect": неверный метод или неверный ответ.
- "unreadable": на изображении нельзя разобрать решение или оно не относится к заданию (и нет введённого ответа).
- score: 1 — верно, 0.5 — частично, 0 — неверно/нечитаемо.
- steps: до 6 строк того, что ты распознал в решении; верность — только в поле ok, в text не дописывай «ok/верно». Пиши кратко: «45:2 = 22, ост. 1».
- feedback: 1–3 предложения: что получилось и где именно ошибка. Обращайся на «ты», доброжелательно, без глаголов с родом (пол ученика неизвестен).
- tip: один короткий совет на будущее.
${lang === "kk" ? "Все тексты (feedback, steps, tip) — на казахском языке (остаток — «қалдық», ЕНТ — «ҰБТ»)." : "Все тексты (feedback, steps, tip) — на русском языке."}
Стиль объяснений ученика: ${ctx.style}.
ВАЖНО: пол ученика неизвестен. Не используй глаголы прошедшего времени при обращении к ученику («ты разделил», «ты прочитала» — запрещено). Пиши безлично: «деление выполнено верно», «остатки прочитаны снизу вверх», «у тебя получилось».`;
}

