/** Всё, от чего зависит выбор текста. */
export interface ReminderCtx {
  lang: Lang;
  /** Серия на сегодня (с учётом заморозок). */
  streak: number;
  freezes: number;
  /** Уроков «пора повторить». */
  due: number;
  /** Дней без занятий (0 — занимался сегодня); null — ещё ни разу. */
  idle: number | null;
  /** Название следующего урока на двух языках или null. */
  nextTitle: { ru: string; kk: string } | null;
  goalXp: number;
  xpToday: number;
  name: string;
  /** Сегодня «ГГГГ-ММ-ДД» — от него зависит вариант. */
  today: string;
}

export interface ReminderText {
  title: string;
  body: string;
}

/** Номер дня от 1970 года по ключу «ГГГГ-ММ-ДД» (UTC — только чтобы дни шли подряд). */
export function dayNumber(key: string): number {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(key);
  return m ? Math.floor(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])) / 86_400_000) : 0;
}

/** Ситуация по приоритету: серия под угрозой > повторение > возвращение > следующий урок > мотивация. */
export function pickSituation(c: ReminderCtx): Situation {
  const hasNext = !!c.nextTitle && !!c.nextTitle[c.lang];
  if (c.streak > 0) {
    // День уже засчитан (тестовое уведомление): серии ничто не грозит — мотивируем целью или следующим уроком.
    if (c.idle === 0) return c.goalXp > 0 && c.xpToday < c.goalXp ? "goal" : hasNext ? "nextLesson" : "goal";
    // Заморозки, уже ушедшие на пропущенные до сегодня дни, на сегодня не остаются.
    const spare = Math.max(0, c.freezes - Math.max(0, (c.idle ?? 0) - 1));
    return spare > 0 ? "streakFreeze" : "streakRisk";
  }
  if (c.due > 0) return "review";
  if (c.idle !== null) {
    if (c.idle >= 7) return "away7";
    if (c.idle >= 4) return "forgetting";
    if (c.idle >= 2) return "away2";
  }
  // Серии нет, пауза короткая: чередуем по дням, чтобы не повторяться.
  const d = dayNumber(c.today) % 3;
  if (d === 0 && hasNext) return "nextLesson";
  if (d === 2 && c.goalXp > 0 && c.xpToday < c.goalXp) return "goal";
  return "newStreak";
}

/** Подстановки шаблона на языке ctx.lang. */
export function reminderVars(c: ReminderCtx): Record<string, string> {
  const kk = c.lang === "kk";
  return {
    streak: String(c.streak),
    days: daysText(c.streak, c.lang),
    n: String(c.due),
    lessons: kk ? "сабақ" : pluralRu(c.due, ["урок", "урока", "уроков"]),
    idleDays: daysText(c.idle ?? 0, c.lang),
    lesson: c.nextTitle?.[c.lang] ?? "",
    goal: String(c.goalXp),
    xp: String(c.xpToday),
    name: c.name.trim(),
  };
}

export function fillTemplate(s: string, vars: Record<string, string>): string {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? "");
}

/** Выбор текста: ситуация по приоритету, вариант — по номеру дня (соседние дни не повторяются). */
export function pickReminder(c: ReminderCtx, pool: ReminderPool = REMINDER_POOL): ReminderText {
  const vars = reminderVars(c);
  const all = pool[pickSituation(c)][c.lang];
  const usable = all.filter((v) => vars.name || !/\{name\}/.test(v.title + v.body));
  const list = usable.length ? usable : all;
  const v = list[dayNumber(c.today) % list.length];
  return { title: fillTemplate(v.title, vars), body: fillTemplate(v.body, vars) };
}
