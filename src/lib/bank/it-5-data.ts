/** Целое число или ошибка: в заданиях ответы — целые. */
function whole(x: number): number {
  if (!Number.isInteger(x)) throw new Error(`it.data: ответ не целый (${x})`);
  return x;
}
/** Показаний у одного датчика за сутки при интервале в секундах. */
const readingsPerDay = (everySec: number) => whole(DAY_S / everySec);
/** Мегабайт за сутки: датчики · байт в показании · показаний в сутки. */
const mbPerDay = (sensors: number, bytes: number, everySec: number) => whole((sensors * bytes * readingsPerDay(everySec)) / KB / KB);
/** Килобайт за промежуток seconds. */
const kbPer = (sensors: number, bytes: number, everySec: number, seconds: number) => whole((sensors * bytes * (seconds / everySec)) / KB);
/** Наибольшее число датчиков, чтобы за час не превысить лимит limitKb. */
const maxSensors = (limitKb: number, bytes: number, everySec: number) => Math.floor((limitKb * KB) / (bytes * (3600 / everySec)));
