const SKILL = "it.trends";

const l = (ru: string, kk: string): L => ({ ru, kk });

interface Opt {
  t: Text;
  /** Почему вариант неверен (для верного — не указывается). */
  why?: L;
}

/** Задание-choice: верный вариант всегда первым, poolBank перемешает варианты вместе с whyWrong. */
function choice(
  id: string,
  level: Level,
  prompt: L,
  hint: L,
  right: Text,
  wrong: Opt[],
  explanation: L,
  scene?: Scene,
): ChoiceStep {
  return {
    id: `q:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [right, ...wrong.map((w) => w.t)],
    correct: 0,
    explanation,
    hint,
    whyWrong: [null, ...wrong.map((w) => w.why ?? null)],
  };
}

/** Задание-multi: верные варианты первыми (индексы 0..k-1). */
function multi(id: string, level: Level, prompt: L, hint: L, rights: Opt[], wrong: Opt[], explanation: L): MultiStep {
  return {
    id: `q:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: [...rights.map((r) => r.t), ...wrong.map((w) => w.t)],
    correct: rights.map((_, i) => i),
    explanation,
    hint,
    whyWrong: [...rights.map(() => null), ...wrong.map((w) => w.why ?? null)],
  };
}

function input(id: string, level: Level, prompt: L, hint: L, answer: string, explanation: L, suffix?: string): InputStep {
  return { id: `q:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, answers: [answer], mode: "number", suffix, explanation, hint };
}

