// ---------- Конструкторы заданий ----------

function choice(
  name: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number,
  whyWrong: (L | null)[],
  hint: L,
  explanation: L,
  scene?: Scene,
): QuestionStep {
  return { id: `p:${SKILL}:${name}`, type: "choice", skill: SKILL, level, prompt, options, correct, whyWrong, hint, explanation, ...(scene ? { scene } : {}) };
}

function multi(
  name: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number[],
  whyWrong: (L | null)[],
  hint: L,
  explanation: L,
  scene?: Scene,
): QuestionStep {
  return { id: `p:${SKILL}:${name}`, type: "multi", skill: SKILL, level, prompt, options, correct, whyWrong, hint, explanation, ...(scene ? { scene } : {}) };
}

function input(name: string, level: Level, prompt: L, answer: string, hint: L, explanation: L, scene?: Scene, reveal?: Scene): QuestionStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt,
    answers: [answer],
    mode: "number",
    hint,
    explanation,
    ...(scene ? { scene } : {}),
    ...(reveal ? { reveal } : {}),
  };
}

