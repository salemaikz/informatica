type Circuit = Extract<Scene, { kind: "circuit" }>;
type Gate = Circuit["gates"][number];
type Bit = 0 | 1;

const circ = (inputs: string[], gates: Gate[], output: string, values?: Record<string, Bit>): Circuit => ({
  kind: "circuit",
  inputs,
  gates,
  output,
  ...(values ? { values } : {}),
});

const g = (id: string, op: Gate["op"], ...ins: string[]): Gate => ({ id, op, in: ins });

