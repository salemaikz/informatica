const SKILL = "base.media";

const w = (ru: string, kk: string): L => ({ ru, kk });

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [Text, boolean, L?][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

/** Ввод числа: ответ единственный. */
function num(id: string, level: Level, prompt: L, answer: string, explanation: L, hint: L): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, answers: [answer], mode: "number", explanation, hint };
}

/** Порядок: элементы в правильной последовательности. */
function or(id: string, level: Level, prompt: L, items: L[], explanation: L, hint: L): OrderStep {
  return { id: `p:${SKILL}:${id}`, type: "order", skill: SKILL, level, prompt, items, explanation, hint };
}

