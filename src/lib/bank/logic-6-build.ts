function countShort(name: string, level: Level, src: string, vars: string[], hint: L): ShortQuestion {
  const col = columnOf(src, vars);
  const ones = countOf(col, "1");
  return {
    id: id(name),
    skill: SKILL,
    level,
    prompt: {
      ru: `Сколько единиц в итоговом столбце таблицы истинности выражения ${src} (переменные ${varList(vars)})?`,
      kk: `${src} өрнегінің ақиқат кестесінің қорытынды бағанында неше бірлік бар (айнымалылар ${varList(vars)})?`,
    },
    answer: String(ones),
    mode: "number",
    hint,
    explanation: { ru: `Столбец F по наборам в порядке двоичного счёта: ${col}. Единиц ${ones}.`, kk: `Екілік санау ретімен жиындар бойынша F бағаны: ${col}. Бірліктер саны: ${ones}.` },
  };
}

