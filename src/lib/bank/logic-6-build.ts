/** Сколько наборов делают выражение истинным (want = 1) или ложным (want = 0). Ответ считает код. */
function countQ(name: string, level: Level, src: string, vars: string[], want: Bit, hint: L, how: L): InputStep {
  const col = columnOf(src, vars);
  const ones = countOf(col, "1");
  const answer = want === 1 ? ones : col.length - ones;
  const total = col.length;
  return {
    id: id(name),
    type: "input",
    skill: SKILL,
    level,
    prompt:
      want === 1
        ? {
            ru: `Сколько наборов значений ${varList(vars)} делают выражение ${src} истинным?`,
            kk: `${varList(vars)} мәндерінің қанша жиыны ${src} өрнегін ақиқат етеді?`,
          }
        : {
            ru: `Сколько наборов значений ${varList(vars)} делают выражение ${src} ложным?`,
            kk: `${varList(vars)} мәндерінің қанша жиыны ${src} өрнегін жалған етеді?`,
          },
    answers: [String(answer)],
    mode: "number",
    ...(total <= 16 ? { reveal: tableScene(src, vars, { ru: "Проверь себя по таблице", kk: "Кестемен тексер" }) } : {}),
    hint,
    explanation: {
      ru: `${how.ru} Столбец F по наборам в порядке двоичного счёта: ${col}. Единиц ${ones}, нулей ${total - ones}, вместе ${total}.`,
      kk: `${how.kk} Екілік санау ретімен жиындар бойынша F бағаны: ${col}. Бірліктер ${ones}, нөлдер ${total - ones}, барлығы ${total}.`,
    },
  };
}

/** Что произойдёт при заданном наборе: ответ 0 или 1 считает код. */
function valueQ(name: string, level: Level, src: string, vars: string[], bits: Bit[], trace: string, hint: L): InputStep {
  const v = valueOf(src, vars, bits);
  return {
    id: id(name),
    type: "input",
    skill: SKILL,
    level,
    prompt: {
      ru: `Найди значение выражения ${src} при ${setText(vars, bits)}.`,
      kk: `${setText(vars, bits)} болғанда ${src} өрнегінің мәнін тап.`,
    },
    answers: [String(v)],
    mode: "number",
    hint,
    explanation: same(`${trace}. F = ${v}.`),
  };
}

/**
 * «По таблице — выражение»: условие — таблица, варианты — выражения. correct считается кодом
 * (должен совпасть со столбцом таблицы), для неверных «почему» — первая строка расхождения.
 */
function fromTableQ(name: string, level: Level, table: string, correct: string, wrongs: string[], vars: string[], hint: L, why: L): ChoiceStep {
  const want = columnOf(table, vars);
  if (columnOf(correct, vars) !== want) throw new Error(`logic.build ${name}: «${correct}» не совпадает с таблицей`);
  const options = [correct, ...wrongs];
  if (new Set(options).size !== options.length) throw new Error(`logic.build ${name}: повторяются варианты`);
  const f = parse(table);
  const whyWrong: (L | null)[] = [
    null,
    ...wrongs.map((w) => {
      const g = parse(w);
      const bad = sets(vars.length).find((s) => g(envOf(vars, s)) !== f(envOf(vars, s)));
      if (!bad) throw new Error(`logic.build ${name}: «${w}» совпадает с таблицей`);
      const got = g(envOf(vars, bad));
      const need = f(envOf(vars, bad));
      return {
        ru: `В строке ${setText(vars, bad)} это выражение даёт ${got}, а в таблице F = ${need}.`,
        kk: `${setText(vars, bad)} жолында бұл өрнек ${got} береді, ал кестеде F = ${need}.`,
      };
    }),
  ];
  return {
    id: id(name),
    type: "choice",
    skill: SKILL,
    level,
    prompt: { ru: "Дана таблица истинности выражения F. Какое выражение ей соответствует?", kk: "F өрнегінің ақиқат кестесі берілген. Қай өрнек оған сәйкес келеді?" },
    scene: givenTable(table, vars),
    options,
    correct: 0,
    whyWrong,
    hint,
    explanation: {
      ru: `${why.ru} Столбец F по порядку строк: ${want}. Правильное выражение даёт тот же столбец, остальные расходятся хотя бы в одной строке.`,
      kk: `${why.kk} Жолдар ретімен F бағаны: ${want}. Дұрыс өрнек дәл сол бағанды береді, қалғандары кемінде бір жолда алшақтайды.`,
    },
  };
}

/** Выбор наборов: верные — те, где выражение равно target. Ровно 6 вариантов. */
function setsMultiQ(name: string, level: Level, src: string, vars: string[], options: Bit[][], target: Bit, hint: L, how: L): MultiStep {
  if (options.length !== 6) throw new Error(`logic.build ${name}: нужно 6 вариантов`);
  const f = parse(src);
  const vals = options.map((s) => f(envOf(vars, s)));
  const correct = vals.flatMap((v, i) => (v === target ? [i] : []));
  if (correct.length < 2 || correct.length > 3) throw new Error(`logic.build ${name}: верных ${correct.length}`);
  const word: L = target === 1 ? { ru: "истинно", kk: "ақиқат" } : { ru: "ложно", kk: "жалған" };
  const rows = options.map((s, i) => `${tuple(s)} → ${vals[i]}`).join("; ");
  return {
    id: id(name),
    type: "multi",
    skill: SKILL,
    level,
    prompt: {
      ru: `При каких наборах значений (${varList(vars)}) выражение ${src} ${word.ru}? Отметь все верные.`,
      kk: `(${varList(vars)}) мәндерінің қандай жиындарында ${src} өрнегі ${word.kk}? Барлық дұрысын белгіле.`,
    },
    options: options.map(tuple),
    correct,
    whyWrong: options.map((s, i) =>
      vals[i] === target
        ? null
        : { ru: `При ${setText(vars, s)} выражение равно ${vals[i]}, а нужно ${target}.`, kk: `${setText(vars, s)} болғанда өрнектің мәні ${vals[i]}, ал ${target} керек.` },
    ),
    hint,
    explanation: { ru: `${how.ru} Проверка по вариантам: ${rows}.`, kk: `${how.kk} Нұсқалар бойынша тексеру: ${rows}.` },
  };
}

/** Выражения и число единиц в столбце (match): правые части не повторяются. */
function countMatchQ(name: string, level: Level, vars: string[], exprs: string[], hint: L): MatchStep {
  const pairs = exprs.map((src) => ({ left: src, right: String(countOf(columnOf(src, vars), "1")) }));
  if (new Set(pairs.map((p) => p.right)).size !== pairs.length) throw new Error(`logic.build ${name}: числа повторяются`);
  const total = 2 ** vars.length;
  return {
    id: id(name),
    type: "match",
    skill: SKILL,
    level,
    prompt: {
      ru: `Соедини выражение с числом наборов, на которых оно истинно. Переменные ${varList(vars)} (всего ${total} наборов)`,
      kk: `Өрнекті ол ақиқат болатын жиындар санымен жұптастыр. Айнымалылар ${varList(vars)} (барлығы ${total} жиын)`,
    },
    pairs,
    hint,
    explanation: {
      ru: `Считаем столбец F каждого выражения: ${pairs.map((p) => `${p.left} — ${p.right}`).join("; ")}.`,
      kk: `Әр өрнектің F бағанын есептейміз: ${pairs.map((p) => `${p.left} — ${p.right}`).join("; ")}.`,
    },
  };
}

/** Выбрать выражения, у которых ровно k единиц (multi, 6 вариантов). */
function countMultiQ(name: string, level: Level, vars: string[], exprs: string[], k: number, hint: L): MultiStep {
  if (exprs.length !== 6) throw new Error(`logic.build ${name}: нужно 6 вариантов`);
  const ones = exprs.map((e) => countOf(columnOf(e, vars), "1"));
  const correct = ones.flatMap((n, i) => (n === k ? [i] : []));
  if (correct.length < 2 || correct.length > 3) throw new Error(`logic.build ${name}: верных ${correct.length}`);
  const total = 2 ** vars.length;
  return {
    id: id(name),
    type: "multi",
    skill: SKILL,
    level,
    prompt: {
      ru: `Выбери все выражения, которые истинны ровно на ${k} наборах из ${total} (переменные ${varList(vars)}).`,
      kk: `Барлығы ${total} жиынның дәл ${k} жиынында ақиқат болатын барлық өрнекті таңда (айнымалылар ${varList(vars)}).`,
    },
    options: exprs,
    correct,
    whyWrong: exprs.map((_, i) =>
      ones[i] === k
        ? null
        : { ru: `У этого выражения единиц ${ones[i]} из ${total}, а нужно ${k}.`, kk: `Бұл өрнектің ${total} жолдың ішінде ${ones[i]} бірлігі бар, ал ${k} керек.` },
    ),
    hint,
    explanation: {
      ru: `Единиц в столбце F: ${exprs.map((e, i) => `${e} — ${ones[i]}`).join("; ")}. Нужны выражения, где единиц ровно ${k}.`,
      kk: `F бағанындағы бірліктер: ${exprs.map((e, i) => `${e} — ${ones[i]}`).join("; ")}. Бірліктері дәл ${k} болатын өрнектер керек.`,
    },
  };
}

