// Банк навыка logic.build: таблица истинности сложного выражения (4–5 переменных, сколько единиц,
// «по таблице — выражение»). Статичный пул, но ответы НЕ вводятся руками: выражения записаны строкой,
// маленький разборщик считает по ней столбец F, а правильный ответ, неверные варианты и «почему неверно»
// берутся из этого расчёта. Тексты после чисел — без падежных окончаний (в казахском оно зависит от числа).
// Весь пул перепроверен независимым разборщиком на python3.

const SKILL = "logic.build";

// ---------- Разборщик выражений: ¬ → ∧ → ∨ → → → ↔ (приоритет по убыванию), скобки ----------

type Bit = 0 | 1;
type Env = Record<string, Bit>;
type Node = (env: Env) => Bit;

function parse(src: string): Node {
  const tokens = src.replace(/\s+/g, "").split("");
  let pos = 0;
  const peek = () => tokens[pos];
  const eat = () => tokens[pos++];

  const atom = (): Node => {
    const t = eat();
    if (t === "¬") {
      const x = atom();
      return (e) => (x(e) === 1 ? 0 : 1);
    }
    if (t === "(") {
      const x = eqv();
      if (eat() !== ")") throw new Error(`logic.build: нет «)» в «${src}»`);
      return x;
    }
    if (t && /^[A-E]$/.test(t)) return (e) => e[t];
    throw new Error(`logic.build: не разобрать «${src}» около «${t}»`);
  };
  const and = (): Node => {
    let l = atom();
    while (peek() === "∧") {
      eat();
      const a = l;
      const r = atom();
      l = (e) => ((a(e) & r(e)) as Bit);
    }
    return l;
  };
  const or = (): Node => {
    let l = and();
    while (peek() === "∨") {
      eat();
      const a = l;
      const r = and();
      l = (e) => ((a(e) | r(e)) as Bit);
    }
    return l;
  };
  const imp = (): Node => {
    const l = or();
    if (peek() === "→") {
      eat();
      const r = imp();
      return (e) => (l(e) === 1 && r(e) === 0 ? 0 : 1);
    }
    return l;
  };
  const eqv = (): Node => {
    let l = imp();
    while (peek() === "↔") {
      eat();
      const a = l;
      const r = imp();
      l = (e) => (a(e) === r(e) ? 1 : 0);
    }
    return l;
  };
  const root = eqv();
  if (pos !== tokens.length) throw new Error(`logic.build: лишнее в конце «${src}»`);
  return root;
}

/** Все наборы значений n переменных двоичным счётом. */
const sets = (n: number): Bit[][] =>
  Array.from({ length: 2 ** n }, (_, i) => Array.from({ length: n }, (_, k) => ((i >> (n - 1 - k)) & 1) as Bit));

const envOf = (vars: string[], bits: Bit[]): Env => Object.fromEntries(vars.map((n, i) => [n, bits[i]]));
const valueOf = (src: string, vars: string[], bits: Bit[]): Bit => parse(src)(envOf(vars, bits));
const columnOf = (src: string, vars: string[]): string => {
  const f = parse(src);
  return sets(vars.length)
    .map((s) => f(envOf(vars, s)))
    .join("");
};
const countOf = (col: string, ch: "0" | "1") => col.split("").filter((c) => c === ch).length;

// ---------- Мелочи ----------

const same = (s: string): L => ({ ru: s, kk: s });
const tuple = (bits: Bit[]) => `(${bits.join(", ")})`;
const setText = (vars: string[], bits: Bit[]) => vars.map((n, i) => `${n} = ${bits[i]}`).join(", ");
const varList = (vars: string[]) => vars.join(", ");
const id = (name: string) => `p:${SKILL}:${name}`;

/** Таблица-иллюстрация (до 16 строк): переменные и столбец F; выделены строки, где F = 1. */
function tableScene(src: string, vars: string[], caption?: L): Scene {
  const f = parse(src);
  const rows = sets(vars.length).map((s) => [...s.map(String), String(f(envOf(vars, s)))]);
  return {
    kind: "table",
    columns: [...vars, "F"],
    rows,
    highlightCols: [vars.length],
    highlightRows: rows.flatMap((r, i) => (r[vars.length] === "1" ? [i] : [])),
    mono: true,
    ...(caption ? { caption } : {}),
  };
}

/** Таблица без заголовка выражения: условие задания «по таблице — выражение» (F считается по эталону). */
function givenTable(src: string, vars: string[]): Scene {
  const f = parse(src);
  return {
    kind: "table",
    columns: [...vars, "F"],
    rows: sets(vars.length).map((s) => [...s.map(String), String(f(envOf(vars, s)))]),
    mono: true,
  };
}

