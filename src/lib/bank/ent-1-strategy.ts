// Банк навыка ent.strategy («Стратегия ЕНТ»).
// Расчётная часть — генератор: баллы за ответ в «нескольких верных» (считает multiPoints из lib/ent.ts),
// ориентир по времени (2 минуты на задание), максимум баллов по видам заданий (25·1, 5·1, 5·2, 5·2 = 50).
// Часть «на знание» — статичный пул: стратегия, формат, частичные баллы, единицы, контекстное задание.
// Генератор берёт только однозначные случаи правил (Правила ЕНТ, п. 18): все верные — 2; не хватает одного
// верного и/или один лишний — 1; два и более неверных, один верный из трёх или ни одного верного — 0. Окончаний после чисел в казахском нет.

const SKILL = "ent.strategy";

const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const shuffled = <T,>(rand: Rand, arr: readonly T[]): T[] => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

const LETTERS = ["A", "B", "C", "D", "E", "F"] as const;
const lettersOf = (idx: number[]) => idx.map((i) => LETTERS[i]).join(", ");

/** «0 баллов / 1 балл / 2 балла» и «N ұпай». */
const ball = (n: number): L => ({
  ru: `${n} ${n === 1 ? "балл" : n >= 2 && n <= 4 ? "балла" : "баллов"}`,
  kk: `${n} ұпай`,
});

// ---------- ядро генератора: одно задание в двух формах (choice / input) и короткий вопрос ----------

interface Core {
  /** Ключ содержимого (для id). */
  key: string;
  prompt: L;
  answer: number;
  explanation: L;
  hint: L;
  /** Неверные варианты с разбором (для формы choice). */
  distractors: { value: number; why: L }[];
}

function toQuestion(core: Core, level: Level, form: "choice" | "input", seed: number): QuestionStep {
  const id = `g:${SKILL}:${core.key}:${form}:${seed}`;
  if (form === "input") {
    return {
      id,
      type: "input",
      skill: SKILL,
      level,
      prompt: core.prompt,
      answers: [String(core.answer)],
      mode: "number",
      explanation: core.explanation,
      hint: core.hint,
    } satisfies InputStep;
  }
  const seen = new Set<number>([core.answer]);
  const wrong: { value: number; why: L }[] = [];
  for (const d of core.distractors) {
    if (seen.has(d.value) || d.value < 0) continue;
    seen.add(d.value);
    wrong.push(d);
    if (wrong.length === 3) break;
  }
  const all = [{ value: core.answer, why: null as L | null }, ...wrong].sort((a, b) => a.value - b.value);
  return {
    id,
    type: "choice",
    skill: SKILL,
    level,
    prompt: core.prompt,
    options: all.map((o) => String(o.value)),
    correct: all.findIndex((o) => o.why === null),
    whyWrong: all.map((o) => o.why),
    explanation: core.explanation,
    hint: core.hint,
  } satisfies ChoiceStep;
}

// ---------- 1. Баллы за ответ в «нескольких верных» ----------

const RULES_EXPL: L = {
  ru: "Правила ЕНТ: все верные без лишних — 2; не хватает одного верного и/или есть один лишний — 1; два и более неверных, только один верный из трёх или ни одного верного — 0.",
  kk: "ҰБТ ережесі: дұрыс жауаптың бәрі, артығы жоқ — 2; бір дұрыс жауап жетпейді және/немесе бір артық бар — 1; екі және одан көп қате, үш дұрыстың тек біреуі немесе бірде-бір дұрыс жоқ — 0.",
};

function reasonOf(c: number, w: number, total: number): L {
  if (w >= 2) return { ru: "отмечено два неверных варианта или больше", kk: "екі немесе одан көп қате нұсқа белгіленген" };
  if (c === total && w === 0) return { ru: "отмечены все верные и ничего лишнего", kk: "барлық дұрыс нұсқа белгіленген, артығы жоқ" };
  if (c === total) return { ru: "отмечены все верные и один лишний", kk: "барлық дұрыс нұсқа және бір артық нұсқа белгіленген" };
  return { ru: "не хватает одного верного, лишнего нет", kk: "бір дұрыс нұсқа жетпейді, артығы жоқ" };
}

function scoreCore(rand: Rand, level: Level): Core {
  const total = pick(rand, [2, 3] as const);
  const order = shuffled(rand, [0, 1, 2, 3, 4, 5]);
  const correct = order.slice(0, total).sort((a, b) => a - b);
  const wrongPool = order.slice(total);
  // Только однозначные случаи правил: A — три вида, B/C — ещё «без одного верного» и «без одного + два лишних».
  const kind = pick(rand, level === 1 ? (["all", "one", "two"] as const) : (["all", "one", "two", "part", "partTwo"] as const));
  let chosenCorrect = [...correct];
  if (kind === "part" || kind === "partTwo") {
    const drop = pick(rand, correct);
    chosenCorrect = correct.filter((i) => i !== drop);
  }
  const extra = kind === "one" ? 1 : kind === "two" || kind === "partTwo" ? 2 : 0;
  const chosen = [...chosenCorrect, ...wrongPool.slice(0, extra)].sort((a, b) => a - b);
  const pts = multiPoints(correct, chosen);
  const c = chosenCorrect.length;
  const w = extra;
  const reason = reasonOf(c, w, total);
  const letters = level === 3;
  const description: L = letters
    ? {
        ru: `Верные варианты: ${lettersOf(correct)}. Отмечены: ${lettersOf(chosen)}.`,
        kk: `Дұрыс нұсқалар: ${lettersOf(correct)}. Белгіленгені: ${lettersOf(chosen)}.`,
      }
    : {
        ru: `В задании «несколько верных» верных ответов: ${total}. Отмечено верных: ${c}, неверных: ${w}.`,
        kk: `«Бірнеше дұрыс жауап» тапсырмасындағы дұрыс жауап саны: ${total}. Белгіленген дұрыс: ${c}, қате: ${w}.`,
      };
  const distractors = [0, 1, 2, 3]
    .filter((v) => v !== pts)
    .map((v) => ({
      value: v,
      why:
        v === 3
          ? { ru: "Больше 2 баллов за такое задание получить нельзя.", kk: "Мұндай тапсырма үшін 2 ұпайдан артық алуға болмайды." }
          : {
              ru: `Здесь ${reason.ru}: по правилам это ${ball(pts).ru}, а не ${ball(v).ru}.`,
              kk: `Мұнда ${reason.kk}: ереже бойынша бұл ${pts} ұпай, ${v} емес.`,
            },
    }));
  return {
    key: letters ? `${lettersOf(correct).replace(/, /g, "")}-${lettersOf(chosen).replace(/, /g, "")}` : `n${total}c${c}w${w}`,
    prompt: {
      ru: `${description.ru} Сколько баллов даёт такой ответ?`,
      kk: `${description.kk} Мұндай жауап қанша ұпай береді?`,
    },
    answer: pts,
    explanation: {
      ru: `${description.ru} Здесь ${reason.ru}: это ${ball(pts).ru}. ${RULES_EXPL.ru}`,
      kk: `${description.kk} Мұнда ${reason.kk}: бұл ${pts} ұпай. ${RULES_EXPL.kk}`,
    },
    hint: {
      ru: "Сравни отмеченное с верным: сколько верных отмечено и сколько лишних? Два и более лишних обнуляют задание.",
      kk: "Белгіленгенді дұрыспен салыстыр: қанша дұрыс белгіленген және қанша артық? Екі және одан көп артық тапсырманы нөлге теңестіреді.",
    },
    distractors,
  };
}

