function archive(rand: Rand, level: Level, seed: number): QuestionStep {
  if (level === 1) {
    const r = int(rand, 2, 6);
    const after = pick(rand, [5, 8, 10, 12, 15, 20, 25]);
    const before = r * after;
    return numInput(
      {
        id: `g:${SKILL}:arch-times:${before}-${after}:${seed}`,
        level,
        prompt: l(`Файл размером ${before} Мбайт после архивации занимает ${after} Мбайт. Во сколько раз он стал меньше?`, `Көлемі ${before} Мбайт файл архивтелгеннен кейін ${after} Мбайт алады. Ол неше есе кішірейді?`),
        hint: RATIO_HINT,
        explanation: l(`Коэффициент сжатия = ${before} : ${after} = ${r}. Ловушка: ${before} − ${after} = ${before - after} — это на сколько Мбайт меньше, а не во сколько раз.`, `Сығу коэффициенті = ${before} : ${after} = ${r}. Тұзақ: ${before} − ${after} = ${before - after} — бұл неше Мбайтқа кішірейгенін көрсетеді, неше есе екенін емес.`),
      },
      String(r),
    );
  }
  if (level === 2) {
    const r = int(rand, 2, 6);
    const after = pick(rand, [6, 8, 10, 12, 15, 20]);
    const N = r * after;
    return choice(
      rand,
      {
        id: `g:${SKILL}:arch-size:${N}-${r}:${seed}`,
        level,
        prompt: l(`Файл размером ${N} Мбайт сжали архиватором в ${r} ${raza(r)}. Каков размер архива, Мбайт?`, `Көлемі ${N} Мбайт файл архиватормен ${r} есе сығылды. Архив көлемі қанша Мбайт?`),
        hint: l("Сжали в несколько раз — значит, размер надо разделить на это число.", "Бірнеше есе сығылды — демек, көлемді осы санға бөлу керек."),
        explanation: l(`Размер архива = ${N} : ${r} = ${after} Мбайт. Ловушки: ${N} − ${r} — вычитание вместо деления, ${N} · ${r} — умножение вместо деления.`, `Архив көлемі = ${N} : ${r} = ${after} Мбайт. Тұзақтар: ${N} − ${r} — бөлудің орнына азайту, ${N} · ${r} — бөлудің орнына көбейту.`),
      },
      String(after),
      [
        { v: String(N - r), why: l("Размер не вычитают: «в несколько раз» — это деление.", "Көлемді азайтпайды: «бірнеше есе» — бұл бөлу.") },
        { v: String(N * r), why: l("Архив стал больше, чем файл: при сжатии размер уменьшается, значит нужно делить.", "Архив файлдан үлкен болып шықты: сығылғанда көлем кішірейеді, демек бөлу керек.") },
        { v: String(r), why: l("Это коэффициент сжатия, а не размер архива.", "Бұл сығу коэффициенті, архив көлемі емес.") },
        { v: String(N + r), why: l("Размеры не складывают: при сжатии размер уменьшается, значит нужно делить.", "Көлемдерді қоспайды: сығылғанда көлем кішірейеді, демек бөлу керек.") },
      ],
    );
  }
  const r = int(rand, 2, 5);
  const t = pick(rand, [5, 8, 10, 12, 15]);
  const j = pick(rand, [1, 2, 3, 4, 5]);
  const T = r * t;
  const J = r * j;
  const correct = t + J;
  return choice(
    rand,
    {
      id: `g:${SKILL}:arch-mixed:${T}-${J}-${r}:${seed}`,
      level,
      prompt: l(
        `В папке текстовые файлы общим размером ${T} Мбайт и JPEG-фото общим размером ${J} Мбайт. Текст при архивации сжимается в ${r} ${raza(r)}, а JPEG не уменьшается. Каков размер архива, Мбайт?`,
        `Қалтада көлемі барлығы ${T} Мбайт мәтіндік файлдар және көлемі барлығы ${J} Мбайт JPEG-фотолар бар. Мәтін архивтегенде ${r} есе сығылады, ал JPEG кішіреймейді. Архив көлемі қанша Мбайт?`,
      ),
      hint: l("Сожми только то, что сжимается, а JPEG оставь как есть. Потом сложи.", "Тек сығылатынын сық, ал JPEG-ті сол күйінде қалдыр. Содан кейін қос."),
      explanation: l(`Текст: ${T} : ${r} = ${t} Мбайт. JPEG не сжимается: ${J} Мбайт. Архив: ${t} + ${J} = ${correct} Мбайт.`, `Мәтін: ${T} : ${r} = ${t} Мбайт. JPEG сығылмайды: ${J} Мбайт. Архив: ${t} + ${J} = ${correct} Мбайт.`),
    },
    String(correct),
    [
      { v: String(t + j), why: l("Так получится, если сжать всё в одинаковое число раз. Но JPEG уже сжат и не уменьшается.", "Егер бәрін бірдей есе сықсаң, осылай шығады. Бірақ JPEG бұрыннан сығылған және кішіреймейді.") },
      { v: String(t), why: l("Это размер только сжатого текста: фото в архиве тоже занимают место.", "Бұл тек сығылған мәтіннің көлемі: архивтегі фотолар да орын алады.") },
      { v: String(T + J), why: l("Это размер до архивации: текст при сжатии уменьшился.", "Бұл архивтеуге дейінгі көлем: мәтін сығылғанда кішірейді.") },
    ],
  );
}

