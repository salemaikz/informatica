const DISKS = ["C:", "D:", "E:"];
const FOLDERS = ["Users", "School", "Work", "Study", "Projects", "Media", "Ali", "Aida", "Dana", "Timur", "Info", "Photos", "Music", "Docs", "Reports", "Games", "Backup", "Archive", "2025", "2026"];
const FILES = ["report.docx", "task.py", "photo.jpg", "song.mp3", "table.xlsx", "plan.pptx", "notes.txt", "video.mp4", "cat.png", "essay.docx"];
const STEMS = ["final", "copy", "new", "draft", "result"];

interface FPath {
  disk: string;
  folders: string[];
  file: string;
}

const BS = "\\";
const folderStr = (disk: string, folders: string[]) => [disk, ...folders].join(BS);
const pathStr = (p: FPath) => [p.disk, ...p.folders, p.file].join(BS);

function randFolders(rand: Rand, n: number, avoid: string[] = []): string[] {
  return shuffle(FOLDERS.filter((f) => !avoid.includes(f)), rand).slice(0, n);
}

function randPath(rand: Rand, depth: number): FPath {
  return { disk: pick(rand, DISKS), folders: randFolders(rand, depth), file: pick(rand, FILES) };
}

const stemOf = (file: string) => file.slice(0, file.lastIndexOf("."));
const extOf = (file: string) => file.slice(file.lastIndexOf(".") + 1);

const HINT_PATH: L = l(
  "Путь — это диск, затем все папки по порядку и в конце имя файла. Подумай, какая часть пути меняется при этом действии.",
  "Жол — диск, содан кейін барлық қалталар ретімен және соңында файл аты. Бұл әрекет кезінде жолдың қай бөлігі өзгеретінін ойлан.",
);

function pathId(kind: string, p: FPath, seed: number) {
  return `g:${SKILL}:${kind}:${slug(pathStr(p))}:${seed}`;
}

/** A: расширение, папка, число папок. */
function pathBasic(rand: Rand, level: Level, seed: number): QuestionStep {
  const p = randPath(rand, int(rand, 2, 4));
  const kind = int(rand, 0, 2);
  const P = pathStr(p);
  const last = p.folders[p.folders.length - 1];
  if (kind === 0) {
    const ext = `.${extOf(p.file)}`;
    return choice(
      rand,
      {
        id: pathId("path-ext", p, seed),
        level,
        prompt: l(`Что является расширением файла в пути ${P}?`, `${P} жолындағы файлдың кеңейтілімі қайсы?`),
        hint: l("Расширение стоит в самом конце имени файла, после точки.", "Кеңейтілім файл атының ең соңында, нүктеден кейін тұрады."),
        explanation: l(`Расширение — часть имени файла после точки: ${code(ext)}. Остальное в пути — диск, папки и имя файла.`, `Кеңейтілім — файл атының нүктеден кейінгі бөлігі: ${code(ext)}. Жолдағы қалғаны — диск, қалталар және файл аты.`),
      },
      ext,
      [
        { v: stemOf(p.file), why: l("Это имя файла без расширения.", "Бұл кеңейтілімсіз файл аты.") },
        { v: last, why: l("Это папка, в которой лежит файл.", "Бұл файл жатқан қалта.") },
        { v: p.folders[0], why: l("Это папка в начале пути.", "Бұл жолдың басындағы қалта.") },
        { v: p.disk, why: l("Это имя диска.", "Бұл диск аты.") },
      ],
    );
  }
  if (kind === 1) {
    return choice(
      rand,
      {
        id: pathId("path-folder", p, seed),
        level,
        prompt: l(`В какой папке лежит файл ${P}?`, `${P} файлы қай қалтада жатыр?`),
        hint: l("Файл лежит в последней папке пути, перед его именем.", "Файл жолдың соңғы қалтасында, оның атының алдында жатыр."),
        explanation: l(`Файл лежит в последней папке пути перед именем файла: ${last}. Остальные папки содержат её.`, `Файл жолдың файл атының алдындағы соңғы қалтасында жатыр: ${last}. Қалған қалталар оны қамтиды.`),
      },
      last,
      [
        { v: p.folders[0], why: l("Это первая папка пути: она содержит остальные, но файл лежит глубже.", "Бұл жолдың бірінші қалтасы: ол қалғандарын қамтиды, бірақ файл тереңірек жатыр.") },
        { v: p.disk, why: l("Это диск, а не папка.", "Бұл диск, қалта емес.") },
        { v: stemOf(p.file), why: l("Это имя файла, а не папка.", "Бұл файл аты, қалта емес.") },
      ],
    );
  }
  return numInput(
    {
      id: pathId("path-count", p, seed),
      level,
      prompt: l(`Сколько папок указано в пути ${P}? Диск не считай.`, `${P} жолында қанша қалта көрсетілген? Дискіні санама.`),
      hint: l("Посчитай части пути между знаками «\\» — диск и имя файла не в счёт.", "Жолдың «\\» белгілері арасындағы бөліктерін сана: диск пен файл аты есепке кірмейді."),
      explanation: l(`В пути ${code(P)} папки: ${p.folders.join(", ")}. Всего ${p.folders.length}.`, `${code(P)} жолындағы қалталар: ${p.folders.join(", ")}. Барлығы ${p.folders.length}.`),
    },
    String(p.folders.length),
  );
}

/** B: перемещение в папку Q. */
function pathMove(rand: Rand, level: Level, seed: number): QuestionStep {
  const p = randPath(rand, int(rand, 2, 3));
  const target = { disk: pick(rand, DISKS), folders: randFolders(rand, int(rand, 1, 2), p.folders.slice(-1)) };
  const Q = folderStr(target.disk, target.folders);
  const P = pathStr(p);
  const correct = `${Q}${BS}${p.file}`;
  return choice(
    rand,
    {
      id: pathId("path-move", p, seed),
      level,
      prompt: l(`Путь файла: ${P}. Файл переместили в папку ${Q}. Каким стал полный путь файла?`, `Файлдың жолы: ${P}. Файл мына қалтаға жылжытылды: ${Q}. Файлдың жаңа толық жолы қандай?`),
      hint: HINT_PATH,
      explanation: l(
        `При перемещении путь становится «путь новой папки + имя файла»: ${code(Q)} + ${code(`${BS}${p.file}`)} = ${code(correct)}. Старые папки в новый путь не входят.`,
        `Жылжытқанда жол «жаңа қалта жолы + файл аты» болады: ${code(Q)} + ${code(`${BS}${p.file}`)} = ${code(correct)}. Ескі қалталар жаңа жолға кірмейді.`,
      ),
    },
    correct,
    [
      { v: P, why: l("Это прежний путь: при перемещении файл покидает старую папку.", "Бұл бұрынғы жол: жылжытқанда файл ескі қалтадан кетеді.") },
      { v: [Q, ...p.folders, p.file].join(BS), why: l("Старые папки не переезжают вместе с файлом: в новую папку попадает только сам файл.", "Ескі қалталар файлмен бірге көшпейді: жаңа қалтаға тек файлдың өзі түседі.") },
      { v: Q, why: l("Это путь папки, а нужен путь файла: в конце должно быть имя файла.", "Бұл қалта жолы, ал файл жолы керек: соңында файл аты болуы керек.") },
      { v: [p.disk, ...target.folders, p.file].join(BS), why: l("Диск остался прежним, но файл перемещён на диск новой папки.", "Диск бұрынғыдай қалған, бірақ файл жаңа қалта дискісіне жылжытылған.") },
    ],
  );
}

/** C: на уровень вверх; перемещение с переименованием; копирование и удаление исходной папки. */
