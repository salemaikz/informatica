const SKILL = "pc.software";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const l = (ru: string, kk: string): L => ({ ru, kk });
const code = (s: string) => `\`${s}\``;
/** «в 2 раза», «в 5 раз». */
const raza = (n: number) => (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? "раза" : "раз");
const slug = (s: string) => s.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "");

type W = L | null;

// ====================================================================================================
// Статичный пул «на знание»
// ====================================================================================================

interface PoolChoice {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number;
  why: W[];
  explanation: L;
}

function q(name: string, level: Level, p: PoolChoice): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

interface PoolMulti {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number[];
  why: W[];
  explanation: L;
}

function qm(name: string, level: Level, p: PoolMulti): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

