const WORDS = ["data", "cat", "bag", "map", "tea", "lamp", "note", "task", "list", "tab", "bat", "car", "tom", "sam", "dan", "bob", "sun", "moon", "plan", "rock", "star", "book", "fish", "kit", "box", "pen", "ten", "sea", "red", "web"];
const EXT3 = ["txt", "doc", "jpg", "png", "mp3", "pdf", "xls", "zip", "exe", "tst", "tot", "ppt", "mp4", "avi", "bmp", "csv"];
const LETTERS = "abcdefghklmnoprstuw";

type FitMode = "exact" | "anyQ" | "optQ" | "plusStar";

/** Регулярка маски. Режимы-«ошибки»: ? как любое количество / как необязательный символ; * как «хотя бы один». */
function maskRe(mask: string, mode: FitMode = "exact"): RegExp {
  let s = "";
  for (const ch of mask) {
    if (ch === "*") s += mode === "plusStar" ? ".+" : ".*";
    else if (ch === "?") s += mode === "anyQ" ? ".*" : mode === "optQ" ? ".?" : ".";
    else s += ch.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${s}$`);
}
const fits = (mask: string, name: string, mode: FitMode = "exact") => maskRe(mask, mode).test(name);

interface MaskCase {
  mask: string;
  /** Имена в порядке показа. */
  names: string[];
  yes: string[];
  no: string[];
  base: string;
}

/** Маска, под которую заведомо подходит имя w.e (так в списке всегда есть подходящее). */
function buildMask(rand: Rand, level: Level, w: string, e: string): string {
  const n = w.length;
  const L1 = [`*.${e}`, `${"?".repeat(n)}.${e}`, `${w[0]}*`];
  const L2 = [`?${w[1]}*.${e}`, `*${w[n - 2]}?.${e}`, `${w[0]}*.${e[0]}?${e[2]}`];
  const L3 = [`?${w[1]}*.${e[0]}?${e[2]}`, `*${w[n - 2]}?.?${e[1]}*`, `${w[0]}?*.?${e[1]}?`, `??${w[2]}*.*${e[2]}`];
  return pick(rand, level === 1 ? L1 : level === 2 ? L2 : L3);
}

/** Похожие на w.e имена: меняем по одному месту — часть подойдёт под маску, часть нет. */
function variants(rand: Rand, w: string, e: string): string[] {
  const rl = () => LETTERS[int(rand, 0, LETTERS.length - 1)];
  const out: string[] = [];
  for (let i = 0; i < w.length; i++) out.push(`${w.slice(0, i)}${rl()}${w.slice(i + 1)}.${e}`);
  for (let i = 0; i < w.length; i++) out.push(`${w.slice(0, i)}${rl()}${w.slice(i + 1)}.${e}`);
  out.push(`${w.slice(1)}.${e}`, `${w}${rl()}.${e}`, `${w[0]}${rl()}${w.slice(1)}.${e}`);
  out.push(`${w}.${pick(rand, EXT3)}`, `${w}.${e.slice(0, 2)}`, `${w}.${e}${rl()}`, `${w}.${e[0]}${rl()}${e[2]}`, `${w}.${e.slice(0, 2)}${rl()}`, `${w}.${rl()}${e.slice(1)}`, `${w}.${e}.bak`);
  return out;
}

function genCase(rand: Rand, level: Level): MaskCase {
  const total = level === 1 ? 6 : level === 2 ? 7 : 8;
  for (let attempt = 0; attempt < 500; attempt++) {
    const w = pick(rand, WORDS);
    const e = pick(rand, EXT3);
    const mask = buildMask(rand, level, w, e);
    const base = `${w}.${e}`;
    const cands = new Set<string>([base, ...variants(rand, w, e)]);
    for (let i = 0; i < 6; i++) cands.add(`${pick(rand, WORDS)}.${pick(rand, EXT3)}`);
    const all = [...cands];
    const yes = all.filter((n) => fits(mask, n));
    const no = all.filter((n) => !fits(mask, n));
    const k = level === 1 ? int(rand, 1, 3) : level === 2 ? int(rand, 2, 3) : int(rand, 2, 4);
    if (yes.length < k || no.length < total - k) continue;
    const others = yes.filter((n) => n !== base);
    const chosenYes = [base, ...shuffle(others, rand).slice(0, k - 1)];
    // Сначала «почти подходящие» имена (подошли бы при ошибочном чтении маски), затем остальные.
    const traps = shuffle(no.filter((n) => fits(mask, n, "anyQ") || fits(mask, n, "optQ") || fits(mask, n, "plusStar")), rand);
    const rest = shuffle(no.filter((n) => !traps.includes(n)), rand);
    const chosenNo = [...traps, ...rest].slice(0, total - k);
    if (chosenNo.length < total - k) continue;
    const names = shuffle([...chosenYes, ...chosenNo], rand);
    return { mask, names, yes: names.filter((n) => chosenYes.includes(n)), no: names.filter((n) => chosenNo.includes(n)), base };
  }
  // Запасной вариант (до него практически не доходит).
  const names = ["a.txt", "ab.txt", "notes.txt", "notes.doc", "txt.jpg", "a.txt.bak"];
  return { mask: "*.txt", names, yes: ["a.txt", "ab.txt", "notes.txt"], no: ["notes.doc", "txt.jpg", "a.txt.bak"], base: "a.txt" };
}

type Reason = "len" | "start" | "end" | "mid" | "chars";

/** Почему имя не подходит под маску (первая найденная причина). */
function reasonOf(mask: string, name: string): Reason {
  const parts = mask.split("*");
  if (parts.length === 1) return name.length !== mask.length ? "len" : "chars";
  const head = parts[0];
  const tail = parts[parts.length - 1];
  if (name.length < parts.join("").length) return "len";
  if (head && !fits(`${head}*`, name)) return "start";
  if (tail && !fits(`*${tail}`, name)) return "end";
  return "mid";
}

const REASON_SHORT: Record<Reason, L> = {
  len: l("длина не подходит", "ұзындығы сәйкес емес"),
  start: l("начало не подходит", "басы сәйкес емес"),
  end: l("конец не подходит", "соңы сәйкес емес"),
  mid: l("не совпадает средняя часть", "ортаңғы бөлігі сәйкес емес"),
  chars: l("не совпадают символы", "таңбалары сәйкес емес"),
};

const whyNot = (mask: string, name: string): L => {
  const r = REASON_SHORT[reasonOf(mask, name)];
  return l(`Имя не подходит под маску: ${r.ru}.`, `Ат маскаға сәйкес емес: ${r.kk}.`);
};

/** Разбор «что подошло, что нет и почему» для объяснения. */
function maskExplanation(c: MaskCase): L {
  const noRu = c.no.map((n) => `${n} (${REASON_SHORT[reasonOf(c.mask, n)].ru})`).join("; ");
  const noKk = c.no.map((n) => `${n} (${REASON_SHORT[reasonOf(c.mask, n)].kk})`).join("; ");
  return l(
    `Проверяем каждое имя по частям маски ${code(c.mask)}. Подходят: ${c.yes.join(", ")}. Не подходят: ${noRu}. Знак ? заменяет ровно один символ, знак * — любое количество, в том числе ноль. Ответ: ${c.yes.length}.`,
    `Әр атты ${code(c.mask)} маскасының бөліктері бойынша тексереміз. Сәйкес келеді: ${c.yes.join(", ")}. Сәйкес келмейді: ${noKk}. ? белгісі дәл бір таңбаны алмастырады, * белгісі — таңбалардың кез келген санын, нөлді де. Жауабы: ${c.yes.length}.`,
  );
}

const HINT_MASK: L = l(
  "Проверяй каждое имя по частям маски: начало, конец, число символов. Помни: ? — ровно один символ, а * — любое количество.",
  "Әр атты маска бөліктері бойынша тексер: басы, соңы, таңба саны. Есте сақта: ? — дәл бір таңба, ал * — кез келген сан.",
);

/** Неверные ответы для «сколько подходит»: типичные ошибки чтения маски. */
function countWrongs(c: MaskCase): Wrong[] {
  const k = c.yes.length;
  const cnt = (mode: FitMode) => c.names.filter((n) => fits(c.mask, n, mode)).length;
  const out: Wrong[] = [];
  const hasQ = c.mask.includes("?");
  if (hasQ) {
    out.push({ v: String(cnt("anyQ")), why: l("Так получится, если считать ? любым количеством символов, как *. Но ? — ровно один символ.", "Егер ? белгісін * сияқты кез келген таңба саны деп санасаң, осылай шығады. Бірақ ? — дәл бір таңба.") });
    out.push({ v: String(cnt("optQ")), why: l("Так получится, если считать ? необязательным символом. Но ? всегда заменяет ровно один символ.", "Егер ? белгісін міндетті емес таңба деп санасаң, осылай шығады. Бірақ ? әрқашан дәл бір таңбаны алмастырады.") });
  }
  out.push({ v: String(cnt("plusStar")), why: l("Так получится, если считать, что * заменяет хотя бы один символ. Но * может заменять и пустое место.", "Егер * белгісі кемінде бір таңбаны алмастырады деп санасаң, осылай шығады. Бірақ * бос орынды да алмастыра алады.") });
  out.push({ v: String(c.names.length), why: l("Подходят не все имена: проверь начало и конец каждого.", "Барлық ат сәйкес келмейді: әрқайсысының басы мен соңын тексер.") });
  out.push({ v: String(k + 1), why: l("Посчитано на одно имя больше: одно из имён на самом деле не подходит.", "Бір атқа артық саналған: аттардың бірі шын мәнінде сәйкес келмейді.") });
  out.push({ v: String(Math.max(0, k - 1)), why: l("Посчитано на одно имя меньше: одно подходящее имя пропущено.", "Бір атқа кем саналған: бір сәйкес ат өткізіліп кеткен.") });
  out.push({ v: String(k + 2), why: l("Подходящих имён меньше: проверь каждое имя по частям маски.", "Сәйкес аттар аз: әр атты маска бөліктері бойынша тексер.") });
  return out.filter((w) => w.v !== String(k) && Number(w.v) >= 0);
}

const stepId = (kind: string, c: MaskCase, seed: number) => `g:${SKILL}:${kind}:${slug(c.mask)}-${c.names.length}:${seed}`;

function maskCount(rand: Rand, level: Level, seed: number, asChoice: boolean): QuestionStep {
  const c = genCase(rand, level);
  const k = c.yes.length;
  const head = {
    id: stepId(asChoice ? "mask-count" : "mask-input", c, seed),
    level,
    prompt: l(`Сколько файлов из таблицы подходят под маску ${c.mask}`, `Кестедегі файлдардың қаншасы ${c.mask} маскасына сәйкес келеді?`),
    hint: HINT_MASK,
    explanation: maskExplanation(c),
    scene: filesTable(c.names),
  };
  if (!asChoice) return numInput({ ...head, prompt: l(`Сколько файлов из таблицы подходят под маску ${c.mask}`, `Кестедегі файлдардың қаншасы ${c.mask} маскасына сәйкес келеді? Санын енгіз.`) }, String(k));
  return choice(rand, head, String(k), countWrongs(c));
}

function maskWhich(rand: Rand, level: Level, seed: number): QuestionStep {
  const c = genCase(rand, level);
  const yes = pick(rand, c.yes);
  const nos = shuffle(c.no, rand).slice(0, 3);
  return choice(
    rand,
    {
      id: stepId("mask-which", c, seed),
      level,
      prompt: l(`Какое имя файла подходит под маску ${c.mask}`, `Қай файл аты ${c.mask} маскасына сәйкес келеді?`),
      hint: HINT_MASK,
      explanation: l(
        `Маска ${code(c.mask)}: подходит ${yes}. Остальные имена не подходят: ${nos.map((n) => `${n} (${REASON_SHORT[reasonOf(c.mask, n)].ru})`).join("; ")}.`,
        `${code(c.mask)} маскасына ${yes} аты сәйкес келеді. Қалған аттар сәйкес емес: ${nos.map((n) => `${n} (${REASON_SHORT[reasonOf(c.mask, n)].kk})`).join("; ")}.`,
      ),
    },
    yes,
    nos.map((n) => ({ v: n, why: whyNot(c.mask, n) })),
  );
}

/** Обратная задача: найти маску, которая подходит ко всем «да»-именам и ни к одному «нет»-имени. */
function maskReverse(rand: Rand, level: Level, seed: number): QuestionStep {
  for (let attempt = 0; attempt < 200; attempt++) {
    const c = genCase(rand, level === 3 ? 3 : 2);
    if (c.yes.length < 2 || c.no.length < 2) continue;
    const yes = c.yes.slice(0, 3);
    const nos = c.no.slice(0, 2);
    const ok = (m: string) => yes.every((n) => fits(m, n)) && !nos.some((n) => fits(m, n));
    // Кандидаты-ошибки: меняем один знак маски.
    const cands = new Set<string>();
    const chars = [...c.mask];
    chars.forEach((ch, i) => {
      if (ch === "?") cands.add(chars.map((x, j) => (j === i ? "*" : x)).join(""));
      if (ch === "*") cands.add(chars.map((x, j) => (j === i ? "?" : x)).join(""));
      if (ch !== "?" && ch !== "*" && ch !== ".") {
        const other = LETTERS[(LETTERS.indexOf(ch) + 3 + LETTERS.length) % LETTERS.length] ?? "a";
        cands.add(chars.map((x, j) => (j === i ? other : x)).join(""));
        cands.add(chars.map((x, j) => (j === i ? "?" : x)).join(""));
      }
    });
    cands.add(c.mask.replace(/\?/g, ""));
    cands.add("*" + c.mask.slice(c.mask.indexOf(".")));
    const wrong = [...cands].filter((m) => m !== c.mask && !ok(m));
    if (!ok(c.mask) || wrong.length < 3) continue;
    const why = (m: string): L => {
      const miss = yes.find((n) => !fits(m, n));
      if (miss) {
        return l(`Эта маска не подходит к файлу ${miss}, а должна.`, `Бұл маска мына файлға сәйкес емес, бірақ сәйкес болуы керек: ${miss}`);
      }
      const extra = nos.find((n) => fits(m, n)) as string;
      return l(`Эта маска подходит к файлу ${extra}, а не должна.`, `Бұл маска мына файлға сәйкес келеді, бірақ келмеуі керек: ${extra}`);
    };
    const picked = shuffle(wrong, rand).slice(0, 3);
    return choice(
      rand,
      {
        id: `g:${SKILL}:mask-reverse:${slug(c.mask)}:${seed}`,
        level,
        prompt: l(
          `Какая маска подходит ко всем файлам: ${yes.join(", ")} — и не подходит ни к одному из файлов: ${nos.join(", ")}`,
          `Қай маска мына файлдардың барлығына сәйкес келеді: ${yes.join(", ")} — және мына файлдардың ешқайсысына сәйкес келмейді: ${nos.join(", ")}?`,
        ),
        hint: l(
          "Сравни имена из первой группы: что у них общего (начало, конец, длина)? Потом проверь, что маска не пропускает имена из второй группы.",
          "Бірінші топтағы аттарды салыстыр: оларда не ортақ (басы, соңы, ұзындығы)? Содан кейін маска екінші топтағы аттарды өткізбейтінін тексер.",
        ),
        explanation: l(
          `Маска ${code(c.mask)} подходит ко всем именам первой группы (${yes.join(", ")}) и ни к одному из второй (${nos.join(", ")}). У остальных масок есть имя, которое они пропускают или отвергают неверно.`,
          `${code(c.mask)} маскасы бірінші топтың барлық атына (${yes.join(", ")}) сәйкес келеді және екінші топтың ешқайсысына (${nos.join(", ")}) сәйкес келмейді. Қалған маскаларда дұрыс өткізбейтін немесе қате қабылдайтын ат бар.`,
        ),
      },
      c.mask,
      picked.map((m) => ({ v: m, why: why(m) })),
    );
  }
  return maskCount(rand, 3, seed, true);
}

