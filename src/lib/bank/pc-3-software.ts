function maskStatement(rand: Rand, level: Level): Statement {
  const c = genCase(rand, level);
  const useYes = rand() < 0.5;
  const name = useYes ? pick(rand, c.yes) : pick(rand, c.no);
  const value = fits(c.mask, name);
  return {
    id: `s:${SKILL}:mask:${slug(c.mask)}:${slug(name)}`,
    skill: SKILL,
    level,
    text: l(`Имя ${name} подходит под маску ${c.mask}`, `${name} аты ${c.mask} маскасына сәйкес келеді`),
    value,
    explanation: value
      ? l(`Имя ${name} проходит все части маски ${code(c.mask)}: начало, конец и число символов совпадают.`, `${name} аты ${code(c.mask)} маскасының барлық бөлігінен өтеді: басы, соңы және таңба саны сәйкес келеді.`)
      : l(`Имя ${name} не подходит под маску ${code(c.mask)}: ${REASON_SHORT[reasonOf(c.mask, name)].ru}.`, `${name} аты ${code(c.mask)} маскасына сәйкес емес: ${REASON_SHORT[reasonOf(c.mask, name)].kk}.`),
    hint: l("Разбери маску на части и проверь имя по очереди: начало, конец, число символов.", "Маскаңды бөліктерге бөліп, атты кезекпен тексер: басы, соңы, таңба саны."),
  };
}

function shortQuestion(rand: Rand, level: Level, seed: number): ShortQuestion {
  let kind = int(rand, 0, 3);
  if (kind === 2 && level > 1) kind = 3;
  if (kind === 0 || (level === 3 && kind === 1)) {
    const c = genCase(rand, level);
    return {
      id: `sh:${SKILL}:mask:${slug(c.mask)}-${c.names.length}:${seed}`,
      skill: SKILL,
      level,
      prompt: l(`Файлы: ${c.names.join(", ")}. Сколько из них подходят под маску ${c.mask}? Введи число.`, `Файлдар: ${c.names.join(", ")}. Олардың қаншасы ${c.mask} маскасына сәйкес келеді? Санды енгіз.`),
      answer: String(c.yes.length),
      mode: "number",
      explanation: maskExplanation(c),
      hint: HINT_MASK,
    };
  }
  if (kind === 1) {
    const p = randPath(rand, int(rand, 2, 4));
    const P = pathStr(p);
    return {
      id: `sh:${SKILL}:folders:${slug(P)}:${seed}`,
      skill: SKILL,
      level,
      prompt: l(`Сколько папок указано в пути ${P}? Диск не считай. Введи число.`, `${P} жолында қанша қалта көрсетілген? Дискіні санама. Санды енгіз.`),
      answer: String(p.folders.length),
      mode: "number",
      explanation: l(`В пути ${code(P)} папки: ${p.folders.join(", ")}. Всего ${p.folders.length}.`, `${code(P)} жолындағы қалталар: ${p.folders.join(", ")}. Барлығы ${p.folders.length}.`),
      hint: l("Посчитай части пути между знаками «\\» — диск и имя файла не в счёт.", "Жолдың «\\» белгілері арасындағы бөліктерін сана: диск пен файл аты есепке кірмейді."),
    };
  }
  if (kind === 2) {
    const file = pick(rand, FILES);
    const ext = extOf(file);
    return {
      id: `sh:${SKILL}:ext:${slug(file)}:${seed}`,
      skill: SKILL,
      level,
      prompt: l(`Введи расширение файла ${file} без точки.`, `${file} файлының кеңейтілімін нүктесіз енгіз.`),
      answer: ext,
      mode: "text",
      explanation: l(`Расширение — часть имени после точки: ${ext}.`, `Кеңейтілім — атаудың нүктеден кейінгі бөлігі: ${ext}.`),
      hint: l("Расширение стоит в самом конце имени, после точки.", "Кеңейтілім атаудың ең соңында, нүктеден кейін тұрады."),
    };
  }
  const r = int(rand, 2, 8);
  const after = pick(rand, [5, 6, 8, 10, 12, 15, 20]);
  return {
    id: `sh:${SKILL}:ratio:${r * after}-${after}:${seed}`,
    skill: SKILL,
    level,
    prompt: l(`Файл размером ${r * after} Мбайт после архивации занимает ${after} Мбайт. Во сколько раз он стал меньше? Введи число.`, `Көлемі ${r * after} Мбайт файл архивтелгеннен кейін ${after} Мбайт алады. Ол неше есе кішірейді? Санды енгіз.`),
    answer: String(r),
    mode: "number",
    explanation: l(`Коэффициент сжатия = ${r * after} : ${after} = ${r}.`, `Сығу коэффициенті = ${r * after} : ${after} = ${r}.`),
    hint: RATIO_HINT,
  };
}

