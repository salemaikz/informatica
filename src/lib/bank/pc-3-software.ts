const pcSoftware: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed);
    const r = rand();
    const poolShare = level === 1 ? 0.4 : level === 2 ? 0.3 : 0.25;
    if (r < poolShare) return pool.question(level, seed + 99991);
    const g = rand();
    if (level === 1) {
      if (g < 0.45) return maskCount(rand, 1, seed, rand() < 0.4);
      if (g < 0.6) return maskWhich(rand, 1, seed);
      if (g < 0.85) return pathBasic(rand, 1, seed);
      return archive(rand, 1, seed);
    }
    if (level === 2) {
      if (g < 0.35) return rand() < 0.5 ? maskCount(rand, 2, seed, rand() < 0.5) : maskWhich(rand, 2, seed);
      if (g < 0.7) return pathMove(rand, 2, seed);
      return archive(rand, 2, seed);
    }
    if (g < 0.35) return maskCount(rand, 3, seed, true);
    if (g < 0.55) return maskReverse(rand, 3, seed);
    if (g < 0.8) return pathHard(rand, 3, seed);
    return archive(rand, 3, seed);
  },
  statement(level, seed): Statement {
    const rand = seeded(seed);
    if (level >= 2 && rand() < 0.35) return maskStatement(rand, level);
    return pool.statement!(level, seed + 99991);
  },
  pair(level, seed): Pair {
    return pool.pair!(level, seed);
  },
  short(level, seed): ShortQuestion {
    return shortQuestion(seeded(seed), level, seed);
  },
};

