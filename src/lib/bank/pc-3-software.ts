interface Wrong {
  v: string;
  why: L;
}

/** Задание «выбор из 4»: верный + три разных неверных (с разбором ошибки), порядок перемешан. */
function choice(
  rand: Rand,
  head: { id: string; level: Level; prompt: L; hint: L; explanation: L; scene?: Scene; reveal?: Scene },
  correct: string,
  wrongs: Wrong[],
): ChoiceStep {
  const seen = new Set<string>([correct]);
  const picked: Wrong[] = [];
  for (const w of wrongs) {
    if (picked.length >= 3) break;
    if (!seen.has(w.v)) {
      seen.add(w.v);
      picked.push(w);
    }
  }
  if (picked.length < 3) throw new Error(`pc-3-software ${head.id}: не хватает неверных вариантов`);
  const all = shuffle<{ v: string; why: L | null }>([{ v: correct, why: null }, ...picked], rand);
  return {
    type: "choice",
    skill: SKILL,
    ...head,
    options: all.map((a): Text => a.v),
    correct: all.findIndex((a) => a.why === null),
    whyWrong: all.map((a) => a.why),
  };
}

function numInput(head: { id: string; level: Level; prompt: L; hint: L; explanation: L; scene?: Scene }, answer: string): InputStep {
  return { type: "input", skill: SKILL, ...head, answers: [answer], mode: "number" };
}

