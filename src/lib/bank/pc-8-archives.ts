/** Утверждение про RLE, истинность которого считает код. */
function rleStatement(rand: Rand, level: Level): Statement {
  const runs = level === 2 ? randomRuns(rand, 3, 6, 2) : randomRuns(rand, int(rand, 3, 5), 3);
  let s = build(runs);
  // Для уровня C иногда делаем строку без серий, чтобы код оказался длиннее.
  if (level === 3 && rand() < 0.5) s = build(randomRuns(rand, 6, 1));
  const code = rle(s);
  const shorter = code.length < s.length;
  const claimShorter = rand() < 0.5;
  return {
    id: `s:${SKILL}:rle:${s}:${claimShorter ? "short" : "long"}`,
    skill: SKILL,
    level,
    text: claimShorter
      ? l(`RLE-код строки ${s} короче самой строки`, `${s} жолының RLE коды жолдың өзінен қысқа`)
      : l(`RLE-код строки ${s} не короче самой строки`, `${s} жолының RLE коды жолдың өзінен қысқа емес`),
    value: claimShorter ? shorter : !shorter,
    explanation: l(
      `${s} → ${code}: в строке ${s.length} символов, в коде ${code.length}. ${shorter ? "Серии длинные, поэтому код короче." : "Серий почти нет, поэтому код не короче."}`,
      `${s} → ${code}: жолда ${s.length} таңба, кодта ${code.length}. ${shorter ? "Сериялар ұзын, сондықтан код қысқа." : "Сериялар дерлік жоқ, сондықтан код қысқа емес."}`,
    ),
    hint: l("Закодируй строку и сравни длины: каждая серия в коде занимает минимум два символа.", "Жолды кодтап, ұзындықтарын салыстыр: әр серия кодта кемінде екі таңба алады."),
  };
}

