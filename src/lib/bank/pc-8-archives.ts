/** Серии одинаковых символов подряд → «число + символ». */
function rle(s: string): string {
  let out = "";
  for (let i = 0; i < s.length; ) {
    let j = i;
    while (j < s.length && s[j] === s[i]) j++;
    out += `${j - i}${s[i]}`;
    i = j;
  }
  return out;
}

/** Строка из серий: runs = [[символ, длина], …]. */
const build = (runs: [string, number][]) => runs.map(([c, n]) => c.repeat(n)).join("");

