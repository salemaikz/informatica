const pcArchives: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed);
    const r = rand();
    const poolShare = level === 1 ? 0.5 : level === 2 ? 0.4 : 0.35;
    if (r < poolShare) return pool.question(level, seed + 99991);
    const g = rand();
    if (level === 1) return g < 0.6 ? ratioQuestion(rand, 1, seed) : rleQuestion(rand, 1, seed);
    if (level === 2) return g < 0.5 ? ratioQuestion(rand, 2, seed) : rleQuestion(rand, 2, seed);
    if (g < 0.4) return ratioQuestion(rand, 3, seed);
    if (g < 0.7) return rleQuestion(rand, 3, seed);
    return imageQuestion(rand, seed);
  },
  statement(level, seed): Statement {
    const rand = seeded(seed);
    if (level >= 2 && rand() < 0.3) return rleStatement(rand, level);
    return pool.statement!(level, seed + 99991);
  },
  pair(level, seed): Pair {
    return pool.pair!(level, seed);
  },
  short(level, seed): ShortQuestion {
    return shortQuestion(seeded(seed), level, seed);
  },
};

