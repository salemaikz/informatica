    const runs = randomRuns(rand, int(rand, 3, 4), 9).map(([c, n], i): [string, number] => (i === 1 ? [c, int(rand, 10, 25)] : [c, n]));
    const code = runs.map(([c, n]) => `${n}${c}`).join("");
