function know(rand: Rand, level: Level, seed: number): ChoiceStep {
  const pool = KNOW.filter((k) => k.level === level);
  const list = pool.length ? pool : KNOW;
  const k = pick(rand, list);
  return { ...choice(rand, { ...k, id: `g:${SKILL}:know:${k.name}:${seed}` }), level: k.level };
}

