function statement(level: Level, seed: number): Statement {
  const rand = seeded(seed);
  const value = rand() < 0.5;
  if (level === 1) {
    if (rand() < 0.45) {
      const i = pick(rand, [2, 3, 4, 5, 6, 7, 8, 16] as const);
      const n = 2 ** i;
      const claim = value ? n : pick(rand, [2 * i, i * i, n * 2, n / 2].filter((x) => x !== n));
      return {
        id: `s:${SKILL}:pal:${i}:${claim}`,
        skill: SKILL,
        level,
        text: {
          ru: `При глубине цвета ${bitsRu(i)} палитра содержит ${num(claim)} ${ruPl(claim, "цвет", "цвета", "цветов")}`,
          kk: `Түс тереңдігі ${i} бит болғанда палитрада ${num(claim)} түс бар`,
        },
        value: claim === n,
        explanation: { ru: `N = 2ⁱ = 2${sup(i)} = ${num(n)}.`, kk: `N = 2ⁱ = 2${sup(i)} = ${num(n)}.` },
        hint: { ru: "Используй формулу N = 2ⁱ.", kk: "N = 2ⁱ формуласын қолдан." },
      };
    }
    return pick(rand, STATEMENTS.filter((s) => s.level === 1));
  }
  if (level === 2) {
    if (rand() < 0.2) return pick(rand, STATEMENTS.filter((s) => s.level === 2));
    const { w, h, i } = pickImage(rand);
    const n = 2 ** i;
    const kb = imgKb(w, h, i);
    const claim = value ? kb : pick(rand, [kb * 2, kb / 2].filter((x) => x !== kb));
    return {
      id: `s:${SKILL}:kb:${w}x${h}:${i}:${claim}`,
      skill: SKILL,
      level,
      text: {
        ru: `Изображение ${w} × ${h} пикселей с палитрой из ${colorsGen(n)} занимает ${kbText(claim)} Кбайт`,
        kk: `${num(n)} түсті палитрасы бар ${w} × ${h} пиксель кескін ${kbText(claim)} Кбайт алады`,
      },
      value: claim === kb,
      explanation: {
        ru: `i = ${i}; ${num(w * h)} · ${i} = ${num(w * h * i)} бит = ${num(w * h * i / 8)} байт = ${num(kb)} Кбайт.`,
        kk: `i = ${i}; ${num(w * h)} · ${i} = ${num(w * h * i)} бит = ${num(w * h * i / 8)} байт = ${num(kb)} Кбайт.`,
      },
      hint: { ru: "Найди i, умножь на число пикселей, потом раздели на 8 и на 1024.", kk: "i тап, пиксель санына көбейт, содан кейін 8-ге және 1024-ке бөл." },
    };
  }
  const { f, i, k, t, sec } = pickSound(rand, false);
  const kb = soundBits(f, i, k, sec) / 8192;
  const claim = value ? kb : pick(rand, [kb * 2, kb / 2].filter((x) => x !== kb));
  return {
    id: `s:${SKILL}:snd:${f}:${i}:${k}:${t}:${claim}`,
    skill: SKILL,
    level,
    text: {
      ru: `Запись (${num(f)} Гц, ${bitsRu(i)}, ${modeL(k).ru}, ${t} с) занимает ${kbText(claim)} Кбайт`,
      kk: `Жазба (${num(f)} Гц, ${i} бит, ${modeL(k).kk}, ${t} с) ${kbText(claim)} Кбайт алады`,
    },
    value: claim === kb,
    explanation: {
      ru: `I = ${num(f)} · ${i} · ${k} · ${t} = ${num(soundBits(f, i, k, sec))} бит = ${num(kb)} Кбайт.`,
      kk: `I = ${num(f)} · ${i} · ${k} · ${t} = ${num(soundBits(f, i, k, sec))} бит = ${num(kb)} Кбайт.`,
    },
    hint: HINT_SOUND,
  };
}

function pair(level: Level, seed: number): Pair {
  const rand = seeded(seed);
  if (level === 1) {
    const i = pick(rand, [1, 2, 3, 4, 5, 6, 7, 8] as const);
    return { id: `p:${SKILL}:pal:${i}`, skill: SKILL, level, left: `i = ${i}`, right: `N = ${2 ** i}` };
  }
  if (level === 2) {
    const c = pick(rand, COLORS);
    return { id: `p:${SKILL}:color:${c.key}`, skill: SKILL, level, left: c.hex, right: c.name };
  }
  const { w, h, i } = pickImage(rand);
  const n = 2 ** i;
  return {
    id: `p:${SKILL}:kb:${w}x${h}:${i}`,
    skill: SKILL,
    level,
    left: { ru: `${w} × ${h}, ${colorsRu(n)}`, kk: `${w} × ${h}, ${num(n)} түс` },
    right: `${num(imgKb(w, h, i))} Кбайт`,
  };
}

function short(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed);
  if (level === 1) {
    if (rand() < 0.5) {
      const i = pick(rand, [2, 3, 4, 5, 6, 7, 8] as const);
      return {
        id: `q:${SKILL}:pal:${i}`,
        skill: SKILL,
        level,
        prompt: { ru: `Глубина цвета ${bitsRu(i)}. Сколько цветов в палитре?`, kk: `Түс тереңдігі ${i} бит. Палитрада неше түс бар?` },
        answer: String(2 ** i),
        mode: "number",
        explanation: same(`N = 2${sup(i)} = ${2 ** i}`),
        hint: { ru: "Используй формулу N = 2ⁱ.", kk: "N = 2ⁱ формуласын қолдан." },
      };
    }
    const i = pick(rand, [2, 3, 4, 5, 6, 7, 8] as const);
    return {
      id: `q:${SKILL}:depth:${i}`,
      skill: SKILL,
      level,
      prompt: { ru: `В палитре ${colorsRu(2 ** i)}. Сколько бит на пиксель?`, kk: `Палитрада ${2 ** i} түс бар. Бір пиксельге неше бит?` },
      answer: String(i),
      mode: "number",
      explanation: same(`2${sup(i)} = ${2 ** i} → i = ${i}`),
      hint: { ru: "Подбери i, при котором 2ⁱ равно числу цветов.", kk: "2ⁱ түс санына тең болатын i таңда." },
    };
  }
  if (level === 2) {
    const { w, h, i } = pickImage(rand);
    const n = 2 ** i;
    const kb = imgKb(w, h, i);
    return {
      id: `q:${SKILL}:kb:${w}x${h}:${i}`,
      skill: SKILL,
      level,
      prompt: {
        ru: `Рисунок ${w} × ${h}, палитра — ${colorsRu(n)}. Сколько Кбайт?`,
        kk: `Сурет ${w} × ${h}, палитрасы — ${num(n)} түс. Неше Кбайт?`,
      },
      answer: String(kb),
      mode: "number",
      explanation: same(`i = ${i}; ${num(w * h)} · ${i} : 8 : 1024 = ${num(kb)} Кбайт`),
      hint: HINT_PIXELS,
    };
  }
  const { f, i, k, t, sec } = pickSound(rand, false);
  const kb = soundBits(f, i, k, sec) / 8192;
  return {
    id: `q:${SKILL}:snd:${f}:${i}:${k}:${t}`,
    skill: SKILL,
    level,
    prompt: {
      ru: `Звук: ${num(f)} Гц, ${bitsRu(i)}, ${modeL(k).ru}, ${t} с. Сколько Кбайт?`,
      kk: `Дыбыс: ${num(f)} Гц, ${i} бит, ${modeL(k).kk}, ${t} с. Неше Кбайт?`,
    },
    answer: String(kb),
    mode: "number",
    explanation: same(`${num(f)} · ${i} · ${k} · ${t} : 8 : 1024 = ${num(kb)} Кбайт`),
    hint: HINT_SOUND,
  };
}

