/** Звук: как изменится объём при смене частоты, глубины и числа каналов. */
function soundChangeTask(rand: Rand, level: Level, seed: number): ChoiceStep {
  let f1 = 8000;
  let f2 = 16000;
  let i1 = 16;
  let i2 = 8;
  let k1 = 1;
  let k2 = 2;
  for (let t = 0; t < 100; t++) {
    f1 = pick(rand, [8000, 16000, 32000] as const);
    const mf = pick(rand, [0.5, 1, 2] as const);
    f2 = f1 * mf;
    const mi = pick(rand, [0.5, 1, 2] as const);
    [i1, i2] = mi === 2 ? [8, 16] : mi === 0.5 ? [16, 8] : [16, 16];
    const mk = pick(rand, [0.5, 1, 2] as const);
    [k1, k2] = mk === 2 ? [1, 2] : mk === 0.5 ? [2, 1] : [1, 1];
    if (f1 !== f2 || i1 !== i2 || k1 !== k2) break;
  }
  const mf = f2 / f1;
  const mi = i2 / i1;
  const mk = k2 / k1;
  const m = mf * mi * mk;
  const fr = (x: number) => (x >= 1 ? String(x) : `1/${1 / x}`);
  const label = (x: number): L => {
    if (x === 1) return { ru: "не изменится", kk: "өзгермейді" };
    if (x > 1) return { ru: `увеличится в ${x} ${ruPl(x, "раз", "раза", "раз")}`, kk: `${x} есе артады` };
    const y = 1 / x;
    return { ru: `уменьшится в ${y} ${ruPl(y, "раз", "раза", "раз")}`, kk: `${y} есе азаяды` };
  };
  const factors = [1 / 8, 1 / 4, 1 / 2, 1, 2, 4, 8].filter((x) => x !== m);
  const why = (x: number): L => ({
    ru: `Нужно перемножить три изменения: частота ×${fr(mf)}, глубина ×${fr(mi)}, каналы ×${fr(mk)} — получается ${label(m).ru}, а не «${label(x).ru}».`,
    kk: `Үш өзгерісті көбейту керек: жиілік ×${fr(mf)}, тереңдік ×${fr(mi)}, арналар ×${fr(mk)} — ${label(m).kk} шығады, «${label(x).kk}» емес.`,
  });
  return choice(rand, {
    id: `g:${SKILL}:sound-change:f${f1}-${f2}-i${i1}-${i2}-k${k1}-${k2}:${seed}`,
    level,
    prompt: {
      ru: `Звук записан с частотой дискретизации ${num(f1)} Гц, глубиной кодирования ${bitsRu(i1)}, режим — ${modeL(k1).ru}. Затем его перезаписали с частотой ${num(f2)} Гц, глубиной ${bitsRu(i2)}, режим — ${modeL(k2).ru} (длительность прежняя). Как изменится объём файла?`,
      kk: `Дыбыс дискреттеу жиілігі ${num(f1)} Гц, кодтау тереңдігі ${i1} бит, ${modeL(k1).kk} режимінде жазылған. Содан кейін ол жиілігі ${num(f2)} Гц, тереңдігі ${i2} бит, ${modeL(k2).kk} режимінде қайта жазылды (ұзақтығы бұрынғыдай). Файл көлемі қалай өзгереді?`,
    },
    hint: {
      ru: "Объём пропорционален f, i и k. Найди, во сколько раз изменилась каждая величина, и перемножь эти коэффициенты.",
      kk: "Көлем f, i және k шамаларына тура пропорционал. Әр шаманың неше есе өзгергенін тауып, коэффициенттерді көбейт.",
    },
    explanation: {
      ru: `Частота: ${num(f2)} : ${num(f1)} = ${fr(mf)}; глубина: ${i2} : ${i1} = ${fr(mi)}; каналы: ${k2} : ${k1} = ${fr(mk)}. Произведение ${fr(mf)} · ${fr(mi)} · ${fr(mk)} = ${fr(m)}: объём ${label(m).ru}.`,
      kk: `Жиілік: ${num(f2)} : ${num(f1)} = ${fr(mf)}; тереңдік: ${i2} : ${i1} = ${fr(mi)}; арналар: ${k2} : ${k1} = ${fr(mk)}. Көбейтінді ${fr(mf)} · ${fr(mi)} · ${fr(mk)} = ${fr(m)}: көлем ${label(m).kk}.`,
    },
    correct: label(m),
    wrongs: factors.map((x) => ({ text: label(x), why: why(x) })),
  });
}

