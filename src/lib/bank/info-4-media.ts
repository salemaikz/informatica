/** Размеры рисунков (все степени двойки или «экранные» размеры, для которых Кбайт часто целые). */
const SIZES: [number, number][] = [
  [32, 32], [64, 32], [64, 64], [128, 64], [128, 128], [256, 128], [256, 256], [320, 240], [512, 128], [512, 256], [640, 480], [1024, 512], [1024, 768],
];
const DEPTHS = [1, 2, 4, 4, 8, 8, 8, 16, 24] as const;

const imgBits = (w: number, h: number, i: number) => w * h * i;
const imgKb = (w: number, h: number, i: number) => imgBits(w, h, i) / 8192;

/** Рисунок, объём которого в Кбайт — целое число. */
function pickImage(rand: Rand): { w: number; h: number; i: number } {
  for (let t = 0; t < 200; t++) {
    const [w, h] = pick(rand, SIZES);
    const i = pick(rand, DEPTHS);
    if (imgBits(w, h, i) % 8192 === 0) return { w, h, i };
  }
  return { w: 128, h: 128, i: 8 };
}

const FREQS = [8000, 16000, 24000, 32000, 48000] as const;
const soundBits = (f: number, i: number, k: number, sec: number) => f * i * k * sec;

/** Звук, объём которого в Кбайт — целое число. minutes — длительность в целых минутах. */
function pickSound(rand: Rand, minutes: boolean, onlyMono = false): { f: number; i: number; k: number; t: number; sec: number } {
  for (let tries = 0; tries < 400; tries++) {
    const f = pick(rand, FREQS);
    const i = pick(rand, [8, 16] as const);
    const k = onlyMono ? 1 : pick(rand, [1, 2] as const);
    const t = minutes ? int(rand, 1, 5) : int(rand, 4, 120);
    const sec = minutes ? t * 60 : t;
    if (soundBits(f, i, k, sec) % 8192 === 0) return { f, i, k, t, sec };
  }
  return minutes ? { f: 8000, i: 8, k: 2, t: 2, sec: 120 } : { f: 8000, i: 16, k: 1, t: 64, sec: 64 };
}

