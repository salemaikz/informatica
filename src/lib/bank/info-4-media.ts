const SKILL = "info.media";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const same = (s: string): L => ({ ru: s, kk: s });

const SUP: Record<string, string> = { "0": "⁰", "1": "¹", "2": "²", "3": "³", "4": "⁴", "5": "⁵", "6": "⁶", "7": "⁷", "8": "⁸", "9": "⁹" };
const sup = (n: number) => String(n).replace(/\d/g, (d) => SUP[d]);

/** Число для показа: от 10 000 — с пробелами между тысячами (65 536). */
const num = (n: number) => (n >= 10000 ? String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ") : String(n));
/** Килобайты: целое или с десятичной запятой (дробные — только в неверных вариантах и утверждениях). */
const kbText = (x: number) => (Number.isInteger(x) ? num(x) : String(Math.round(x * 100) / 100).replace(".", ","));

const log2 = (n: number) => Math.round(Math.log2(n));

function ruPl(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
