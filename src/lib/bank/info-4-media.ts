const textKey = (t: Text) => (typeof t === "string" ? t : t.ru);

interface Opt {
  text: Text;
  why: L | null;
}

interface ChoiceInput {
  id: string;
  level: Level;
  prompt: L;
  hint: L;
  explanation: L;
  correct: Text;
  wrongs: Opt[];
}

/** Задание choice: правильный + 3 уникальных неверных (с разбором ошибки), перемешаны. */
function choice(rand: Rand, c: ChoiceInput): ChoiceStep {
  const seen = new Set<string>([textKey(c.correct)]);
  const wrongs: Opt[] = [];
  for (const w of shuffle(c.wrongs, rand)) {
    if (wrongs.length >= 3) break;
    const key = textKey(w.text);
    if (key && !seen.has(key)) {
      seen.add(key);
      wrongs.push(w);
    }
  }
  if (wrongs.length < 3) throw new Error(`info.media: мало неверных вариантов для ${c.id}`);
  const all: Opt[] = shuffle([{ text: c.correct, why: null } as Opt, ...wrongs], rand);
  return {
    id: c.id,
    type: "choice",
    skill: SKILL,
    level: c.level,
    prompt: c.prompt,
    hint: c.hint,
    options: all.map((o) => o.text),
    correct: all.findIndex((o) => o.why === null),
    whyWrong: all.map((o) => o.why),
    explanation: c.explanation,
  };
}

function input(id: string, level: Level, prompt: L, hint: L, explanation: L, answer: number, suffix?: string): InputStep {
  return { id, type: "input", skill: SKILL, level, prompt, hint, answers: [String(answer)], mode: "number", suffix, explanation };
}

