// ---------- Мини-вычислитель логических выражений ----------

type Bit = 0 | 1;
type Env = Record<string, Bit>;
type Expr = { t: "v"; n: string } | { t: "not"; a: Expr } | { t: "bin"; op: string; a: Expr; b: Expr };

const PREC: Record<string, number> = { "∧": 4, "∨": 3, "⊕": 3, "→": 2, "↔": 1 };

function parse(src: string): Expr {
  const tok = [...src.replace(/\s+/g, "")];
  let pos = 0;
  const prim = (): Expr => {
    const x = tok[pos++];
    if (x === "¬") return { t: "not", a: prim() };
    if (x === "(") {
      const e = expr(1);
      pos++; // закрывающая скобка
      return e;
    }
    return { t: "v", n: x };
  };
  const expr = (min: number): Expr => {
    let left = prim();
    while (tok[pos] in PREC && PREC[tok[pos]] >= min) {
      const op = tok[pos++];
      // импликация правоассоциативна, остальные — левоассоциативны
      const right = expr(op === "→" ? PREC[op] : PREC[op] + 1);
      left = { t: "bin", op, a: left, b: right };
    }
    return left;
  };
  return expr(1);
}

function ev(e: Expr, env: Env): Bit {
  if (e.t === "v") return env[e.n];
  if (e.t === "not") return ev(e.a, env) === 1 ? 0 : 1;
  const a = ev(e.a, env);
  const b = ev(e.b, env);
  switch (e.op) {
    case "∧":
      return a === 1 && b === 1 ? 1 : 0;
    case "∨":
      return a === 1 || b === 1 ? 1 : 0;
    case "⊕":
      return a !== b ? 1 : 0;
    case "→":
      return a === 1 && b === 0 ? 0 : 1;
    default:
      return a === b ? 1 : 0;
  }
}

function varsOf(src: string): string[] {
  return [...new Set(src.match(/[A-Z]/g) ?? [])].sort();
}

/** Все наборы значений (двоичный счёт, первая переменная — старший разряд). */
function allEnvs(names: string[]): Env[] {
  const out: Env[] = [];
  for (let i = 0; i < 2 ** names.length; i++) {
    const env: Env = {};
    names.forEach((n, k) => (env[n] = ((i >> (names.length - 1 - k)) & 1) as Bit));
    out.push(env);
  }
  return out;
}

const calc = (src: string, env: Env): Bit => ev(parse(src), env);
const setsWhere = (src: string, value: Bit): Env[] => allEnvs(varsOf(src)).filter((env) => calc(src, env) === value);
const countWhere = (src: string, value: Bit): number => setsWhere(src, value).length;
const envText = (env: Env): string =>
  Object.keys(env)
    .sort()
    .map((n) => `${n} = ${env[n]}`)
    .join(", ");
const envBits = (env: Env): string =>
  Object.keys(env)
    .sort()
    .map((n) => env[n])
    .join("");

/** Подвыражения в порядке выполнения: «¬A = 1; ¬A ∨ B = 1; ¬A ∨ B → C = 0». */
function show(e: Expr, parentPrec = 0): string {
  if (e.t === "v") return e.n;
  if (e.t === "not") return e.a.t === "bin" ? `¬(${show(e.a)})` : `¬${show(e.a)}`;
  const p = PREC[e.op];
  const text = `${show(e.a, p)} ${e.op} ${show(e.b, p + 1)}`;
  // ⊕ внутри другой операции всегда в скобках — как советуем ученику
  return p < parentPrec || (e.op === "⊕" && parentPrec > 0) ? `(${text})` : text;
}

function trace(src: string, env: Env): string {
  const out: string[] = [];
  const walk = (e: Expr): void => {
    if (e.t === "v") return;
    if (e.t === "not") walk(e.a);
    else {
      walk(e.a);
      walk(e.b);
    }
    const line = `${show(e)} = ${ev(e, env)}`;
    if (!out.includes(line)) out.push(line);
  };
  walk(parse(src));
  return out.join("; ");
}

