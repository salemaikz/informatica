/** Значение выражения при заданных значениях переменных — ввод числа 0 или 1. */
function valueQuestion(name: string, level: Level, src: string, env: Env, extra?: L): InputStep {
  const v = calc(src, env);
  return {
    id: `p:logic.impl:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt: l(`${envText(env)}. Найди значение выражения ${src}`, `${envText(env)} болғанда ${src} өрнегінің мәнін тап`),
    answers: [String(v)],
    mode: "number",
    hint: extra ?? HINT_VALUE,
    explanation: l(
      `Считаем по приоритету: ${trace(src, env)}. ${ruleOf(src).ru} Ответ: ${v}.`,
      `Басымдық бойынша есептейміз: ${trace(src, env)}. ${ruleOf(src).kk} Жауабы: ${v}.`,
    ),
  };
}

/** Сколько наборов делают выражение истинным/ложным. */
function countQuestion(name: string, level: Level, src: string, value: Bit, hint: L = HINT_COUNT): InputStep {
  const names = varsOf(src);
  const total = 2 ** names.length;
  const n = countWhere(src, value);
  const sets = setsWhere(src, value)
    .map(envBits)
    .join(", ");
  const word = value === 1 ? l("истинным", "ақиқат") : l("ложным", "жалған");
  const vars = names.join(", ");
  return {
    id: `p:logic.impl:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt: l(
      `Сколько наборов (${vars}) из ${total} делают выражение ${src} ${word.ru}?`,
      `${src} өрнегін ${word.kk} ететін (${vars}) ${total} жиынның нешеуі бар?`,
    ),
    answers: [String(n)],
    mode: "number",
    hint,
    explanation: l(
      `Перебор всех ${total} наборов показывает: значение ${value} у наборов ${sets}. Всего ${n}.`,
      `Барлық ${total} жиынды санап шығу көрсеткендей, ${value} мәні мына жиындарда: ${sets}. Барлығы ${n}.`,
    ),
  };
}

