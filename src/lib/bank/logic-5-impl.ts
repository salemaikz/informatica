/** Набор в виде «A = 1, B = 0, C = 1». */
const setOptions = (src: string, picks: string[]): { options: Text[]; env: Env[] } => {
  const names = varsOf(src);
  const env = picks.map((p) => {
    const e: Env = {};
    names.forEach((n, i) => (e[n] = p[i] === "1" ? 1 : 0));
    return e;
  });
  return { options: env.map(optText), env };
};

/** Задание «при каких значениях выражение ложно»: верный вариант находит код. */
function falseSetQuestion(name: string, src: string, picks: string[]): ChoiceStep {
  const { options, env } = setOptions(src, picks);
  const right = env.map((e) => calc(src, e));
  const correct = right.indexOf(0);
  if (right.filter((v) => v === 0).length !== 1) throw new Error(`${name}: должен быть ровно один ложный набор`);
  return {
    id: `p:logic.impl:${name}`,
    type: "choice",
    skill: SKILL,
    level: 3,
    prompt: l(`При каких значениях ложно выражение ${src}?`, `${src} өрнегі қандай мәндерде жалған?`),
    options,
    correct,
    hint: HINT_FALSE_IMP,
    explanation: l(
      `Проверяем варианты: ${env.map((e) => `${envText(e)}: ${trace(src, e)}`).join(". ")}. Ложное значение только у варианта «${envText(env[correct])}».`,
      `Нұсқаларды тексереміз: ${env.map((e) => `${envText(e)}: ${trace(src, e)}`).join(". ")}. Жалған мән тек «${envText(env[correct])}» нұсқасында.`,
    ),
    whyWrong: env.map((e, i) =>
      i === correct
        ? null
        : l(`При ${envText(e)} выражение равно 1: ${trace(src, e)}.`, `${envText(e)} болғанда өрнек 1-ге тең: ${trace(src, e)}.`),
    ),
  };
}

/** Задание «какие наборы делают выражение истинным»: верные индексы находит код. */
function trueSetsQuestion(name: string, src: string, picks: string[]): MultiStep {
  const { options, env } = setOptions(src, picks);
  const correct = env.map((e, i) => (calc(src, e) === 1 ? i : -1)).filter((i) => i >= 0);
  if (correct.length < 2 || correct.length > 3) throw new Error(`${name}: нужно 2–3 верных набора`);
  return {
    id: `p:logic.impl:${name}`,
    type: "multi",
    skill: SKILL,
    level: 3,
    prompt: l(
      `Какие наборы делают истинным выражение ${src}? Отметь все верные.`,
      `Қай жиындар ${src} өрнегін ақиқат етеді? Барлық дұрысын белгіле.`,
    ),
    options,
    correct,
    hint: l(
      "Выражение — конъюнкция: обе части в скобках должны быть равны 1. Проверь каждую часть отдельно на каждом наборе.",
      "Өрнек — конъюнкция: жақшадағы екі бөлік те 1-ге тең болуы керек. Әр бөлікті әр жиында бөлек тексер.",
    ),
    explanation: l(
      `Считаем для каждого набора: ${env.map((e) => `${envText(e)}: ${trace(src, e)}`).join(". ")}. Истинны ${correct.length} набора.`,
      `Әр жиын үшін есептейміз: ${env.map((e) => `${envText(e)}: ${trace(src, e)}`).join(". ")}. Ақиқат жиын саны: ${correct.length}.`,
    ),
    whyWrong: env.map((e, i) =>
      correct.includes(i) ? null : l(`При ${envText(e)} значение 0: ${trace(src, e)}.`, `${envText(e)} болғанда мән 0: ${trace(src, e)}.`),
    ),
  };
}

