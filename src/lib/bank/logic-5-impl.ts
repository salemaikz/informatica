const sh = (name: string, level: Level, prompt: L, answer: string, explanation: L, hint: L): ShortQuestion => ({
  id: `p:logic.impl:sh-${name}`,
  skill: SKILL,
  level,
  prompt,
  answer,
  mode: "number",
  explanation,
  hint,
});

/** Короткий вопрос «значение выражения»: ответ считает код. */
function shortValue(name: string, level: Level, src: string, env: Env): ShortQuestion {
  const v = calc(src, env);
  return sh(
    name,
    level,
    l(`${envText(env)}. Чему равно ${src}? (0 или 1)`, `${envText(env)} болғанда ${src} неге тең? (0 немесе 1)`),
    String(v),
    l(`${trace(src, env)}. ${ruleOf(src).ru} Ответ: ${v}.`, `${trace(src, env)}. ${ruleOf(src).kk} Жауабы: ${v}.`),
    HINT_VALUE,
  );
}

/** Короткий вопрос «сколько наборов»: ответ считает код. */
function shortCount(name: string, level: Level, src: string, value: Bit): ShortQuestion {
  const names = varsOf(src);
  const n = countWhere(src, value);
  const word = value === 1 ? l("истинным", "ақиқат") : l("ложным", "жалған");
  return sh(
    name,
    level,
    l(`Сколько из ${2 ** names.length} наборов (${names.join(", ")}) делают ${src} ${word.ru}?`, `${src} өрнегін ${word.kk} ететін (${names.join(", ")}) ${2 ** names.length} жиынның нешеуі бар?`),
    String(n),
    l(
      `Перебор всех наборов: значение ${value} получается в ${n} из ${2 ** names.length}.`,
      `Барлық жиындарды санап шығу: ${value} мәні ${n} жиында шығады.`,
    ),
    HINT_COUNT,
  );
}

