/** A: какое свойство задаёт то-то. */
function propFor(rand: Rand, level: Level, seed: number): QuestionStep {
  const target = pick(rand, PROPS);
  const others = shuffle(
    PROPS.filter((p) => p.prop !== target.prop),
    rand,
  );
  return buildChoice(
    rand,
    {
      id: `g:${SKILL}:prop:${target.prop}:${seed}`,
      level,
      hint: HINT_PROP,
      prompt: w(`Какое свойство CSS задаёт ${target.ru}?`, `CSS-тің қай қасиеті ${target.kk} белгілейді?`),
      explanation: w(
        `Свойство **${target.prop}** задаёт ${target.ru}. Свойство и значение записывают так: \`${target.prop}: значение;\`.`,
        `**${target.prop}** қасиеті ${target.kk} белгілейді. Қасиет пен мәнді былай жазады: \`${target.prop}: мән;\`.`,
      ),
    },
    target.prop,
    others.map((o) => ({ v: o.prop, why: w(`Это свойство задаёт ${o.ru}, а не ${target.ru}.`, `Бұл қасиет ${o.kk} белгілейді, ${target.kk} емес.`) })),
  );
}

