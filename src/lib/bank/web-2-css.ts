function selectorFor(rand: Rand, level: Level, seed: number): QuestionStep {
  const kind = pick(rand, ["class", "id"] as const);
  const name = pick(rand, ["note", "title", "price", "menu", "main", "big"] as const);
  const tag = pick(rand, ["p", "h1", "div"] as const);
  const attr = kind === "class" ? "class" : "id";
  const correct = kind === "class" ? `.${name}` : `#${name}`;
  const otherSymbol = kind === "class" ? `#${name}` : `.${name}`;
  return buildChoice(
    rand,
    {
      id: `g:${SKILL}:sel:${kind}${name}${tag}:${seed}`,
      level,
      hint: w(
        "Класс и id выбирают по-разному: у одного селектора в начале точка, у другого решётка. Вспомни, какой значок относится к атрибуту из тега.",
        "Класс пен id әртүрлі таңдалады: біреуінің басында нүкте, екіншісінде тор (#). Тегтегі атрибутқа қай белгі сәйкес келетінін еске түсір.",
      ),
      prompt: w("Каким селектором выбрать этот элемент по его атрибуту?", "Бұл элементті атрибуты бойынша қандай селектормен таңдауға болады?"),
      scene: codeHtml([`<${tag} ${attr}="${name}">Hello</${tag}>`]),
      explanation: w(
        kind === "class"
          ? `Атрибут \`class="${name}"\` выбирают селектором класса: точка и имя — \`.${name}\`. С решёткой (\`#${name}\`) выбирают элемент по id.`
          : `Атрибут \`id="${name}"\` выбирают селектором id: решётка и имя — \`#${name}\`. С точкой (\`.${name}\`) выбирают элементы по классу.`,
        kind === "class"
          ? `\`class="${name}"\` атрибутын класс селекторымен таңдайды: нүкте және атау — \`.${name}\`. Тормен (\`#${name}\`) элементті id бойынша таңдайды.`
          : `\`id="${name}"\` атрибутын id селекторымен таңдайды: тор (#) және атау — \`#${name}\`. Нүктемен (\`.${name}\`) элементтерді класс бойынша таңдайды.`,
      ),
    },
    correct,
    [
      {
        v: otherSymbol,
        why:
          kind === "class"
            ? w(`Решётка — это селектор id, а в теге записан атрибут class.`, `Тор (#) — id селекторы, ал тегте class атрибуты жазылған.`)
            : w(`Точка — это селектор класса, а в теге записан атрибут id.`, `Нүкте — класс селекторы, ал тегте id атрибуты жазылған.`),
      },
      { v: name, why: w(`Без значка это селектор тега: так выбирают элементы \`<${name}>\`, а не по атрибуту.`, `Белгісіз — бұл тег селекторы: \`<${name}>\` элементтерін таңдайды, атрибут бойынша емес.`) },
      { v: `@${name}`, why: w(`Такого селектора в CSS нет: нужна точка (класс) или решётка (id).`, `CSS-те мұндай селектор жоқ: нүкте (класс) немесе тор (id) қажет.`) },
    ],
  );
}

