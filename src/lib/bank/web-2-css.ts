const CH_VALUES = [0, 255, 128, 64, 192, 165, 100, 200, 50, 30, 250, 175, 20, 220, 32, 96];
const hex2 = (v: number) => v.toString(16).toUpperCase().padStart(2, "0");
const HEX_DIGIT = (v: number) => "0123456789ABCDEF"[v];

/** Разложение числа на две 16-ричные цифры для объяснения: 165 = 10 · 16 + 5 = A5. */
function hexExplain(v: number): string {
  if (v === 0) return "0 = 00";
  if (v === 255) return "255 = FF";
  const hi = Math.floor(v / 16);
  const lo = v % 16;
  return `${v} = ${hi} · 16 + ${lo} = ${HEX_DIGIT(hi)}${HEX_DIGIT(lo)}`;
}

function pickRgb(rand: Rand): [number, number, number] {
  for (let i = 0; i < 50; i++) {
    const rgb: [number, number, number] = [pick(rand, CH_VALUES), pick(rand, CH_VALUES), pick(rand, CH_VALUES)];
    // Нужны хотя бы два разных канала, иначе перестановка каналов не даёт неверных вариантов.
    if (new Set(rgb).size >= 2) return rgb;
  }
  return [255, 165, 0];
}

const toHexColor = (rgb: number[]) => `#${rgb.map(hex2).join("")}`;
const toRgbText = (rgb: number[]) => `rgb(${rgb.join(", ")})`;

const HINT_HEX: L = w(
  "Переводи каждое число отдельно в 16-ричную систему, по две цифры: R, затем G, затем B. Для числа делением на 16 получаются две цифры (10 = A, 11 = B, … 15 = F).",
  "Әр санды жеке-жеке он алтылық жүйеге аудар, екі цифрдан: R, содан кейін G, содан кейін B. 16-ға бөлгенде екі цифр шығады (10 = A, 11 = B, … 15 = F).",
);

/** B: rgb(R, G, B) → #RRGGBB. */
function rgbToHex(rand: Rand, level: Level, seed: number): QuestionStep {
  const rgb = pickRgb(rand);
  const [r, g, b] = rgb;
  const hex = toHexColor(rgb);
  const head: Head = {
    id: `g:${SKILL}:hex:${hex.slice(1)}:${seed}`,
    level,
    hint: HINT_HEX,
    prompt: w(
      `Цвет задан как ${toRgbText(rgb)}. Как записать его в виде #RRGGBB?`,
      `Түс ${toRgbText(rgb)} түрінде берілген. Оны #RRGGBB түрінде қалай жазуға болады?`,
    ),
    explanation: w(
      `Каждое число переводим в 16-ричную систему по две цифры: ${hexExplain(r)}; ${hexExplain(g)}; ${hexExplain(b)}. Склеиваем: **${hex}**.`,
      `Әр санды он алтылық жүйеге екі цифрмен аударамыз: ${hexExplain(r)}; ${hexExplain(g)}; ${hexExplain(b)}. Жалғаймыз: **${hex}**.`,
    ),
  };
  if (rand() < 0.3) return buildInput(head, [hex, hex.slice(1)], "text");
  const swap = (a: number, c: number) => {
    const t = [...rgb];
    [t[a], t[c]] = [t[c], t[a]];
    return t;
  };
  const rev = (v: number) => hex2(v).split("").reverse().join("");
  const ci = int(rand, 0, 2);
  const reversedPair = `#${rgb.map((v, i) => (i === ci ? rev(v) : hex2(v))).join("")}`;
  const nearMiss = `#${rgb.map((v, i) => (i === ci ? hex2(v === 255 ? 254 : v + 1) : hex2(v))).join("")}`;
  const wrongs: Wrong[] = [
    { v: toHexColor(swap(0, 2)), why: w("Каналы переставлены (получилось B, G, R): порядок всегда R, G, B.", "Арналар ауыстырылып кеткен (B, G, R шықты): реті әрқашан R, G, B.") },
    { v: toHexColor(swap(0, 1)), why: w("Красный и зелёный каналы поменялись местами: порядок всегда R, G, B.", "Қызыл және жасыл арналар орындарымен ауысқан: реті әрқашан R, G, B.") },
    { v: toHexColor(swap(1, 2)), why: w("Зелёный и синий каналы поменялись местами: порядок всегда R, G, B.", "Жасыл және көк арналар орындарымен ауысқан: реті әрқашан R, G, B.") },
    { v: reversedPair, why: w("В одной паре цифры записаны наоборот: старшая цифра идёт первой.", "Бір жұпта цифрлар кері жазылған: үлкен разряд цифры бірінші тұрады.") },
    { v: nearMiss, why: w("Один из каналов переведён с ошибкой на единицу: проверь деление на 16 и остаток.", "Арналардың бірі бір бірлікке қате аударылған: 16-ға бөлуді және қалдықты тексер.") },
  ];
  return buildChoice(rand, head, hex, wrongs);
}

/** C: #RRGGBB → rgb(R, G, B). */
function hexToRgb(rand: Rand, level: Level, seed: number): QuestionStep {
  const rgb = pickRgb(rand);
  const hex = toHexColor(rgb);
  const head: Head = {
    id: `g:${SKILL}:rgb:${hex.slice(1)}:${seed}`,
    level,
    hint: w(
      "Раздели код на три пары цифр: RR, GG, BB. Каждую пару переведи из 16-ричной системы: первая цифра · 16 + вторая.",
      "Кодты үш жұп цифрға бөл: RR, GG, BB. Әр жұпты он алтылық жүйеден аудар: бірінші цифр · 16 + екінші.",
    ),
    prompt: w(`Цвет задан как ${hex}. Как записать его в виде rgb(R, G, B)?`, `Түс ${hex} түрінде берілген. Оны rgb(R, G, B) түрінде қалай жазуға болады?`),
    explanation: w(
      `Делим на пары: ${hex.slice(1, 3)} | ${hex.slice(3, 5)} | ${hex.slice(5, 7)}. Переводим каждую: ${hexExplain(rgb[0])}; ${hexExplain(rgb[1])}; ${hexExplain(rgb[2])}. Ответ: **${toRgbText(rgb)}**.`,
      `Жұптарға бөлеміз: ${hex.slice(1, 3)} | ${hex.slice(3, 5)} | ${hex.slice(5, 7)}. Әрқайсысын аударамыз: ${hexExplain(rgb[0])}; ${hexExplain(rgb[1])}; ${hexExplain(rgb[2])}. Жауабы: **${toRgbText(rgb)}**.`,
    ),
  };
  const ci = int(rand, 0, 2);
  const asDecimal = rgb.map((v, i) => {
    const pair = hex.slice(1 + i * 2, 3 + i * 2);
    const d = /^\d+$/.test(pair) ? parseInt(pair, 10) : v;
    return i === ci ? d : v;
  });
  const off = rgb.map((v, i) => (i === ci ? (v >= 16 ? v - 16 : v + 16) : v));
  const wrongs: Wrong[] = [
    { v: toRgbText([rgb[2], rgb[1], rgb[0]]), why: w("Порядок каналов перевёрнут (B, G, R): в коде сначала красный, потом зелёный, потом синий.", "Арналар реті кері (B, G, R): кодта алдымен қызыл, содан кейін жасыл, содан кейін көк тұрады.") },
    { v: toRgbText([rgb[1], rgb[0], rgb[2]]), why: w("Красный и зелёный каналы переставлены: в коде первая пара — R, вторая — G.", "Қызыл және жасыл арналар ауыстырылған: кодта бірінші жұп — R, екінші — G.") },
    { v: toRgbText(asDecimal), why: w("Пара прочитана как десятичное число. Это 16-ричная запись: первую цифру нужно умножить на 16.", "Жұп ондық сан ретінде оқылған. Бұл он алтылық жазба: бірінші цифрды 16-ға көбейту керек.") },
    { v: toRgbText(off), why: w("Один канал переведён с ошибкой: проверь, что первая цифра умножена на 16, а не на 10.", "Бір арна қате аударылған: бірінші цифр 10-ға емес, 16-ға көбейтілгенін тексер.") },
    { v: toRgbText([rgb[0], rgb[2], rgb[1]]), why: w("Зелёный и синий каналы переставлены: в коде третья пара — B.", "Жасыл және көк арналар ауыстырылған: кодта үшінші жұп — B.") },
  ];
  return buildChoice(rand, head, toRgbText(rgb), wrongs);
}

// ---------- Блочная модель ----------

const CSS_BOX = (wd: number, p: number, b: number, m: number | null): string[] => [
  "div {",
  `    width: ${wd}px;`,
  `    padding: ${p}px;`,
  `    border: ${b}px solid red;`,
  ...(m === null ? [] : [`    margin: ${m}px;`]),
  "}",
];

/** B/C: ширина блока по горизонтали (B — без margin, C — вместе с margin). */
function boxWidth(rand: Rand, level: Level, seed: number): QuestionStep {
  const withMargin = level === 3;
  const wd = pick(rand, [100, 120, 150, 200, 240, 300]);
  const p = pick(rand, [5, 8, 10, 12, 15, 20]);
  const b = pick(rand, [1, 2, 3, 4, 5]);
  const m = withMargin ? pick(rand, [5, 10, 15, 20, 25]) : 0;
  const total = wd + 2 * p + 2 * b + 2 * m;
  const head: Head = {
    id: `g:${SKILL}:box:${wd}x${p}x${b}x${withMargin ? m : 0}:${seed}`,
    level,
    hint: w(
      "Padding, border и margin есть и слева, и справа. Запиши, сколько каждый слой даёт по горизонтали, и сложи.",
      "Padding, border және margin сол жақта да, оң жақта да бар. Әр қабат көлденеңінен қанша беретінін жазып, қос.",
    ),
    prompt: withMargin
      ? w(
          "Сколько пикселей по горизонтали занимает блок вместе с внешними отступами? (width — ширина содержимого)",
          "Блок сыртқы шегіністерімен бірге көлденеңінен неше пиксель орын алады? (width — мазмұнның ені)",
        )
      : w(
          "Какова полная ширина блока в пикселях — вместе с внутренними отступами и рамкой, без внешних? (width — ширина содержимого)",
          "Блоктың толық ені неше пиксель — ішкі шегіністермен және жиекпен бірге, сыртқыларсыз? (width — мазмұнның ені)",
        ),
    scene: codeCss(CSS_BOX(wd, p, b, withMargin ? m : null)),
    explanation: withMargin
      ? w(
          `Складываем слои: ${wd} (содержимое) + 2 · ${p} (padding) + 2 · ${b} (border) + 2 · ${m} (margin) = ${wd} + ${2 * p} + ${2 * b} + ${2 * m} = ${total}.`,
          `Қабаттарды қосамыз: ${wd} (мазмұн) + 2 · ${p} (padding) + 2 · ${b} (border) + 2 · ${m} (margin) = ${wd} + ${2 * p} + ${2 * b} + ${2 * m} = ${total}.`,
        )
      : w(
          `Складываем слои: ${wd} (содержимое) + 2 · ${p} (padding) + 2 · ${b} (border) = ${wd} + ${2 * p} + ${2 * b} = ${total}.`,
          `Қабаттарды қосамыз: ${wd} (мазмұн) + 2 · ${p} (padding) + 2 · ${b} (border) = ${wd} + ${2 * p} + ${2 * b} = ${total}.`,
        ),
  };
  if (rand() < 0.4) return buildInput(head, [String(total)], "number");
  const wrongs: Wrong[] = [
    { v: String(wd + p + b + m), why: w("Учтена только одна сторона каждого слоя, а отступы и рамка есть и слева, и справа.", "Әр қабаттың тек бір жағы есепке алынған, ал шегіністер мен жиек сол жақта да, оң жақта да бар.") },
    { v: String(wd), why: w("Это только ширина содержимого: padding, border (и margin) добавляются к ней.", "Бұл тек мазмұнның ені: оған padding, border (және margin) қосылады.") },
    { v: String(wd + 2 * p + 2 * m), why: w("Забыта рамка: border тоже занимает место слева и справа.", "Жиек ұмытылған: border де сол жақта және оң жақта орын алады.") },
    { v: String(wd + 2 * b + 2 * m), why: w("Забыт внутренний отступ padding: он тоже добавляется с двух сторон.", "Ішкі шегініс padding ұмытылған: ол да екі жағынан қосылады.") },
    ...(withMargin
      ? [{ v: String(wd + 2 * p + 2 * b), why: w("Это ширина без внешних отступов: в условии нужны ещё два margin.", "Бұл сыртқы шегіністерсіз ені: шартта тағы екі margin қажет.") }]
      : []),
    { v: String(total + 2 * p), why: w("Padding посчитан дважды: каждый слой входит в сумму по два раза (слева и справа), не больше.", "Padding екі рет есептелген: әр қабат қосындыға екі рет (сол және оң жақтан) кіреді, артық емес.") },
    { v: String(total + p + b), why: w("Лишние слои добавлены: считаются только padding, border (и margin) с двух сторон и ширина содержимого.", "Артық қабаттар қосылған: тек екі жақтағы padding, border (және margin) және мазмұн ені есептеледі.") },
  ];
  return buildChoice(rand, head, String(total), wrongs);
}

// ---------- Приоритет селекторов ----------

interface Rule {
  sel: string;
  /** Ключ цвета из PALETTE. */
  color: string;
  kind: "t" | "c" | "i" | "n";
  matches: boolean;
}

const PALETTE = [
  { key: "red", ru: "красный", kk: "қызыл" },
  { key: "blue", ru: "синий", kk: "көк" },
  { key: "green", ru: "зелёный", kk: "жасыл" },
  { key: "orange", ru: "оранжевый", kk: "қызғылт сары" },
];

const strength = (r: Rule) => (r.kind === "i" ? 3 : r.kind === "c" ? 2 : 1);

/** Побеждает самое сильное подходящее правило; при равенстве — записанное ниже. */
export function winnerRule(rules: Rule[]): Rule {
  let best: Rule | undefined;
  for (const r of rules) {
    if (!r.matches) continue;
    if (!best || strength(r) >= strength(best)) best = r;
  }
  if (!best) throw new Error("нет подходящего правила");
  return best;
}

function priority(rand: Rand, level: Level, seed: number): QuestionStep {
  const cls = pick(rand, ["note", "big", "menu"] as const);
  const idName = pick(rand, ["main", "title", "top"] as const);
  const colors = shuffle(PALETTE, rand);
  let ci = 0;
  const mk = (kind: Rule["kind"]): Rule => {
    const sel = kind === "t" ? "p" : kind === "c" ? `.${cls}` : kind === "i" ? `#${idName}` : pick(rand, ["h1", ".other", "#extra"]);
    return { sel, kind, matches: kind !== "n", color: colors[ci++ % colors.length].key };
  };
  let kinds: Rule["kind"][];
  if (level === 2) {
    kinds = pick(rand, [["t", "c"], ["c", "i"], ["t", "i"]] as Rule["kind"][][]);
    if (rand() < 0.25) kinds = [...kinds, "n"];
  } else {
    kinds = pick(rand, [
      ["t", "c", "i", "n"],
      ["t", "t", "c"],
      ["c", "c", "t"],
      ["i", "c", "c"],
      ["t", "c", "i"],
    ] as Rule["kind"][][]);
  }
  const rules = shuffle(kinds, rand).map(mk);
  const win = winnerRule(rules);
  const hasClass = rules.some((r) => r.kind === "c");
  const hasId = rules.some((r) => r.kind === "i");
  const element = `<p${hasClass ? ` class="${cls}"` : ""}${hasId ? ` id="${idName}"` : ""}>Hello</p>`;
  const css = rules.flatMap((r) => [`${r.sel} {`, `    color: ${r.color};`, "}"]).join("\n");
  const colorL = (key: string): L => {
    const c = PALETTE.find((x) => x.key === key)!;
    return w(c.ru, c.kk);
  };
  const wrongs: Wrong[] = PALETTE.filter((c) => c.key !== win.color).map((c) => {
    const rule = rules.find((r) => r.color === c.key);
    let why: L;
    if (!rule) why = w("Правила с таким цветом в коде нет.", "Кодта мұндай түсті ереже жоқ.");
    else if (!rule.matches) why = w(`Правило ${rule.sel} к этому элементу не относится.`, `${rule.sel} ережесі бұл элементке қатысты емес.`);
    else if (strength(rule) < strength(win)) why = w(`Правило ${rule.sel} подходит, но его селектор слабее: id > класс > тег.`, `${rule.sel} ережесі сәйкес келеді, бірақ оның селекторы әлсіз: id > класс > тег.`);
    else why = w(`Правила ${rule.sel} и ${win.sel} одинаковы по приоритету, а побеждает то, что записано ниже.`, `${rule.sel} және ${win.sel} ережелерінің басымдығы бірдей, ал төменірек жазылғаны жеңеді.`);
    return { v: colorL(c.key), why };
  });
  const winL = colorL(win.color);
  const sameStrength = rules.filter((r) => r.matches && strength(r) === strength(win)).length > 1;
  const sig = rules.map((r) => r.kind + r.color[0]).join("");
  return buildChoice(
    rand,
    {
      id: `g:${SKILL}:prio:${sig}:${seed}`,
      level,
      hint: w(
        "Сначала вычеркни правила, которые к этому элементу не относятся. Среди остальных сравни селекторы: id > класс > тег.",
        "Алдымен бұл элементке қатысы жоқ ережелерді сызып таста. Қалғандарының селекторларын салыстыр: id > класс > тег.",
      ),
      prompt: w("Какого цвета будет текст абзаца?", "Абзац мәтіні қандай түсті болады?"),
      scene: codeHtml(["<style>", ...rules.map((r) => `    ${r.sel} { color: ${r.color}; }`), "</style>", element]),
      reveal: { kind: "web", html: element, css },
      explanation: w(
        sameStrength
          ? `Подходящих правил несколько, самые сильные из них одинаковы по приоритету (${win.sel}), поэтому побеждает записанное ниже. Цвет: **${win.color}**.`
          : `Из подходящих правил самый приоритетный селектор — ${win.sel} (id > класс > тег), порядок записи не важен. Цвет: **${win.color}**.`,
        sameStrength
          ? `Сәйкес келетін ережелер бірнеше, олардың ең күштілерінің басымдығы бірдей (${win.sel}), сондықтан төменірек жазылғаны жеңеді. Түсі: **${win.color}**.`
          : `Сәйкес келетін ережелердің ішінде селекторы ең басымы — ${win.sel} (id > класс > тег), жазылу реті маңызды емес. Түсі: **${win.color}**.`,
      ),
    },
    winL,
    wrongs,
  );
}

// ---------- Порядок значений margin ----------

type Side = 0 | 1 | 2 | 3; // сверху, справа, снизу, слева

/** Раскрывает margin из 1–4 значений в [верх, право, низ, лево] (как в CSS). */
export function expandBox(vals: number[]): [number, number, number, number] {
  if (vals.length === 1) return [vals[0], vals[0], vals[0], vals[0]];
  if (vals.length === 2) return [vals[0], vals[1], vals[0], vals[1]];
  if (vals.length === 3) return [vals[0], vals[1], vals[2], vals[1]];
  return [vals[0], vals[1], vals[2], vals[3]];
}

const SIDE_ADJ: { ru: string; kk: string; from: string; fromKk: string }[] = [
  { ru: "верхний", kk: "жоғарғы", from: "сверху", fromKk: "жоғарыдан" },
  { ru: "правый", kk: "оң жақ", from: "справа", fromKk: "оңнан" },
  { ru: "нижний", kk: "төменгі", from: "снизу", fromKk: "төменнен" },
  { ru: "левый", kk: "сол жақ", from: "слева", fromKk: "солдан" },
];

function marginSide(rand: Rand, level: Level, seed: number): QuestionStep {
  const n = level === 2 ? 2 : pick(rand, [3, 4, 4]);
  const pool = shuffle([5, 10, 15, 20, 25, 30, 40], rand);
  const vals = pool.slice(0, n);
  const sides = expandBox(vals);
  const ask = pick(rand, (n === 2 ? [0, 1] : n === 3 ? [0, 2, 3] : [0, 1, 2, 3]) as Side[]);
  const answer = sides[ask];
  const adj = SIDE_ADJ[ask];
  const extra = [vals.reduce((s, v) => s + v, 0), pool[n], pool[n + 1]].filter((v) => !vals.includes(v));
  const candidates = [...vals.filter((v) => v !== answer), ...extra];
  const sideOf = (v: number): number => sides.findIndex((s, i) => s === v && i !== ask);
  const wrongs: Wrong[] = candidates.map((v) => {
    const i = sideOf(v);
    if (i >= 0) {
      const s = SIDE_ADJ[i];
      return {
        v: `${v}px`,
        why: w(
          `Это значение для стороны «${s.from}»: значения идут по часовой стрелке — сверху, справа, снизу, слева.`,
          `Бұл «${s.fromKk}» жағының мәні: мәндер сағат тілі бойымен — жоғарыдан, оңнан, төменнен, солдан.`,
        ),
      };
    }
    return {
      v: `${v}px`,
      why: w("Значения разных сторон не складывают, и такого числа в записи нет.", "Әртүрлі жақтардың мәндері қосылмайды, жазбада мұндай сан жоқ."),
    };
  });
  const lineCss = `    margin: ${vals.map((v) => `${v}px`).join(" ")};`;
  return buildChoice(
    rand,
    {
      id: `g:${SKILL}:margin:${vals.join("x")}a${ask}:${seed}`,
      level,
      hint: w(
        "Значения идут по часовой стрелке, начиная с верха: сверху, справа, снизу, слева. Если значений меньше четырёх, недостающие берутся у противоположной стороны.",
        "Мәндер сағат тілі бойымен, жоғарыдан бастап жүреді: жоғарыдан, оңнан, төменнен, солдан. Мән төрттен аз болса, жетпейтіндері қарама-қарсы жақтан алынады.",
      ),
      prompt: w(`Чему равен ${adj.ru} внешний отступ блока?`, `Блоктың ${adj.kk} сыртқы шегінісі неге тең?`),
      scene: codeCss(["div {", lineCss, "}"]),
      explanation: w(
        `Значения margin идут сверху, справа, снизу, слева. ${n === 2 ? "Два значения: первое — сверху и снизу, второе — справа и слева." : n === 3 ? "Три значения: сверху, справа и слева, снизу." : "Четыре значения — по часовой стрелке."} Для стороны «${adj.from}» получается ${answer}px.`,
        `margin мәндері жоғарыдан, оңнан, төменнен, солдан жүреді. ${n === 2 ? "Екі мән: біріншісі — жоғарыдан және төменнен, екіншісі — оңнан және солдан." : n === 3 ? "Үш мән: жоғарыдан, оңнан және солдан, төменнен." : "Төрт мән — сағат тілі бойымен."} «${adj.fromKk}» жағы үшін ${answer}px шығады.`,
      ),
    },
    `${answer}px`,
    wrongs,
  );
}

