/** Задание-choice: верный ответ первым (poolBank перемешает варианты вместе с whyWrong). */
function choice(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  correct: Text,
  wrong: [Text, L][],
  hint: L,
  explanation: L,
): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrong.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrong.map((w) => w[1])],
    hint,
    explanation,
  };
}

/** Задание-input с числовым ответом. */
function input(name: string, level: Level, scene: Scene, answer: string, hint: L, explanation: L, prompt: L = OUT_NUM): InputStep {
  return { id: `p:${SKILL}:${name}`, type: "input", skill: SKILL, level, prompt, scene, answers: [answer], mode: "number", hint, explanation };
}

