const SUBJECTS: L[] = [l("Информатика", "Информатика"), l("Математика", "Математика"), l("Физика", "Физика"), l("История", "Тарих")];

const compositeGen: Gen = (rand, level, seed) => {
  type Row = { a: number; b: L; c: string };
  const dupOf = (xs: string[]) => new Set(xs).size < xs.length;
  let rows: Row[] | undefined;
  for (let tries = 0; tries < 300 && !rows; tries++) {
    const nA = int(rand, 2, 3);
    const nB = int(rand, 2, 3);
    const subj = shuffle(SUBJECTS, rand).slice(0, nB);
    const combos: { a: number; b: L }[] = [];
    for (let a = 1; a <= nA; a++) for (const b of subj) combos.push({ a, b });
    const n = int(rand, 4, combos.length);
    const chosen = shuffle(combos, rand)
      .slice(0, n)
      .sort((x, y) => x.a - y.a || subj.indexOf(x.b) - subj.indexOf(y.b));
    const cand: Row[] = chosen.map((x) => ({ ...x, c: pick(rand, ["3", "4", "5"]) }));
    const A = cand.map((r) => String(r.a));
    const B = cand.map((r) => r.b.ru);
    const C = cand.map((r) => r.c);
    const AC = cand.map((r) => `${r.a}|${r.c}`);
    const BC = cand.map((r) => `${r.b.ru}|${r.c}`);
    if (dupOf(A) && dupOf(B) && dupOf(C) && dupOf(AC) && dupOf(BC)) rows = cand;
  }
  rows ??= [
    { a: 1, b: SUBJECTS[0], c: "5" },
    { a: 1, b: SUBJECTS[1], c: "5" },
    { a: 2, b: SUBJECTS[0], c: "4" },
    { a: 2, b: SUBJECTS[1], c: "5" },
  ];
  const nameA = l("№ ученика", "Оқушы №");
  const nameB = l("Предмет", "Пән");
  const nameC = l("Оценка", "Баға");
  const cells: Text[][] = rows.map((r) => [String(r.a), r.b, r.c]);
  const scene: Scene = {
    kind: "table",
    columns: [nameA, nameB, nameC],
    rows: cells,
    caption: l("Таблица «Оценки»", "«Бағалар» кестесі"),
  };
  const dupPair = (i: number, j: number, lang: "ru" | "kk"): string => {
    const seen = new Set<string>();
    for (const r of cells) {
      const k = `${lv(r[i], "ru")}|${lv(r[j], "ru")}`;
      if (seen.has(k)) return `(${lv(r[i], lang)}, ${lv(r[j], lang)})`;
      seen.add(k);
    }
    return "";
  };
  const dupSingle = (i: number, lang: "ru" | "kk"): string => {
    const seen = new Set<string>();
    for (const r of cells) {
      if (seen.has(lv(r[i], "ru"))) return lv(r[i], lang);
      seen.add(lv(r[i], "ru"));
    }
    return "";
  };
  const sig = rows.map((r) => `${r.a}${r.b.ru[0]}${r.c}`).join("");
  const head = {
    id: `g:${SKILL}:comp:${sig}:${seed}`,
    level,
    scene,
    hint: l(
      "Одно поле повторяется. Проверь пары: у какой пары полей все сочетания значений разные?",
      "Бір өріс қайталанады. Жұптарды тексер: қай өрістер жұбының барлық мән үйлесімдері әртүрлі?",
    ),
    prompt: l("В таблице нет поля без повторов. Какая пара полей может быть составным ключом?", "Кестеде қайталанбайтын өріс жоқ. Қай өрістер жұбы құрама кілт бола алады?"),
    explanation: l(
      `Для «${nameA.ru} + ${nameB.ru}» все пары значений разные. У других вариантов есть повтор: ${nameA.ru} + ${nameC.ru} — ${dupPair(0, 2, "ru")}, ${nameB.ru} + ${nameC.ru} — ${dupPair(1, 2, "ru")}.`,
      `«${nameA.kk} + ${nameB.kk}» үшін мәндердің барлық жұбы әртүрлі. Басқа нұсқаларда қайталану бар: ${nameA.kk} + ${nameC.kk} — ${dupPair(0, 2, "kk")}, ${nameB.kk} + ${nameC.kk} — ${dupPair(1, 2, "kk")}.`,
    ),
  };
  return buildChoice(rand, head, l(`${nameA.ru} + ${nameB.ru}`, `${nameA.kk} + ${nameB.kk}`), [
    {
      v: l(`${nameA.ru} + ${nameC.ru}`, `${nameA.kk} + ${nameC.kk}`),
      why: l(`Пара ${dupPair(0, 2, "ru")} встречается больше одного раза.`, `${dupPair(0, 2, "kk")} жұбы бірнеше рет кездеседі.`),
    },
    {
      v: l(`${nameB.ru} + ${nameC.ru}`, `${nameB.kk} + ${nameC.kk}`),
      why: l(`Пара ${dupPair(1, 2, "ru")} встречается больше одного раза.`, `${dupPair(1, 2, "kk")} жұбы бірнеше рет кездеседі.`),
    },
    {
      v: l(`Одно поле «${nameA.ru}»`, `Жалғыз «${nameA.kk}» өрісі`),
      why: l(`Это одно поле, а не пара, и его значение ${dupSingle(0, "ru")} повторяется.`, `Бұл жұп емес, бір өріс, және оның ${dupSingle(0, "kk")} мәні қайталанады.`),
    },
  ]);
};

/** C: значения после добавления записей и изменения числа полей. */
const growGen: Gen = (rand, level, seed) => {
  const R = int(rand, 6, 30);
  const F = int(rand, 3, 7);
  const addR = int(rand, 2, 9);
  const variant = int(rand, 0, 1);
  const addF = int(rand, 1, 3);
  const newR = R + addR;
  const newF = variant === 0 ? F + addF : F - 1;
  const ans = newR * newF;
  return buildInput(
    {
      id: `g:${SKILL}:grow:${variant}${R}-${F}:${seed}`,
      level,
      hint: l(
        "Сначала найди, сколько станет записей и сколько полей, потом перемножь.",
        "Алдымен жазбалар мен өрістер қанша болатынын тап, содан соң көбейт.",
      ),
      prompt:
        variant === 0
          ? l(
              `В таблице ${recordsRu(R)} и ${fieldsRu(F)}. Добавили ${recordsRu(addR)} и ${fieldsRu(addF)}. Сколько значений хранится в таблице теперь?`,
              `Кестеде ${R} жазба және ${F} өріс бар. ${addR} жазба және ${addF} өріс қосылды. Енді кестеде неше мән сақталған?`,
            )
          : l(
              `В таблице ${recordsRu(R)} и ${fieldsRu(F)}. Добавили ${recordsRu(addR)} и удалили одно поле. Сколько значений хранится в таблице теперь?`,
              `Кестеде ${R} жазба және ${F} өріс бар. ${addR} жазба қосылып, бір өріс жойылды. Енді кестеде неше мән сақталған?`,
            ),
      explanation: l(
        `Записей стало ${R} + ${addR} = ${newR}, полей ${variant === 0 ? `${F} + ${addF}` : `${F} − 1`} = ${newF}. Значений ${newR} · ${newF} = ${ans}.`,
        `Жазбалар ${R} + ${addR} = ${newR} болды, өрістер ${variant === 0 ? `${F} + ${addF}` : `${F} − 1`} = ${newF}. Мәндер ${newR} · ${newF} = ${ans}.`,
      ),
    },
    String(ans),
  );
};

