interface Opt {
  v: Text;
  why: L | null;
}

/** Задание с выбором: верный вариант + до трёх разных неверных (с разбором ошибки). */
function buildChoice(
  rand: Rand,
  head: { id: string; level: Level; hint: L; prompt: L; explanation: L; scene?: Scene },
  correct: Text,
  wrongs: { v: Text; why: L }[],
): ChoiceStep {
  const seen = new Set<string>([JSON.stringify(correct)]);
  const picked: Opt[] = [];
  for (const w of wrongs) {
    if (picked.length >= 3) break;
    const k = JSON.stringify(w.v);
    if (!seen.has(k)) {
      seen.add(k);
      picked.push(w);
    }
  }
  const all = shuffle<Opt>([{ v: correct, why: null }, ...picked], rand);
  return {
    ...head,
    type: "choice",
    skill: SKILL,
    options: all.map((a) => a.v),
    correct: all.findIndex((a) => a.why === null),
    whyWrong: all.map((a) => a.why),
  };
}

function buildInput(head: { id: string; level: Level; hint: L; prompt: L; explanation: L; scene?: Scene }, answer: string): InputStep {
  return { ...head, type: "input", skill: SKILL, answers: [answer], mode: "number" };
}

