interface Table {
  tpl: Tpl;
  fields: { name: L; type: DType }[];
  rows: Text[][];
}

/** Таблица: ключ уникален, в остальных полях гарантированно есть повторы. */
function makeTable(rand: Rand, tpl: Tpl, nFields: number, nRows: number): Table {
  const others = shuffle(tpl.fields, rand).slice(0, nFields - 1);
  const keys = new Set<string>();
  while (keys.size < nRows) keys.add(tpl.key.make(rand));
  const keyVals = [...keys];
  const cols: Text[][] = others.map((f) => {
    const vals: Text[] = Array.from({ length: nRows }, () => pick(rand, f.pool));
    if (new Set(vals.map(vkey)).size === nRows) vals[nRows - 1] = vals[0];
    return vals;
  });
  const rows = Array.from({ length: nRows }, (_, i) => [keyVals[i], ...cols.map((c) => c[i])] as Text[]);
  return { tpl, fields: [{ name: tpl.key.name, type: "text" as DType }, ...others.map((f) => ({ name: f.name, type: f.type }))], rows };
}

const columnOf = (t: Table, c: number): Text[] => t.rows.map((r) => r[c]);
const isUnique = (t: Table, c: number): boolean => new Set(columnOf(t, c).map(vkey)).size === t.rows.length;
/** Первое повторяющееся значение столбца (или undefined). */
function firstDup(t: Table, c: number): Text | undefined {
  const seen = new Set<string>();
  for (const v of columnOf(t, c)) {
    if (seen.has(vkey(v))) return v;
    seen.add(vkey(v));
  }
  return undefined;
}

function sceneOf(t: Table): Scene {
  return {
    kind: "table",
    columns: t.fields.map((f) => f.name),
    rows: t.rows,
    caption: l(`Таблица «${t.tpl.title.ru}»`, `«${t.tpl.title.kk}» кестесі`),
  };
}

