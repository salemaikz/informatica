/** choice: верный вариант первым, неверные с разбором. Порядок перемешает poolBank. */
function choice(id: string, level: Level, prompt: L, scene: Scene | undefined, right: Text, wrongs: Wrong[], hint: L, explanation: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [right, ...wrongs.map((w) => w.v)],
    correct: 0,
    whyWrong: [null, ...wrongs.map((w) => T(w.ru, w.kk))],
    hint,
    explanation,
  };
}

function input(id: string, level: Level, prompt: L, scene: Scene | undefined, answer: string, hint: L, explanation: L): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, answers: [answer], mode: "number", hint, explanation };
}

/** multi: верные — по индексам; whyWrong — для неверных (в порядке options, у верных null). */
function multi(id: string, level: Level, prompt: L, scene: Scene | undefined, options: Text[], correct: number[], why: ([string, string] | null)[], hint: L, explanation: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    scene,
    options,
    correct,
    whyWrong: why.map((w) => (w ? T(w[0], w[1]) : null)),
    hint,
    explanation,
  };
}

