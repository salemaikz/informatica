const SKILL = "py.patterns";

const code = (lines: string[]): Scene => ({ kind: "code", lang: "python", lines });
const PRINT_Q: L = { ru: "Что выведет программа?", kk: "Программа не шығарады?" };
const YES: L = { ru: "да", kk: "иә" };
const NO: L = { ru: "нет", kk: "жоқ" };

interface Base {
  id: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  hint: L;
  explanation: L;
  reveal?: Scene;
}

type Wrong = [Text, L];

/** choice: верный вариант и неверные с разбором ошибки (poolBank перемешает варианты вместе с whyWrong). */
function choice(base: Base, right: Text, wrong: Wrong[]): ChoiceStep {
  return {
    type: "choice",
    skill: SKILL,
    ...base,
    options: [right, ...wrong.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrong.map((w) => w[1])],
  };
}

function input(base: Base, answer: string): InputStep {
  return { type: "input", skill: SKILL, ...base, answers: [answer], mode: "number" };
}

/** multi: верные и неверные утверждения; whyWrong — у неверных. */
function multi(base: Base, right: Text[], wrong: Wrong[]): MultiStep {
  return {
    type: "multi",
    skill: SKILL,
    ...base,
    options: [...right, ...wrong.map((w) => w[0])],
    correct: right.map((_, i) => i),
    whyWrong: [...right.map(() => null), ...wrong.map((w) => w[1])],
  };
}

