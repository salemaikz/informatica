// Банк навыка pc.cpu («Процессор и память», тема ЕНТ t01).
// Знания (части процессора, виды памяти, шины, принципы фон Неймана) — статичный пул.
// Расчёты — генераторы: сколько ячеек и памяти адресует шина адреса из k разрядов (N = 2ᵏ), обратная задача,
// «во сколько раз выросла память», единицы частоты и такты. Правильный ответ всегда считает код.
// Тексты после переменных чисел — без падежных окончаний (в казахском окончание зависит от числа).
// Сверка с реальным расчётом: scripts/out/pc-2-cpu/verify.py (разбирает id заданий и пересчитывает ответ).

const SKILL = "pc.cpu";

const w = (ru: string, kk: string): L => ({ ru, kk });
const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];

/** Верхний индекс для степени: sup(16) → «¹⁶». */
const sup = (n: number) =>
  String(n)
    .split("")
    .map((d) => "⁰¹²³⁴⁵⁶⁷⁸⁹"[Number(d)])
    .join("");

type Unit = "Кбайт" | "Мбайт" | "Гбайт";
const UNIT_BASE: Record<Unit, number> = { Кбайт: 10, Мбайт: 20, Гбайт: 30 };

// ---------- Расчётные задания ----------

interface Wrong {
  v: string;
  why: L;
}

interface Calc {
  /** Идентификатор «семейства» без seed: g:pc.cpu:<вид>:<параметры>. */
  id: string;
  prompt: L;
  answer: string;
  wrongs: Wrong[];
  hint: L;
  explanation: L;
}

/** A: сколько ячеек адресует шина адреса из k разрядов. */
function calcCells(rand: Rand): Calc {
  const k = int(rand, 3, 12);
  const n = 2 ** k;
  return {
    id: `g:${SKILL}:cells:${k}`,
    prompt: w(
      `Шина адреса процессора ${k}-разрядная. Сколько разных ячеек памяти можно адресовать?`,
      `Процессордың мекенжай шинасы ${k} разрядты. Жадтың неше түрлі ұяшығын мекенжайлауға болады?`,
    ),
    answer: String(n),
    wrongs: [
      { v: String(2 * k), why: w("Разряды не умножают на 2: число адресов — это 2 в степени k.", "Разрядтарды 2-ге көбейтпейді: мекенжайлар саны — 2-нің k дәрежесі.") },
      { v: String(k * k), why: w("Число разрядов возведено в квадрат, а нужно 2ᵏ.", "Разрядтар саны квадратқа шығарылған, ал 2ᵏ керек.") },
      { v: String(2 ** (k - 1)), why: w("Потерян один разряд: при k разрядах адресов 2ᵏ, а не 2ᵏ⁻¹.", "Бір разряд жоғалған: k разрядта мекенжай 2ᵏ, ал 2ᵏ⁻¹ емес.") },
      { v: String(2 ** (k + 1)), why: w("Взят лишний разряд: при k разрядах адресов 2ᵏ, а не 2ᵏ⁺¹.", "Артық разряд алынған: k разрядта мекенжай 2ᵏ, ал 2ᵏ⁺¹ емес.") },
      { v: String(k), why: w("k — это число разрядов, а не число ячеек.", "k — ұяшықтар саны емес, разрядтар саны.") },
    ],
    hint: w(
      "Каждый разряд (провод) удваивает число адресов: один провод — 2 адреса, два — 4, три — 8…",
      "Әр разряд (сым) мекенжайлар санын екі есе арттырады: бір сым — 2 мекенжай, екі — 4, үш — 8…",
    ),
    explanation: w(
      `Для k разрядов число адресов N = 2ᵏ. При k = ${k}: N = 2${sup(k)} = ${n}.`,
      `k разряд үшін мекенжайлар саны N = 2ᵏ. k = ${k} болғанда: N = 2${sup(k)} = ${n}.`,
    ),
  };
}

/** B: какой объём памяти (в Кбайт, Мбайт или Гбайт) адресует шина адреса из k разрядов. */
function calcSize(rand: Rand): Calc {
  const k = pick(rand, [11, 12, 13, 14, 15, 16, 18, 21, 22, 23, 24, 25, 31, 32]);
  const unit: Unit = k < 20 ? "Кбайт" : k < 30 ? "Мбайт" : "Гбайт";
  const base = UNIT_BASE[unit];
  const value = 2 ** (k - base);
  return {
    id: `g:${SKILL}:size:${k}`,
    prompt: w(
      `Шина адреса ${k}-разрядная, ячейка памяти хранит 1 байт. Какой объём памяти можно адресовать? Ответ в ${unit}.`,
      `Мекенжай шинасы ${k} разрядты, жад ұяшығы 1 байт сақтайды. Қанша жадты мекенжайлауға болады? Жауапты ${unit} түрінде жаз.`,
    ),
    answer: String(value),
    wrongs: [
      { v: String(k), why: w("k — это число разрядов, а не объём памяти.", "k — жад көлемі емес, разрядтар саны.") },
      { v: String(value / 2), why: w("Потерян один разряд: каждый разряд удваивает объём.", "Бір разряд жоғалған: әр разряд көлемді екі есе арттырады.") },
      { v: String(value * 2), why: w("Взят лишний разряд: каждый разряд удваивает объём.", "Артық разряд алынған: әр разряд көлемді екі есе арттырады.") },
      {
        v: String(value * 1024),
        why: w(
          `Это объём в более мелких единицах: переведи в ${unit}, разделив на 1024.`,
          `Бұл — ұсағырақ бірліктегі көлем: 1024-ке бөліп, ${unit} түріне аудар.`,
        ),
      },
    ],
    hint: w(
      "Разбей k на 10, 20 или 30 и остаток: 2¹⁰ байт — это 1 Кбайт, 2²⁰ — 1 Мбайт, 2³⁰ — 1 Гбайт.",
      "k санын 10, 20 немесе 30 және қалдыққа бөл: 2¹⁰ байт — 1 Кбайт, 2²⁰ — 1 Мбайт, 2³⁰ — 1 Гбайт.",
    ),
    explanation: w(
      `N = 2${sup(k)} = 2${sup(k - base)} · 2${sup(base)} = ${value} · 1 ${unit} = ${value} ${unit}, потому что 2${sup(base)} байт = 1 ${unit}.`,
      `N = 2${sup(k)} = 2${sup(k - base)} · 2${sup(base)} = ${value} · 1 ${unit} = ${value} ${unit}, себебі 2${sup(base)} байт = 1 ${unit}.`,
    ),
  };
}

/** C: обратная задача — сколько разрядов нужно, чтобы адресовать заданный объём. */
function calcBits(rand: Rand): Calc {
  const unit: Unit = pick(rand, ["Кбайт", "Мбайт", "Мбайт", "Гбайт"]);
  const exps = unit === "Гбайт" ? [0, 1, 2, 3] : [1, 2, 3, 4, 5, 6, 7, 8, 9];
  const e = pick(rand, exps);
  const value = 2 ** e;
  const base = UNIT_BASE[unit];
  const k = base + e;
  const why = (a: number) =>
    w(
      `При ${a} разрядах адресуется 2${sup(a)} байт, а нужно 2${sup(k)} байт.`,
      `${a} разрядта 2${sup(a)} байт мекенжайланады, ал 2${sup(k)} байт керек.`,
    );
  return {
    id: `g:${SKILL}:bits:${value}${unit}`,
    prompt: w(
      `Нужно адресовать ${value} ${unit} памяти (ячейка — 1 байт). Сколько разрядов должна иметь шина адреса?`,
      `${value} ${unit} жадты мекенжайлау керек (ұяшық — 1 байт). Мекенжай шинасы неше разрядты болуы керек?`,
    ),
    answer: String(k),
    wrongs: [
      { v: String(k - 1), why: w("Не хватит: на один разряд меньше — вдвое меньше памяти.", "Жетпейді: бір разряд аз болса — жад екі есе аз.") },
      { v: String(k + 1), why: w("С запасом вдвое: лишний разряд удваивает память.", "Екі есе қормен: артық разряд жадты екі есе арттырады.") },
      { v: String(value), why: w("Это число из условия, а не число разрядов: нужно найти k, при котором 2ᵏ байт равно объёму.", "Бұл — шарттағы сан, разрядтар саны емес: 2ᵏ байт көлемге тең болатын k табу керек.") },
      { v: String(k - 2), why: why(k - 2) },
      { v: String(k + 2), why: why(k + 2) },
      { v: String(base), why: w(`${base} разрядов хватает только на 1 ${unit}, а нужно больше.`, `${base} разряд тек 1 ${unit} үшін жетеді, ал көбірек керек.`) },
    ],
    hint: w(
      "Запиши объём в байтах как степень двойки: 1 Кбайт = 2¹⁰ байт, 1 Мбайт = 2²⁰, 1 Гбайт = 2³⁰. Число перед единицей тоже разложи на двойки.",
      "Көлемді байтпен екінің дәрежесі етіп жаз: 1 Кбайт = 2¹⁰ байт, 1 Мбайт = 2²⁰, 1 Гбайт = 2³⁰. Бірлік алдындағы санды да екілерге жікте.",
    ),
    explanation:
      e === 0
        ? w(
            `1 ${unit} = 2${sup(base)} байт, значит нужно ${k} разрядов.`,
            `1 ${unit} = 2${sup(base)} байт, демек ${k} разряд керек.`,
          )
        : w(
            `${value} ${unit} = 2${sup(e)} · 2${sup(base)} байт = 2${sup(k)} байт, значит нужно ${k} разрядов.`,
            `${value} ${unit} = 2${sup(e)} · 2${sup(base)} байт = 2${sup(k)} байт, демек ${k} разряд керек.`,
          ),
  };
}

/** C: во сколько раз вырос объём, когда шину адреса расширили на d разрядов. */
function calcGrow(rand: Rand): Calc {
  const a = int(rand, 8, 28);
  const d = int(rand, 2, 5);
  const b = a + d;
  const ans = 2 ** d;
  return {
    id: `g:${SKILL}:grow:${a}-${d}`,
    prompt: w(
      `Шину адреса расширили с ${a} до ${b} разрядов. Во сколько раз увеличился объём адресуемой памяти?`,
      `Мекенжай шинасын ${a} разрядтан ${b} разрядқа дейін кеңейтті. Мекенжайланатын жад көлемі неше есе артты?`,
    ),
    answer: String(ans),
    wrongs: [
      { v: String(d), why: w(`${d} — это прибавка в разрядах, а объём вырос в 2${sup(d)} раз.`, `${d} — разрядтардағы өсім, ал көлем 2${sup(d)} есе өсті.`) },
      { v: String(2 * d), why: w("Разряды не умножают на 2: каждый новый разряд удваивает объём.", "Разрядтарды 2-ге көбейтпейді: әр жаңа разряд көлемді екі есе арттырады.") },
      { v: String(d * d), why: w("Прибавка разрядов возведена в квадрат, а нужно 2 в степени прибавки.", "Разрядтардың өсімі квадратқа шығарылған, ал өсімнің 2 дәрежесі керек.") },
      { v: String(2 ** (d + 1)), why: w("Один лишний разряд: добавлено d разрядов, значит объём вырос в 2ᵈ раз.", "Бір артық разряд: d разряд қосылды, демек көлем 2ᵈ есе өсті.") },
      { v: String(2 ** (d - 1)), why: w("Один разряд потерян: добавлено d разрядов, значит объём вырос в 2ᵈ раз.", "Бір разряд жоғалған: d разряд қосылды, демек көлем 2ᵈ есе өсті.") },
      { v: String(2 ** (d + 2)), why: w("Два лишних разряда: добавлено d разрядов, значит объём вырос в 2ᵈ раз.", "Екі артық разряд: d разряд қосылды, демек көлем 2ᵈ есе өсті.") },
      { v: String(ans + 1), why: w("Ошибка на 1: объём вырос ровно в 2ᵈ раз.", "1-ге қателесу: көлем дәл 2ᵈ есе өсті.") },
    ],
    hint: w(
      "Каждый новый разряд удваивает число адресов. Сколько разрядов добавили?",
      "Әр жаңа разряд мекенжайлар санын екі есе арттырады. Қанша разряд қосылды?",
    ),
    explanation: w(
      `Добавили ${b} − ${a} = ${d} разряд${d < 5 ? "а" : "ов"}, каждый удваивает объём: 2${sup(d)} = ${ans} раз. Проверка: 2${sup(b)} : 2${sup(a)} = 2${sup(d)}.`,
      `${b} − ${a} = ${d} разряд қосылды, әрқайсысы көлемді екі есе арттырады: 2${sup(d)} = ${ans} есе. Тексеру: 2${sup(b)} : 2${sup(a)} = 2${sup(d)}.`,
    ),
  };
}

/** A: ГГц → МГц (приставки частоты десятичные, в отличие от байтов). */
function calcFreq1(rand: Rand): Calc {
  const x = int(rand, 2, 5);
  const ans = x * 1000;
  return {
    id: `g:${SKILL}:freq1:${x}`,
    prompt: w(
      `Тактовая частота процессора ${x} ГГц. Выразите её в МГц.`,
      `Процессордың тактілік жиілігі ${x} ГГц. Оны МГц түрінде өрнектеңіз.`,
    ),
    answer: String(ans),
    wrongs: [
      { v: String(x * 1024), why: w("1024 — это для байтов (1 Гбайт = 1024 Мбайт). Для частоты приставки десятичные: 1 ГГц = 1000 МГц.", "1024 — байттарға тән (1 Гбайт = 1024 Мбайт). Жиілікте қосымшалар ондық: 1 ГГц = 1000 МГц.") },
      { v: String(x * 100), why: w("В одном гигагерце 1000 мегагерц, а не 100.", "Бір гигагерцте 1000 мегагерц бар, 100 емес.") },
      { v: String(x * 10000), why: w("Перебор на порядок: 1 ГГц = 1000 МГц.", "Бір ретке артық: 1 ГГц = 1000 МГц.") },
      { v: String(x), why: w("Число осталось прежним: единицы разные, и значение нужно пересчитать.", "Сан бұрынғыдай қалған: бірліктер әртүрлі, мәнді қайта есептеу керек.") },
    ],
    hint: w(
      "Г — гига (миллиард), М — мега (миллион). Во сколько раз гига больше мега?",
      "Г — гига (миллиард), М — мега (миллион). Гига мегадан неше есе үлкен?",
    ),
    explanation: w(
      `1 ГГц = 1000 МГц, значит ${x} ГГц = ${x} · 1000 = ${ans} МГц. Не путай с байтами: там 1 Гбайт = 1024 Мбайт.`,
      `1 ГГц = 1000 МГц, демек ${x} ГГц = ${x} · 1000 = ${ans} МГц. Байттармен шатастырма: онда 1 Гбайт = 1024 Мбайт.`,
    ),
  };
}

/** B: сколько миллиардов тактов за t секунд. */
function calcFreq2(rand: Rand): Calc {
  const x = int(rand, 2, 5);
  const t = int(rand, 2, 9);
  const ans = x * t;
  return {
    id: `g:${SKILL}:freq2:${x}x${t}`,
    prompt: w(
      `Процессор с тактовой частотой ${x} ГГц работает ${t} секунд. Сколько миллиардов тактов он выполнит?`,
      `Тактілік жиілігі ${x} ГГц процессор ${t} секунд жұмыс істейді. Ол неше миллиард такт орындайды?`,
    ),
    answer: String(ans),
    wrongs: [
      { v: String(x + t), why: w("Частоту и время не складывают, а перемножают: такты за секунду × секунды.", "Жиілік пен уақытты қоспайды, көбейтеді: секундтағы такт × секунд.") },
      { v: String(ans * 1000), why: w("Ответ нужен в миллиардах тактов, а ГГц уже означает миллиарды в секунду.", "Жауап миллиард тактпен керек, ал ГГц секундына миллиардты білдіреді.") },
      { v: String(ans * 10), why: w("Перебор на порядок: проверь умножение.", "Бір ретке артық: көбейтуді тексер.") },
      { v: String(x), why: w("Это такты за одну секунду, а работа длилась несколько секунд.", "Бұл — бір секундтағы такт, ал жұмыс бірнеше секунд созылды.") },
      { v: String(t), why: w("Это время, а нужно умножить его на число миллиардов тактов в секунду.", "Бұл — уақыт, оны секундтағы миллиард такт санына көбейту керек.") },
    ],
    hint: w(
      "1 ГГц — это миллиард тактов в секунду. Сколько миллиардов тактов за одну секунду, а потом за все секунды?",
      "1 ГГц — секундына миллиард такт. Бір секундта неше миллиард такт, содан кейін барлық секундта ше?",
    ),
    explanation: w(
      `За секунду процессор делает ${x} млрд тактов, за ${t} с — ${x} · ${t} = ${ans} млрд тактов.`,
      `Процессор бір секундта ${x} млрд такт жасайды, ${t} с ішінде — ${x} · ${t} = ${ans} млрд такт.`,
    ),
  };
}

const CALCS: Record<Level, ((rand: Rand) => Calc)[]> = {
  1: [calcCells, calcFreq1],
  2: [calcSize, calcFreq2, calcSize],
  3: [calcBits, calcGrow],
};

/** Правильный + три разных неверных (из типичных ошибок), порядок перемешан по seed. */
function buildOptions(rand: Rand, calc: Calc): { options: string[]; correct: number; whyWrong: (L | null)[] } {
  const seen = new Set<string>([calc.answer]);
  const picked: Wrong[] = [];
  for (const wr of shuffle(calc.wrongs, rand)) {
    if (picked.length >= 3) break;
    if (!seen.has(wr.v)) {
      seen.add(wr.v);
      picked.push(wr);
    }
  }
  const all = shuffle<{ v: string; why: L | null }>([{ v: calc.answer, why: null }, ...picked], rand);
  return { options: all.map((a) => a.v), correct: all.findIndex((a) => a.why === null), whyWrong: all.map((a) => a.why) };
}

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const calc = pick(rand, CALCS[level])(rand);
  const head = { id: `${calc.id}:${seed}`, skill: SKILL, level, prompt: calc.prompt, hint: calc.hint, explanation: calc.explanation };
  if (rand() < 0.5) {
    const step: InputStep = { ...head, type: "input", answers: [calc.answer], mode: "number" };
    return step;
  }
  const step: ChoiceStep = { ...head, type: "choice", ...buildOptions(rand, calc) };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x51ed270b);
  const calc = pick(rand, CALCS[level])(rand);
  return {
    id: `${calc.id}:${seed}`,
    skill: SKILL,
    level,
    prompt: calc.prompt,
    answer: calc.answer,
    mode: "number",
    explanation: calc.explanation,
    hint: calc.hint,
  };
}

// ---------- Статичный пул: знания ----------

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [Text, boolean, L?][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

