/** Короткий вопрос-генератор: число устройств / префикс по маске / адрес сети. */
function genShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x51ed270b);
  if (level === 1) {
    const n = int(rand, 24, 30);
    return {
      id: `q:${SKILL}:hosts:${n}`,
      skill: SKILL,
      level,
      prompt: w(`Сколько устройств можно подключить в сеть с префиксом /${n}?`, `/${n} префиксі бар желіге қанша құрылғыны қосуға болады?`),
      answer: String(hostsOf(n)),
      mode: "number",
      explanation: hostsExplanation(n),
      hint: HINT_HOSTS,
    };
  }
  if (level === 2) {
    const n = pick(rand, [17, 18, 19, 20, 21, 22, 23, 25, 26, 27, 28, 29, 30]);
    return {
      id: `q:${SKILL}:prefix:${n}`,
      skill: SKILL,
      level,
      prompt: w(`Запиши префикс (число) маски ${ipStr(maskOf(n))}.`, `${ipStr(maskOf(n))} маскасының префиксін (санмен) жаз.`),
      answer: String(n),
      mode: "number",
      explanation: prefixExplanation(n),
      hint: HINT_PREFIX,
    };
  }
  const n = pick(rand, NET_N3);
  const ip = hostIp(rand, n);
  return {
    id: `q:${SKILL}:net:${ipKey(ip)}-${n}`,
    skill: SKILL,
    level,
    prompt: w(`Компьютер имеет адрес ${ipStr(ip)}/${n}. Чему равен адрес его сети?`, `Компьютердің мекенжайы ${ipStr(ip)}/${n}. Оның желі мекенжайы неге тең?`),
    answer: ipStr(andIp(ip, maskOf(n))),
    mode: "text",
    explanation: netExplanation(ip, n),
    hint: HINT_NET,
  };
}

const mask: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed ^ 0x7f4a7c15);
    // Примерно половина заданий — генераторы (расчёты), остальное — знания и классические задачи из пула.
    if (rand() < 0.5) return pool.question(level, seed);
    return pick(rand, GENERATORS[level])(level, seed, rand);
  },
  statement: pool.statement,
  pair: pool.pair,
  short(level, seed) {
    const rand = seeded(seed ^ 0x3c6ef372);
    if (rand() < 0.4) return genShort(level, seed);
    return pool.short!(level, seed);
  },
};

export const BANKS: SkillBank[] = [mask];
