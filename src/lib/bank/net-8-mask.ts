/** Разложение префикса по октетам: «8 + 8 + 4 + 0». */
const prefixSum = (n: number) => [0, 1, 2, 3].map((i) => Math.max(0, Math.min(8, n - 8 * i))).join(" + ");

function netExplanation(ip: Ip, n: number): L {
  const mask = maskOf(n);
  const net = andIp(ip, mask);
  const i = Math.floor(n / 8);
  return w(
    `Маска /${n} = ${ipStr(mask)}. В ${ORD_RU[i]} числе она не 255 и не 0, считаем его в двоичной системе: ${ip[i]} И ${mask[i]} = ${bin8(ip[i])} И ${bin8(mask[i])} = ${bin8(net[i])} = ${net[i]}. Числа левее сохраняются${i < 3 ? ", правее обнуляются" : ""}. Адрес сети: ${ipStr(net)}.`,
    `/${n} маскасы = ${ipStr(mask)}. ${cap(ORD_KK[i])} санда ол 255 те, 0 де емес, оны екілік жүйеде есептейміз: ${ip[i]} ЖӘНЕ ${mask[i]} = ${bin8(ip[i])} ЖӘНЕ ${bin8(mask[i])} = ${bin8(net[i])} = ${net[i]}. Сол жақтағы сандар сақталады${i < 3 ? ", оң жақтағылар нөлге айналады" : ""}. Желі мекенжайы: ${ipStr(net)}.`,
  );
}

function bcastExplanation(ip: Ip, n: number): L {
  const mask = maskOf(n);
  const net = andIp(ip, mask);
  const bc = bcastOf(net, mask);
  const i = Math.floor(n / 8);
  const h = 32 - n;
  return w(
    `Маска /${n} = ${ipStr(mask)}. Адрес сети: ${ip[i]} И ${mask[i]} = ${net[i]}, то есть ${ipStr(net)}. Под номер устройства ${h} бит, у широковещательного адреса они все равны 1: в ${ORD_RU[i]} числе ${net[i]} + ${~mask[i] & 255} = ${bc[i]}${i < 3 ? ", а числа правее становятся 255" : ""}. Широковещательный адрес: ${ipStr(bc)}.`,
    `/${n} маскасы = ${ipStr(mask)}. Желі мекенжайы: ${ip[i]} ЖӘНЕ ${mask[i]} = ${net[i]}, яғни ${ipStr(net)}. Құрылғы нөміріне ${h} бит, тарату мекенжайында олардың бәрі 1: ${ORD_KK[i]} санда ${net[i]} + ${~mask[i] & 255} = ${bc[i]}${i < 3 ? ", ал оң жақтағы сандар 255 болады" : ""}. Тарату мекенжайы: ${ipStr(bc)}.`,
  );
}

function hostsExplanation(n: number): L {
  const h = 32 - n;
  return w(
    `Префикс /${n}: под номер устройства отдано h = 32 − ${n} = ${h} бит. Адресов ${pow2(h)} = ${2 ** h}, два из них служебные (адрес сети и широковещательный), устройств ${2 ** h} − 2 = ${hostsOf(n)}.`,
    `/${n} префиксі: құрылғы нөміріне h = 32 − ${n} = ${h} бит берілген. Мекенжай ${pow2(h)} = ${2 ** h}, оның екеуі қызметтік (желі мекенжайы және тарату мекенжайы), құрылғы ${2 ** h} − 2 = ${hostsOf(n)}.`,
  );
}

function prefixExplanation(n: number): L {
  const mask = maskOf(n);
  const i = Math.floor(n / 8);
  const border = n % 8 === 0 ? "" : ` ${mask[i]} = ${bin8(mask[i])}₂.`;
  return w(
    `Префикс /n — число единиц в маске. ${n} = ${prefixSum(n)}: числа по 8 единиц дают 255, нулевые дают 0. Маска ${ipStr(mask)}.${border}`,
    `/n префиксі — маскадағы бірлер саны. ${n} = ${prefixSum(n)}: 8 бірлік 255 береді, нөлдік сан 0 береді. Маска ${ipStr(mask)}.${border}`,
  );
}

