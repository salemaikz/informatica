// Банк навыка net.mask (IP-адрес и маска сети): генераторы + статичный пул.
// Генераторы: маска ↔ префикс, число устройств (2ʰ − 2), адрес сети, широковещательный адрес, «одна ли сеть у двух
// компьютеров», наименьшая маска под N устройств, маска из двоичной записи. Ответ всегда считает код (маска, И, ИЛИ по
// октетам), неверные варианты — типичные ошибки (забыли «минус 2», считали нули вместо единиц, ИЛИ вместо И, /24 «по привычке»).
// Параметры задачи зашиты в id (g:net.mask:<вид>:<параметры>:<seed>) — по ним ответы перепроверены независимо в python3
// (модуль ipaddress). После переменных чисел казахские тексты без падежных окончаний.

const SKILL = "net.mask";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const w = (ru: string, kk: string): L => ({ ru, kk });

// ---------- Арифметика адресов ----------

type Ip = number[];
const ipStr = (o: Ip) => o.join(".");
const ipKey = (o: Ip) => o.join("-");

/** Маска /n по октетам: 256 − 2^(8 − k), где k — число единиц в октете. */
const maskOf = (n: number): Ip =>
  [0, 1, 2, 3].map((i) => {
    const k = Math.max(0, Math.min(8, n - 8 * i));
    return 256 - (1 << (8 - k));
  });
const andIp = (a: Ip, b: Ip): Ip => a.map((x, i) => x & b[i]);
const orIp = (a: Ip, b: Ip): Ip => a.map((x, i) => x | b[i]);
const bcastOf = (net: Ip, mask: Ip): Ip => net.map((x, i) => x | (~mask[i] & 255));
const toInt = (o: Ip) => ((o[0] * 256 + o[1]) * 256 + o[2]) * 256 + o[3];
const fromInt = (x: number): Ip => [Math.floor(x / 16777216) % 256, Math.floor(x / 65536) % 256, Math.floor(x / 256) % 256, x % 256];
const bin8 = (x: number) => x.toString(2).padStart(8, "0");

const SUP = "⁰¹²³⁴⁵⁶⁷⁸⁹";
const sup = (n: number) => String(n).split("").map((d) => SUP[Number(d)]).join("");
const pow2 = (h: number) => `2${sup(h)}`;

const ORD_RU = ["первом", "втором", "третьем", "четвёртом"];
const ORD_KK = ["бірінші", "екінші", "үшінші", "төртінші"];
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** «устройство / устройства / устройств» по числу. */
function devRu(x: number): string {
  const d = x % 10;
  const dd = x % 100;
  if (d === 1 && dd !== 11) return `${x} устройство`;
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return `${x} устройства`;
  return `${x} устройств`;
}

/** Случайный «частный» адрес: 10.x.x.x, 172.16–31.x.x или 192.168.x.x. */
function randIp(rand: Rand): Ip {
  const kind = int(rand, 0, 2);
  if (kind === 0) return [10, int(rand, 0, 255), int(rand, 0, 255), int(rand, 1, 254)];
  if (kind === 1) return [172, int(rand, 16, 31), int(rand, 0, 255), int(rand, 1, 254)];
  return [192, 168, int(rand, 0, 255), int(rand, 1, 254)];
}

/** Адрес, который не совпадает ни с адресом сети, ни с широковещательным (обычный адрес устройства). */
function hostIp(rand: Rand, n: number): Ip {
  const mask = maskOf(n);
  for (let i = 0; i < 100; i++) {
    const ip = randIp(rand);
    const net = andIp(ip, mask);
    const bc = bcastOf(net, mask);
    if (ipStr(ip) !== ipStr(net) && ipStr(ip) !== ipStr(bc)) return ip;
  }
  return [192, 168, 5, 70];
}

const hostsOf = (n: number) => 2 ** (32 - n) - 2;

