/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: options — пары [вариант, почему неверен | null для верного]. */
function mu(id: string, level: Level, prompt: L, rows: [Text, L | null][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: rows.map((r) => r[0]),
    correct: rows.flatMap((r, i) => (r[1] === null ? [i] : [])),
    whyWrong: rows.map((r) => r[1]),
    explanation,
    hint,
  };
}

