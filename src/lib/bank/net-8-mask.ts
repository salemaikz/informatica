// ---------- Конструктор выбора ----------

interface Opt {
  v: string;
  why: L | null;
}

function buildChoice(rand: Rand, id: string, level: Level, prompt: L, correct: string, wrongs: Opt[], explanation: L, hint: L): ChoiceStep {
  const seen = new Set<string>([correct]);
  const picked: Opt[] = [];
  for (const x of wrongs) {
    if (seen.has(x.v)) continue;
    seen.add(x.v);
    picked.push(x);
    if (picked.length === 3) break;
  }
  if (picked.length < 3) throw new Error(`${id}: не хватило разных неверных вариантов`);
  const list = shuffle<Opt>([{ v: correct, why: null }, ...picked], rand);
  return {
    id,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: list.map((x) => x.v),
    correct: list.findIndex((x) => x.why === null),
    whyWrong: list.map((x) => x.why),
    explanation,
    hint,
  };
}

function inputStep(id: string, level: Level, prompt: L, answer: string, mode: "number" | "text", explanation: L, hint: L): InputStep {
  return { id, type: "input", skill: SKILL, level, prompt, answers: [answer], mode, explanation, hint };
}

// ---------- Генератор: маска ↔ префикс ----------

const PM_N: Record<1 | 2, number[]> = {
  1: [8, 16, 24, 25, 26, 27, 28, 29, 30],
  2: [12, 17, 18, 19, 20, 21, 22, 23, 25, 26, 27, 28, 29, 30],
};

function genPrefixMask(level: Level, seed: number, rand: Rand): QuestionStep {
  const n = pick(rand, PM_N[level === 1 ? 1 : 2]);
  const mask = maskOf(n);
  const near = [n - 1, n + 1, 32 - n, n - 8, n + 8, n - 2, n + 2].filter((m) => m >= 1 && m <= 31 && m !== n);
  const wrongPrefixes = shuffle(near, rand);
  if (rand() < 0.5) {
    return buildChoice(
      rand,
      `g:net.mask:pmf:${n}:${seed}`,
      level,
      w(`Какой маске соответствует префикс /${n}?`, `/${n} префиксі қандай маскаға сәйкес келеді?`),
      ipStr(mask),
      wrongPrefixes.map((m) => ({
        v: ipStr(maskOf(m)),
        why: w(`Это маска /${m}: в ней ${m} единиц, а нужно ${n}.`, `Бұл /${m} маскасы: онда ${m} бірлік бар, ал ${n} керек.`),
      })),
      prefixExplanation(n),
      HINT_PREFIX,
    );
  }
  return buildChoice(
    rand,
    `g:net.mask:pmr:${n}:${seed}`,
    level,
    w(`Маска сети ${ipStr(mask)}. Как записать её префиксом?`, `Желі маскасы ${ipStr(mask)}. Оны префикс ретінде қалай жазады?`),
    `/${n}`,
    wrongPrefixes.map((m) => ({
      v: `/${m}`,
      why: w(`/${m} — это маска ${ipStr(maskOf(m))}: единиц ${m}, а в данной маске их ${n}.`, `/${m} — бұл ${ipStr(maskOf(m))} маскасы: бірлік ${m}, ал берілген маскада олар ${n}.`),
    })),
    prefixExplanation(n),
    HINT_PREFIX,
  );
}

// ---------- Генератор: сколько устройств ----------

function genHosts(level: Level, seed: number, rand: Rand): QuestionStep {
  const n = level === 1 ? int(rand, 24, 30) : level === 2 ? int(rand, 20, 30) : int(rand, 12, 23);
  const byMask = rand() < 0.5;
  const prompt = byMask
    ? w(`Маска сети ${ipStr(maskOf(n))}. Сколько устройств можно подключить в такую сеть?`, `Желі маскасы ${ipStr(maskOf(n))}. Мұндай желіге қанша құрылғыны қосуға болады?`)
    : w(`Сеть имеет префикс /${n}. Сколько устройств можно подключить в такую сеть?`, `Желінің префиксі /${n}. Мұндай желіге қанша құрылғыны қосуға болады?`);
  const id = `g:net.mask:hosts-${byMask ? "m" : "p"}:${n}:${seed}`;
  const h = 32 - n;
  const ans = hostsOf(n);
  if (level >= 2) return inputStep(id, level, prompt, String(ans), "number", hostsExplanation(n), HINT_HOSTS);
  const wrongs: Opt[] = [
    { v: String(2 ** h), why: w("Это всего адресов в сети, но два из них служебные.", "Бұл желідегі барлық мекенжай, бірақ екеуі қызметтік.") },
    { v: String(2 ** h - 1), why: w("Вычтен один служебный адрес, а их два: адрес сети и широковещательный.", "Бір қызметтік мекенжай алынған, ал олар екеу: желі мекенжайы және тарату мекенжайы.") },
    { v: String(h), why: w("Это число бит под устройства (h), а не число устройств.", "Бұл құрылғыға арналған бит саны (h), құрылғы саны емес.") },
    { v: String(2 ** (h + 1) - 2), why: w("Так получится для сети вдвое больше: префикс на единицу короче.", "Бұл екі есе үлкен желі үшін шығады: префикс бірге қысқа.") },
    { v: String(2 ** (h - 1) - 2), why: w("Так получится для сети вдвое меньше: префикс на единицу длиннее.", "Бұл екі есе кіші желі үшін шығады: префикс бірге ұзын.") },
  ].filter((x) => x.v !== String(ans) && Number(x.v) > 0);
  return buildChoice(rand, id, level, prompt, String(ans), wrongs, hostsExplanation(n), HINT_HOSTS);
}

// ---------- Генератор: адрес сети ----------

const NET_N2 = [25, 26, 27, 28, 29, 30];
const NET_N3 = [10, 11, 12, 13, 14, 15, 17, 18, 19, 20, 21, 22, 23];

function genNetAddr(level: Level, seed: number, rand: Rand): QuestionStep {
  const n = pick(rand, level === 3 ? NET_N3 : NET_N2);
  const ip = hostIp(rand, n);
  const mask = maskOf(n);
  const net = andIp(ip, mask);
  const id = `g:net.mask:netaddr:${ipKey(ip)}-${n}:${seed}`;
  const prompt = w(
    `Компьютер имеет адрес ${ipStr(ip)}/${n}. Чему равен адрес его сети?`,
    `Компьютердің мекенжайы ${ipStr(ip)}/${n}. Оның желі мекенжайы неге тең?`,
  );
  if (level === 3) return inputStep(id, level, prompt, ipStr(net), "text", netExplanation(ip, n), HINT_NET);
  const bc = bcastOf(net, mask);
  const next = fromInt(toInt(net) + 2 ** (32 - n));
  const wrongs: Opt[] = [
    { v: ipStr(ip), why: w("Это сам IP-адрес: маска к нему не применена.", "Бұл IP мекенжайдың өзі: маска оған қолданылмаған.") },
    { v: ipStr(bc), why: w("Это широковещательный адрес (все биты устройства — единицы), а не адрес сети.", "Бұл тарату мекенжайы (құрылғының барлық биті — бірлік), желі мекенжайы емес.") },
    { v: ipStr(orIp(ip, mask)), why: w("Применено ИЛИ вместо И: адрес сети получают побитовым И.", "ЖӘНЕ орнына НЕМЕСЕ қолданылған: желі мекенжайын биттік ЖӘНЕ арқылы алады.") },
    { v: ipStr(next), why: w("Это начало следующей сети: адрес сети не бывает больше самого адреса.", "Бұл келесі желінің басы: желі мекенжайы мекенжайдың өзінен үлкен болмайды.") },
  ].filter((x) => x.v !== ipStr(net));
  return buildChoice(rand, id, level, prompt, ipStr(net), wrongs, netExplanation(ip, n), HINT_NET);
}

// ---------- Генератор: широковещательный адрес ----------

function genBroadcast(level: Level, seed: number, rand: Rand): QuestionStep {
  const n = pick(rand, level === 3 ? NET_N3 : NET_N2);
  const ip = hostIp(rand, n);
  const mask = maskOf(n);
  const net = andIp(ip, mask);
  const bc = bcastOf(net, mask);
  const id = `g:net.mask:bcast:${ipKey(ip)}-${n}:${seed}`;
  const prompt = w(
    `Компьютер имеет адрес ${ipStr(ip)}/${n}. Чему равен широковещательный адрес его сети?`,
    `Компьютердің мекенжайы ${ipStr(ip)}/${n}. Оның желісінің тарату мекенжайы неге тең?`,
  );
  if (level === 3) return inputStep(id, level, prompt, ipStr(bc), "text", bcastExplanation(ip, n), HINT_BCAST);
  const wrongs: Opt[] = [
    { v: ipStr(net), why: w("Это адрес самой сети (все биты устройства — нули).", "Бұл желінің өз мекенжайы (құрылғының барлық биті — нөл).") },
    { v: ipStr(fromInt(toInt(bc) - 1)), why: w("Это последний адрес для устройства, а широковещательный стоит на единицу дальше.", "Бұл құрылғыға арналған соңғы мекенжай, ал тарату мекенжайы бір саннан кейін тұр.") },
    { v: ipStr([ip[0], ip[1], ip[2], 255]), why: w("Так получится для маски /24, а здесь префикс другой.", "Бұл /24 маскасы үшін шығады, ал мұнда префикс басқа.") },
    { v: ipStr(fromInt(toInt(bc) + 1)), why: w("Это начало следующей сети, уже за границей этой.", "Бұл келесі желінің басы, осы желінің шекарасынан тыс.") },
  ].filter((x) => x.v !== ipStr(bc));
  return buildChoice(rand, id, level, prompt, ipStr(bc), wrongs, bcastExplanation(ip, n), HINT_BCAST);
}

// ---------- Генератор: одна ли сеть ----------

function genSameNet(level: Level, seed: number, rand: Rand): QuestionStep {
  const n = pick(rand, level === 3 ? [18, 19, 20, 21, 22, 25, 26, 27, 28, 29] : [25, 26, 27, 28, 29]);
  const size = 2 ** (32 - n);
  const wide = n < 25; // граница сети проходит в третьем числе
  const span = wide ? 65536 : 256;
  const base = wide ? [...randIp(rand).slice(0, 2), 0, 0] : [...randIp(rand).slice(0, 3), 0];
  const blocks = span / size;
  const jA = int(rand, 0, blocks - 1);
  const same = rand() < 0.5;
  let jB = jA;
  if (!same) while (jB === jA) jB = int(rand, 0, blocks - 1);
  const offA = jA * size + int(rand, 1, size - 2);
  let offB = jB * size + int(rand, 1, size - 2);
  if (offB === offA) offB = jB * size + (offA - jA * size === 1 ? 2 : 1);
  const ipA = fromInt(toInt(base) + offA);
  const ipB = fromInt(toInt(base) + offB);
  const mask = maskOf(n);
  const netA = andIp(ipA, mask);
  const netB = andIp(ipB, mask);
  const verdict = (a: Ip, b: Ip): L => (ipStr(a) === ipStr(b) ? w("одна сеть", "бір желі") : w("разные сети", "әртүрлі желілер"));
  const label = (a: Ip, b: Ip): string => `A: ${ipStr(a)}, B: ${ipStr(b)}`;
  // Вариант ответа: адреса сетей A и B + вывод. Для сравнения вариантов используем «ru-версию» строки.
  const opt = (a: Ip, b: Ip): Text => w(`${label(a, b)} — ${verdict(a, b).ru}`, `${label(a, b)} — ${verdict(a, b).kk}`);
  const key = (a: Ip, b: Ip) => label(a, b);
  const next = (x: Ip) => fromInt(toInt(x) + size);
  const prev = (x: Ip) => fromInt(toInt(x) - size);
  const net24 = (x: Ip): Ip => [x[0], x[1], x[2], 0];
  const cand: { a: Ip; b: Ip; why: L }[] = [
    { a: netA, b: netA, why: w("Для B адрес сети посчитан неверно: его надо находить так же, как для A.", "B үшін желі мекенжайы дұрыс есептелмеген: оны A үшіндегідей табу керек.") },
    { a: netB, b: netB, why: w("Для A адрес сети посчитан неверно: надо выполнить И с маской.", "A үшін желі мекенжайы дұрыс есептелмеген: маскамен ЖӘНЕ орындау керек.") },
    { a: netA, b: next(netB), why: w("Для B получен адрес следующей сети: сеть начинается раньше самого адреса.", "B үшін келесі желінің мекенжайы шыққан: желі мекенжайдың өзінен бұрын басталады.") },
    { a: prev(netA), b: netB, why: w("Для A получен адрес предыдущей сети: сеть, в которой лежит адрес, начинается не там.", "A үшін алдыңғы желінің мекенжайы шыққан: мекенжай жатқан желі басқа жерден басталады.") },
    { a: ipA, b: ipB, why: w("Это сами IP-адреса: маска не применена.", "Бұл IP мекенжайлардың өзі: маска қолданылмаған.") },
    { a: net24(ipA), b: net24(ipB), why: w("Так получится, если считать маску /24 «по привычке»: числа обнулены не по заданной маске.", "Бұл масканы «әдеттегіше» /24 деп есептегенде шығады: сандар берілген маска бойынша нөлденбеген.") },
    { a: netA, b: orIp(ipB, mask), why: w("Для B применено ИЛИ вместо И.", "B үшін ЖӘНЕ орнына НЕМЕСЕ қолданылған.") },
  ];
  const correctKey = key(netA, netB);
  const seen = new Set<string>([correctKey]);
  const wrongs: { text: Text; why: L }[] = [];
  for (const c of shuffle(cand, rand)) {
    const k = key(c.a, c.b);
    if (seen.has(k)) continue;
    seen.add(k);
    wrongs.push({ text: opt(c.a, c.b), why: c.why });
    if (wrongs.length === 3) break;
  }
  if (wrongs.length < 3) throw new Error("same: мало вариантов");
  const list = shuffle<{ text: Text; why: L | null }>([{ text: opt(netA, netB), why: null }, ...wrongs], rand);
  const bi = Math.floor(n / 8); // октет, в котором проходит граница
  return {
    id: `g:net.mask:same:${ipKey(ipA)}-${ipKey(ipB)}-${n}:${seed}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: w(
      `Компьютеры A (${ipStr(ipA)}) и B (${ipStr(ipB)}) имеют маску ${ipStr(mask)}. Выберите верные адреса их сетей и вывод.`,
      `A (${ipStr(ipA)}) және B (${ipStr(ipB)}) компьютерлерінің маскасы ${ipStr(mask)}. Олардың желі мекенжайларын және қорытындыны дұрыс көрсетіңіз.`,
    ),
    options: list.map((x) => x.text),
    correct: list.findIndex((x) => x.why === null),
    whyWrong: list.map((x) => x.why),
    explanation: w(
      `Адрес сети — IP И маска. A: ${ipA[bi]} И ${mask[bi]} = ${bin8(ipA[bi])} И ${bin8(mask[bi])} = ${bin8(netA[bi])} = ${netA[bi]}, сеть ${ipStr(netA)}. B: ${ipB[bi]} И ${mask[bi]} = ${bin8(ipB[bi])} И ${bin8(mask[bi])} = ${bin8(netB[bi])} = ${netB[bi]}, сеть ${ipStr(netB)}. ${same ? "Адреса сетей совпадают — одна сеть, маршрутизатор не нужен." : "Адреса сетей разные — это разные сети, для связи нужен маршрутизатор."}`,
      `Желі мекенжайы — IP ЖӘНЕ маска. A: ${ipA[bi]} ЖӘНЕ ${mask[bi]} = ${bin8(ipA[bi])} ЖӘНЕ ${bin8(mask[bi])} = ${bin8(netA[bi])} = ${netA[bi]}, желі ${ipStr(netA)}. B: ${ipB[bi]} ЖӘНЕ ${mask[bi]} = ${bin8(ipB[bi])} ЖӘНЕ ${bin8(mask[bi])} = ${bin8(netB[bi])} = ${netB[bi]}, желі ${ipStr(netB)}. ${same ? "Желі мекенжайлары сәйкес — бір желі, маршрутизатор керек емес." : "Желі мекенжайлары әртүрлі — бұл әртүрлі желілер, байланыс үшін маршрутизатор керек."}`,
    ),
    hint: HINT_SAME,
  };
}

// ---------- Генератор: маска под N устройств ----------

function genNeed(level: Level, seed: number, rand: Rand): QuestionStep {
  const maxK = level === 2 ? 7 : 10;
  let need: number;
  if (rand() < 0.5) {
    const k = int(rand, 3, maxK - 1);
    need = rand() < 0.5 ? 2 ** k - 1 : 2 ** k; // ловушка: без «минус 2» хватило бы 2ᵏ адресов
  } else {
    const hh = int(rand, 4, maxK);
    need = int(rand, 2 ** (hh - 1) - 1, 2 ** hh - 2);
  }
  let h = 2;
  while (2 ** h - 2 < need) h++;
  const n = 32 - h;
  const id = `g:net.mask:need:${need}:${seed}`;
  const prompt = w(
    `В сети должно работать ${devRu(need)}. Какую маску имеет наименьшая сеть, в которую они поместятся?`,
    `Желіде ${need} құрылғы жұмыс істеуі керек. Олар сиятын ең кіші желінің маскасы қандай?`,
  );
  const explanation = w(
    `Нужно наименьшее h, при котором 2ʰ − 2 ≥ ${need}. При h = ${h - 1} получаем ${2 ** (h - 1) - 2} — не хватает, при h = ${h} получаем ${2 ** h - 2} — хватает. Префикс 32 − ${h} = ${n}, маска ${ipStr(maskOf(n))}.`,
    `2ʰ − 2 ≥ ${need} болатын ең кіші h керек. h = ${h - 1} болғанда ${2 ** (h - 1) - 2} шығады — жетпейді, h = ${h} болғанда ${2 ** h - 2} шығады — жетеді. Префикс 32 − ${h} = ${n}, маска ${ipStr(maskOf(n))}.`,
  );
  if (level === 3 && rand() < 0.5) return inputStep(`g:net.mask:needi:${need}:${seed}`, level, w(`${prompt.ru} Запиши маску в десятичном виде.`, `${prompt.kk} Масканы ондық түрде жаз.`), ipStr(maskOf(n)), "text", explanation, HINT_NEED);
  const wrongs: Opt[] = [
    { v: ipStr(maskOf(n + 1)), why: w(`Вмещает ${devRu(hostsOf(n + 1))} — меньше нужного.`, `${hostsOf(n + 1)} құрылғы сыйғызады — қажеттіден аз.`) },
    { v: ipStr(maskOf(n - 1)), why: w(`Вмещает ${devRu(hostsOf(n - 1))} — хватит, но сеть не наименьшая.`, `${hostsOf(n - 1)} құрылғы сыйғызады — жетеді, бірақ желі ең кіші емес.`) },
    { v: ipStr(maskOf(n + 2)), why: w(`Вмещает ${devRu(hostsOf(n + 2))} — слишком мало.`, `${hostsOf(n + 2)} құрылғы сыйғызады — тым аз.`) },
    { v: ipStr(maskOf(n - 2)), why: w(`Вмещает ${devRu(hostsOf(n - 2))} — хватит, но сеть намного больше нужной.`, `${hostsOf(n - 2)} құрылғы сыйғызады — жетеді, бірақ желі қажеттіден әлдеқайда үлкен.`) },
  ];
  return buildChoice(rand, id, level, prompt, ipStr(maskOf(n)), wrongs, explanation, HINT_NEED);
}

