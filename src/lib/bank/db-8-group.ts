const inp = (id: string, level: Level, q: { prompt: L; hint: L; answer: string; explanation: L; scene?: Scene }): InputStep => ({
  type: "input",
  id: `p:${SKILL}:${id}`,
  skill: SKILL,
  level,
  prompt: q.prompt,
  hint: q.hint,
  answers: [q.answer],
  mode: "number",
  explanation: q.explanation,
  scene: q.scene,
});

