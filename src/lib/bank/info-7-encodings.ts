// Банк навыка info.encodings («Кодировки: ASCII, KZ-1048, Unicode», тема ЕНТ t03): статичный пул.
// Правила: ASCII — 128 кодов (7 бит), в памяти 1 байт; KZ-1048 — 1 байт на символ; UTF-8: ASCII — 1 байт,
// кириллица (в т. ч. казахские буквы) — 2, эмодзи — 4; UTF-16: обычные символы — 2 байта, эмодзи — 4.
// Объёмы фраз считает код (utf8/utf16 ниже), а не человек. Казахские тексты без падежных окончаний после чисел.
// Эмодзи-символы в заданиях не выводим (интерфейс без эмодзи) — только описание «эмодзи».

const SKILL = "info.encodings";

const w = (ru: string, kk: string): L => ({ ru, kk });

/** Объём фразы в UTF-8 (байт). */
const utf8 = (s: string) => new TextEncoder().encode(s).length;
/** Объём фразы в UTF-16 (байт): 2 на символ, 4 для символов вне BMP. */
const utf16 = (s: string) => [...s].reduce((a, c) => a + ((c.codePointAt(0) ?? 0) > 0xffff ? 4 : 2), 0);
/** Объём фразы в KZ-1048 (байт): 1 на символ. */
const kz = (s: string) => [...s].length;

// ---------- Конструкторы заданий ----------

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [L, boolean, L?][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

/** Соответствие «символ/запись — значение». */
function ma(id: string, level: Level, prompt: L, pairs: [Text, Text][], explanation: L, hint: L): MatchStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "match",
    skill: SKILL,
    level,
    prompt,
    pairs: pairs.map(([left, right]) => ({ left, right })),
    explanation,
    hint,
  };
}

/** Ввод ответа (число, двоичная запись или текст). */
function inp(id: string, level: Level, prompt: L, answers: string[], explanation: L, hint: L, mode: InputStep["mode"] = "number"): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, answers, mode, explanation, hint };
}

