/** C: на сколько кабелей полная сетка требует больше, чем звезда. */
const calcMeshVsStar: Gen = (rand) => {
  const n = int(rand, 5, 9);
  const mesh = (n * (n - 1)) / 2;
  const ans = mesh - n;
  return {
    id: `g:${SKILL}:meshdiff:n${n}`,
    level: 3,
    stem: w(
      `Школа выбирает между топологиями «звезда» и «полная сетка» для ${n} компьютеров.`,
      `Мектеп ${n} компьютер үшін «жұлдыз» және «толық тор» топологиялары арасынан таңдайды.`,
    ),
    ask: w("На сколько кабелей больше нужно для полной сетки, чем для звезды?", "Толық тор үшін жұлдызға қарағанда неше кабель артық қажет?"),
    answer: ans,
    wrongs: [
      { v: mesh, why: w("Это число кабелей полной сетки, а нужно найти разницу со звездой.", "Бұл — толық тордың кабель саны, ал жұлдызбен айырманы табу керек.") },
      { v: n, why: w("Это число кабелей звезды, а нужна разница между полной сеткой и звездой.", "Бұл — жұлдыздың кабель саны, ал толық тор мен жұлдыз арасындағы айырма керек.") },
      { v: n * (n - 1) - n, why: w("Кабели полной сетки посчитаны дважды: n · (n − 1) надо поделить на 2.", "Толық тордың кабельдері екі рет есептелген: n · (n − 1) санын 2-ге бөлу керек.") },
      { v: ans + 1, why: w("Ошибка на единицу: вычти из кабелей полной сетки кабели звезды, они равны числу компьютеров.", "Бірге қателесу: толық тордың кабелінен жұлдыздың кабелін алу керек, ол компьютер санына тең.") },
    ].filter((x) => x.v !== ans && x.v > 0),
    mode: "input",
    hint: w(
      "Посчитай отдельно кабели полной сетки (каждый кабель — на пару) и кабели звезды, потом вычти.",
      "Толық тордың кабельдерін (әр кабель — жұпқа) және жұлдыздың кабельдерін бөлек сана, содан кейін азайт.",
    ),
    explanation: w(
      `Полная сетка: ${n} · ${n - 1} : 2 = ${mesh} (кабелей). Звезда: ${n} (кабелей). Разница: ${mesh} − ${n} = ${ans}.`,
      `Толық тор: ${n} · ${n - 1} : 2 = ${mesh} кабель. Жұлдыз: ${n} кабель. Айырма: ${mesh} − ${n} = ${ans}.`,
    ),
  };
};

const GENS: Record<Level, Gen[]> = {
  1: [calcSimple],
  2: [calcMesh(2), calcStarRouter],
  3: [calcMesh(3), calcMeshAdd, calcMeshVsStar],
};

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const c = pick(rand, GENS[level])(rand);
  const base = { skill: SKILL, level: c.level, scene: undefined, hint: c.hint, explanation: c.explanation };
  const prompt = w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`);
  const id = `${c.id}:${seed % 100000}`;
  if (c.mode === "input") {
    const step: InputStep = { ...base, id, type: "input", prompt, answers: [String(c.answer)], mode: "number" };
    return step;
  }
  // Три неверных варианта (разные значения), верный — среди них в случайном месте.
  const uniq: Wrong[] = [];
  for (const x of c.wrongs) if (!uniq.some((u) => u.v === x.v)) uniq.push(x);
  const items = shuffle([{ v: c.answer, why: null as L | null }, ...uniq.slice(0, 3)], rand);
  const step: ChoiceStep = {
    ...base,
    id,
    type: "choice",
    prompt,
    options: items.map((x) => String(x.v)),
    correct: items.findIndex((x) => x.v === c.answer),
    whyWrong: items.map((x) => x.why),
  };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x3c6ef372);
  const c = pick(rand, GENS[level])(rand);
  return {
    id: `${c.id}:s${seed % 100000}`,
    skill: SKILL,
    level: c.level,
    prompt: w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`),
    answer: String(c.answer),
    mode: "number",
    explanation: c.explanation,
    hint: c.hint,
  };
}

// ---------- Статичный пул: знания ----------

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

