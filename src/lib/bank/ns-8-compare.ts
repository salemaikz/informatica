const SKILL = "ns.compare";
const w = (ru: string, kk: string): L => ({ ru, kk });

type W = L | null;

function choice(name: string, level: Level, p: { prompt: L; hint: L; options: Text[]; correct: number; why: W[]; explanation: L }): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

function input(name: string, level: Level, p: { prompt: L; hint: L; answer: string; explanation: L; suffix?: string }): InputStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    answers: [p.answer],
    mode: "number",
    suffix: p.suffix,
    explanation: p.explanation,
  };
}

