type W = L | null;

// ====================================================================================================
// Статичный пул «на знание»
// ====================================================================================================

interface PoolChoice {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number;
  why: W[];
  explanation: L;
  scene?: Scene;
}

function q(name: string, level: Level, p: PoolChoice): QuestionStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
    scene: p.scene,
  };
}

interface PoolMulti {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number[];
  why: W[];
  explanation: L;
}

function qm(name: string, level: Level, p: PoolMulti): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

interface PoolInput {
  prompt: L;
  hint: L;
  answer: string;
  explanation: L;
}

function qi(name: string, level: Level, p: PoolInput): InputStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    answers: [p.answer],
    mode: "number",
    explanation: p.explanation,
  };
}

