const pool = poolBank({ skill: SKILL, questions: POOL, statements: STATEMENTS, pairs: PAIRS, shorts: SHORTS });

const pcOs: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed);
    const r = rand();
    if (level === 1) return r < 0.75 ? pool.question(level, seed + 99991) : clusterOne(rand, level, seed);
    if (level === 2) {
      if (r < 0.5) return pool.question(level, seed + 99991);
      const g = rand();
      return g < 0.4 ? clusterMany(rand, level, seed) : fitCheck(rand, level, seed);
    }
    if (r < 0.5) return pool.question(level, seed + 99991);
    const g = rand();
    return g < 0.65 ? clusterList(rand, level, seed) : splitParts(rand, level, seed);
  },
  statement(level, seed): Statement {
    return pool.statement!(level, seed);
  },
  pair(level, seed): Pair {
    return pool.pair!(level, seed);
  },
  short(level, seed): ShortQuestion {
    return pool.short!(level, seed);
  },
};

export const BANKS: SkillBank[] = [pcOs];
