/** choice-задание с одним верным и несколькими неверными вариантами, у каждого неверного — свой разбор. */
function gChoice(
  rand: Rand,
  base: { id: string; level: Level; prompt: L; hint: L; explanation: L; scene?: Scene },
  correct: Text,
  wrongs: { v: Text; why: L }[],
): ChoiceStep {
  const items: { v: Text; why: L | null }[] = [{ v: correct, why: null }, ...wrongs.map((w) => ({ v: w.v, why: w.why as L | null }))];
  const order = shuffle(items, rand);
  return {
    id: base.id,
    type: "choice",
    skill: SKILL,
    level: base.level,
    prompt: base.prompt,
    hint: base.hint,
    scene: base.scene,
    options: order.map((i) => i.v),
    correct: order.findIndex((i) => i.why === null),
    whyWrong: order.map((i) => i.why),
    explanation: base.explanation,
  };
}

function gInput(base: { id: string; level: Level; prompt: L; hint: L; explanation: L }, answer: number): InputStep {
  return { id: base.id, type: "input", skill: SKILL, level: base.level, prompt: base.prompt, hint: base.hint, answers: [String(answer)], mode: "number", explanation: base.explanation };
}

/** Один файл: сколько КБ на диске (уровень A). */
function clusterOne(rand: Rand, level: Level, seed: number): QuestionStep {
  const c = pick(rand, [2, 4, 8]);
  const s = c * int(rand, 1, 4) + int(rand, 1, c - 1);
  const n = ceilDiv(s, c);
  return gInput(
    {
      id: `g:${SKILL}:cl1:${s}-${c}:${seed}`,
      level,
      prompt: l(`Размер кластера — ${c} КБ. Сколько КБ на диске занимает файл размером ${s} КБ? Введи число.`, `Кластер көлемі — ${c} КБ. Көлемі ${s} КБ файл дискіде неше КБ орын алады? Санды енгіз.`),
      hint: CLUSTER_HINT,
      explanation: l(
        `${s} : ${c} = ${dec(s / c)}, округляем вверх до ${n}. Занято ${n} · ${c} = ${n * c} КБ. Ловушка: ${s} КБ — это размер файла, а на диске он занимает целые кластеры.`,
        `${s} : ${c} = ${dec(s / c)}, ${n} санына дейін жоғары қарай дөңгелектейміз. Алынған орын: ${n} · ${c} = ${n * c} КБ. Тұзақ: ${s} КБ — файл көлемі, ал дискіде ол бүтін кластерлерді алады.`,
      ),
    },
    n * c,
  );
}

/** Несколько одинаковых файлов (уровень B). */
function clusterMany(rand: Rand, level: Level, seed: number): QuestionStep {
  const c = pick(rand, [2, 4, 8]);
  const s = c * int(rand, 0, 3) + int(rand, 1, c - 1);
  const k = int(rand, 3, 9);
  const n = ceilDiv(s, c);
  return gInput(
    {
      id: `g:${SKILL}:clmany:${k}x${s}-${c}:${seed}`,
      level,
      prompt: l(`Размер кластера — ${c} КБ. Сколько КБ на диске занимают ${k} файлов по ${s} КБ каждый? Введи число.`, `Кластер көлемі — ${c} КБ. Әрқайсысы ${s} КБ ${k} файл дискіде неше КБ орын алады? Санды енгіз.`),
      hint: CLUSTER_HINT,
      explanation: l(
        `Один файл: ⌈${s} : ${c}⌉ = ${n}, то есть ${n} · ${c} = ${n * c} КБ. Все файлы: ${k} · ${n * c} = ${k * n * c} КБ. Ловушка: ${k} · ${s} = ${k * s} КБ — это сумма размеров, а не место на диске.`,
        `Бір файл: ⌈${s} : ${c}⌉ = ${n}, яғни ${n} · ${c} = ${n * c} КБ. Барлық файл: ${k} · ${n * c} = ${k * n * c} КБ. Тұзақ: ${k} · ${s} = ${k * s} КБ — бұл көлемдер қосындысы, дискідегі орын емес.`,
      ),
    },
    k * n * c,
  );
}

