/** Объединение двух: |A| + |B| − |A ∩ B|. */
function unionQ(name: string, a: number, b: number, ab: number, text: L): InputStep {
  const r = a + b - ab;
  return inputQ(
    `union-${name}`,
    1,
    text,
    r,
    HINT_FORMULA,
    {
      ru: `Общих посчитали дважды, поэтому вычитаем их один раз: |A ∪ B| = |A| + |B| − |A ∩ B| = ${a} + ${b} − ${ab} = ${r}.`,
      kk: `Ортақтар екі рет саналды, сондықтан оларды бір рет шегереміз: |A ∪ B| = |A| + |B| − |A ∩ B| = ${a} + ${b} − ${ab} = ${r}.`,
    },
  );
}

