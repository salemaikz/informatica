/** Выбор: первый вариант верный (пул сам перемешает варианты вместе с whyWrong). */
function choiceQ(
  name: string,
  level: Level,
  prompt: L,
  correct: Text,
  wrong: { v: Text; why: L }[],
  hint: L,
  explanation: L,
  scene?: Scene,
): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    ...(scene ? { scene } : {}),
    options: [correct, ...wrong.map((w) => w.v)],
    correct: 0,
    whyWrong: [null, ...wrong.map((w) => w.why)],
    hint,
    explanation,
  };
}

/** Несколько верных: ok — верный ли вариант; why — почему неверен. */
function multiQ(name: string, level: Level, prompt: L, items: { v: Text; ok: boolean; why?: L }[], hint: L, explanation: L, scene?: Scene): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    ...(scene ? { scene } : {}),
    options: items.map((i) => i.v),
    correct: items.flatMap((i, k) => (i.ok ? [k] : [])),
    whyWrong: items.map((i) => (i.ok ? null : (i.why ?? null))),
    hint,
    explanation,
  };
}

function inputQ(name: string, level: Level, prompt: L, answer: number, hint: L, explanation: L, scene?: Scene): InputStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "input",
    skill: SKILL,
    level,
    prompt,
    ...(scene ? { scene } : {}),
    answers: [String(answer)],
    mode: "number",
    hint,
    explanation,
  };
}

