interface ChoiceArgs {
  name: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  reveal?: Scene;
  correct: Text;
  wrongs: [Text, L][];
  hint: L;
  explanation: L;
}

function choice(a: ChoiceArgs): ChoiceStep {
  return {
    id: id(a.name),
    type: "choice",
    skill: SKILL,
    level: a.level,
    prompt: a.prompt,
    scene: a.scene,
    reveal: a.reveal,
    options: [a.correct, ...a.wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...a.wrongs.map((x) => x[1])],
    hint: a.hint,
    explanation: a.explanation,
  };
}

interface InputArgs {
  name: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  answer: number | string;
  hint: L;
  explanation: L;
}

function input(a: InputArgs): InputStep {
  return {
    id: id(a.name),
    type: "input",
    skill: SKILL,
    level: a.level,
    prompt: a.prompt,
    scene: a.scene,
    answers: [String(a.answer)],
    mode: "number",
    hint: a.hint,
    explanation: a.explanation,
  };
}

function multi(name: string, level: Level, prompt: L, opts: { t: Text; ok: boolean; why?: L }[], hint: L, explanation: L, scene?: Scene): MultiStep {
  return {
    id: id(name),
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: opts.map((o) => o.t),
    correct: opts.flatMap((o, i) => (o.ok ? [i] : [])),
    whyWrong: opts.map((o) => (o.ok ? null : (o.why ?? null))),
    hint,
    explanation,
  };
}

