/** Пузырёк: k проходов; внутренний цикл каждого прохода идёт по n − 1 − p парам (или по всем парам, если full). */
function bubble(a: readonly number[], passes: number, full = false): number[] {
  const x = [...a];
  for (let p = 0; p < passes && p < x.length; p++) {
    const end = full ? x.length - 1 : x.length - 1 - p;
    for (let i = 0; i < end; i++) if (x[i] > x[i + 1]) [x[i], x[i + 1]] = [x[i + 1], x[i]];
  }
  return x;
}

/** Выбор: k проходов. */
function select(a: readonly number[], passes: number): number[] {
  const x = [...a];
  for (let p = 0; p < passes && p < x.length - 1; p++) {
    let m = p;
    for (let j = p + 1; j < x.length; j++) if (x[j] < x[m]) m = j;
    [x[p], x[m]] = [x[m], x[p]];
  }
  return x;
}

/** «Неправильные пары» — столько обменов делает пузырёк. */
const inversions = (a: readonly number[]) => a.reduce((s, x, i) => s + a.slice(i + 1).filter((y) => y < x).length, 0);

/** Сравнений пузырька без досрочного выхода: n(n − 1) / 2. */
const pairsCount = (n: number) => (n * (n - 1)) / 2;

/** Наименьшее число проходов, после которого пузырёк даёт упорядоченный список. */
function passesToSort(a: readonly number[]): number {
  const sorted = [...a].sort((x, y) => x - y).join();
  let k = 0;
  while (bubble(a, k).join() !== sorted) k++;
  return k;
}

/** Число проходов программы с флагом «были обмены» (последний проход — без обменов). */
function flagPasses(a: readonly number[]): number {
  const x = [...a];
  let p = 0;
  let swapped = true;
  while (swapped) {
    swapped = false;
    p++;
    for (let i = 0; i < x.length - 1; i++) {
      if (x[i] > x[i + 1]) {
        [x[i], x[i + 1]] = [x[i + 1], x[i]];
        swapped = true;
      }
    }
  }
  return p;
}

/** sorted(words, key=len): сортировка устойчивая, при reverse=True равные тоже остаются в исходном порядке. */
const byLen = (words: readonly string[], reverse = false) => [...words].sort((x, y) => (reverse ? y.length - x.length : x.length - y.length));
/** sorted(строки): посимвольное сравнение (для ASCII совпадает с Python). */
const strSorted = (a: readonly string[], reverse = false) => [...a].sort((x, y) => (x < y ? -1 : x > y ? 1 : 0) * (reverse ? -1 : 1));

const asc = (a: readonly number[]) => [...a].sort((x, y) => x - y);
const desc = (a: readonly number[]) => asc(a).reverse();

