const SKILL = "net.speed";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];

/** Число с неразрывными пробелами между тысячами: 1 075 200. */
const nf = (n: number) => (n >= 10000 ? String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ") : String(n));

/** Русское склонение: 2 раза, 5 раз. */
const timesRu = (n: number) => (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? "раза" : "раз");

interface Wrong {
  v: number;
  why: L;
}

interface Task {
  kind: string;
  params: string;
  /** Условие без вопроса. */
  stem: L;
  /** Вопрос. */
  ask: L;
  /** Подпись искомой величины для утверждения «верно / неверно». */
  claimWord: L;
  answer: number;
  /** Единица ответа: «с», «байт», «Кбит/с». */
  unit: string;
  explanation: L;
  hint: L;
  wrongs: Wrong[];
  mode: "choice" | "input";
  scene?: Scene;
  /** Пара «условие ↔ ответ» для игр на соответствие. */
  pair?: { left: Text; right: string };
}

