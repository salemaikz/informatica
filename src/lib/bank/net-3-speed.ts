// не переведены байты в биты, не переведены минуты в секунды, лишний ×8, сложены скорости, забыт этап архивации.
// Параметры задачи зашиты в id (g:net.speed:<вид>:<параметры>:<seed>) — по ним ответы перепроверены независимо
// (scripts/out/net-3-speed/verify_bank.py).
