function toPair(level: Level, seed: number): Pair {
  const rand = seeded(seed);
  if (level === 1) {
    const i = int(rand, 0, UNIT_PAIRS.length - 1);
    return { id: `p:${SKILL}:u:${i}`, skill: SKILL, level, ...UNIT_PAIRS[i] };
  }
  if (level === 2) {
    const i = int(rand, 0, POW_PAIRS.length - 1);
    return { id: `p:${SKILL}:p:${i}`, skill: SKILL, level, ...POW_PAIRS[i] };
  }
  const task = tKbyteByte(rand);
  return { id: `p:${SKILL}:t:${task.params}`, skill: SKILL, level, left: task.pair!.left, right: task.pair!.right };
}

