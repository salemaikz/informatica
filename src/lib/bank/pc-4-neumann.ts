const CALCS: Record<Level, ((rand: Rand, level: Level) => Calc)[]> = {
  1: [calcRange, calcBytesPer, calcToy],
  2: [calcRange, calcLast, calcPerAccess, calcToy],
  3: [calcToy, calcRoundUp, calcTransfersKb, calcWord],
};

/** Для short: без учебных программ (у короткого вопроса нет схемы-условия). */
const SHORT_CALCS: Record<Level, ((rand: Rand, level: Level) => Calc)[]> = {
  1: [calcRange, calcBytesPer],
  2: [calcRange, calcLast, calcPerAccess],
  3: [calcRoundUp, calcTransfersKb, calcWord],
};

/** Правильный + три разных неверных (из типичных ошибок), порядок перемешан по seed. */
function buildOptions(rand: Rand, calc: Calc): { options: string[]; correct: number; whyWrong: (L | null)[] } {
  const seen = new Set<string>([calc.answer]);
  const picked: Wrong[] = [];
  for (const wr of shuffle(calc.wrongs, rand)) {
    if (picked.length >= 3) break;
    if (!seen.has(wr.v) && Number(wr.v) > 0) {
      seen.add(wr.v);
      picked.push(wr);
    }
  }
  const all = shuffle<{ v: string; why: L | null }>([{ v: calc.answer, why: null }, ...picked], rand);
  return { options: all.map((a) => a.v), correct: all.findIndex((a) => a.why === null), whyWrong: all.map((a) => a.why) };
}

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const calc = pick(rand, CALCS[level])(rand, level);
  const head = { id: `${calc.id}:${seed}`, skill: SKILL, level, prompt: calc.prompt, hint: calc.hint, explanation: calc.explanation, scene: calc.scene };
  if (rand() < 0.5) {
    const step: InputStep = { ...head, type: "input", answers: [calc.answer], mode: "number" };
    return step;
  }
  const step: ChoiceStep = { ...head, type: "choice", ...buildOptions(rand, calc) };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x51ed270b);
  const calc = pick(rand, SHORT_CALCS[level])(rand, level);
  return {
    id: `${calc.id}:${seed}`,
    skill: SKILL,
    level,
    prompt: calc.prompt,
    answer: calc.answer,
    mode: "number",
    explanation: calc.explanation,
    hint: calc.hint,
  };
}

