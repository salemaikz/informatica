/** C: наименьшее число разрядов шины адреса для объёма, который не степень двойки. */
function calcRoundUp(rand: Rand): Calc {
  const unit: Unit = pick(rand, ["Кбайт", "Мбайт", "Гбайт"]);
  const m = pick(rand, unit === "Гбайт" ? [3, 5, 6, 12] : [3, 5, 6, 7, 9, 10, 12, 24, 48, 100]);
  const base = UNIT_BASE[unit];
  const bytes = m * 2 ** base;
  let k = 0;
  while (2 ** k < bytes) k++;
  return {
    id: `g:${SKILL}:roundup:${m}${unit}`,
    prompt: w(
      `Нужно адресовать ${m} ${unit} памяти (ячейка — 1 байт). Какое наименьшее число разрядов должно быть у шины адреса?`,
      `${m} ${unit} жадты мекенжайлау керек (ұяшық — 1 байт). Мекенжай шинасында ең аз дегенде неше разряд болуы керек?`,
    ),
    answer: String(k),
    wrongs: [
      { v: String(k - 1), why: w(`Округлено вниз: при ${k - 1} разрядах адресов только 2${sup(k - 1)}, а нужно больше.`, `Төмен қарай дөңгелектелген: ${k - 1} разряд тек 2${sup(k - 1)} мекенжай береді, ал көбірек керек.`) },
      { v: String(k + 1), why: w(`Лишний разряд: при ${k} разрядах адресов уже хватает, а нужно наименьшее число разрядов.`, `Артық разряд: ${k} разряд жетеді, ал разрядтардың ең аз саны керек.`) },
      { v: String(m), why: w("Это число из условия, а не число разрядов.", "Бұл — шарттағы сан, разрядтар саны емес.") },
      { v: String(base), why: w(`${base} разрядов хватает только на 1 ${unit}, а нужно больше.`, `${base} разряд тек 1 ${unit} үшін жетеді, ал көбірек керек.`) },
    ],
    hint: w(
      "Запиши объём в байтах через 2¹⁰, 2²⁰ или 2³⁰ и найди ближайшую степень двойки, которая не меньше этого объёма.",
      "Көлемді байтпен 2¹⁰, 2²⁰ немесе 2³⁰ арқылы жаз да, осы көлемнен кем емес ең жақын екінің дәрежесін тап.",
    ),
    explanation: w(
      `${m} ${unit} = ${m} · 2${sup(base)} байт. Степень двойки: 2${sup(k - 1)} < ${m} · 2${sup(base)} ≤ 2${sup(k)}. Объём не степень двойки, поэтому округляем вверх. Ответ: ${k}.`,
      `${m} ${unit} = ${m} · 2${sup(base)} байт. Екінің дәрежесі: 2${sup(k - 1)} < ${m} · 2${sup(base)} ≤ 2${sup(k)}. Көлем екінің дәрежесі емес, сондықтан жоғары қарай дөңгелектейміз. Жауабы: ${k}.`,
    ),
  };
}

