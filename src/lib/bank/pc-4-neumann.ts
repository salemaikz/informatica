const neumann: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed ^ 0x9e3779b1);
    // Около 40% заданий — расчётные (ячейки «от и до», обращения, учебная программа), остальные — знания из пула.
    if (rand() < 0.4) return calcQuestion(level, rand, seed);
    return pool.question(level, seed);
  },
  statement: pool.statement,
  pair: pool.pair,
  short(level, seed) {
    const rand = seeded(seed ^ 0x2545f491);
    return rand() < 0.5 ? calcShort(level, seed) : pool.short!(level, seed);
  },
};

