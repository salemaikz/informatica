const TOY_KK = "Оқу процессоры: LOAD n — n ұяшығындағы санды аккумуляторға алу; ADD n және SUB n — аккумуляторға n ұяшығындағы санды қосу немесе одан алу; STORE n — аккумуляторды n ұяшығына жазу (аккумулятор өзгермейді); STOP — тоқтау.";

const codeScene = (lines: string[], caption: L): Scene => ({ kind: "code", lang: "text", lines, caption });

/** A и B: сколько ячеек занимает программа, записанная в ячейках от a до b включительно. */
function calcRange(rand: Rand, level: Level): Calc {
  const a = level === 1 ? int(rand, 3, 20) : int(rand, 20, 400);
  const n = level === 1 ? int(rand, 5, 15) : int(rand, 20, 120);
  const b = a + n - 1;
  return {
    id: `g:${SKILL}:range:${a}-${b}`,
    prompt: w(
      `Программа записана в ячейках с адресами от ${a} до ${b} включительно. Сколько ячеек она занимает?`,
      `Программа қатар тұрған ұяшықтарға жазылған: бірінші ұяшықтың мекенжайы — ${a}, соңғысының мекенжайы — ${b} (екеуі де кіреді). Программа неше ұяшық алады?`,
    ),
    answer: String(n),
    wrongs: [
      { v: String(b - a), why: w("Разность не учитывает одну крайнюю ячейку: оба конца входят в диапазон, к разности надо прибавить 1.", "Айырма бір шеткі ұяшықты есепке алмайды: екі шеті де диапазонға кіреді, айырмаға 1 қосу керек.") },
      { v: String(b - a + 2), why: w("Прибавлена лишняя единица: нужно b − a + 1.", "Артық бірлік қосылған: b − a + 1 керек.") },
      { v: String(b), why: w("Это адрес последней ячейки, а не количество ячеек.", "Бұл — соңғы ұяшықтың мекенжайы, ұяшықтар саны емес.") },
      { v: String(a + b), why: w("Адреса не складывают: количество ячеек — это b − a + 1.", "Мекенжайларды қоспайды: ұяшықтар саны — b − a + 1.") },
    ],
    hint: w(
      "Проверь на маленьком примере: ячейки от 1 до 3 — сколько их? А чему равна разность 3 − 1?",
      "Кішкентай мысалмен тексер: 1 мен 3 аралығындағы ұяшықтар неше? Ал 3 − 1 айырмасы неге тең?",
    ),
    explanation: w(
      `Оба конца входят в диапазон, поэтому число ячеек: ${b} − ${a} + 1 = ${n}. Просто разность ${b} − ${a} = ${b - a} не учитывает первую ячейку.`,
      `Екі шеті де диапазонға кіреді: ${b} − ${a} + 1 = ${n} ұяшық. Жай айырма ${b} − ${a} = ${b - a} бірінші ұяшықты есепке алмайды.`,
    ),
  };
}

/** A: сколько байт передаётся за одно обращение по шине данных. */
function calcBytesPer(rand: Rand): Calc {
  const bits = pick(rand, [8, 16, 32, 64]);
  const bytes = bits / 8;
  return {
    id: `g:${SKILL}:bytesper:${bits}`,
    prompt: w(
      `Шина данных ${bits}-разрядная. Сколько байт передаётся за одно обращение?`,
      `Деректер шинасы ${bits} разрядты. Бір жүгінуде неше байт беріледі?`,
    ),
    answer: String(bytes),
    wrongs: [
      { v: String(bits), why: w("Это число бит, а в байте 8 бит: нужно разделить на 8.", "Бұл — биттер саны, ал байтта 8 бит бар: 8-ге бөлу керек.") },
      { v: String(bits * 8), why: w("Умножать на 8 не надо: из бит в байты переходят делением на 8.", "8-ге көбейту қажет емес: биттен байтқа 8-ге бөлу арқылы өтеді.") },
      { v: String(bytes * 2), why: w("Лишнее удвоение: байтов столько, сколько восьмёрок бит в шине.", "Артық екі еселеу: байт саны шинадағы биттердегі сегіздіктер санына тең.") },
    ],
    hint: w("В одном байте 8 бит. Сколько байтов помещается в шину такой ширины?", "Бір байтта 8 бит бар. Мұндай разрядтылықтағы шинаға неше байт сияды?"),
    explanation: w(
      `${bits} бит : 8 = ${bytes} байт за одно обращение.`,
      `${bits} бит : 8 = ${bytes} байт бір жүгінуде.`,
    ),
  };
}

/** B: сколько обращений нужно, чтобы передать V байт по шине данных ширины bits. */
function calcPerAccess(rand: Rand): Calc {
  const bits = pick(rand, [16, 32, 64]);
  const total = pick(rand, [64, 128, 256, 512]);
  const bytes = bits / 8;
  const n = total / bytes;
  return {
    id: `g:${SKILL}:peraccess:${bits}-${total}`,
    prompt: w(
      `Шина данных ${bits}-разрядная. Сколько обращений к памяти нужно, чтобы передать ${total} байт?`,
      `Деректер шинасы ${bits} разрядты. ${total} байтты жіберу үшін жадқа неше рет жүгіну керек?`,
    ),
    answer: String(n),
    wrongs: [
      { v: String(total), why: w("Так получилось бы, если бы за раз шёл только один байт. Шина передаёт больше.", "Бұл бір мезгілде тек бір байт жүрсе ғана болар еді. Шина көбірек береді.") },
      { v: String(total / bits), why: w("Байты поделены на ширину шины в битах: единицы надо привести к одним (бит : 8 = байт).", "Байттар шинаның биттегі разрядтылығына бөлінген: бірліктерді біріне келтіру керек (бит : 8 = байт).") },
      { v: String(n * 2), why: w("Лишнее удвоение: проверь, сколько байт идёт за одно обращение.", "Артық екі еселеу: бір жүгінуде неше байт жүретінін тексер.") },
      { v: String(n / 2), why: w("Шина принята вдвое шире, чем в условии: проверь деление бит на 8.", "Шина шарттағыдан екі есе кең деп алынған: битті 8-ге бөлуді тексер.") },
    ],
    hint: w(
      "Сначала узнай, сколько байт едет за одно обращение (бит : 8), потом раздели весь объём на эту порцию.",
      "Алдымен бір жүгінуде неше байт жүретінін біл (бит : 8), содан кейін бүкіл көлемді осы үлеске бөл.",
    ),
    explanation: w(
      `За одно обращение идёт ${bits} : 8 = ${bytes} байт. Всего ${total} байт, значит число обращений: ${total} : ${bytes} = ${n}.`,
      `Бір жүгінуде ${bits} : 8 = ${bytes} байт жүреді. Барлығы ${total} байт, демек жүгіну саны: ${total} : ${bytes} = ${n}.`,
    ),
  };
}

/** B: номер последней ячейки при k разрядах адреса (нумерация с нуля). */
function calcLast(rand: Rand): Calc {
  const k = int(rand, 4, 10);
  const n = 2 ** k;
  return {
    id: `g:${SKILL}:last:${k}`,
    prompt: w(
      `Шина адреса ${k}-разрядная, ячейки нумеруются с нуля. Какой номер у последней ячейки?`,
      `Мекенжай шинасы ${k} разрядты, ұяшықтар нөлден бастап нөмірленеді. Соңғы ұяшықтың нөмірі қандай?`,
    ),
    answer: String(n - 1),
    wrongs: [
      { v: String(n), why: w(`Ячеек ${n}, но номера идут с нуля, поэтому у последней номер на 1 меньше.`, `Ұяшық ${n}, бірақ нөмірлер нөлден басталады, сондықтан соңғысының нөмірі 1-ге кем.`) },
      { v: String(n / 2), why: w(`Это число ячеек при ${k - 1} разрядах, а здесь на один разряд больше.`, `Бұл — ${k - 1} разрядтағы ұяшықтар саны, ал мұнда бір разряд артық.`) },
      { v: String(2 * k), why: w("Разряды не умножают на 2: число ячеек — 2 в степени разрядов.", "Разрядтарды 2-ге көбейтпейді: ұяшықтар саны — разрядтардың 2 дәрежесі.") },
      { v: String(k), why: w("Это число разрядов, а не номер ячейки.", "Бұл — разрядтар саны, ұяшық нөмірі емес.") },
    ],
    hint: w(
      "Сначала найди, сколько всего ячеек (2 в степени разрядов). Нумерация начинается с 0, а не с 1.",
      "Алдымен барлығы неше ұяшық екенін тап (разрядтардың 2 дәрежесі). Нөмірлеу 1-ден емес, 0-ден басталады.",
    ),
    explanation: w(
      `Ячеек 2${sup(k)} = ${n}. Нумерация идёт с 0, значит номера от 0 до ${n} − 1 = ${n - 1}.`,
      `Ұяшық 2${sup(k)} = ${n}. Нөмірлеу нөлден басталады, демек соңғы нөмір: ${n} − 1 = ${n - 1}.`,
    ),
  };
}

