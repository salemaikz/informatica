// Знания (четыре принципа, регистры, шины, учебный процессор) — статичный пул.
// Расчёты — генераторы: ячейки «от и до», последний адрес, обращения по шине данных, учебная программа (LOAD/ADD/SUB/STORE),
// округление числа разрядов вверх, ячейка из 2 байт. Правильный ответ всегда считает код.
// Тексты после переменных чисел — без падежных окончаний (в казахском окончание зависит от числа).

const SKILL = "pc.neumann";

const w = (ru: string, kk: string): L => ({ ru, kk });
const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];

/** Верхний индекс для степени: sup(16) → «¹⁶». */
const sup = (n: number) =>
  String(n)
    .split("")
    .map((d) => "⁰¹²³⁴⁵⁶⁷⁸⁹"[Number(d)])
    .join("");

type Unit = "Кбайт" | "Мбайт" | "Гбайт";
const UNIT_BASE: Record<Unit, number> = { Кбайт: 10, Мбайт: 20, Гбайт: 30 };

