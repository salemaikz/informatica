function input(o: { id: string; level: Level; prompt: L; answer: number; suffix?: string; explanation: L; hint: L }): InputStep {
  return {
    type: "input",
    id: o.id,
    skill: SKILL,
    level: o.level,
    prompt: o.prompt,
    answers: [String(o.answer)],
    mode: "number",
    suffix: o.suffix,
    explanation: o.explanation,
    hint: o.hint,
  };
}

type InputGen = (rand: Rand, level: Level, seed: number) => InputStep;

/** Прибыль = выручка − переменные − постоянные. */
const profitGen: InputGen = (rand, level) => {
  const rev = pick(rand, [300000, 400000, 450000, 600000, 800000]);
  const vari = pick(rand, [50000, 80000, 120000, 150000]);
  const fixed = pick(rand, [40000, 60000, 90000, 100000]);
  const profit = rev - vari - fixed;
  return input({
    id: `g:${SKILL}:profit:${rev}:${vari}:${fixed}`,
    level,
    prompt: l(
      `За месяц: выручка ${n(rev)} ₸, переменные расходы ${n(vari)} ₸, постоянные расходы ${n(fixed)} ₸. Чему равна прибыль (в ₸)?`,
      `Бір айда: түсім ${n(rev)} ₸, айнымалы шығындар ${n(vari)} ₸, тұрақты шығындар ${n(fixed)} ₸. Пайда неге тең (₸)?`,
    ),
    answer: profit,
    suffix: "₸",
    explanation: l(
      `Расходы: ${n(vari)} + ${n(fixed)} = ${n(vari + fixed)} ₸. Прибыль = ${n(rev)} − ${n(vari + fixed)} = ${n(profit)} ₸.`,
      `Шығындар: ${n(vari)} + ${n(fixed)} = ${n(vari + fixed)} ₸. Пайда = ${n(rev)} − ${n(vari + fixed)} = ${n(profit)} ₸.`,
    ),
    hint: l("Сложи оба вида расходов и вычти сумму из выручки.", "Шығынның екі түрін қосып, қосындыны түсімнен ал."),
  });
};

/** CAC = расходы на рекламу / число клиентов. */
