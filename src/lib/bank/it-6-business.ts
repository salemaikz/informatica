const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const l = (ru: string, kk: string): L => ({ ru, kk });
/** Число с пробелами между разрядами: 250 000. */
const n = (x: number) => String(x).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
/** Десятичная дробь с запятой: 0,25. */
const dec = (x: number) => String(x).replace(".", ",");

type W = L | null;

// ====================================================================================================
// Статичный пул «на знание»
// ====================================================================================================

interface PoolChoice {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number;
  why: W[];
  explanation: L;
}

function q(name: string, level: Level, p: PoolChoice): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

interface PoolMulti {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number[];
  why: W[];
  explanation: L;
}

function qm(name: string, level: Level, p: PoolMulti): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

