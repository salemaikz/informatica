export const BANKS: SkillBank[] = [
  {
    skill: SKILL,
    question(level, seed) {
      const rand = seeded(seed);
      if (rand() < 0.4) return pick(rand, Q_GENS[level])(rand, level, seed);
      return pool.question(level, seed + 99991);
    },
    statement(level, seed) {
      return pool.statement!(level, seed + 99991);
    },
    pair(level, seed) {
      return pool.pair!(level, seed + 99991);
    },
    short(level, seed) {
      const rand = seeded(seed);
      const fixed = SHORT_STATIC.filter((s) => s.level === level);
      if (fixed.length && rand() < 0.4) return pick(rand, fixed);
      return toShort(pick(rand, Q_GENS[level])(rand, level, seed));
    },
  },
];
