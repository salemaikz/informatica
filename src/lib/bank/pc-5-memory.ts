// Банк навыка pc.memory («Виды памяти», тема ЕНТ t01).
// Знания (кэш L1–L3, SRAM и DRAM, ПЗУ/UEFI, флеш, HDD/SSD, загрузка компьютера) — статичный пул.
// Расчёты — генераторы: время чтения файла (время = объём : скорость), цена за ГБ (отношение цен),
// среднее время доступа с кэшем (попадания · t₁ + промахи · t₂). Правильный ответ всегда считает код.
// Тексты после переменных чисел — без падежных окончаний (в казахском окончание зависит от числа).

const SKILL = "pc.memory";

const w = (ru: string, kk: string): L => ({ ru, kk });
const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
/** Число с неразрывными пробелами между тысячами: 25600 → «25 600». */
const money = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");

// ---------- Расчётные задания ----------

interface Wrong {
  v: string;
  why: L;
}

interface Calc {
  /** Идентификатор «семейства» без seed: g:pc.memory:<вид>:<параметры>. */
  id: string;
  prompt: L;
  answer: string;
  wrongs: Wrong[];
  hint: L;
  explanation: L;
}

/** B: время чтения файла (ГБ → МБ, потом объём : скорость). */
function calcLoad(rand: Rand): Calc {
  const gb = int(rand, 2, 12);
  const speed = pick(rand, [64, 128, 256, 512]);
  const mb = gb * 1024;
  const t = mb / speed;
  return {
    id: `g:${SKILL}:load:${gb}x${speed}`,
    prompt: w(
      `Накопитель читает ${speed} МБ/с. За сколько секунд он прочитает файл размером ${gb} ГБ? (1 ГБ = 1024 МБ)`,
      `Жинақтауыш ${speed} МБ/с жылдамдықпен оқиды. Көлемі ${gb} ГБ файлды неше секундта оқиды? (1 ГБ = 1024 МБ)`,
    ),
    answer: String(t),
    wrongs: [
      { v: String(Math.round(gb * speed)), why: w("Объём и скорость перемножены, а время = объём : скорость.", "Көлем мен жылдамдық көбейтілген, ал уақыт = көлем : жылдамдық.") },
      { v: String(Math.round((gb * 1000) / speed)), why: w("Взято 1000 вместо 1024: для байтов 1 ГБ = 1024 МБ.", "1024 орнына 1000 алынған: байттарда 1 ГБ = 1024 МБ.") },
      { v: String(Math.round(speed / gb)), why: w("Поделено наоборот: скорость на объём, а время = объём : скорость.", "Керісінше бөлінген: жылдамдық көлемге, ал уақыт = көлем : жылдамдық.") },
      { v: String(mb), why: w("Это объём в мегабайтах: его ещё нужно разделить на скорость.", "Бұл — мегабайтпен көлем: оны әлі жылдамдыққа бөлу керек.") },
      { v: String(Math.round((gb / speed) * 100) / 100).replace(".", ","), why: w("Гигабайты не переведены в мегабайты: единицы объёма и скорости должны совпадать.", "Гигабайттар мегабайтқа аударылмаған: көлем мен жылдамдық бірліктері сәйкес болуы керек.") },
    ],
    hint: w(
      "Скорость в МБ/с, а размер в ГБ: сначала приведи их к одной единице, потом дели объём на скорость.",
      "Жылдамдық МБ/с-пен, ал көлем ГБ-пен: алдымен оларды бір бірлікке келтір, сосын көлемді жылдамдыққа бөл.",
    ),
    explanation: w(
      `${gb} ГБ = ${gb} · 1024 = ${mb} МБ. Время = ${mb} : ${speed} = ${t} с.`,
      `${gb} ГБ = ${gb} · 1024 = ${mb} МБ. Уақыт = ${mb} : ${speed} = ${t} с.`,
    ),
  };
}

/** B/C: во сколько раз гигабайт SSD дороже гигабайта HDD. */
function calcPrice(rand: Rand): Calc {
  const ssdGb = pick(rand, [128, 256, 512, 1024]);
  const hddTb = pick(rand, [1, 2, 4]);
  const p2 = pick(rand, [5, 10]);
  const ratio = pick(rand, [4, 5, 6, 8, 10]);
  const p1 = p2 * ratio;
  const hddGb = hddTb * 1024;
  const ssdPrice = p1 * ssdGb;
  const hddPrice = p2 * hddGb;
  const total = Math.round((ssdPrice / hddPrice) * 100) / 100;
  return {
    id: `g:${SKILL}:price:${ssdGb}x${hddTb}x${p1}x${p2}`,
    prompt: w(
      `SSD на ${ssdGb} ГБ стоит ${money(ssdPrice)} ₸, HDD на ${hddTb} ТБ стоит ${money(hddPrice)} ₸ (1 ТБ = 1024 ГБ). Во сколько раз гигабайт SSD дороже гигабайта HDD?`,
      `${ssdGb} ГБ SSD ${money(ssdPrice)} ₸ тұрады, ${hddTb} ТБ HDD ${money(hddPrice)} ₸ тұрады (1 ТБ = 1024 ГБ). SSD-дің бір гигабайты HDD-дің бір гигабайтынан неше есе қымбат?`,
    ),
    answer: String(ratio),
    wrongs: [
      { v: String(p1), why: w("Это цена гигабайта SSD в тенге, а нужно отношение цен гигабайта.", "Бұл — SSD гигабайтының теңгемен бағасы, ал гигабайт бағаларының қатынасы керек.") },
      { v: String(p2), why: w("Это цена гигабайта HDD в тенге, а нужно отношение цен.", "Бұл — HDD гигабайтының теңгемен бағасы, ал бағалардың қатынасы керек.") },
      { v: String(total).replace(".", ","), why: w("Сравнены цены целых накопителей, а объёмы у них разные: нужна цена за 1 ГБ.", "Тұтас жинақтауыштардың бағасы салыстырылған, ал олардың көлемі әртүрлі: 1 ГБ бағасы керек.") },
      { v: String(p1 - p2), why: w("Найдена разность цен за ГБ (на сколько тенге дороже), а спрашивают «во сколько раз» — нужно деление.", "1 ГБ бағаларының айырмасы табылған (қанша теңгеге қымбат), ал сұрақ «неше есе» — бөлу керек.") },
      { v: String(Math.round((p2 / p1) * 100) / 100).replace(".", ","), why: w("Поделено наоборот: дешёвый гигабайт на дорогой. Дорогую цену делят на дешёвую.", "Керісінше бөлінген: арзан гигабайт қымбатына. Қымбат бағаны арзанына бөледі.") },
    ],
    hint: w(
      "Найди цену одного гигабайта для каждого накопителя (цена : объём в ГБ), затем раздели большую на меньшую.",
      "Әр жинақтауыштың бір гигабайтының бағасын тап (баға : көлем ГБ-пен), сосын үлкенін кішісіне бөл.",
    ),
    explanation: w(
      `SSD: ${money(ssdPrice)} : ${ssdGb} = ${p1} ₸ за ГБ. HDD: ${hddTb} ТБ = ${hddGb} ГБ, ${money(hddPrice)} : ${hddGb} = ${p2} ₸ за ГБ. Отношение: ${p1} : ${p2} = ${ratio}.`,
      `SSD: ${money(ssdPrice)} : ${ssdGb} = бір ГБ үшін ${p1} ₸. HDD: ${hddTb} ТБ = ${hddGb} ГБ, ${money(hddPrice)} : ${hddGb} = бір ГБ үшін ${p2} ₸. Қатынасы: ${p1} : ${p2} = ${ratio}.`,
    ),
  };
}

/** C: общее время обращений с кэшем: попадания · t₁ + промахи · t₂. */
function calcCache(rand: Rand): Calc {
  const n = pick(rand, [100, 200, 500]);
  const hits = Math.round(n * pick(rand, [0.8, 0.9, 0.95]));
  const miss = n - hits;
  const t1 = pick(rand, [1, 2, 5]);
  const t2 = pick(rand, [50, 80, 100]);
  const total = hits * t1 + miss * t2;
  return {
    id: `g:${SKILL}:cache:${n}x${hits}x${t1}x${t2}`,
    prompt: w(
      `Процессор сделал ${n} обращений к данным. ${hits} из них нашлись в кэше (время одного обращения ${t1} нс), остальные ушли в ОЗУ (время одного обращения ${t2} нс). Сколько нс заняли все обращения?`,
      `Процессор деректерге ${n} рет жүгінді. Кэштен табылғаны: ${hits} (бір жүгінудің уақыты ${t1} нс). Қалғаны жедел жадқа кетті (бір жүгінудің уақыты ${t2} нс). Барлық жүгінуге неше нс кетті?`,
    ),
    answer: String(total),
    wrongs: [
      { v: String(miss * t2), why: w("Посчитаны только промахи: время попаданий в кэше тоже нужно добавить.", "Тек табылмағандар есептелген: кэштен табылғандардың уақытын да қосу керек.") },
      { v: String(hits * t1), why: w("Посчитаны только попадания: промахи по времени ОЗУ забыты.", "Тек табылғандар есептелген: жедел жадқа кеткен табылмағандар ұмытылған.") },
      { v: String(n * t2), why: w("Так считают, если кэша нет и все обращения идут в ОЗУ.", "Кэш жоқ және барлық жүгіну жедел жадқа кетсе осылай есептейді.") },
      { v: String(n * t1), why: w("Так считают, если все обращения нашлись в кэше, а промахи есть.", "Барлық жүгіну кэштен табылса осылай есептейді, ал табылмағандар бар.") },
      { v: String(hits * t2 + miss * t1), why: w("Времена перепутаны: попадания идут по времени кэша, промахи — по времени ОЗУ.", "Уақыттар шатастырылған: табылғандар кэш уақытымен, табылмағандар жедел жад уақытымен есептеледі.") },
    ],
    hint: w(
      "Сначала найди число промахов (всего − попаданий). Потом посчитай отдельно время попаданий и время промахов и сложи.",
      "Алдымен табылмағандар санын тап (барлығы − табылғандар). Сосын табылғандардың және табылмағандардың уақытын бөлек есептеп, қос.",
    ),
    explanation: w(
      `Промахов: ${n} − ${hits} = ${miss}. Попадания: ${hits} · ${t1} = ${hits * t1} нс. Промахи: ${miss} · ${t2} = ${miss * t2} нс. Всего: ${hits * t1} + ${miss * t2} = ${total} нс.`,
      `Табылмағандар: ${n} − ${hits} = ${miss}. Табылғандар: ${hits} · ${t1} = ${hits * t1} нс. Табылмағандар: ${miss} · ${t2} = ${miss * t2} нс. Барлығы: ${hits * t1} + ${miss * t2} = ${total} нс.`,
    ),
  };
}

/** C (обратная задача): по общему времени найти число промахов. промахи = (T − n · t₁) : (t₂ − t₁). */
function calcCacheInverse(rand: Rand): Calc {
  const n = pick(rand, [100, 200, 500]);
  const miss = pick(rand, [10, 20, 25, 40, 50]);
  const t1 = pick(rand, [1, 2, 5]);
  const t2 = pick(rand, [50, 80, 100]);
  const total = (n - miss) * t1 + miss * t2;
  const base = n * t1;
  const fmt = (x: number) => String(Math.round(x * 100) / 100).replace(".", ",");
  return {
    id: `g:${SKILL}:cache-inv:${n}x${miss}x${t1}x${t2}`,
    prompt: w(
      `Процессор сделал ${n} обращений к данным. Обращение к кэшу занимает ${t1} нс, а промах (обращение к ОЗУ) — ${t2} нс. Все обращения заняли ${total} нс. Сколько было промахов?`,
      `Процессор деректерге ${n} рет жүгінді. Кэшке жүгіну ${t1} нс алады, ал кэштен табылмаған жүгіну (жедел жадқа жүгіну) — ${t2} нс. Барлық жүгіну ${total} нс алды. Кэштен неше жүгіну табылмады?`,
    ),
    answer: String(miss),
    wrongs: [
      { v: String(n - miss), why: w("Это число попаданий, а спрашивают про промахи.", "Бұл — табылғандар саны, ал сұрақ табылмағандар туралы.") },
      { v: fmt(total / t2), why: w("Всё время поделено на время промаха, а попадания тоже заняли время.", "Бүкіл уақыт табылмау уақытына бөлінген, ал табылғандар да уақыт алды.") },
      { v: fmt((total - base) / t2), why: w("Лишнее время поделено на t₂, а промах добавляет к попаданию только t₂ − t₁.", "Артық уақыт t₂-ге бөлінген, ал табылмау табылуға қарағанда тек t₂ − t₁ қосады.") },
      { v: String(total - base), why: w("Это лишнее время в нс: его ещё нужно разделить на t₂ − t₁.", "Бұл — нс-пен артық уақыт: оны әлі t₂ − t₁ айырмасына бөлу керек.") },
    ],
    hint: w(
      "Представь, что все обращения — попадания: сколько времени это заняло бы? Сколько добавляет к этому каждый промах?",
      "Барлық жүгіну кэштен табылды деп елестет: оған қанша уақыт кетер еді? Әр табылмау бұған қанша қосады?",
    ),
    explanation: w(
      `Если бы все были попаданиями: ${n} · ${t1} = ${base} нс. Лишнее время: ${total} − ${base} = ${total - base} нс. Каждый промах добавляет ${t2} − ${t1} = ${t2 - t1} нс. Промахов: ${total - base} : ${t2 - t1} = ${miss}.`,
      `Бәрі кэштен табылса: ${n} · ${t1} = ${base} нс. Артық уақыт: ${total} − ${base} = ${total - base} нс. Әр табылмау ${t2} − ${t1} = ${t2 - t1} нс қосады. Табылмағандар саны: ${total - base} : ${t2 - t1} = ${miss}.`,
    ),
  };
}

const CALCS: Record<Level, ((rand: Rand) => Calc)[]> = {
  1: [],
  2: [calcLoad, calcLoad, calcPrice],
  3: [calcCache, calcPrice, calcCacheInverse],
};

/** Правильный + три разных неверных (из типичных ошибок), порядок перемешан по seed. */
function buildOptions(rand: Rand, calc: Calc): { options: string[]; correct: number; whyWrong: (L | null)[] } {
  const seen = new Set<string>([calc.answer]);
  const picked: Wrong[] = [];
  for (const wr of shuffle(calc.wrongs, rand)) {
    if (picked.length >= 3) break;
    if (!seen.has(wr.v)) {
      seen.add(wr.v);
      picked.push(wr);
    }
  }
  const all = shuffle<{ v: string; why: L | null }>([{ v: calc.answer, why: null }, ...picked], rand);
  return { options: all.map((a) => a.v), correct: all.findIndex((a) => a.why === null), whyWrong: all.map((a) => a.why) };
}

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const calc = pick(rand, CALCS[level])(rand);
  const head = { id: `${calc.id}:${seed}`, skill: SKILL, level, prompt: calc.prompt, hint: calc.hint, explanation: calc.explanation };
  if (rand() < 0.5) {
    const step: InputStep = { ...head, type: "input", answers: [calc.answer], mode: "number" };
    return step;
  }
  const step: ChoiceStep = { ...head, type: "choice", ...buildOptions(rand, calc) };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x51ed270b);
  const calc = pick(rand, CALCS[level])(rand);
  return {
    id: `${calc.id}:${seed}`,
    skill: SKILL,
    level,
    prompt: calc.prompt,
    answer: calc.answer,
    mode: "number",
    explanation: calc.explanation,
    hint: calc.hint,
  };
}

