/** Сцена «код» (опционально: текущая строка, отмеченные строки, значения, вывод). */
function pc(lines: string[], opt: { active?: number; marks?: number[]; vars?: [string, string][]; output?: string[]; caption?: L } = {}): Scene {
  return {
    kind: "code",
    lang: "python",
    lines,
    active: opt.active,
    marks: opt.marks,
    vars: opt.vars?.map(([name, value]) => ({ name, value })),
    output: opt.output,
    caption: opt.caption,
  };
}

// ---------- Конструкторы заданий ----------

/** Выбор одного ответа: верный первым — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene, reveal?: Scene): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    reveal,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [Text, boolean, L?][], explanation: L, hint: L, scene?: Scene): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

/** Соответствие: справа без повторов. */
function ma(id: string, level: Level, prompt: L, pairs: [Text, Text][], explanation: L, hint: L): MatchStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "match",
    skill: SKILL,
    level,
    prompt,
    pairs: pairs.map(([left, right]) => ({ left, right })),
    explanation,
    hint,
  };
}

/** Порядок: элементы в правильной последовательности. */
function or(id: string, level: Level, prompt: L, items: L[], explanation: L, hint: L): OrderStep {
  return { id: `p:${SKILL}:${id}`, type: "order", skill: SKILL, level, prompt, items, explanation, hint };
}

/** Ввод ответа: программа в сцене, ответ — число или короткий текст. */
function inp(id: string, level: Level, prompt: L, scene: Scene, answers: string[], mode: "number" | "text", explanation: L, hint: L, reveal?: Scene): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, reveal, answers, mode, explanation, hint };
}

