const convRu = (terms: Term[]) => (conv(terms) ? `Приводим к степеням двойки: ${conv(terms)}. ` : "");
const convKk = (terms: Term[]) => (conv(terms) ? `Екінің дәрежелеріне келтіреміз: ${conv(terms)}. ` : "");
const exps = (terms: Term[]) => terms.map((t) => twoExp(t) ?? 0);
export const L2 = (a: L, b: L): L => T(`${a.ru} ${b.ru}`, `${a.kk} ${b.kk}`);

/** Сумма степеней двойки с разными показателями: единиц столько, сколько слагаемых. */
export function howSum(terms: Term[]): L {
  const f = facts(terms);
  const ex = exps(terms);
  const list = [...ex].sort((a, b) => b - a).join(", ");
  const max = Math.max(...ex);
  return T(
    `${convRu(terms)}Показатели: ${list} — все разные, значит, каждое слагаемое ставит свою единицу и склеиваться им не с чем. Единиц столько, сколько слагаемых: ${terms.length}. Старшая единица стоит на разряде с номером ${max}, поэтому цифр ${max} + 1 = ${f.digits}, а нулей ${f.digits} − ${terms.length} = ${f.zeros}.`,
    `${convKk(terms)}Көрсеткіштер: ${list} — бәрі әртүрлі, демек әр қосылғыш өз бірлігін қояды да, қосылып кететін ештеңе жоқ. Бірлік қосылғыштар санындай: ${terms.length}. Ең үлкен бірлік нөмірі ${max} болатын разрядта тұр, сондықтан цифр саны ${max} + 1 = ${f.digits}, ал нөлдер ${f.digits} − ${terms.length} = ${f.zeros}.`,
  );
}

/** Одна степень: единица и n нулей. */
export function howPow(terms: Term[]): L {
  const n = twoExp(terms[0]) ?? 0;
  return T(
    `${convRu(terms)}2${sup(n)} — это единица и ${nZeros(n).ru}; цифр в записи ${n} + 1 = ${n + 1}.`,
    `${convKk(terms)}2${sup(n)} — бір бірлік және ${n} нөл; жазбадағы цифр саны ${n} + 1 = ${n + 1}.`,
  );
}

/** 2ⁿ − 1: одни единицы. */
export function howAll1(terms: Term[]): L {
  const n = twoExp(terms[0]) ?? 0;
  return T(
    `${convRu(terms)}2${sup(n)} − 1 записывается одними единицами: ${n} единиц, нулей нет, цифр тоже ${n}.`,
    `${convKk(terms)}2${sup(n)} − 1 тек бірліктен тұратын жазба: ${n} бірлік, нөл жоқ, цифр да ${n}.`,
  );
}

/** 2ⁿ − 2ᵐ: n − m единиц подряд, затем m нулей. */
export function howDiff(terms: Term[]): L {
  const n = twoExp(terms[0]) ?? 0;
  const m = twoExp(terms[1]) ?? 0;
  return T(
    `${convRu(terms)}Выносим 2${sup(m)} за скобку: 2${sup(n)} − 2${sup(m)} = 2${sup(m)} · (2${sup(n - m)} − 1). В скобке ${nOnes(n - m).ru} подряд, а умножение на 2${sup(m)} дописывает справа ${nZeros(m).ru}. Единиц ${n - m}, нулей ${m}, цифр ${n}.`,
    `${convKk(terms)}2${sup(m)} санын жақшаның сыртына шығарамыз: 2${sup(n)} − 2${sup(m)} = 2${sup(m)} · (2${sup(n - m)} − 1). Жақшада қатар тұрған ${n - m} бірлік, ал 2${sup(m)} санына көбейту оң жаққа ${m} нөл жазады. Бірлік ${n - m}, нөл ${m}, цифр ${n}.`,
  );
}

/** 2ⁿ + 2ᵐ − 1 (n > m): единица на разряде n и m единиц подряд справа. */
export function howMix(terms: Term[]): L {
  const n = twoExp(terms[0]) ?? 0;
  const m = twoExp(terms[1]) ?? 0;
  const f = { ones: 1 + m, digits: n + 1, zeros: n - m };
  return T(
    `${convRu(terms)}2${sup(m)} − 1 — это ${nOnes(m).ru} подряд (разряды 0…${m - 1}). 2${sup(n)} — одна единица на разряде ${n}. Они не пересекаются, ведь ${n} > ${m - 1}. Единиц: 1 + ${m} = ${f.ones}; цифр: ${n} + 1 = ${f.digits}; нулей: ${n} − ${m} = ${f.zeros} (разряды ${m}…${n - 1}).`,
    `${convKk(terms)}2${sup(m)} − 1 — қатар тұрған ${m} бірлік (0…${m - 1} нөмірлі разрядтар). 2${sup(n)} — нөмірі ${n} разрядтағы бір бірлік. Олар қиылыспайды, себебі ${n} > ${m - 1}. Бірлік: 1 + ${m} = ${f.ones}; цифр: ${n} + 1 = ${f.digits}; нөл: ${n} − ${m} = ${f.zeros} (${m}…${n - 1} нөмірлі разрядтар).`,
  );
}

/** 2ⁿ − k: из «всех единиц» вычитается k − 1. */
export function howSmall(n: number, k: number): L {
  const x = k - 1;
  const xb = x.toString(2);
  const c = xb.split("").filter((ch) => ch === "1").length;
  return T(
    `Запишем 2${sup(n)} − ${k} = (2${sup(n)} − 1) − ${x}. У числа 2${sup(n)} − 1 все ${n} цифр — единицы. При вычитании ${x} = ${xb}₂ займов нет (1 − 1 = 0 и 1 − 0 = 1): единицы превращаются в нули ровно там, где у ${x} стоит 1. У ${x} единиц ${c}, значит, остаётся ${n} − ${c} = ${n - c}.`,
    `2${sup(n)} − ${k} = (2${sup(n)} − 1) − ${x} деп жазамыз. 2${sup(n)} − 1 санының ${n} цифрының бәрі — бірлік. ${x} = ${xb}₂ санын шегергенде қарыз болмайды (1 − 1 = 0 және 1 − 0 = 1): бірліктер дәл ${x} санында 1 тұрған жерде нөлге айналады. ${x} санында ${c} бірлік бар, демек ${n} − ${c} = ${n - c} бірлік қалады.`,
  );
}

