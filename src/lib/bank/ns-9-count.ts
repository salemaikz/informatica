// ---------- Описание вопроса данными ----------

type Wrong = [number, L];

interface Spec {
  /** Имя в id: p:ns.count:<name>. */
  name: string;
  level: Level;
  terms: Term[];
  ask: Ask;
  mode: "choice" | "input";
  /** Разбор рассуждения (до итога). */
  how: L;
  hint: L;
  /** Типичные неверные ответы (для choice), числа считает код. */
  wrongs?: Wrong[];
  /** Сделать из вопроса ещё и «короткий» (шифровка, бинго). */
  short?: boolean;
}

/** Правильный вариант + три неверных; недостающие — «рядом» с верным. */
function options(correct: number, wrongs: Wrong[]): { options: Text[]; correct: number; whyWrong: (L | null)[] } {
  const seen = new Set([correct]);
  const picked: Wrong[] = [];
  for (const w of wrongs) {
    if (picked.length >= 3) break;
    if (w[0] <= 0 || seen.has(w[0])) continue;
    seen.add(w[0]);
    picked.push(w);
  }
  for (const d of [1, -1, 2, -2, 3]) {
    if (picked.length >= 3) break;
    const v = correct + d;
    if (v > 0 && !seen.has(v)) {
      seen.add(v);
      picked.push([v, WHY.off]);
    }
  }
  const all: [number, L | null][] = [[correct, null], ...picked];
  return { options: all.map((x) => String(x[0])), correct: 0, whyWrong: all.map((x) => x[1]) };
}

function question(sp: Spec): QuestionStep {
  const f = facts(sp.terms);
  const a = answerOf(f, sp.ask);
  const base = {
    id: `p:${SKILL}:${sp.name}`,
    skill: SKILL,
    level: sp.level,
    prompt: askPrompt(sp.ask, expr(sp.terms)),
    explanation: L2(sp.how, closing(f)),
    hint: sp.hint,
  };
  if (sp.mode === "input") return { ...base, type: "input", answers: [String(a)], mode: "number" };
  return { ...base, type: "choice", ...options(a, sp.wrongs ?? []) };
}

function shortOf(sp: Spec): ShortQuestion {
  const f = facts(sp.terms);
  return {
    id: `p:${SKILL}:short-${sp.name}`,
    skill: SKILL,
    level: sp.level,
    prompt: askPrompt(sp.ask, expr(sp.terms)),
    answer: String(answerOf(f, sp.ask)),
    mode: "number",
    explanation: L2(sp.how, closing(f)),
    hint: sp.hint,
  };
}

/** Неверные ответы «стандартного набора» для вопроса про единицы суммы с разными показателями. */
function sumWrongs(terms: Term[]): Wrong[] {
  const f = facts(terms);
  const ex = exps(terms);
  return [
    [f.digits, WHY.digitsForOnes],
    [ex.reduce((x, y) => x + y, 0), WHY.sumExp],
    [terms.length - 1, WHY.lost],
    [terms.length + 1, WHY.off],
  ];
}

