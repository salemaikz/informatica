/** Утверждение о числе единиц/нулей/цифр выражения: claimed — то, что заявлено; value считает код. */
function claim(name: string, level: Level, terms: Term[], ask: Ask, claimed: number, how: L, hint: L): Statement {
  const f = facts(terms);
  const real = answerOf(f, ask);
  const noun = ask === "ones" ? nOnes(claimed) : ask === "zeros" ? nZeros(claimed) : nDigits(claimed);
  const e = expr(terms);
  const ok = real === claimed;
  return {
    id: `p:${SKILL}:st-${name}`,
    skill: SKILL,
    level,
    text: T(`В двоичной записи числа ${e} ровно ${noun.ru}.`, `${e} санының екілік жазбасында дәл ${noun.kk} бар.`),
    value: ok,
    explanation: L2(how, closing(f)),
    hint,
  };
}

