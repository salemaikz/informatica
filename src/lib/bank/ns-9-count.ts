// Банк навыка ns.count: сколько единиц, нулей и цифр в двоичной записи числа, заданного выражением
// со степенями (2ⁿ, 4ᵏ, 8ᵏ, 16ᵏ), суммами и разностями — без перевода в двоичную систему.
// Статичный пул, но числа в нём не набираются руками: выражение описано данными (Term), а единицы, нули
// и цифры считает код (BigInt → toString(2)). Типичные ошибки (склеивание одинаковых степеней, 4ᵏ ≠ 2ᵏ⁺²,
// число цифр = показатель + 1, путаница n − m) — готовые «неверные варианты» с пояснением.
// Хелперы (P, M, expr, facts…) используют урок и задания ЕНТ. Тексты после чисел — без падежных окончаний.

const SKILL = "ns.count";
const T = (ru: string, kk: string): L => ({ ru, kk });

// ---------- Математика: выражения со степенями ----------

const SUPS = "⁰¹²³⁴⁵⁶⁷⁸⁹";
/** Верхний индекс: 12 → «¹²». */
export const sup = (n: number): string =>
  String(n)
    .split("")
    .map((d) => SUPS[Number(d)])
    .join("");

/** Слагаемое выражения: s · bᵉ (s = ±1). Константа c — это P(c, 1), единица — P(2, 0). */
export interface Term {
  s: 1 | -1;
  b: number;
  e: number;
}
/** Слагаемое со знаком «+». */
export const P = (b: number, e: number): Term => ({ s: 1, b, e });
/** Слагаемое со знаком «−». */
export const M = (b: number, e: number): Term => ({ s: -1, b, e });

/** Запись одного слагаемого: 2⁹, 4, 1 (e = 0 — единица, e = 1 — просто основание). */
export function term(t: Term): string {
  if (t.e === 0) return "1";
  if (t.e === 1) return String(t.b);
  return `${t.b}${sup(t.e)}`;
}

/** Запись выражения: «4²⁰ + 2¹⁰ − 1». */
export function expr(terms: Term[]): string {
  return terms.map((t, i) => (i === 0 ? (t.s < 0 ? "−" : "") : t.s < 0 ? " − " : " + ") + term(t)).join("");
}

function pow(b: number, e: number): bigint {
  let r = BigInt(1);
  const bb = BigInt(b);
  for (let i = 0; i < e; i++) r *= bb;
  return r;
}

/** Значение выражения. */
export function value(terms: Term[]): bigint {
  return terms.reduce((acc, t) => acc + BigInt(t.s) * pow(t.b, t.e), BigInt(0));
}

export interface Facts {
  /** Двоичная запись без приставки. */
  bin: string;
  ones: number;
  zeros: number;
  digits: number;
}

/** Единицы, нули и цифры в двоичной записи значения выражения. */
export function facts(terms: Term[]): Facts {
  const v = value(terms);
  if (v <= BigInt(0)) throw new Error(`ns.count: значение выражения ${expr(terms)} должно быть положительным`);
  const bin = v.toString(2);
  const ones = bin.split("").filter((c) => c === "1").length;
  return { bin, ones, zeros: bin.length - ones, digits: bin.length };
}

/** Показатель, если слагаемое — степень двойки (4ᵏ = 2²ᵏ, 8ᵏ = 2³ᵏ, 16ᵏ = 2⁴ᵏ); иначе null. */
export function twoExp(t: Term): number | null {
  const k = ({ 2: 1, 4: 2, 8: 3, 16: 4 } as Record<number, number>)[t.b];
  return k === undefined ? null : k * t.e;
}

/** Строка перевода слагаемых в степени двойки: «4⁵ = 2¹⁰; 8² = 2⁶» (пусто, если переводить нечего). */
export function conv(terms: Term[]): string {
  const parts: string[] = [];
  for (const t of terms) {
    const n = twoExp(t);
    if (n === null) continue;
    if (t.b === 2 && t.e >= 2) continue;
    if (t.e === 0) parts.push("1 = 2⁰");
    else if (t.b === 2) parts.push("2 = 2¹");
    else parts.push(`${term(t)} = 2${sup(n)}`);
  }
  return [...new Set(parts)].join("; ");
}

// ---------- Подписи: количества и вопросы ----------

function ruPlural(n: number, one: string, few: string, many: string): string {
  const a = n % 100;
  const b = n % 10;
  if (a >= 11 && a <= 14) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

/** «3 единицы» / «3 бірлік». */
export const nOnes = (n: number): L => T(`${n} ${ruPlural(n, "единица", "единицы", "единиц")}`, `${n} бірлік`);
/** «5 нулей» / «5 нөл». */
export const nZeros = (n: number): L => T(`${n} ${ruPlural(n, "нуль", "нуля", "нулей")}`, `${n} нөл`);
/** «8 цифр» / «8 цифр». */
export const nDigits = (n: number): L => T(`${n} ${ruPlural(n, "цифра", "цифры", "цифр")}`, `${n} цифр`);

/** Описание записи: «5 единиц, 3 нуля» (если нулей нет — «только единицы»). */
export function describe(f: Facts): L {
  const o = nOnes(f.ones);
  if (f.zeros === 0) return T(`${o.ru}, нулей нет`, `${o.kk}, нөл жоқ`);
  const z = nZeros(f.zeros);
  return T(`${o.ru}, ${z.ru}`, `${o.kk}, ${z.kk}`);
}

export type Ask = "ones" | "zeros" | "digits";
const ASK_RU: Record<Ask, string> = { ones: "единиц", zeros: "нулей", digits: "цифр" };
const ASK_KK: Record<Ask, string> = { ones: "бірлік", zeros: "нөл", digits: "цифр" };
export const answerOf = (f: Facts, ask: Ask): number => (ask === "ones" ? f.ones : ask === "zeros" ? f.zeros : f.digits);

/** «Сколько единиц в двоичной записи числа …?» */
export const askPrompt = (ask: Ask, e: string): L =>
  T(`Сколько ${ASK_RU[ask]} в двоичной записи числа ${e}?`, `${e} санының екілік жазбасында неше ${ASK_KK[ask]} бар?`);

/** Итог разбора: единицы, нули, цифры и (для коротких записей) сама запись. */
export function closing(f: Facts): L {
  const rec = f.digits <= 20 ? ` ${f.bin}₂.` : "";
  return T(
    `Итого: единиц — ${f.ones}, нулей — ${f.zeros}, цифр — ${f.digits}.${rec ? ` Запись:${rec}` : ""}`,
    `Қорытынды: бірлік — ${f.ones}, нөл — ${f.zeros}, цифр — ${f.digits}.${rec ? ` Жазба:${rec}` : ""}`,
  );
}

