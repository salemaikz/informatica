// ---------- Расчёты нейрона ----------
const dot = (x: number[], w: number[]) => x.reduce((a, v, i) => a + v * w[i], 0);
/** Все наборы из n бинарных входов. */
const combos = (n: number): number[][] => Array.from({ length: 2 ** n }, (_, k) => Array.from({ length: n }, (_, i) => (k >> (n - 1 - i)) & 1));
/** Сколько наборов бинарных входов дают выход 1 (s ≥ T). */
const countOn = (w: number[], T: number) => combos(w.length).filter((x) => dot(x, w) >= T).length;
const fire = (x: number[], w: number[], T: number) => (dot(x, w) >= T ? 1 : 0);
const pct = (right: number, all: number) => Math.round((right / all) * 100);
const fmt = (v: number[]) => `(${v.join(", ")})`.replace(/-/g, "−");
const neg = (n: number) => String(n).replace("-", "−");
/** Запись суммы по шагам: «1·5 + 1·(−3) + 0·4». */
const expand = (x: number[], w: number[]) => x.map((v, i) => `${v}·${w[i] < 0 ? `(${neg(w[i])})` : w[i]}`).join(" + ");
const cmp = (s: number, T: number) => `${neg(s)} ${s >= T ? "≥" : "<"} ${T}`;

interface Opt {
  t: Text;
  /** Почему вариант неверен (для верного — не указывается). */
  why?: L;
}

/** Задание-choice: верный вариант всегда первым, poolBank перемешает варианты вместе с whyWrong. */
function choice(
  id: string,
  level: Level,
  prompt: L,
  hint: L,
  right: Text,
  wrong: Opt[],
  explanation: L,
  scene?: Scene,
): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [right, ...wrong.map((w) => w.t)],
    correct: 0,
    explanation,
    hint,
    whyWrong: [null, ...wrong.map((w) => w.why ?? null)],
  };
}

/** Задание-multi: верные варианты первыми (индексы 0..k-1). */
function multi(id: string, level: Level, prompt: L, hint: L, rights: Opt[], wrong: Opt[], explanation: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: [...rights.map((r) => r.t), ...wrong.map((w) => w.t)],
    correct: rights.map((_, i) => i),
    explanation,
    hint,
    whyWrong: [...rights.map(() => null), ...wrong.map((w) => w.why ?? null)],
  };
}

function input(id: string, level: Level, prompt: L, hint: L, answer: number | string, explanation: L, scene?: Scene): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, answers: [String(answer)], mode: "number", explanation, hint };
}

function match(id: string, level: Level, prompt: L, hint: L, pairs: { left: Text; right: Text }[], explanation: L): MatchStep {
  return { id: `p:${SKILL}:${id}`, type: "match", skill: SKILL, level, prompt, pairs, explanation, hint };
}

function order(id: string, level: Level, prompt: L, hint: L, items: L[], explanation: L): OrderStep {
  return { id: `p:${SKILL}:${id}`, type: "order", skill: SKILL, level, prompt, items, explanation, hint };
}

