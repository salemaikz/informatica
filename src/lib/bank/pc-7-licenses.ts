/** B: что дешевле на заданный срок. */
function compare(rand: Rand, seed: number): ChoiceStep {
  const p = pick(rand, MONTHLY);
  const n0 = int(rand, 10, 20);
  const buy = p * n0;
  const t = rand() < 0.2 ? n0 : Math.max(2, n0 + pick(rand, [-6, -4, -3, 3, 4, 6, 8]));
  const sub = p * t;
  const correct = sub < buy ? 0 : sub > buy ? 1 : 2;
  const opts: { text: L; why: L | null }[] = [
    { text: l("Подписка", "Жазылым"), why: l(`За ${t} месяцев подписка стоит ${fmt(sub)} ₸, а покупка ${fmt(buy)} ₸: подписка не дешевле.`, `${t} айға жазылым ${fmt(sub)} ₸ тұрады, ал сатып алу ${fmt(buy)} ₸: жазылым арзан емес.`) },
    { text: l("Покупка навсегда", "Мәңгілікке сатып алу"), why: l(`За ${t} месяцев подписка стоит ${fmt(sub)} ₸, а покупка ${fmt(buy)} ₸: покупка не дешевле.`, `${t} айға жазылым ${fmt(sub)} ₸ тұрады, ал сатып алу ${fmt(buy)} ₸: сатып алу арзан емес.`) },
    { text: l("Стоимость одинаковая", "Құны бірдей"), why: l(`Суммы различаются: подписка ${fmt(sub)} ₸, покупка ${fmt(buy)} ₸.`, `Сомалар әртүрлі: жазылым ${fmt(sub)} ₸, сатып алу ${fmt(buy)} ₸.`) },
    { text: l("По этим данным определить нельзя", "Осы деректер бойынша анықтау мүмкін емес"), why: l("Данных достаточно: нужно сравнить цену месяца · число месяцев с ценой покупки.", "Деректер жеткілікті: айлық баға · ай санын сатып алу бағасымен салыстыру керек.") },
  ];
  opts[correct].why = null;
  const order = shuffle([0, 1, 2, 3], rand);
  return {
    id: `g:${SKILL}:compare:${p}-${n0}-${t}:${seed}`,
    type: "choice",
    skill: SKILL,
    level: 2,
    prompt: l(
      `Подписка стоит ${fmt(p)} ₸ в месяц, покупка навсегда — ${fmt(buy)} ₸. Программа нужна на ${t} месяцев. Что обойдётся дешевле?`,
      `Жазылым айына ${fmt(p)} ₸ тұрады, мәңгілікке сатып алу — ${fmt(buy)} ₸. Программа ${t} айға керек. Не арзанырақ болады?`,
    ),
    options: order.map((i) => opts[i].text),
    correct: order.indexOf(correct),
    whyWrong: order.map((i) => opts[i].why),
    hint: l("Найди стоимость подписки за весь срок и сравни её с ценой покупки.", "Жазылымның бүкіл мерзімге құнын тауып, оны сатып алу бағасымен салыстыр."),
    explanation: l(
      `Подписка за ${t} месяцев: ${fmt(p)} · ${t} = ${fmt(sub)} ₸. Покупка: ${fmt(buy)} ₸. ${correct === 0 ? "Подписка дешевле." : correct === 1 ? "Покупка дешевле." : "Суммы равны."}`,
      `${t} айға жазылым: ${fmt(p)} · ${t} = ${fmt(sub)} ₸. Сатып алу: ${fmt(buy)} ₸. ${correct === 0 ? "Жазылым арзан." : correct === 1 ? "Сатып алу арзан." : "Сомалар тең."}`,
    ),
  };
}

/** Наименьшая цена за n компьютеров из пакетов по k и одиночных лицензий (перебор числа пакетов). */
export function minCost(n: number, single: number, k: number, packPrice: number): number {
  let best = Infinity;
  for (let p = 0; p <= Math.ceil(n / k); p++) {
    best = Math.min(best, p * packPrice + Math.max(0, n - p * k) * single);
  }
  return best;
}

interface PackTask {
  n: number;
  single: number;
  k: number;
  price: number;
}

function packTask(rand: Rand): PackTask {
  const single = pick(rand, [2000, 3000, 4000, 5000, 6000, 8000]);
  const k = pick(rand, [5, 8, 10, 12]);
  const f = pick(rand, [0.6, 0.65, 0.7, 0.75, 0.8]);
  const price = Math.round((k * single * f) / 100) * 100;
  const n = k * int(rand, 2, 4) + int(rand, 1, k - 1);
  return { n, single, k, price };
}

/** C: наименьшая сумма за n лицензий (пакеты + отдельные). */
function packMin(rand: Rand, seed: number): InputStep {
  const { n, single, k, price } = packTask(rand);
  const best = minCost(n, single, k, price);
  const q = Math.floor(n / k);
  const r = n - q * k;
  const costA = q * price + r * single;
  const costB = (q + 1) * price;
  const costC = n * single;
  return inputStep(
    `g:${SKILL}:pack-min:${n}-${single}-${k}-${price}:${seed}`,
    3,
    l(
      `Школе нужна программа на ${n} компьютеров. Лицензия на 1 ПК стоит ${fmt(single)} ₸, пакет на ${k} ПК — ${fmt(price)} ₸. Какая наименьшая сумма в тенге потребуется? Введи число.`,
      `Мектепке ${n} компьютерге программа керек. 1 ПК-ге лицензия ${fmt(single)} ₸, ${k} ПК-ге пакет ${fmt(price)} ₸ тұрады. Ең аз қанша теңге қажет? Санды енгіз.`,
    ),
    String(best),
    l(
      "Переберите варианты: сколько пакетов взять, остаток закройте отдельными лицензиями, а ещё проверьте вариант с лишним пакетом.",
      "Нұсқаларды қарап шық: қанша пакет алу керек, қалғанын жеке лицензиялармен жап, сондай-ақ артық пакеті бар нұсқаны да тексер.",
    ),
    l(
      `Варианты: ${q} пак. + ${r} отдельных = ${fmt(costA)} ₸; ${q + 1} пак. = ${fmt(costB)} ₸; все отдельные = ${fmt(costC)} ₸. Наименьшая сумма: ${fmt(best)} ₸.`,
      `Нұсқалар: ${q} пакет + ${r} жеке = ${fmt(costA)} ₸; ${q + 1} пакет = ${fmt(costB)} ₸; бәрі жеке = ${fmt(costC)} ₸. Ең аз сома: ${fmt(best)} ₸.`,
    ),
  );
}

