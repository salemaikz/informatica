/** A: сколько заплатишь по подписке за m месяцев. */
function subsTotal(rand: Rand, seed: number): InputStep {
  const p = pick(rand, MONTHLY);
  const m = pick(rand, [3, 4, 6, 8, 10, 12]);
  const total = p * m;
  return inputStep(
    `g:${SKILL}:subs-total:${p}-${m}:${seed}`,
    1,
    l(
      `Подписка на программу стоит ${fmt(p)} ₸ в месяц. Сколько тенге нужно заплатить за ${m} месяцев? Введи число.`,
      `Программаға жазылым айына ${fmt(p)} ₸ тұрады. ${m} айға қанша теңге төлеу керек? Санды енгіз.`,
    ),
    String(total),
    l("Подписка оплачивается каждый месяц: умножь цену месяца на число месяцев.", "Жазылым әр ай сайын төленеді: айлық бағаны ай санына көбейт."),
    l(`${fmt(p)} · ${m} = ${fmt(total)} ₸.`, `${fmt(p)} · ${m} = ${fmt(total)} ₸.`),
  );
}

/** A: цена лицензии на один компьютер по пакету. */
