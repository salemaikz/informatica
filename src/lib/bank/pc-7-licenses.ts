function shortQuestion(rand: Rand, level: Level, seed: number): ShortQuestion {
  if (rand() < 0.5) {
    const g = level === 1 ? (rand() < 0.5 ? subsTotal(rand, seed) : perSeat(rand, seed)) : level === 2 ? breakEven(rand, seed) : packMin(rand, seed);
    return {
      id: g.id.replace(/^g:/, "sh:"),
      skill: SKILL,
      level,
      prompt: g.prompt,
      answer: g.answers[0],
      mode: "number",
      explanation: g.explanation,
      hint: g.hint,
    };
  }
  const list = STATIC_SHORTS.filter((s) => s.level === level);
  const s = pick(rand, list);
  return { id: `sh:${SKILL}:${s.id}:${seed}`, skill: SKILL, level, prompt: s.prompt, answer: s.answer, mode: s.mode, explanation: s.explanation, hint: s.hint };
}

