// Расчёты — генераторы: стоимость подписки, цена за компьютер в пакете, «через сколько месяцев сравняются»,
// что дешевле, наименьшая цена пакетов для N компьютеров (перебор кодом). Ответ в генераторах всегда считает код.
// Цены выдуманные. После переменных чисел в казахском нет падежных окончаний (число стоит перед существительным).

const SKILL = "pc.licenses";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const l = (ru: string, kk: string): L => ({ ru, kk });
/** 12000 → «12 000». */
const fmt = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");

type W = L | null;

// ====================================================================================================
// Статичный пул «на знание»
// ====================================================================================================

interface PoolChoice {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number;
  why: W[];
  explanation: L;
}

function q(name: string, level: Level, p: PoolChoice): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

interface PoolMulti {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number[];
  why: W[];
  explanation: L;
}

function qm(name: string, level: Level, p: PoolMulti): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

