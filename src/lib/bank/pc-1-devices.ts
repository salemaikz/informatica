// ---------- Сборка банка ----------

const pool = poolBank({ skill: SKILL, questions, statements, pairs, shorts });

const devices: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed ^ 0x6a09e667);
    // Около трети заданий уровней B и C — расчётные (пиксели, dpi, объём), остальные — знания из пула.
    if (level > 1 && rand() < 0.35) return calcQuestion(level, rand, seed);
    return pool.question(level, seed);
  },
  statement: pool.statement,
  pair: pool.pair,
  short(level, seed) {
    const rand = seeded(seed ^ 0x3c6ef372);
    if (level > 1 && rand() < 0.3) return calcShort(level, seed);
    return pool.short!(level, seed);
  },
};

export const BANKS: SkillBank[] = [devices];
