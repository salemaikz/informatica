const SKILL = "pc.devices";

const w = (ru: string, kk: string): L => ({ ru, kk });
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];

// ---------- Расчётные задания ----------

interface Wrong {
  v: string;
  why: L;
}

interface Calc {
  /** Идентификатор «семейства» без seed: g:pc.devices:<вид>:<параметры>. */
  id: string;
  prompt: L;
  answer: string;
  wrongs: Wrong[];
  hint: L;
  explanation: L;
}

/** B: сколько пикселей на всём экране при разрешении W × H. */
function calcPixels(rand: Rand): Calc {
  const [px, py] = pick(rand, [
    [1280, 720],
    [1366, 768],
    [1600, 900],
    [1920, 1080],
    [2560, 1440],
  ] as const);
  const total = px * py;
  return {
    id: `g:${SKILL}:pixels:${px}x${py}`,
    prompt: w(
      `Разрешение экрана монитора — ${px} × ${py} пикселей. Сколько пикселей на всём экране?`,
      `Монитор экранының ажыратымдылығы — ${px} × ${py} пиксель. Бүкіл экранда неше пиксель бар?`,
    ),
    answer: String(total),
    wrongs: [
      { v: String(px + py), why: w("Ширину и высоту нужно умножить, а не сложить: пиксели стоят рядами.", "Ені мен биіктігін қосуға емес, көбейтуге болады: пиксельдер қатарлап тұрады.") },
      { v: String(2 * (px + py)), why: w("Так считают периметр рамки, а не число всех пикселей.", "Бұлай жиектің периметрін санайды, барлық пиксельдер санын емес.") },
      { v: String(Math.floor(total / 10)), why: w("Потеряна цифра: проверь умножение.", "Бір цифр жоғалған: көбейтуді тексер.") },
      { v: String(total * 2), why: w("Результат удвоен: проверь умножение.", "Нәтиже екі еселенген: көбейтуді тексер.") },
    ],
    hint: w(
      "Пиксели расположены строками и столбцами, как клетки в тетради. Сколько клеток во всём листе?",
      "Пиксельдер дәптердегі тор көздері сияқты жолдар мен бағандарға орналасқан. Бүкіл беттегі тор көз саны қанша?",
    ),
    explanation: w(
      `В каждой строке ${px} пикселей, а строк ${py}. Всего ${px} · ${py} = ${total} пикселей.`,
      `Әр жолда ${px} пиксель, ал жолдар саны ${py}. Барлығы ${px} · ${py} = ${total} пиксель.`,
    ),
  };
}

/** C: сколько пикселей по стороне A дюймов нужно для печати при R dpi. */
function calcDpi(rand: Rand): Calc {
  const [a, b] = pick(rand, [
    [6, 4],
    [7, 5],
    [8, 6],
    [10, 8],
    [12, 9],
  ] as const);
  const r = pick(rand, [150, 200, 300, 600] as const);
  const ans = a * r;
  return {
    id: `g:${SKILL}:dpi:${a}x${b}:${r}`,
    prompt: w(
      `Фотографию ${a} × ${b} дюймов печатают с разрешением ${r} dpi. Сколько пикселей должно быть у изображения по длинной стороне (${a} дюймов)?`,
      `Көлемі ${a} × ${b} дюйм фотоны ${r} dpi ажыратымдылықпен басады. Суреттің ұзын жағында (${a} дюйм) неше пиксель болуы керек?`,
    ),
    answer: String(ans),
    wrongs: [
      { v: String(a + r), why: w("Дюймы и точки на дюйм не складывают, а перемножают.", "Дюймдер мен дюймдегі нүктелерді қоспайды, көбейтеді.") },
      { v: String(b * r), why: w("Это число пикселей по короткой стороне, а нужна длинная.", "Бұл — қысқа жағындағы пиксель саны, ал ұзын жағы керек.") },
      { v: String(a * b * r), why: w("Так получается лишний множитель: нужна одна сторона, а не площадь.", "Бұлай артық көбейткіш шығады: бір жағы керек, ауданы емес.") },
      { v: String(Math.round((a * r) / 10)), why: w("Потеряна цифра: проверь умножение.", "Бір цифр жоғалған: көбейтуді тексер.") },
    ],
    hint: w(
      "dpi — это точки (пиксели) на один дюйм. Сколько дюймов в нужной стороне, столько раз и берём это число.",
      "dpi — бір дюймдегі нүктелер (пиксельдер). Қажет жақта неше дюйм болса, осы санды сонша рет аламыз.",
    ),
    explanation: w(
      `На каждый дюйм приходится ${r} пикселей, а длинная сторона — ${a} дюймов: ${a} · ${r} = ${ans} пикселей.`,
      `Әр дюймге ${r} пиксель келеді, ал ұзын жағы — ${a} дюйм: ${a} · ${r} = ${ans} пиксель.`,
    ),
  };
}

/** C: сколько фото размера M Мбайт поместится на накопитель V Гбайт (1 Гбайт = 1024 Мбайт). */
function calcPhotos(rand: Rand): Calc {
  const v = pick(rand, [8, 16, 32, 64, 128] as const);
  const m = pick(rand, [2, 4, 8, 16] as const);
  const ans = (v * 1024) / m;
  return {
    id: `g:${SKILL}:photos:${v}:${m}`,
    prompt: w(
      `Объём флешки — ${v} Гбайт, одна фотография занимает ${m} Мбайт. Сколько таких фотографий поместится? (1 Гбайт = 1024 Мбайт)`,
      `Флешканың көлемі — ${v} Гбайт, бір фотосурет ${m} Мбайт алады. Осындай неше фотосурет сияды? (1 Гбайт = 1024 Мбайт)`,
    ),
    answer: String(ans),
    wrongs: [
      { v: String((v * 1000) / m), why: w("1 Гбайт принят за 1000 Мбайт, а в информатике 1 Гбайт = 1024 Мбайт.", "1 Гбайт 1000 Мбайт деп алынған, ал информатикада 1 Гбайт = 1024 Мбайт.") },
      { v: String(v * m), why: w("Объём и размер фото не умножают: нужно разделить, сколько раз фото помещается в объём.", "Көлем мен фото өлшемін көбейтпейді: фото көлемге неше рет сыятынын бөлу керек.") },
      { v: String(v * 1024), why: w("Не учтён размер одной фотографии: надо разделить на него.", "Бір фотосуреттің өлшемі ескерілмеген: соған бөлу керек.") },
      { v: String(ans / 2), why: w("Потерян множитель 2 при делении: проверь вычисление.", "Бөлгенде 2 еселік жоғалған: есептеуді тексер.") },
    ],
    hint: w(
      "Сначала переведи Гбайт в Мбайт, а потом узнай, сколько раз размер фотографии укладывается в этот объём.",
      "Алдымен Гбайтты Мбайтқа аудар, содан кейін фотосурет өлшемі осы көлемге неше рет сыятынын тап.",
    ),
    explanation: w(
      `${v} Гбайт = ${v} · 1024 = ${v * 1024} Мбайт. Фотографий поместится ${v * 1024} / ${m} = ${ans}.`,
      `${v} Гбайт = ${v} · 1024 = ${v * 1024} Мбайт. Фотосурет саны ${v * 1024} / ${m} = ${ans}.`,
    ),
  };
}

const CALCS: Record<Level, ((rand: Rand) => Calc)[]> = {
  1: [],
  2: [calcPixels],
  3: [calcDpi, calcPhotos, calcPixels],
};

/** Правильный + три разных неверных (из типичных ошибок), порядок перемешан по seed. */
function buildOptions(rand: Rand, calc: Calc): { options: string[]; correct: number; whyWrong: (L | null)[] } {
  const seen = new Set<string>([calc.answer]);
  const picked: Wrong[] = [];
  for (const wr of shuffle(calc.wrongs, rand)) {
    if (picked.length >= 3) break;
    if (!seen.has(wr.v)) {
      seen.add(wr.v);
      picked.push(wr);
    }
  }
  const all = shuffle<{ v: string; why: L | null }>([{ v: calc.answer, why: null }, ...picked], rand);
  return { options: all.map((a) => a.v), correct: all.findIndex((a) => a.why === null), whyWrong: all.map((a) => a.why) };
}

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const calc = pick(rand, CALCS[level])(rand);
  const head = { id: `${calc.id}:${seed}`, skill: SKILL, level, prompt: calc.prompt, hint: calc.hint, explanation: calc.explanation };
  if (rand() < 0.5) {
    const step: InputStep = { ...head, type: "input", answers: [calc.answer], mode: "number" };
    return step;
  }
  const step: ChoiceStep = { ...head, type: "choice", ...buildOptions(rand, calc) };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x2b7e1516);
  const calc = pick(rand, CALCS[level])(rand);
  return {
    id: `${calc.id}:${seed}`,
    skill: SKILL,
    level,
    prompt: calc.prompt,
    answer: calc.answer,
    mode: "number",
    explanation: calc.explanation,
    hint: calc.hint,
  };
}

