const SKILL = "info.text";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const same = (s: string): L => ({ ru: s, kk: s });

const UP = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const LOW = "abcdefghijklmnopqrstuvwxyz";

const plural = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};
const bytesRu = (n: number) => `${n} ${plural(n, "байт", "байта", "байт")}`;
const symRu = (n: number) => `${n} ${plural(n, "символ", "символа", "символов")}`;
const lettersRu = (n: number) => `${n} ${plural(n, "буква", "буквы", "букв")}`;
const stepsRu = (n: number) => `${n} ${plural(n, "шаг", "шага", "шагов")}`;

interface Enc {
  name: string;
  bits: 8 | 16;
}
const ASCII: Enc = { name: "ASCII", bits: 8 };
const KZ: Enc = { name: "KZ-1048", bits: 8 };
const UNI: Enc = { name: "Unicode", bits: 16 };

interface Wrong {
  v: string;
  why: L;
}

/** Задание с выбором: правильный ответ + до трёх разных неверных (с разбором ошибки). */
function buildChoice(
  rand: Rand,
  head: { id: string; level: Level; hint: L; prompt: L; explanation: L; scene?: Scene },
  correct: string,
  wrongs: Wrong[],
): ChoiceStep {
  const seen = new Set<string>([correct]);
  const picked: Wrong[] = [];
  for (const w of wrongs) {
    if (picked.length >= 3) break;
    if (!seen.has(w.v)) {
      seen.add(w.v);
      picked.push(w);
    }
  }
  const all = shuffle<{ v: string; why: L | null }>([{ v: correct, why: null }, ...picked], rand);
  return {
    ...head,
    type: "choice",
    skill: SKILL,
    options: all.map((a) => a.v),
    correct: all.findIndex((a) => a.why === null),
    whyWrong: all.map((a) => a.why),
  };
}

function buildInput(head: { id: string; level: Level; hint: L; prompt: L; explanation: L }, answer: string): InputStep {
  return { ...head, type: "input", skill: SKILL, answers: [answer], mode: "number" };
}

