/** A: объём текста из K символов по размеру символа. */
const volSym: Gen = (rand, level, seed) => {
  const enc = pick(rand, [ASCII, KZ, UNI, UNI]);
  const K = int(rand, 12, 96);
  const b = enc.bits / 8;
  const ans = K * b;
  const head = {
    id: `g:${SKILL}:vol:${K}${enc.name}:${seed}`,
    level,
    hint: {
      ru: "Объём = число символов × размер одного символа. Сначала переведи биты в байты.",
      kk: "Көлем = символдар саны × бір символдың өлшемі. Алдымен биттерді байтқа аудар.",
    },
    prompt: {
      ru: `Текст из ${K} символов записан в кодировке ${enc.name} (${enc.bits} бит на символ). Объём текста в байтах:`,
      kk: `${K} символдан тұратын мәтін ${enc.name} кодтауында жазылған (бір символға ${enc.bits} бит). Мәтіннің көлемі (байтпен):`,
    },
    explanation: {
      ru: `${enc.bits} бит = ${enc.bits / 8} ${plural(enc.bits / 8, "байт", "байта", "байт")} на символ. I = K · i = ${K} · ${b} = ${bytesRu(ans)}.`,
      kk: `${enc.bits} бит = ${b} байт бір символға. I = K · i = ${K} · ${b} = ${ans} байт.`,
    },
  };
  if (rand() < 0.5) return buildInput(head, String(ans));
  const wrongs: Wrong[] =
    b === 2
      ? [
          { v: String(K), why: { ru: "Так выйдет при 1 байте на символ, а в Unicode символ занимает 2 байта.", kk: "Бір символға 1 байт болса, осылай шығады, ал Unicode-та символ 2 байт алады." } },
          { v: String(K * 16), why: { ru: "16 — это биты. Число символов нужно умножать на размер символа в байтах (2).", kk: "16 — бұл биттер. Символдар санын символдың байттағы өлшеміне (2) көбейту керек." } },
          { v: String(K + 16), why: { ru: "Число символов и размер символа не складывают, а перемножают.", kk: "Символдар саны мен символ өлшемін қосуға болмайды, көбейту керек." } },
        ]
      : [
          { v: String(K * 8), why: { ru: "Так получатся биты, а не байты: 1 байт = 8 бит, символ занимает 1 байт.", kk: "Бұл — байт емес, бит: 1 байт = 8 бит, ал символ 1 байт алады." } },
          { v: String(K * 2), why: { ru: "2 байта на символ — это Unicode, а здесь символ занимает 8 бит = 1 байт.", kk: "Бір символға 2 байт — бұл Unicode, ал мұнда символ 8 бит = 1 байт алады." } },
          { v: String(K + 8), why: { ru: "Число символов и размер символа не складывают, а перемножают.", kk: "Символдар саны мен символ өлшемін қосуға болмайды, көбейту керек." } },
        ];
  return buildChoice(rand, head, String(ans), wrongs);
};

