const SKILL = "db.keys";

const l = (ru: string, kk: string): L => ({ ru, kk });
const tbl = (columns: Text[], rows: Text[][], caption?: Text): Scene => ({ kind: "table", columns, rows, caption });

// ---------- Конструкторы заданий ----------

const c = (
  id: string,
  level: Level,
  q: { prompt: L; hint: L; options: Text[]; correct: number; whyWrong: (L | null)[]; explanation: L; scene?: Scene },
): ChoiceStep => ({ type: "choice", id: `p:${SKILL}:${id}`, skill: SKILL, level, ...q });

const mu = (
  id: string,
  level: Level,
  q: { prompt: L; hint: L; options: Text[]; correct: number[]; whyWrong: (L | null)[]; explanation: L; scene?: Scene },
): MultiStep => ({ type: "multi", id: `p:${SKILL}:${id}`, skill: SKILL, level, ...q });

const inp = (id: string, level: Level, q: { prompt: L; hint: L; answer: string; explanation: L; scene?: Scene }): InputStep => ({
  type: "input",
  id: `p:${SKILL}:${id}`,
  skill: SKILL,
  level,
  prompt: q.prompt,
  hint: q.hint,
  answers: [q.answer],
  mode: "number",
  explanation: q.explanation,
  scene: q.scene,
});

const ord = (id: string, level: Level, q: { prompt: L; hint: L; items: L[]; explanation: L }): OrderStep => ({
  type: "order",
  id: `p:${SKILL}:${id}`,
  skill: SKILL,
  level,
  ...q,
});

const mat = (id: string, level: Level, q: { prompt: L; hint: L; pairs: { left: Text; right: Text }[]; explanation: L }): MatchStep => ({
  type: "match",
  id: `p:${SKILL}:${id}`,
  skill: SKILL,
  level,
  ...q,
});

