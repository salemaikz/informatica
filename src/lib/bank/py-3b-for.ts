/** choice: верный ответ первым (poolBank перемешает варианты вместе с whyWrong). */
function choice(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  correct: Text,
  wrong: [Text, L][],
  hint: L,
  explanation: L,
): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrong.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrong.map((w) => w[1])],
    hint,
    explanation,
  };
}

/** input с числовым ответом. */
function input(name: string, level: Level, prompt: L, scene: Scene | undefined, answer: string, hint: L, explanation: L): InputStep {
  return { id: `p:${SKILL}:${name}`, type: "input", skill: SKILL, level, prompt, scene, answers: [answer], mode: "number", hint, explanation };
}

/** multi из 6 вариантов: верные задаются индексами, whyWrong — для неверных (в порядке options). */
function multi(
  name: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number[],
  why: Record<number, L>,
  hint: L,
  explanation: L,
): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options,
    correct,
    whyWrong: options.map((_, i) => (correct.includes(i) ? null : why[i])),
    hint,
    explanation,
  };
}

function match(name: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], hint: L, explanation: L): MatchStep {
  return { id: `p:${SKILL}:${name}`, type: "match", skill: SKILL, level, prompt, pairs, hint, explanation };
}

