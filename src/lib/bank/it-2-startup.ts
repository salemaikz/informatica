/** Воронка: посетители → установили → вернулись. */
const funnel: InputGen = (rand, level) => {
  const options: [number, number, number][] = [];
  for (const v of [1000, 2000, 5000, 10000]) for (const p1 of [10, 20, 25, 40, 50]) for (const p2 of [10, 20, 25, 40, 50]) {
    const a = (v * p1) / 100;
    const b = (a * p2) / 100;
    if (Number.isInteger(a) && Number.isInteger(b) && b >= 10) options.push([v, p1, p2]);
  }
  const [v, p1, p2] = pick(rand, options);
  const a = (v * p1) / 100;
  const b = (a * p2) / 100;
  return input({
    id: `g:${SKILL}:funnel:${v}:${p1}:${p2}`,
    level,
    prompt: l(
      `Страницу приложения открыли ${n(v)} человек. ${p1}% из них установили приложение, а из установивших через неделю вернулись ${p2}%. Сколько человек вернулись?`,
      `Қосымша бетін ${n(v)} адам ашты. Орнатқандардың үлесі: ${p1}%. Орнатқандардан бір аптадан кейін оралғандардың үлесі: ${p2}%. Қанша адам оралды?`,
    ),
    answer: b,
    explanation: l(
      `Установили: ${n(v)} · ${p1} / 100 = ${n(a)} человек. Вернулись: ${n(a)} · ${p2} / 100 = ${n(b)} человек. Второй процент берём от установивших, а не от всех посетителей.`,
      `Орнатты: ${n(v)} · ${p1} / 100 = ${n(a)} адам. Оралды: ${n(a)} · ${p2} / 100 = ${n(b)} адам. Екінші пайызды барлық келушілерден емес, орнатқандардан аламыз.`,
    ),
    hint: l("Считай по шагам: сначала сколько установили, потом какая часть от них вернулась.", "Қадамдап есепте: алдымен қанша адам орнатқанын, сосын олардың қандай бөлігі оралғанын."),
  });
};

/** Сравнение двух приложений по удержанию (ловушка: у «проигравшего» вернулось больше человек). */
const compare: Gen = (rand, level, seed) => {
  const pairs: [number, number, number, number][] = [];
  for (const nHi of [100, 200, 250, 400]) for (const pHi of [30, 40, 50, 60]) for (const nLo of [500, 800, 1000]) for (const pLo of [10, 20, 25]) {
    const bHi = (nHi * pHi) / 100;
    const bLo = (nLo * pLo) / 100;
    if (Number.isInteger(bHi) && Number.isInteger(bLo) && bLo > bHi) pairs.push([nHi, bHi, nLo, bLo]);
  }
  const [nHi, bHi, nLo, bLo] = pick(rand, pairs);
  const swap = rand() < 0.5;
  // A — первое по порядку приложение. Лучшее удержание у «Hi»-приложения.
  const A = swap ? { n: nLo, b: bLo } : { n: nHi, b: bHi };
  const B = swap ? { n: nHi, b: bHi } : { n: nLo, b: bLo };
  const pA = (A.b / A.n) * 100;
  const pB = (B.b / B.n) * 100;
  const bestIsA = pA > pB;
  const bestWord = bestIsA ? "A" : "B";
  const otherWord = bestIsA ? "B" : "A";
  const app = (x: string): L => l(`Приложение ${x}`, `${x} қосымшасы`);
  const scene: Scene = {
    kind: "table",
    columns: [l("Приложение", "Қосымша"), l("Установили", "Орнатты"), l("Вернулись", "Оралды")],
    rows: [
      ["A", String(A.n), String(A.b)],
      ["B", String(B.n), String(B.b)],
    ],
    mono: true,
  };
  return choice(
    rand,
    {
      id: `g:${SKILL}:compare:${A.n}-${A.b}:${B.n}-${B.b}`,
      level,
      prompt: l("Какое приложение лучше удерживает пользователей?", "Қай қосымша пайдаланушыларды жақсырақ ұстап тұр?"),
      scene,
      hint: l("Сравнивай не число вернувшихся, а долю: удержание каждого приложения в процентах.", "Оралғандар санын емес, үлесті салыстыр: әр қосымшаның ұстап қалуын пайызбен."),
      explanation: l(
        `Удержание A: ${A.b} / ${A.n} · 100% = ${pA}%. Удержание B: ${B.b} / ${B.n} · 100% = ${pB}%. Лучше удерживает приложение ${bestWord}. Число вернувшихся больше у приложения ${otherWord}, но у него и установок больше — сравнивать нужно доли.`,
        `A ұстап қалуы: ${A.b} / ${A.n} · 100% = ${pA}%. B ұстап қалуы: ${B.b} / ${B.n} · 100% = ${pB}%. ${bestWord} қосымшасы жақсырақ ұстап тұр. Оралғандар саны ${otherWord} қосымшасында көп, бірақ онда орнатулар да көп — үлестерді салыстыру керек.`,
      ),
    },
    app(bestWord),
    [
      {
        v: app(otherWord),
        why: l("Так получается, если смотреть на число вернувшихся. Но у этого приложения и установок больше — нужно сравнивать доли.", "Оралғандар санына қарағанда осылай шығады. Бірақ бұл қосымшада орнатулар да көп — үлестерді салыстыру керек."),
      },
      { v: l("Одинаково", "Бірдей"), why: l("Удержание в процентах у приложений разное: посчитай доли.", "Қосымшалардың пайыздағы ұстап қалуы әртүрлі: үлестерді есепте.") },
      { v: l("Сравнить нельзя", "Салыстыруға болмайды"), why: l("Сравнить можно: у каждого приложения есть и установки, и вернувшиеся, значит, можно найти долю.", "Салыстыруға болады: әр қосымшада орнатулар да, оралғандар да бар, демек үлесті табуға болады.") },
    ],
  ) as ChoiceStep;
};

