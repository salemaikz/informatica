export const BANKS: SkillBank[] = [
  {
    skill: SKILL,
    question(level, seed) {
      const rand = seeded(seed);
      if (rand() < 0.4) return pick(rand, Q_GENS[level])(rand, level, seed);
      return pool.question(level, seed + 99991);
    },
    statement(level, seed) {
      const rand = seeded(seed);
      const r = rand();
      if (r < 0.55) return pool.statement!(level, seed + 99991);
      if (level === 1) return retentionStatement(rand, level);
      return r < 0.8 ? retentionStatement(rand, level) : commissionStatement(rand, level);
    },
    pair(level, seed) {
      return pool.pair!(level, seed + 99991);
    },
    short(level, seed) {
      const rand = seeded(seed);
      if (level === 1 && rand() < 0.3) return pick(rand, STATIC_SHORTS);
      return toShort(pick(rand, S_GENS[level])(rand, level, seed));
    },
  },
];
