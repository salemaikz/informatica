/** Пары (всего, процент), для которых число вернувшихся целое. */
function totalPct(rand: Rand, totals: number[], pcts: number[]): [number, number] {
  const ok: [number, number][] = [];
  for (const t of totals) for (const p of pcts) if ((t * p) % 100 === 0) ok.push([t, p]);
  return pick(rand, ok);
}

const RET_HINT = l("Удержание = вернувшиеся / все · 100%. Что в числителе, а что в знаменателе?", "Ұстап қалу = оралғандар / барлығы · 100%. Алымында не, бөлімінде не тұр?");

