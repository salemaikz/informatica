// ---------- Утверждения с расчётом кодом ----------

function retentionStatement(rand: Rand, level: Level): Statement {
  const [total, pct] = totalPct(rand, TOTALS, level === 1 ? [10, 20, 25, 50] : PCTS);
  const back = (total * pct) / 100;
  const value = rand() < 0.5;
  const shown = value ? pct : pick(rand, [100 - pct, Math.round((total / back) * 100)].filter((x) => x !== pct && x > 0));
  return {
    id: `s:${SKILL}:ret:${total}:${back}:${shown}`,
    skill: SKILL,
    level,
    text: l(
      `Установили: ${total} человек, вернулись: ${back} человек. Удержание равно ${shown}%`,
      `Орнатқандар: ${total} адам, оралғандар: ${back} адам. Ұстап қалу: ${shown}%`,
    ),
    value: shown === pct,
    explanation: l(
      `Удержание = ${back} / ${total} · 100% = ${pct}%.${shown === pct ? "" : ` Значение ${shown}% получилось бы при ошибке в формуле.`}`,
      `Ұстап қалу = ${back} / ${total} · 100% = ${pct}%.${shown === pct ? "" : ` ${shown}% формуладағы қателікте шығар еді.`}`,
    ),
    hint: RET_HINT,
  };
}

function commissionStatement(rand: Rand, level: Level): Statement {
  const sales = pick(rand, [10000, 20000, 50000, 100000]);
  const p = pick(rand, [5, 10, 20]);
  const income = (sales * p) / 100;
  const value = rand() < 0.5;
  const shown = value ? income : pick(rand, [income * 10, income / 10, sales - income]);
  return {
    id: `s:${SKILL}:comm:${sales}:${p}:${shown}`,
    skill: SKILL,
    level,
    text: l(
      `Продажи: ${n(sales)} тенге, комиссия: ${p}%. Доход площадки: ${n(shown)} тенге`,
      `Сатылым: ${n(sales)} теңге, комиссия: ${p}%. Алаңның табысы: ${n(shown)} теңге`,
    ),
    value: shown === income,
    explanation: l(
      `Комиссия = ${n(sales)} · ${p} / 100 = ${n(income)} тенге.${shown === income ? "" : ` Значение ${n(shown)} — ошибка в расчёте.`}`,
      `Комиссия = ${n(sales)} · ${p} / 100 = ${n(income)} теңге.${shown === income ? "" : ` ${n(shown)} мәні — есептеудегі қате.`}`,
    ),
    hint: l("Найди указанный процент от суммы продаж и сравни с утверждением.", "Сатылым сомасының көрсетілген пайызын тауып, тұжырыммен салыстыр."),
  };
}

function toShort(q: InputStep): ShortQuestion {
  return {
    id: q.id.replace(/^g:/, "sh:"),
    skill: SKILL,
    level: q.level ?? 1,
    prompt: q.prompt,
    answer: q.answers[0],
    mode: "number",
    explanation: q.explanation,
    hint: q.hint,
  };
}

