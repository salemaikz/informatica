// ====================================================================================================
// Статичный пул «на знание»
// ====================================================================================================

interface PoolChoice {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number;
  why: W[];
  explanation: L;
}

function q(name: string, level: Level, p: PoolChoice): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

interface PoolMulti {
  prompt: L;
  hint: L;
  options: Text[];
  correct: number[];
  why: W[];
  explanation: L;
}

function qm(name: string, level: Level, p: PoolMulti): MultiStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt: p.prompt,
    hint: p.hint,
    options: p.options,
    correct: p.correct,
    whyWrong: p.why,
    explanation: p.explanation,
  };
}

