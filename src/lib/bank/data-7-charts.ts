// ---------- Конструкторы заданий ----------

function choice(name: string, level: Level, prompt: L, options: Text[], correct: number, whyWrong: (L | null)[], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return { id: pid(name), type: "choice", skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint, scene };
}

function input(name: string, level: Level, prompt: L, answer: string, explanation: L, hint: L, scene?: Scene, suffix?: string): InputStep {
  return { id: pid(name), type: "input", skill: SKILL, level, prompt, answers: [answer], mode: "number", suffix, explanation, hint, scene };
}

function multi(name: string, level: Level, prompt: L, options: Text[], correct: number[], whyWrong: (L | null)[], explanation: L, hint: L, scene?: Scene): MultiStep {
  return { id: pid(name), type: "multi", skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint, scene };
}

function match(name: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], explanation: L, hint: L, scene?: Scene): MatchStep {
  return { id: pid(name), type: "match", skill: SKILL, level, prompt, pairs, explanation, hint, scene };
}

function order(name: string, level: Level, prompt: L, items: L[], explanation: L, hint: L, scene?: Scene): OrderStep {
  return { id: pid(name), type: "order", skill: SKILL, level, prompt, items, explanation, hint, scene };
}

