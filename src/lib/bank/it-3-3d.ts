function layers(rand: Rand, level: Level, seed: number): InputStep {
  if (level === 1) {
    const t10 = pick(rand, [10, 5, 2]);
    const H = int(rand, 4, 30);
    const N = (H * 10) / t10;
    return input({
      id: `g:${SKILL}:layers-1:${H}:${t10}`,
      level,
      prompt: l(
        `Высота модели ${H} мм, слайсер задал толщину слоя ${dec(t10)} мм. Сколько слоёв напечатает принтер?`,
        `Модельдің биіктігі ${H} мм, слайсер қабат қалыңдығын ${dec(t10)} мм етіп қойды. Принтер неше қабат басады?`,
      ),
      answer: N,
      explanation: l(
        `Число слоёв = высота : толщина слоя = ${H} : ${dec(t10)} = ${N}.`,
        `Қабат саны = биіктік : қабат қалыңдығы = ${H} : ${dec(t10)} = ${N}.`,
      ),
      hint: l("Раздели высоту модели на толщину одного слоя.", "Модель биіктігін бір қабаттың қалыңдығына бөл."),
    });
  }
  const t10 = pick(rand, [1, 2, 4, 5]);
  const cm = int(rand, 2, level === 2 ? 9 : 8);
  const N = (cm * 100) / t10;
  if (level === 2) {
    return input({
      id: `g:${SKILL}:layers-2:${cm}:${t10}`,
      level,
      prompt: l(
        `Деталь высотой ${cm} см печатают слоями толщиной ${dec(t10)} мм. Сколько слоёв получится?`,
        `Биіктігі ${cm} см бөлшекті қалыңдығы ${dec(t10)} мм қабаттармен басады. Неше қабат шығады?`,
      ),
      answer: N,
      explanation: l(
        `${cm} см = ${cm * 10} мм. Слоёв: ${cm * 10} : ${dec(t10)} = ${N}.`,
        `${cm} см = ${cm * 10} мм. Қабат саны: ${cm * 10} : ${dec(t10)} = ${N}.`,
      ),
      hint: l("Сначала переведи сантиметры в миллиметры (1 см = 10 мм), потом раздели на толщину слоя.", "Алдымен сантиметрді миллиметрге айналдыр (1 см = 10 мм), содан соң қабат қалыңдығына бөл."),
    });
  }
  let sec = pick(rand, [20, 30, 40, 60]);
  for (let i = 0; i < 20 && (N * sec) % 60 !== 0; i++) sec = pick(rand, [20, 30, 40, 60]);
  if ((N * sec) % 60 !== 0) sec = 60;
  const minutes = (N * sec) / 60;
  return input({
    id: `g:${SKILL}:layers-3:${cm}:${t10}:${sec}`,
    level,
    prompt: l(
      `Деталь высотой ${cm} см печатают слоями толщиной ${dec(t10)} мм. Каждый слой печатается ${sec} секунд. Сколько минут займёт печать?`,
      `Биіктігі ${cm} см бөлшекті қалыңдығы ${dec(t10)} мм қабаттармен басады. Әр қабат ${sec} секундта басылады. Басып шығаруға неше минут кетеді?`,
    ),
    answer: minutes,
    explanation: l(
      `${cm} см = ${cm * 10} мм. Слоёв: ${cm * 10} : ${dec(t10)} = ${N}. Время: ${N} · ${sec} с = ${N * sec} с = ${N * sec} : 60 = ${minutes} мин.`,
      `${cm} см = ${cm * 10} мм. Қабат саны: ${cm * 10} : ${dec(t10)} = ${N}. Уақыт: ${N} · ${sec} с = ${N * sec} с = ${N * sec} : 60 = ${minutes} мин.`,
    ),
    hint: l("Найди число слоёв (не забудь перевести см в мм), умножь на время одного слоя и переведи секунды в минуты.", "Қабат санын тап (см-ді мм-ге айналдыруды ұмытпа), бір қабат уақытына көбейтіп, секундты минутқа айналдыр."),
  });
}

