/** L1: по двум числам из (В, Р, Г) известного многогранника найти третье. */
function eulerFind(rand: Rand, level: Level, seed: number): InputStep {
  const s = pick(rand, SOLIDS);
  const hidden = pick(rand, ["F", "E", "V"] as const);
  let prompt: L;
  let answer: number;
  let calc: L;
  if (hidden === "F") {
    answer = 2 - s.V + s.E;
    prompt = l(`У выпуклого многогранника ${vertsRu(s.V)} и ${edgesRu(s.E)}. Сколько у него граней?`, `Дөңес көпжақтының ${s.V} төбесі және ${s.E} қыры бар. Оның неше жағы бар?`);
    calc = l(`Г = 2 − В + Р = 2 − ${s.V} + ${s.E} = ${answer}`, `Ж = 2 − Т + Қ = 2 − ${s.V} + ${s.E} = ${answer}`);
  } else if (hidden === "E") {
    answer = s.V + s.F - 2;
    prompt = l(
      `У выпуклого многогранника ${vertsRu(s.V)} и ${s.F} ${plural(s.F, "грань", "грани", "граней")}. Сколько у него рёбер?`,
      `Дөңес көпжақтының ${s.V} төбесі және ${s.F} жағы бар. Оның неше қыры бар?`,
    );
    calc = l(`Р = В + Г − 2 = ${s.V} + ${s.F} − 2 = ${answer}`, `Қ = Т + Ж − 2 = ${s.V} + ${s.F} − 2 = ${answer}`);
  } else {
    answer = 2 + s.E - s.F;
    prompt = l(
      `У выпуклого многогранника ${edgesRu(s.E)} и ${s.F} ${plural(s.F, "грань", "грани", "граней")}. Сколько у него вершин?`,
      `Дөңес көпжақтының ${s.E} қыры және ${s.F} жағы бар. Оның неше төбесі бар?`,
    );
    calc = l(`В = 2 + Р − Г = 2 + ${s.E} − ${s.F} = ${answer}`, `Т = 2 + Қ − Ж = 2 + ${s.E} − ${s.F} = ${answer}`);
  }
  return input({
    id: `g:${SKILL}:euler-${hidden}:${s.key}:${seed}`,
    level,
    prompt,
    answer,
    explanation: l(
      `По формуле Эйлера В − Р + Г = 2. Отсюда ${calc.ru}. Такие числа, например, у фигуры «${s.name.ru}».`,
      `Эйлер формуласы бойынша Т − Қ + Ж = 2. Осыдан ${calc.kk}. Мысалы, «${s.name.kk}» фигурасында дәл осындай сандар.`,
    ),
    hint: l("Подставь два известных числа в формулу В − Р + Г = 2 и найди третье.", "Белгілі екі санды Т − Қ + Ж = 2 формуласына қойып, үшіншісін тап."),
  });
}

/** L2: число вершин/рёбер/граней призмы или пирамиды с n-угольным основанием (выбор или ввод). */
function polyCount(rand: Rand, level: Level, seed: number, asInput?: boolean): ChoiceStep | InputStep {
  const kind = pick(rand, ["prism", "pyramid"] as const);
  const what = pick(rand, ["V", "E", "F"] as const);
  const n = int(rand, 5, 9);
  const c = kind === "prism" ? prismOf(n) : pyramidOf(n);
  const answer = c[what];
  const WHAT = {
    V: { ru: "вершин", kk: "төбесі", hint: l("Посчитай вершины у каждого основания и вспомни, сколько оснований, а для пирамиды не забудь вершину наверху.", "Әр негіздің төбелерін санап, негіз санын еске түсір, ал пирамидада жоғарғы төбені ұмытпа.") },
    E: { ru: "рёбер", kk: "қыры", hint: l("Рёбра бывают двух видов: рёбра оснований и боковые рёбра. Посчитай каждый вид отдельно.", "Қырлар екі түрлі: негіздердің қырлары және бүйір қырлар. Әр түрін бөлек сана.") },
    F: { ru: "граней", kk: "жағы", hint: l("Грани — это основания и боковые грани. Посчитай и те и другие.", "Жақтар — негіздер мен бүйір жақтар. Екеуін де сана.") },
  }[what];
  const base = l(`${n}-угольник`, `${n}-бұрыш`);
  const prompt =
    kind === "prism"
      ? l(`Сколько ${WHAT.ru} у призмы, в основании которой ${base.ru}?`, `Негізі ${n}-бұрышты призманың неше ${WHAT.kk} бар?`)
      : l(`Сколько ${WHAT.ru} у пирамиды, в основании которой ${base.ru}?`, `Негізі ${n}-бұрышты пирамиданың неше ${WHAT.kk} бар?`);
  const formula =
    kind === "prism"
      ? l(`У призмы: В = 2n = ${2 * n}, Р = 3n = ${3 * n}, Г = n + 2 = ${n + 2}.`, `Призмада: Т = 2n = ${2 * n}, Қ = 3n = ${3 * n}, Ж = n + 2 = ${n + 2}.`)
      : l(`У пирамиды: В = n + 1 = ${n + 1}, Р = 2n = ${2 * n}, Г = n + 1 = ${n + 1}.`, `Пирамидада: Т = n + 1 = ${n + 1}, Қ = 2n = ${2 * n}, Ж = n + 1 = ${n + 1}.`);
  const explanation = l(
    `${formula.ru} Проверка по Эйлеру: ${c.V} − ${c.E} + ${c.F} = 2.`,
    `${formula.kk} Эйлер бойынша тексеру: ${c.V} − ${c.E} + ${c.F} = 2.`,
  );
  const id = `g:${SKILL}:poly-${kind}-${what}:${n}:${seed}`;
  if (asInput) return input({ id, level, prompt, answer, explanation, hint: WHAT.hint });

  const miss: L = l("Ошибка в подсчёте: пересчитай по группам — основания, боковые элементы, вершина пирамиды.", "Санауда қате: топтап қайта сана — негіздер, бүйір элементтер, пирамида төбесі.");
  const mix = (a: string, b: string, ak: string, bk: string): L => l(`Это число ${a}, а нужно число ${b}.`, `Бұл ${ak} саны, ал ${bk} саны керек.`);
  const wrongs: Wrong[] = [];
  if (kind === "prism") {
    if (what === "V") wrongs.push({ v: String(n), why: l("Это вершины одного основания, а оснований два.", "Бұл бір негіздің төбелері, ал негіз екеу.") }, { v: String(n + 2), why: mix("граней", "вершин", "жақтардың", "төбелердің") }, { v: String(3 * n), why: mix("рёбер", "вершин", "қырлардың", "төбелердің") }, { v: String(2 * n + 1), why: miss });
    if (what === "E") wrongs.push({ v: String(2 * n), why: l("Посчитаны только рёбра двух оснований, боковые рёбра забыты.", "Тек екі негіздің қырлары саналған, бүйір қырлар ұмытылған.") }, { v: String(n), why: l("Это только боковые рёбра, а ещё есть рёбра двух оснований.", "Бұл тек бүйір қырлар, ал екі негіздің қырлары да бар.") }, { v: String(4 * n), why: l("Лишние рёбра: у призмы по n рёбер у каждого из двух оснований и n боковых — всего 3n.", "Артық қырлар: призмада екі негіздің әрқайсысында n қыр және n бүйір қыр бар — барлығы 3n.") }, { v: String(3 * n + 1), why: miss });
    if (what === "F") wrongs.push({ v: String(n), why: l("Посчитаны только боковые грани, а два основания тоже грани.", "Тек бүйір жақтар саналған, ал екі негіз де жақ.") }, { v: String(n + 1), why: l("Учтено одно основание, а у призмы их два.", "Бір негіз ескерілген, ал призмада екеу.") }, { v: String(2 * n), why: mix("вершин", "граней", "төбелердің", "жақтардың") }, { v: String(3 * n), why: mix("рёбер", "граней", "қырлардың", "жақтардың") });
  } else {
    if (what === "V") wrongs.push({ v: String(n), why: l("Это вершины основания, а вершину пирамиды забыли.", "Бұл негіздің төбелері, ал пирамиданың төбесі ұмытылған.") }, { v: String(2 * n), why: mix("рёбер", "вершин", "қырлардың", "төбелердің") }, { v: String(n + 2), why: l("Лишняя вершина: у пирамиды n вершин основания и одна вершина наверху.", "Артық төбе: пирамидада негіздің n төбесі және жоғарыда бір төбе бар.") }, { v: String(n - 1), why: miss });
    if (what === "E") wrongs.push({ v: String(n), why: l("Посчитаны только рёбра основания или только боковые, а нужны оба вида.", "Тек негіздің немесе тек бүйір қырлар саналған, ал екеуі де керек.") }, { v: String(n + 1), why: mix("вершин", "рёбер", "төбелердің", "қырлардың") }, { v: String(3 * n), why: l("Лишние рёбра: n рёбер основания и n боковых дают 2n, а не 3n.", "Артық қырлар: негіздің n қыры және n бүйір қыр барлығы 2n береді, 3n емес.") }, { v: String(2 * n + 1), why: miss });
    if (what === "F") wrongs.push({ v: String(n), why: l("Посчитаны только боковые грани, а основание тоже грань.", "Тек бүйір жақтар саналған, ал негіз де жақ.") }, { v: String(n + 2), why: l("Учтено лишнее основание: у пирамиды оно одно.", "Артық негіз ескерілген: пирамидада ол біреу.") }, { v: String(2 * n), why: mix("рёбер", "граней", "қырлардың", "жақтардың") }, { v: String(2 * n + 1), why: miss });
  }
  return choice(rand, { id, level, prompt, correct: String(answer), wrongs, explanation, hint: WHAT.hint });
}

/** L3: найти число вершин или рёбер по составу граней (каждое ребро общее у двух граней) + формула Эйлера. */
function facesTri(rand: Rand, level: Level, seed: number): InputStep {
  const k = pick(rand, [4, 6, 8, 10, 12, 20]);
  const E = (3 * k) / 2;
  const V = 2 + E - k;
  return input({
    id: `g:${SKILL}:faces-tri:${k}:${seed}`,
    level,
    prompt: l(`Поверхность выпуклого многогранника составлена из ${k} треугольных граней. Сколько у него вершин?`, `Дөңес көпжақтының беті ${k} үшбұрышты жақтан құралған. Оның неше төбесі бар?`),
    answer: V,
    reveal: eulerRow(l("Многогранник", "Көпжақты"), V, E, k),
    explanation: l(
      `У ${k} треугольников ${k} · 3 = ${3 * k} сторон. Каждое ребро общее у двух граней, поэтому Р = ${3 * k} : 2 = ${E}. По Эйлеру В = 2 + Р − Г = 2 + ${E} − ${k} = ${V}.`,
      `${k} үшбұрыштың ${k} · 3 = ${3 * k} қабырғасы бар. Әр қыр екі жаққа ортақ, сондықтан Қ = ${3 * k} : 2 = ${E}. Эйлер бойынша Т = 2 + Қ − Ж = 2 + ${E} − ${k} = ${V}.`,
    ),
    hint: l("Сначала найди число рёбер: у каждой грани 3 стороны, но каждое ребро принадлежит двум граням. Потом подставь в формулу Эйлера.", "Алдымен қыр санын тап: әр жақтың 3 қабырғасы бар, бірақ әр қыр екі жаққа тиесілі. Содан соң Эйлер формуласына қой."),
  });
}

function facesPrism(rand: Rand, level: Level, seed: number): InputStep {
  const n = int(rand, 3, 8);
  const F = n + 2;
  const E = (2 * n + 4 * n) / 2;
  const V = 2 + E - F;
  return input({
    id: `g:${SKILL}:faces-prism:${n}:${seed}`,
    level,
    prompt: l(
      `Две грани выпуклого многогранника — многоугольники с ${n} сторонами, остальные ${n} граней — четырёхугольники. Сколько у него вершин?`,
      `Дөңес көпжақтының екі жағы — ${n} қабырғалы көпбұрыш, ал қалған ${n} жағы — төртбұрыш. Оның неше төбесі бар?`,
    ),
    answer: V,
    explanation: l(
      `Граней Г = 2 + ${n} = ${F}. Сумма сторон: 2 · ${n} + ${n} · 4 = ${6 * n}. Каждое ребро посчитано дважды, поэтому Р = ${6 * n} : 2 = ${E}. По Эйлеру В = 2 + Р − Г = 2 + ${E} − ${F} = ${V}.`,
      `Жақ саны Ж = 2 + ${n} = ${F}. Қабырғалар қосындысы: 2 · ${n} + ${n} · 4 = ${6 * n}. Әр қыр екі рет саналған, сондықтан Қ = ${6 * n} : 2 = ${E}. Эйлер бойынша Т = 2 + Қ − Ж = 2 + ${E} − ${F} = ${V}.`,
    ),
    hint: l("Найди число граней и сумму сторон всех граней, раздели её на 2 — получишь рёбра. Потом используй формулу Эйлера.", "Жақ санын және барлық жақтардың қабырғаларының қосындысын тап, оны 2-ге бөл — қырларды аласың. Содан соң Эйлер формуласын қолдан."),
  });
}

function facesPyr(rand: Rand, level: Level, seed: number): InputStep {
  const n = int(rand, 3, 9);
  const E = (n + 3 * n) / 2;
  return input({
    id: `g:${SKILL}:faces-pyr:${n}:${seed}`,
    level,
    prompt: l(
      `Одна грань многогранника — многоугольник с ${n} сторонами, остальные ${n} граней — треугольники. Сколько у него рёбер?`,
      `Көпжақтының бір жағы — ${n} қабырғалы көпбұрыш, ал қалған ${n} жағы — үшбұрыш. Оның неше қыры бар?`,
    ),
    answer: E,
    explanation: l(
      `Сумма сторон всех граней: ${n} + ${n} · 3 = ${4 * n}. Каждое ребро общее у двух граней и посчитано дважды, поэтому Р = ${4 * n} : 2 = ${E}.`,
      `Барлық жақтардың қабырғаларының қосындысы: ${n} + ${n} · 3 = ${4 * n}. Әр қыр екі жаққа ортақ және екі рет саналған, сондықтан Қ = ${4 * n} : 2 = ${E}.`,
    ),
    hint: l("Сложи стороны всех граней: у каждой грани-многоугольника столько сторон, сколько у неё углов. Каждое ребро попало в сумму дважды.", "Барлық жақтардың қабырғаларын қос. Әр қыр қосындыға екі рет кірген."),
  });
}

/** L3: сетка только из треугольников: по числу рёбер найти число треугольников или вершин (3Г = 2Р). */
function triMesh(rand: Rand, level: Level, seed: number): InputStep {
  const E = pick(rand, [9, 12, 15, 18, 21, 24, 30, 36, 45]);
  const F = (2 * E) / 3;
  const V = 2 + E - F;
  const askV = rand() < 0.5;
  return input({
    id: `g:${SKILL}:trimesh-${askV ? "V" : "F"}:${E}:${seed}`,
    level,
    prompt: askV
      ? l(`Сетка модели — поверхность выпуклого многогранника из одних треугольников, в ней ${edgesRu(E)}. Сколько в ней вершин?`, `Модель торы — тек үшбұрыштардан тұратын дөңес көпжақтының беті, онда ${E} қыр бар. Онда неше төбе бар?`)
      : l(`Сетка модели — поверхность выпуклого многогранника из одних треугольников, в ней ${edgesRu(E)}. Сколько в ней треугольников?`, `Модель торы — тек үшбұрыштардан тұратын дөңес көпжақтының беті, онда ${E} қыр бар. Онда неше үшбұрыш бар?`),
    answer: askV ? V : F,
    explanation: l(
      `У каждого треугольника 3 стороны, а каждое ребро общее у двух треугольников: 3 · Г = 2 · Р, значит Г = 2 · ${E} : 3 = ${F}. Тогда В = 2 + Р − Г = 2 + ${E} − ${F} = ${V}.`,
      `Әр үшбұрыштың 3 қабырғасы бар, ал әр қыр екі үшбұрышқа ортақ: 3 · Ж = 2 · Қ, демек Ж = 2 · ${E} : 3 = ${F}. Сонда Т = 2 + Қ − Ж = 2 + ${E} − ${F} = ${V}.`,
    ),
    hint: l("Каждый треугольник даёт 3 стороны, но каждое ребро общее у двух треугольников. Составь равенство 3 · Г = 2 · Р.", "Әр үшбұрыш 3 қабырға береді, бірақ әр қыр екі үшбұрышқа ортақ. 3 · Ж = 2 · Қ теңдігін құр."),
  });
}

/** L2: сколько треугольников в сетке, если каждую k-угольную грань разбили на k − 2 треугольника. */
function triangles(rand: Rand, level: Level, seed: number): ChoiceStep {
  const kind = pick(rand, ["prism", "pyramid"] as const);
  const n = int(rand, 4, 8);
  const F = kind === "prism" ? n + 2 : n + 1;
  const T = kind === "prism" ? 4 * n - 4 : 2 * n - 2;
  const wrongs: Wrong[] =
    kind === "prism"
      ? [
          { v: String(F), why: l("Это число граней, а каждое основание-многоугольник состоит из нескольких треугольников.", "Бұл жақ саны, ал көпбұрышты негіздің әрқайсысы бірнеше үшбұрыштан тұрады.") },
          { v: String(2 * F), why: l("Каждая грань принята за 2 треугольника, но n-угольник даёт n − 2 треугольника.", "Әр жақ 2 үшбұрыш деп алынған, ал n-бұрыш n − 2 үшбұрыш береді.") },
          { v: String(4 * n), why: l("Основания посчитаны как n треугольников, а нужно n − 2.", "Негіздер n үшбұрыш деп саналған, ал n − 2 керек.") },
          { v: String(4 * n - 2), why: l("Ошибка в счёте: пересчитай боковые грани (по 2 треугольника) и основания (n − 2).", "Санауда қате: бүйір жақтарды (2 үшбұрыштан) және негіздерді (n − 2) қайта сана.") },
          { v: String(3 * n), why: l("Ошибка в счёте: пересчитай по группам.", "Санауда қате: топтап қайта сана.") },
        ]
      : [
          { v: String(F), why: l("Это число граней, а основание-многоугольник состоит из нескольких треугольников.", "Бұл жақ саны, ал көпбұрышты негіз бірнеше үшбұрыштан тұрады.") },
          { v: String(2 * n), why: l("Основание посчитано как n треугольников, а нужно n − 2.", "Негіз n үшбұрыш деп саналған, ал n − 2 керек.") },
          { v: String(n), why: l("Учтены только боковые грани, а основание тоже разбивается на треугольники.", "Тек бүйір жақтар ескерілген, ал негіз де үшбұрыштарға бөлінеді.") },
          { v: String(2 * n - 1), why: l("Ошибка на 1: основание даёт n − 2 треугольника.", "1-ге қателесу: негіз n − 2 үшбұрыш береді.") },
        ];
  const name = kind === "prism" ? l("призма", "призма") : l("пирамида", "пирамида");
  const baseTri = kind === "prism" ? l(`2 · (${n} − 2) = ${2 * (n - 2)}`, `2 · (${n} − 2) = ${2 * (n - 2)}`) : l(`${n} − 2 = ${n - 2}`, `${n} − 2 = ${n - 2}`);
  const side = kind === "prism" ? `${n} · 2 = ${2 * n}` : `${n}`;
  return choice(rand, {
    id: `g:${SKILL}:tri-${kind}:${n}:${seed}`,
    level,
    prompt: l(
      `Грань-многоугольник с k сторонами можно разбить на k − 2 треугольника. Модель — ${name.ru} с ${n}-угольным основанием. Все грани разбили на треугольники. Сколько всего треугольников?`,
      `k қабырғалы көпбұрышты жақты k − 2 үшбұрышқа бөлуге болады. Модель — негізі ${n}-бұрышты ${name.kk}. Барлық жақтар үшбұрыштарға бөлінді. Барлығы неше үшбұрыш болады?`,
    ),
    correct: String(T),
    wrongs,
    explanation: l(
      `${kind === "prism" ? "Основания дают" : "Основание даёт"} ${baseTri.ru}, боковые грани — ${side}. Всего ${T}.`,
      `${kind === "prism" ? "Негіздер" : "Негіз"} ${baseTri.kk} береді, бүйір жақтар — ${side}. Барлығы ${T}.`,
    ),
    hint: l("Разбей на треугольники отдельно основания (n − 2 каждое) и боковые грани (треугольники остаются, четырёхугольники дают 2).", "Негіздерді (әрқайсысы n − 2) және бүйір жақтарды бөлек үшбұрышқа бөл (үшбұрыштар қалады, төртбұрыштар 2 береді)."),
  });
}

// ---------- Генераторы: координаты ----------

const XYZ = (p: readonly number[]) => pt(p);

function coordWrongs(p: number[], d: number[], k: number | null): Wrong[] {
  const add = (a: number[], b: number[]) => a.map((x, i) => x + b[i]);
  const w: Wrong[] = [];
  w.push({ v: XYZ(p.map((x, i) => x - d[i])), why: l("Сдвиг вычтен, а его нужно прибавить.", "Жылжу азайтылған, ал оны қосу керек.") });
  w.push({ v: XYZ([p[0] + d[0], p[1] + d[1], p[2]]), why: l("Третья координата z забыта: сдвиг применяется ко всем трём координатам.", "Үшінші z координатасы ұмытылған: жылжу үш координатаға да қолданылады.") });
  w.push({ v: XYZ([p[0] + d[1], p[1] + d[0], p[2] + d[2]]), why: l("Сдвиги по x и y перепутаны местами.", "x және y бойынша жылжулар орындары ауыстырылған.") });
  w.push({ v: XYZ(p.map((x, i) => x * d[i])), why: l("Координаты умножены на сдвиг, а нужно прибавить.", "Координаталар жылжуға көбейтілген, ал қосу керек.") });
  w.push({ v: XYZ(p.map((x, i) => x + 2 * d[i])), why: l("Сдвиг прибавлен дважды, а нужно один раз.", "Жылжу екі рет қосылған, ал бір рет қосу керек.") });
  if (k !== null) {
    w.length = 0;
    const sum = add(p, d);
    w.push({ v: XYZ(p.map((x, i) => x * k + d[i])), why: l("Порядок действий нарушен: сначала сдвиг, потом масштаб — умножается вся сумма.", "Әрекет реті бұзылған: алдымен жылжу, содан соң масштаб — бүкіл қосынды көбейтіледі.") });
    w.push({ v: XYZ(sum), why: l("Забыто масштабирование: после сдвига координаты нужно ещё умножить на коэффициент.", "Масштабтау ұмытылған: жылжудан кейін координаталарды коэффициентке көбейту керек.") });
    w.push({ v: XYZ(p.map((x) => x * k)), why: l("Забыт сдвиг: к координатам нужно было прибавить числа.", "Жылжу ұмытылған: координаталарға сандарды қосу керек еді.") });
    w.push({ v: XYZ(sum.map((x) => x + k)), why: l("Коэффициент прибавлен, а нужно умножить.", "Коэффициент қосылған, ал көбейту керек.") });
  }
  return w;
}

function randPoint(rand: Rand): number[] {
  return [int(rand, -4, 6), int(rand, -4, 6), int(rand, -4, 6)];
}
function randShift(rand: Rand): number[] {
  const one = () => {
    let v = 0;
    while (v === 0) v = int(rand, -3, 5);
    return v;
  };
  return [one(), one(), one()];
}

/** L2: сдвиг вершины. */
function moveGen(rand: Rand, level: Level, seed: number): ChoiceStep {
  const p = randPoint(rand);
  const d = randShift(rand);
  const res = p.map((x, i) => x + d[i]);
  return choice(rand, {
    id: `g:${SKILL}:move:${p.join("_")}:${d.join("_")}`,
    level,
    prompt: l(
      `К координатам вершины ${pt(p)} прибавили: к x — ${sg(d[0])}, к y — ${sg(d[1])}, к z — ${sg(d[2])}. Какие стали координаты?`,
      `${pt(p)} төбесінің координаталарына қосты: x-ке ${sg(d[0])}, y-ке ${sg(d[1])}, z-ке ${sg(d[2])}. Жаңа координаталары қандай?`,
    ),
    correct: XYZ(res),
    wrongs: coordWrongs(p, d, null),
    explanation: l(
      `Перемещение — прибавление к каждой координате: (${sg(p[0])} + ${sg(d[0])}; ${sg(p[1])} + ${sg(d[1])}; ${sg(p[2])} + ${sg(d[2])}) = ${pt(res)}.`,
      `Орын ауыстыру — әр координатаға қосу: (${sg(p[0])} + ${sg(d[0])}; ${sg(p[1])} + ${sg(d[1])}; ${sg(p[2])} + ${sg(d[2])}) = ${pt(res)}.`,
    ),
    hint: l("Прибавь каждое число сдвига к своей координате: x к x, y к y, z к z.", "Жылжудың әр санын өз координатасына қос: x-ке x, y-ке y, z-ке z."),
  });
}

/** L2: масштаб от начала координат. */
function scaleGen(rand: Rand, level: Level, seed: number): ChoiceStep {
  const p = randPoint(rand).map((v) => (v === 0 ? 1 : v));
  const k = int(rand, 2, 4);
  const res = p.map((x) => x * k);
  return choice(rand, {
    id: `g:${SKILL}:scale-pt:${p.join("_")}:${k}`,
    level,
    prompt: l(
      `Модель увеличили в ${k} ${timesRu(k)} относительно начала координат. В какую точку перейдёт вершина ${pt(p)}?`,
      `Модель координаталар басына қатысты ${k} есе үлкейтілді. ${pt(p)} төбесі қай нүктеге ауысады?`,
    ),
    correct: XYZ(res),
    wrongs: [
      { v: XYZ(p.map((x) => x + k)), why: l("Коэффициент прибавлен, а при масштабировании координаты умножают.", "Коэффициент қосылған, ал масштабтағанда координаталарды көбейтеді.") },
      { v: XYZ([p[0] * k, p[1], p[2]]), why: l("Умножена только координата x, а масштаб применяется ко всем трём.", "Тек x координатасы көбейтілген, ал масштаб үшеуіне де қолданылады.") },
      { v: XYZ([p[1] * k, p[0] * k, p[2] * k]), why: l("Координаты x и y перепутаны местами.", "x және y координаталарының орындары ауыстырылған.") },
      { v: XYZ(p.map((x) => x * k * k)), why: l("Коэффициент применён дважды.", "Коэффициент екі рет қолданылған.") },
      { v: XYZ(p.map((x) => x * (k + 1))), why: l("Ошибка в коэффициенте: нужно умножать на " + k + ".", "Коэффициентте қате: " + k + " санына көбейту керек.") },
    ],
    explanation: l(
      `Масштабирование — умножение каждой координаты на ${k}: ${pt(p)} → ${pt(res)}.`,
      `Масштабтау — әр координатаны ${k} санына көбейту: ${pt(p)} → ${pt(res)}.`,
    ),
    hint: l("Умножь каждую из трёх координат на коэффициент масштаба.", "Үш координатаның әрқайсысын масштаб коэффициентіне көбейт."),
  });
}

/** L3: сначала сдвиг, потом масштаб. */
function comboGen(rand: Rand, level: Level, seed: number): ChoiceStep {
  const p = randPoint(rand);
  const d = randShift(rand);
  const k = int(rand, 2, 3);
  const sum = p.map((x, i) => x + d[i]);
  const res = sum.map((x) => x * k);
  return choice(rand, {
    id: `g:${SKILL}:combo:${p.join("_")}:${d.join("_")}:${k}`,
    level,
    prompt: l(
      `Вершину ${pt(p)} сначала сдвинули: к x, y, z прибавили ${sg(d[0])}, ${sg(d[1])}, ${sg(d[2])}. Затем модель увеличили в ${k} ${timesRu(k)} относительно начала координат. Какие стали координаты вершины?`,
      `${pt(p)} төбесі алдымен жылжытылды: x, y, z-ке ${sg(d[0])}, ${sg(d[1])}, ${sg(d[2])} қосылды. Содан кейін модель координаталар басына қатысты ${k} есе үлкейтілді. Төбенің жаңа координаталары қандай?`,
    ),
    correct: XYZ(res),
    wrongs: coordWrongs(p, d, k),
    explanation: l(
      `После сдвига: ${pt(sum)}. После увеличения в ${k} ${timesRu(k)}: ${pt(res)}.`,
      `Жылжудан кейін: ${pt(sum)}. ${k} есе үлкейткеннен кейін: ${pt(res)}.`,
    ),
    hint: l("Выполняй действия по порядку: сначала прибавь сдвиг, потом умножь результат на коэффициент.", "Әрекеттерді ретімен орында: алдымен жылжуды қос, содан соң нәтижені коэффициентке көбейт."),
  });
}

// ---------- Генераторы: масштаб объёма ----------

