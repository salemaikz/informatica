export const BANKS: SkillBank[] = [
  {
    skill: SKILL,
    question(level, seed) {
      const rand = seeded(seed);
      if (rand() < 0.55) return pick(rand, Q_GENS[level])(rand, level, seed);
      return pool.question(level, seed + 99991);
    },
    statement(level, seed) {
      const rand = seeded(seed);
      const r = rand();
      if (r < 0.45) return pool.statement!(level, seed + 99991);
      if (level === 1) return layersStatement(rand, level);
      if (level === 2) return r < 0.7 ? eulerStatement(rand, level) : layersStatement(rand, level);
      return r < 0.75 ? eulerStatement(rand, level) : scaleStatement(rand, level);
    },
    pair(level, seed) {
      const rand = seeded(seed);
      if (level >= 2 && rand() < 0.35) return solidPair(rand, level);
      return pool.pair!(level, seed + 99991);
    },
    short(level, seed) {
      const rand = seeded(seed);
      if (level === 1 && rand() < 0.4) return pick(rand, STATIC_SHORTS);
      return toShort(pick(rand, S_GENS[level])(rand, level, seed));
    },
  },
];
