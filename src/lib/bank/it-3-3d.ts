// ---------- Утверждения (с расчётом кодом) ----------

function eulerStatement(rand: Rand, level: Level): Statement {
  const s = pick(rand, SOLIDS_PAIR);
  const value = rand() < 0.5;
  let { V, E, F } = s;
  if (!value) {
    const which = int(rand, 0, 2);
    const delta = pick(rand, [-1, 1, 2]);
    if (which === 0) V += delta;
    else if (which === 1) E += delta;
    else F += delta;
  }
  const sum = V - E + F;
  return {
    id: `s:${SKILL}:euler:${V}:${E}:${F}`,
    skill: SKILL,
    level,
    text: l(`Числа В = ${V}, Р = ${E}, Г = ${F} удовлетворяют формуле Эйлера`, `Т = ${V}, Қ = ${E}, Ж = ${F} сандары Эйлер формуласын қанағаттандырады`),
    value: sum === 2,
    explanation: l(
      `${V} − ${E} + ${F} = ${sum}, ${sum === 2 ? "это равно 2: формула выполняется." : "а по формуле Эйлера должно быть 2."}`,
      `${V} − ${E} + ${F} = ${sum}, ${sum === 2 ? "бұл 2-ге тең: формула орындалады." : "ал Эйлер формуласы бойынша 2 болуы керек."}`,
    ),
    hint: l("Вычисли В − Р + Г и сравни с двойкой.", "Т − Қ + Ж-ны есепте де, екімен салыстыр."),
  };
}

function layersStatement(rand: Rand, level: Level): Statement {
  const t10 = pick(rand, [10, 5, 2]);
  const H = int(rand, 4, 30);
  const N = (H * 10) / t10;
  const value = rand() < 0.5;
  const delta = pick(rand, [-10, -5, 5, 10, N]);
  const claim = value ? N : N + delta > 0 ? N + delta : N + 5;
  return {
    id: `s:${SKILL}:layers:${H}:${t10}:${claim}`,
    skill: SKILL,
    level,
    text: l(
      `Модель высотой ${H} мм при толщине слоя ${dec(t10)} мм печатается за ${claim} ${plural(claim, "слой", "слоя", "слоёв")}`,
      `Биіктігі ${H} мм модель қабат қалыңдығы ${dec(t10)} мм болғанда ${claim} қабатпен басылады`,
    ),
    value: claim === N,
    explanation: l(
      `Число слоёв = ${H} : ${dec(t10)} = ${N}${claim === N ? "." : `, а не ${claim}.`}`,
      `Қабат саны = ${H} : ${dec(t10)} = ${N}${claim === N ? "." : `, ${claim} емес.`}`,
    ),
    hint: l("Раздели высоту на толщину слоя.", "Биіктікті қабат қалыңдығына бөл."),
  };
}

function scaleStatement(rand: Rand, level: Level): Statement {
  const k = int(rand, 2, 5);
  const value = rand() < 0.5;
  const claim = value ? k ** 3 : pick(rand, [k * k, k, 3 * k]);
  return {
    id: `s:${SKILL}:scale:${k}:${claim}`,
    skill: SKILL,
    level,
    text: l(
      `При увеличении всех размеров модели в ${k} ${timesRu(k)} её объём вырастет в ${claim} ${timesRu(claim)}`,
      `Модельдің барлық өлшемдерін ${k} есе үлкейткенде, оның көлемі ${claim} есе өседі`,
    ),
    value: claim === k ** 3,
    explanation: l(
      `Объём растёт как k³: ${k}³ = ${k ** 3}${claim === k ** 3 ? "." : `, а не ${claim}.`}`,
      `Көлем k³ болып өседі: ${k}³ = ${k ** 3}${claim === k ** 3 ? "." : `, ${claim} емес.`}`,
    ),
    hint: l("Объём зависит от трёх размеров.", "Көлем үш өлшемге тәуелді."),
  };
}

// ---------- Пары: фигура ↔ числа ----------

function solidPair(rand: Rand, level: Level): Pair {
  const list = level === 1 ? SOLIDS.slice(0, 3) : level === 2 ? SOLIDS : SOLIDS_PAIR;
  const s = pick(rand, list);
  return {
    id: `p:${SKILL}:solid:${s.key}`,
    skill: SKILL,
    level,
    left: s.name,
    right: l(`В = ${s.V}, Р = ${s.E}, Г = ${s.F}`, `Т = ${s.V}, Қ = ${s.E}, Ж = ${s.F}`),
  };
}

