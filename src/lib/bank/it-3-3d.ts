interface Wrong {
  v: string;
  why: L;
}

/** Вопрос с 4 вариантами: верный + три разных неверных (лишние кандидаты отбрасываются). */
function choice(
  rand: Rand,
  o: { id: string; level: Level; prompt: L; scene?: Scene; correct: string; wrongs: Wrong[]; explanation: L; hint: L },
): ChoiceStep {
  const seen = new Set([o.correct]);
  const picked: Wrong[] = [];
  for (const w of o.wrongs) {
    if (seen.has(w.v)) continue;
    seen.add(w.v);
    picked.push(w);
    if (picked.length === 3) break;
  }
  if (picked.length < 3) throw new Error(`${SKILL} ${o.id}: не хватило неверных вариантов`);
  const items = shuffle([{ v: o.correct, why: null as L | null }, ...picked.map((w) => ({ v: w.v, why: w.why as L | null }))], rand);
  return {
    type: "choice",
    id: o.id,
    skill: SKILL,
    level: o.level,
    prompt: o.prompt,
    scene: o.scene,
    options: items.map((i) => i.v),
    correct: items.findIndex((i) => i.why === null),
    whyWrong: items.map((i) => i.why),
    explanation: o.explanation,
    hint: o.hint,
  };
}

function input(o: { id: string; level: Level; prompt: L; scene?: Scene; answer: number; explanation: L; hint: L; reveal?: Scene }): InputStep {
  return {
    type: "input",
    id: o.id,
    skill: SKILL,
    level: o.level,
    prompt: o.prompt,
    scene: o.scene,
    reveal: o.reveal,
    answers: [String(o.answer)],
    mode: "number",
    explanation: o.explanation,
    hint: o.hint,
  };
}

const eulerRow = (name: Text, V: number, E: number, F: number): Scene => ({
  kind: "table",
  columns: [l("Фигура", "Фигура"), l("В", "Т"), l("Р", "Қ"), l("Г", "Ж"), l("В − Р + Г", "Т − Қ + Ж")],
  rows: [[name, String(V), String(E), String(F), String(V - E + F)]],
  mono: true,
});

