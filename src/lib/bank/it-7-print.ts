// Банк навыка it.print (3D-печать и форматы моделей). Знания (технологии, форматы, настройки слайсера) — статичный пул.
// Расчёты — генераторы: масса и стоимость детали, расход Q = h · w · v и время печати, размер двоичного STL (84 + 50 · n).
// Ответ всегда считает код; параметры подбираются так, чтобы ответ получался целым.
// Тексты после переменных чисел — без падежных окончаний (в казахском окончание зависит от числа).

const SKILL = "it.print";

const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const l = (ru: string, kk: string): L => ({ ru, kk });
const same = (s: string): L => ({ ru: s, kk: s });

/** Число с неразрывными пробелами по тысячам: 1 000 084. */
const grp = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00a0");
/** Десятичное число с запятой: 1.25 → «1,25». */
const dc = (x: number) => String(x).replace(".", ",");
/** 1000 : m — точно или с многоточием (отбрасываем, а не округляем: 19,96… → «19,9…»). */
const div1000 = (m: number) => (1000 % m === 0 ? String(1000 / m) : `${dc(Math.floor((10000 / m)) / 10)}…`);

// ---------- Сборка заданий ----------

function input(o: { id: string; level: Level; prompt: L; scene?: Scene; answer: number; explanation: L; hint: L; reveal?: Scene }): InputStep {
  return {
    type: "input",
    id: o.id,
    skill: SKILL,
    level: o.level,
    prompt: o.prompt,
    scene: o.scene,
    reveal: o.reveal,
    answers: [String(o.answer)],
    mode: "number",
    explanation: o.explanation,
    hint: o.hint,
  };
}

// ---------- Генераторы: масса и стоимость ----------

/** Куб с ребром a см, заполнение k %, плотность ρ/100 г/см³: масса — целое число граммов. */
function massParams(rand: Rand, minM = 1, maxM = 100000) {
  for (let i = 0; i < 80; i++) {
    const a = pick(rand, [2, 3, 4, 5, 6, 8, 10]);
    const k = pick(rand, [20, 25, 40, 50, 60, 75, 100]);
    const rho = pick(rand, [120, 125, 105]);
    const num = a ** 3 * k * rho;
    const m = num / 10000;
    if (num % 10000 === 0 && m >= minM && m <= maxM) return { a, k, rho, m, V: a ** 3, Vp: (a ** 3 * k) / 100 };
  }
  return { a: 4, k: 50, rho: 125, m: 40, V: 64, Vp: 32 };
}

function massGen(rand: Rand, level: Level): InputStep {
  if (level === 1) {
    const V = pick(rand, [8, 12, 16, 20, 24, 28, 32, 40, 60, 80]);
    const m = (V * 125) / 100;
    return input({
      id: `g:${SKILL}:mass-1:${V}`,
      level,
      prompt: l(
        `Деталь занимает объём ${V} см³. Плотность пластика 1,25 г/см³. Какова масса детали в граммах?`,
        `Бөлшектің көлемі ${V} см³. Пластик тығыздығы 1,25 г/см³. Бөлшек массасы неше грамм?`,
      ),
      answer: m,
      explanation: l(`Масса = плотность · объём = 1,25 · ${V} = ${m} г.`, `Масса = тығыздық · көлем = 1,25 · ${V} = ${m} г.`),
      hint: l("Умножь плотность на объём.", "Тығыздықты көлемге көбейт."),
    });
  }
  if (level === 2) {
    const { a, k, rho, m, V, Vp } = massParams(rand, 4, 400);
    const price = pick(rand, [6000, 8000, 9000, 10000]);
    const cost = (m * price) / 1000;
    return input({
      id: `g:${SKILL}:mass-2:${a}:${k}:${rho}:${price}`,
      level,
      prompt: l(
        `Куб с ребром ${a} см печатают с заполнением ${k} % (стенки не считаем). Плотность пластика ${dc(rho / 100)} г/см³, катушка 1 кг стоит ${grp(price)} ₸. Сколько тенге стоит пластик на эту деталь?`,
        `Қыры ${a} см кубты ${k} % толтырумен басып шығарады (қабырғаларды санамаймыз). Пластик тығыздығы ${dc(rho / 100)} г/см³, 1 кг катушка ${grp(price)} ₸ тұрады. Осы бөлшекке кететін пластиктің құны неше теңге?`,
      ),
      answer: cost,
      explanation: l(
        `Объём куба ${a}³ = ${V} см³. Пластика внутри: ${V} · ${k} % = ${dc(Vp)} см³. Масса: ${dc(rho / 100)} · ${dc(Vp)} = ${m} г. Один грамм стоит ${price / 1000} ₸, значит ${m} · ${price / 1000} = ${cost} ₸.`,
        `Куб көлемі ${a}³ = ${V} см³. Ішіндегі пластик: ${V} · ${k} % = ${dc(Vp)} см³. Масса: ${dc(rho / 100)} · ${dc(Vp)} = ${m} г. Бір грамның құны ${price / 1000} ₸, яғни ${m} · ${price / 1000} = ${cost} ₸.`,
      ),
      hint: l(
        "Найди объём пластика (доля заполнения от объёма куба), потом массу, потом переведи цену катушки в цену грамма.",
        "Пластик көлемін тап (куб көлемінің толтыру үлесі), содан соң массаны, одан кейін катушка бағасын грамм бағасына айналдыр.",
      ),
    });
  }
  const { a, k, rho, m, V, Vp } = massParams(rand, 12, 300);
  const count = Math.floor(1000 / m);
  return input({
    id: `g:${SKILL}:mass-3:${a}:${k}:${rho}`,
    level,
    prompt: l(
      `Куб с ребром ${a} см печатают с заполнением ${k} % (стенки не считаем). Плотность пластика ${dc(rho / 100)} г/см³. Сколько таких кубов можно напечатать из катушки массой 1 кг?`,
      `Қыры ${a} см кубты ${k} % толтырумен басып шығарады (қабырғаларды санамаймыз). Пластик тығыздығы ${dc(rho / 100)} г/см³. Массасы 1 кг катушкадан осындай неше куб басып шығаруға болады?`,
    ),
    answer: count,
    explanation: l(
      `Объём ${a}³ = ${V} см³, пластика ${V} · ${k} % = ${dc(Vp)} см³, масса ${dc(rho / 100)} · ${dc(Vp)} = ${m} г. Из 1000 г: 1000 : ${m} = ${div1000(m)}, целых деталей — ${count} (округляем вниз).`,
      `Көлемі ${a}³ = ${V} см³, пластик ${V} · ${k} % = ${dc(Vp)} см³, масса ${dc(rho / 100)} · ${dc(Vp)} = ${m} г. 1000 г массадан: 1000 : ${m} = ${div1000(m)}, бүтін бөлшек саны — ${count} (төмен қарай дөңгелектейміз).`,
    ),
    hint: l(
      "Найди массу одного куба, потом раздели 1000 г на неё. Дробную часть отбрось: половинки детали не бывает.",
      "Бір кубтың массасын тап, содан соң 1000 г массаны соған бөл. Үтірден кейінгі бөлігін алып таста: жарты бөлшек болмайды.",
    ),
  });
}

// ---------- Генераторы: расход Q = h · w · v и время ----------

/** Толщина слоя и ширина линии — в десятых долях мм, скорость — мм/с; Q = h10 · w10 · v / 100 — целое. */
function flowParams(rand: Rand) {
  for (let i = 0; i < 80; i++) {
    const h10 = pick(rand, [1, 2, 3]);
    const w10 = pick(rand, [4, 5, 6]);
    const v = pick(rand, [30, 40, 50, 60, 80, 100]);
    const prod = h10 * w10 * v;
    if (prod % 100 === 0) return { h10, w10, v, Q: prod / 100 };
  }
  return { h10: 2, w10: 4, v: 50, Q: 4 };
}

function flowGen(rand: Rand, level: Level): InputStep {
  const { h10, w10, v, Q } = flowParams(rand);
  const h = dc(h10 / 10);
  const w = dc(w10 / 10);
  if (level === 1) {
    return input({
      id: `g:${SKILL}:flow-1:${h10}:${w10}:${v}`,
      level,
      prompt: l(
        `Слайсер задал толщину слоя ${h} мм, ширину линии ${w} мм и скорость сопла ${v} мм/с. Каков расход пластика Q = h · w · v в мм³/с?`,
        `Слайсер қабат қалыңдығын ${h} мм, сызық енін ${w} мм және саптама жылдамдығын ${v} мм/с етіп қойды. Пластик шығыны Q = h · w · v неше мм³/с?`,
      ),
      answer: Q,
      explanation: l(`Q = h · w · v = ${h} · ${w} · ${v} = ${Q} мм³/с.`, `Q = h · w · v = ${h} · ${w} · ${v} = ${Q} мм³/с.`),
      hint: l("Перемножь три числа: толщину слоя, ширину линии и скорость.", "Үш санды көбейт: қабат қалыңдығын, сызық енін және жылдамдықты."),
    });
  }
  if (level === 2) {
    // Объём V (см³) подбираем так, чтобы время было целым числом минут.
    const volumes = Array.from({ length: 59 }, (_, i) => i + 2).filter((x) => (x * 1000) % (Q * 60) === 0);
    const V = volumes.length ? pick(rand, volumes) : Q * 6;
    const sec = (V * 1000) / Q;
    const min = sec / 60;
    return input({
      id: `g:${SKILL}:flow-2:${h10}:${w10}:${v}:${V}`,
      level,
      prompt: l(
        `Толщина слоя ${h} мм, ширина линии ${w} мм, скорость ${v} мм/с. На деталь уходит ${V} см³ пластика. Сколько минут печатать? Сопло всё время выдавливает пластик.`,
        `Қабат қалыңдығы ${h} мм, сызық ені ${w} мм, жылдамдық ${v} мм/с. Бөлшекке ${V} см³ пластик кетеді. Неше минут басып шығару керек? Саптама бүкіл уақыт бойы пластик сығып шығарады.`,
      ),
      answer: min,
      explanation: l(
        `Q = ${h} · ${w} · ${v} = ${Q} мм³/с. ${V} см³ = ${grp(V * 1000)} мм³. Время: ${grp(V * 1000)} : ${Q} = ${sec} с = ${min} мин.`,
        `Q = ${h} · ${w} · ${v} = ${Q} мм³/с. ${V} см³ = ${grp(V * 1000)} мм³. Уақыт: ${grp(V * 1000)} : ${Q} = ${sec} с = ${min} мин.`,
      ),
      hint: l(
        "Найди расход Q, переведи см³ в мм³ (в 1 см³ тысяча мм³), раздели объём на расход и переведи секунды в минуты.",
        "Q шығынын тап, см³ бірлігін мм³ бірлігіне айналдыр (1 см³ ішінде мың мм³), көлемді шығынға бөл де, секундты минутқа айналдыр.",
      ),
    });
  }
  // Уровень C: время печати → объём → масса (плотность 1,25) → сколько деталей из катушки.
  const rhoTxt = "1,25";
  const mins = [30, 40, 50, 60, 75, 80, 90, 100, 120, 150].filter((t) => Number.isInteger((Q * t * 60 * 125) / 100000));
  const ok = mins.filter((t) => {
    const g = (Q * t * 60 * 125) / 100000;
    return g >= 12 && g <= 400;
  });
  if (!ok.length) return reverseFixed();
  const min = pick(rand, ok);
  const m = (Q * min * 60 * 125) / 100000;
  const count = Math.floor(1000 / m);
  const sec = min * 60;
  const V = Q * sec;
  return input({
    id: `g:${SKILL}:flow-3:${Q}:${min}`,
    level,
    prompt: l(
      `Одна деталь печатается ${min} мин при расходе ${Q} мм³/с. Плотность пластика ${rhoTxt} г/см³. Сколько таких деталей можно напечатать из катушки массой 1 кг? Сопло всё время выдавливает пластик.`,
      `Бір бөлшек ${min} мин басылады, шығын ${Q} мм³/с. Пластик тығыздығы ${rhoTxt} г/см³. Массасы 1 кг катушкадан осындай неше бөлшек басып шығаруға болады? Саптама бүкіл уақыт бойы пластик сығып шығарады.`,
    ),
    answer: count,
    explanation: l(
      `${min} мин = ${sec} с. Объём V = Q · t = ${Q} · ${sec} = ${grp(V)} мм³ = ${dc(V / 1000)} см³. Масса: ${rhoTxt} · ${dc(V / 1000)} = ${m} г. Из 1000 г: 1000 : ${m} = ${div1000(m)}, целых деталей — ${count} (округляем вниз).`,
      `${min} мин = ${sec} с. Көлем V = Q · t = ${Q} · ${sec} = ${grp(V)} мм³ = ${dc(V / 1000)} см³. Масса: ${rhoTxt} · ${dc(V / 1000)} = ${m} г. 1000 г массадан: 1000 : ${m} = ${div1000(m)}, бүтін бөлшек саны — ${count} (төмен қарай дөңгелектейміз).`,
    ),
    hint: l(
      "Цепочка: минуты в секунды, объём V = Q · t, перевод мм³ в см³, масса, потом сколько раз масса детали укладывается в 1000 г (дробную часть отбрось).",
      "Тізбек: минутты секундқа айналдыру, көлем V = Q · t, мм³ бірлігін см³ бірлігіне айналдыру, масса, содан соң бөлшек массасы 1000 г массаға неше рет сияды (үтірден кейінгі бөлігін алып таста).",
    ),
  });
}

/** Запасной вариант уровня C (числа из урока): 2 ч 30 мин, Q = 4 мм³/с, 1,25 г/см³ → 45 г → 22 детали. */
function reverseFixed(): InputStep {
  return input({
    id: `g:${SKILL}:flow-3:4:150`,
    level: 3,
    prompt: l(
      "Одна деталь печатается 150 мин при расходе 4 мм³/с. Плотность пластика 1,25 г/см³. Сколько таких деталей можно напечатать из катушки массой 1 кг? Сопло всё время выдавливает пластик.",
      "Бір бөлшек 150 мин басылады, шығын 4 мм³/с. Пластик тығыздығы 1,25 г/см³. Массасы 1 кг катушкадан осындай неше бөлшек басып шығаруға болады? Саптама бүкіл уақыт бойы пластик сығып шығарады.",
    ),
    answer: 22,
    explanation: l(
      "150 мин = 9000 с. V = 4 · 9000 = 36 000 мм³ = 36 см³. Масса: 1,25 · 36 = 45 г. 1000 : 45 = 22,2…, целых деталей — 22.",
      "150 мин = 9000 с. V = 4 · 9000 = 36 000 мм³ = 36 см³. Масса: 1,25 · 36 = 45 г. 1000 : 45 = 22,2…, бүтін бөлшек саны — 22.",
    ),
    hint: l("Минуты в секунды, V = Q · t, затем масса и деление 1000 г на неё.", "Минутты секундқа айналдыр, V = Q · t, содан соң масса және 1000 г массаны соған бөлу."),
  });
}

// ---------- Генераторы: размер двоичного STL ----------

function stlGen(rand: Rand, level: Level): InputStep {
  const n = pick(rand, [1000, 2000, 4000, 5000, 8000, 10000, 20000, 25000, 50000, 100000]);
  if (level === 1) {
    const size = 84 + 50 * n;
    return input({
      id: `g:${SKILL}:stl-1:${n}`,
      level,
      prompt: l(
        `Двоичный STL: 80 байт заголовок, 4 байта число треугольников и по 50 байт на треугольник. Модель из ${grp(n)} треугольников. Сколько байт займёт файл?`,
        `Екілік STL: 80 байт тақырып, үшбұрыштар санына 4 байт және әр үшбұрышқа 50 байттан. Модель ${grp(n)} үшбұрыштан тұрады. Файл неше байт алады?`,
      ),
      answer: size,
      explanation: l(`Размер = 84 + 50 · n = 84 + 50 · ${grp(n)} = ${grp(size)} байт.`, `Көлем = 84 + 50 · n = 84 + 50 · ${grp(n)} = ${grp(size)} байт.`),
      hint: l("Умножь число треугольников на 50 и прибавь служебные байты: заголовок и счётчик.", "Үшбұрыштар санын 50-ге көбейтіп, қызметтік байттарды қос: тақырып пен санауыш."),
    });
  }
  if (level === 2) {
    const size = 84 + 50 * n;
    return input({
      id: `g:${SKILL}:stl-2:${n}`,
      level,
      prompt: l(
        `Двоичный STL: 80 байт заголовок, 4 байта число треугольников и по 50 байт на треугольник. Размер файла ${grp(size)} байт. Сколько в модели треугольников?`,
        `Екілік STL: 80 байт тақырып, үшбұрыштар санына 4 байт және әр үшбұрышқа 50 байттан. Файл көлемі ${grp(size)} байт. Модельде неше үшбұрыш бар?`,
      ),
      answer: n,
      explanation: l(
        `Служебные данные: 80 + 4 = 84 байта. На треугольники: ${grp(size)} − 84 = ${grp(50 * n)} байт. Число треугольников: ${grp(50 * n)} : 50 = ${grp(n)}.`,
        `Қызметтік деректер: 80 + 4 = 84 байт. Үшбұрыштарға: ${grp(size)} − 84 = ${grp(50 * n)} байт. Үшбұрыштар саны: ${grp(50 * n)} : 50 = ${grp(n)}.`,
      ),
      hint: l("Сначала вычти служебные байты, потом раздели остаток на 50.", "Алдымен қызметтік байттарды алып таста, содан соң қалғанын 50-ге бөл."),
    });
  }
  const k = pick(rand, [2, 3, 4]);
  const size = 84 + 50 * k * n;
  return input({
    id: `g:${SKILL}:stl-3:${n}:${k}`,
    level,
    prompt: l(
      `Двоичный STL: 80 байт заголовок, 4 байта число треугольников и по 50 байт на треугольник. Модель из ${grp(n)} треугольников сгладили, и треугольников стало в ${k} раза больше. Сколько байт займёт новый файл?`,
      `Екілік STL: 80 байт тақырып, үшбұрыштар санына 4 байт және әр үшбұрышқа 50 байттан. ${grp(n)} үшбұрыштан тұратын модельді тегістеді, үшбұрыштар ${k} есе көбейді. Жаңа файл неше байт алады?`,
    ),
    answer: size,
    explanation: l(
      `Новое число треугольников: ${grp(n)} · ${k} = ${grp(k * n)}. Размер: 84 + 50 · ${grp(k * n)} = ${grp(size)} байт. Служебные 84 байта от числа треугольников не зависят.`,
      `Үшбұрыштардың жаңа саны: ${grp(n)} · ${k} = ${grp(k * n)}. Көлем: 84 + 50 · ${grp(k * n)} = ${grp(size)} байт. Қызметтік 84 байт үшбұрыштар санына тәуелді емес.`,
    ),
    hint: l(
      "Сначала найди новое число треугольников, потом применяй формулу 84 + 50 · n. Не умножай на k служебные байты.",
      "Алдымен үшбұрыштардың жаңа санын тап, содан соң 84 + 50 · n формуласын қолдан. Қызметтік байттарды k-ға көбейтпе.",
    ),
  });
}

