/** Вопрос с одним верным: верный вариант первым (poolBank перемешивает варианты сам). */
function mc(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return {
    type: "choice",
    id: `p:${SKILL}:${id}`,
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrongs.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((w) => w[1])],
    explanation,
    hint,
  };
}

/** Вопрос «выберите верные»: options — [текст, верно?, почему неверно (для неверных)]. */
function mm(id: string, level: Level, prompt: L, rows: [Text, boolean, L | null][], explanation: L, hint: L): MultiStep {
  return {
    type: "multi",
    id: `p:${SKILL}:${id}`,
    skill: SKILL,
    level,
    prompt,
    options: rows.map((r) => r[0]),
    correct: rows.flatMap((r, i) => (r[1] ? [i] : [])),
    whyWrong: rows.map((r) => (r[1] ? null : r[2])),
    explanation,
    hint,
  };
}

