/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: верные первыми, потом неверные. */
function mu(id: string, level: Level, prompt: L, rights: Text[], wrongs: [Text, L][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: [...rights, ...wrongs.map((x) => x[0])],
    correct: rights.map((_, i) => i),
    whyWrong: [...rights.map(() => null), ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Ввод числа. */
function inp(id: string, level: Level, prompt: L, answer: number, explanation: L, hint: L): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, answers: [String(answer)], mode: "number", explanation, hint };
}

function mt(id: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], explanation: L, hint: L): MatchStep {
  return { id: `p:${SKILL}:${id}`, type: "match", skill: SKILL, level, prompt, pairs, explanation, hint };
}

