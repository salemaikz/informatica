// Банк навыка net.topology («Виды сетей и топологии», тема ЕНТ t02).
// Знания (PAN/LAN/MAN/WAN, топологии и их поломки, архитектуры, выбор сети) — статичный пул.
// Расчёты — генератор: кабели звезды/кольца, полной сетки, дерева; порты; обратная задача «по числу кабелей найти число
// компьютеров»; размер группы после двух обрывов двустороннего кольца. Ответ всегда считает код (в id — параметры),
// независимо перепроверено в scripts/out/net-5-topology/verify.py.
// Договорённость: классическое кольцо — данные в одну сторону (обрыв останавливает передачу); в задачах про группы
// сказано «кабели передают данные в обе стороны». После переменных чисел казахские тексты без падежных окончаний.

const SKILL = "net.topology";

const w = (ru: string, kk: string): L => ({ ru, kk });
const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const mesh = (n: number) => (n * (n - 1)) / 2;

// ---------- Расчётные задания ----------

interface Wrong {
  v: number;
  why: L;
}

interface Calc {
  /** Семейство с параметрами: g:net.topology:<вид>:<параметры>. */
  id: string;
  level: Level;
  stem: L;
  ask: L;
  answer: number;
  wrongs: Wrong[];
  mode: "choice" | "input";
  hint: L;
  explanation: L;
}

type Gen = (rand: Rand) => Calc;

const ASK_CABLES = w("Сколько кабелей нужно?", "Неше кабель қажет?");
const ASK_PORTS = w("Сколько портов сетевой карты нужно у каждого компьютера?", "Әр компьютерде желілік картаның неше порты қажет?");

