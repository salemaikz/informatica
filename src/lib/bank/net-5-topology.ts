/** B: кабели дерева — главный коммутатор, f этажных, по p компьютеров. */
const calcTree = (level: 2 | 3): Gen => (rand) => {
  const f = level === 2 ? int(rand, 2, 4) : int(rand, 4, 6);
  const p = level === 2 ? int(rand, 4, 10) : int(rand, 8, 15);
  const ans = f + f * p;
  return {
    id: `g:${SKILL}:tree${level}:f${f}p${p}`,
    level,
    stem: w(
      `Школа-дерево: один главный коммутатор. Коммутаторов этажей: ${f} (по одному на этаж). Компьютеров на каждом этаже: ${p}. Коммутаторы этажей подключены к главному, компьютеры к своему коммутатору, каждое устройство одним кабелем.`,
      `Мектеп-ағаш: бір басты коммутатор. Қабат коммутаторларының саны: ${f} (әр қабатқа біреу). Әр қабаттағы компьютер саны: ${p}. Қабат коммутаторлары басты коммутаторға, компьютерлер өз коммутаторына жалғанған, әр құрылғы бір кабельмен.`,
    ),
    ask: w("Сколько всего кабелей?", "Барлығы неше кабель?"),
    answer: ans,
    wrongs: [
      { v: f * p, why: w("Забыты кабели между главным коммутатором и коммутаторами этажей.", "Басты коммутатор мен қабат коммутаторлары арасындағы кабельдер ұмытылған.") },
      { v: f * p + f + 1, why: w("Это число устройств, а кабелей на один меньше.", "Бұл құрылғы саны, ал кабель біреуге аз.") },
      { v: f + p, why: w("Сложены число этажей и число компьютеров на этаже, а нужно учесть все компьютеры.", "Қабат саны мен қабаттағы компьютер саны қосылған, ал барлық компьютерді есепке алу керек.") },
      { v: f * (p + 1) + 1, why: w("Лишний кабель: у главного коммутатора нет кабеля «наверх».", "Артық кабель: басты коммутатордың «жоғары» баратын кабелі жоқ.") },
    ].filter((x) => x.v > 0),
    mode: level === 2 ? "choice" : "input",
    hint: w(
      "Считай по уровням: кабели от главного коммутатора к этажным и кабели от этажных к компьютерам. Или найди число устройств и вычти 1.",
      "Деңгейлер бойынша сана: басты коммутатордан қабаттықтарға және қабаттықтардан компьютерлерге баратын кабельдер. Немесе құрылғы санын тауып, 1-ді азайт.",
    ),
    explanation: w(
      `Кабелей к этажным коммутаторам: ${f}. Кабелей к компьютерам: ${f} · ${p} = ${f * p}. Всего ${f} + ${f * p} = ${ans}. Проверка: устройств 1 + ${f} + ${f * p} = ${1 + f + f * p}, а кабелей на 1 меньше: ${ans}.`,
      `Қабат коммутаторларына баратын кабель: ${f}. Компьютерлерге баратын кабель: ${f} · ${p} = ${f * p}. Барлығы ${f} + ${f * p} = ${ans}. Тексеру: құрылғы 1 + ${f} + ${f * p} = ${1 + f + f * p}, ал кабель 1-ге аз: ${ans}.`,
    ),
  };
};

/** C: обратная задача — по числу кабелей полной сетки найти число компьютеров или портов. */
const calcMeshInverse: Gen = (rand) => {
  const n = int(rand, 5, 12);
  const cables = mesh(n);
  const ports = rand() < 0.5;
  const ans = ports ? n - 1 : n;
  return {
    id: `g:${SKILL}:meshi${ports ? "p" : "n"}:n${n}`,
    level: 3,
    stem: w(`Сеть построена по схеме «каждый с каждым». Кабелей в сети: ${cables}.`, `Желі «әрқайсысы әрқайсысымен» схемасымен құрылған. Желідегі кабель саны: ${cables}.`),
    ask: ports ? w("Сколько портов у каждого компьютера?", "Әр компьютерде неше порт бар?") : w("Сколько компьютеров в сети?", "Желіде неше компьютер бар?"),
    answer: ans,
    wrongs: [
      { v: ports ? n : n - 1, why: w("Перепутаны число компьютеров и число портов: портов на один меньше, чем компьютеров.", "Компьютер саны мен порт саны шатастырылған: порт компьютер санынан біреуге аз.") },
      { v: cables, why: w("Это число кабелей из условия, а не ответ.", "Бұл шарттағы кабель саны, жауап емес.") },
    ],
    mode: "input",
    hint: w(
      `Составь уравнение n(n − 1) / 2 = ${cables} и подбери два соседних числа, произведение которых ${2 * cables}.`,
      `n(n − 1) / 2 = ${cables} теңдеуін құрып, көбейтіндісі ${2 * cables} болатын екі көрші санды таңда.`,
    ),
    explanation: w(
      `n(n − 1) / 2 = ${cables}, значит n(n − 1) = ${2 * cables} = ${n} · ${n - 1}, то есть компьютеров n = ${n}. ${ports ? `Портов у каждого компьютера: ${n} − 1 = ${n - 1}.` : ""}`.trim(),
      `n(n − 1) / 2 = ${cables}, демек n(n − 1) = ${2 * cables} = ${n} · ${n - 1}, яғни компьютер саны n = ${n}. ${ports ? `Әр компьютерде ${n} − 1 = ${n - 1} порт бар.` : ""}`.trim(),
    ),
  };
};

/** C: два обрыва двустороннего кольца — размер меньшей группы. */
const calcRingCuts: Gen = (rand) => {
  const N = int(rand, 6, 10);
  let a = 1;
  let b = 2;
  do {
    a = int(rand, 1, N - 2);
    b = int(rand, a + 1, N - 1);
  } while (2 * (b - a) === N);
  const d = b - a;
  const small = Math.min(d, N - d);
  const large = Math.max(d, N - d);
  return {
    id: `g:${SKILL}:ringcut:N${N}a${a}b${b}`,
    level: 3,
    stem: w(
      `Кольцо из ${N} компьютеров, пронумерованных по кругу; кабели передают данные в обе стороны. Оборваны кабели ${a}–${a + 1} и ${b}–${b + 1}.`,
      `${N} компьютерден тұратын сақина, компьютерлер шеңбер бойымен нөмірленген; кабельдер деректерді екі бағытта береді. Үзілген кабельдер: ${a}–${a + 1} және ${b}–${b + 1}.`,
    ),
    ask: w("Сколько компьютеров в меньшей из двух образовавшихся групп?", "Пайда болған екі топтың кішісінде неше компьютер бар?"),
    answer: small,
    wrongs: [
      { v: large, why: w("Это размер большей группы, а нужна меньшая.", "Бұл үлкен топтың өлшемі, ал кішісі керек.") },
      { v: N, why: w("Два обрыва делят кольцо на две отдельные группы: все компьютеры уже не связаны.", "Екі үзіліс сақинаны екі бөлек топқа бөледі: барлық компьютер енді байланыспаған.") },
      { v: 2, why: w("Это число групп, а нужно число компьютеров в меньшей из них.", "Бұл топ саны, ал олардың кішісіндегі компьютер саны керек.") },
    ],
    mode: "input",
    hint: w(
      "Две группы — это два участка кольца между обрывами. Посчитай, сколько компьютеров лежит между номерами обрывов.",
      "Екі топ — үзілістер арасындағы сақинаның екі бөлігі. Үзіліс нөмірлерінің арасында неше компьютер жатқанын сана.",
    ),
    explanation: w(
      `Обрывы делят кольцо на участок ${a + 1}…${b} (компьютеров: ${d}) и остальные (компьютеров: ${N} − ${d} = ${N - d}). Меньшая группа: ${small}.`,
      `Үзілістер сақинаны ${a + 1}…${b} бөлігіне (компьютер саны: ${d}) және қалғанына (компьютер саны: ${N} − ${d} = ${N - d}) бөледі. Кіші топ: ${small}.`,
    ),
  };
};

const GENS: Record<Level, Gen[]> = {
  1: [calcStarRing],
  2: [calcMeshCables, calcMeshPorts, calcTree(2)],
  3: [calcTree(3), calcMeshInverse, calcRingCuts],
};

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const c = pick(rand, GENS[level])(rand);
  const base = { skill: SKILL, level: c.level, hint: c.hint, explanation: c.explanation };
  const prompt = w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`);
  const id = `${c.id}:${seed % 100000}`;
  if (c.mode === "input") {
    const step: InputStep = { ...base, id, type: "input", prompt, answers: [String(c.answer)], mode: "number" };
    return step;
  }
  // Три неверных варианта (разные значения), верный — среди них в случайном месте.
  const uniq: Wrong[] = [];
  for (const x of c.wrongs) if (x.v !== c.answer && !uniq.some((u) => u.v === x.v)) uniq.push(x);
  const items = shuffle([{ v: c.answer, why: null as L | null }, ...uniq.slice(0, 3)], rand);
  const step: ChoiceStep = {
    ...base,
    id,
    type: "choice",
    prompt,
    options: items.map((x) => String(x.v)),
    correct: items.findIndex((x) => x.v === c.answer),
    whyWrong: items.map((x) => x.why),
  };
  return step;
}

function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x3c6ef372);
  const c = pick(rand, GENS[level])(rand);
  return {
    id: `${c.id}:s${seed % 100000}`,
    skill: SKILL,
    level: c.level,
    prompt: w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`),
    answer: String(c.answer),
    mode: "number",
    explanation: c.explanation,
    hint: c.hint,
  };
}

