// ---------- Таблицы ----------

type Cell = Text;
const table = (columns: Text[], rows: Cell[][], caption?: Text): Scene => ({ kind: "table", columns, rows, caption });

/** Две таблицы рядом (пустой столбец-разделитель); короткая таблица добивается пустыми строками. */
const side = (lc: Text[], lr: Cell[][], rc: Text[], rr: Cell[][]): Scene => {
  const n = Math.max(lr.length, rr.length);
  const pad = (rows: Cell[][], w: number): Cell[][] => Array.from({ length: n }, (_, i) => rows[i] ?? Array<Cell>(w).fill(""));
  const a = pad(lr, lc.length);
  const b = pad(rr, rc.length);
  return table([...lc, "", ...rc], a.map((row, i) => [...row, "", ...b[i]]));
};

