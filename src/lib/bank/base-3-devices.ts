const w = (ru: string, kk: string): L => ({ ru, kk });

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: ChoiceStep["scene"]): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
    ...(scene ? { scene } : {}),
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [Text, boolean, L?][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

/** Ввод числа (сколько устройств ввода/вывода). */
function num(id: string, level: Level, prompt: L, answer: number, explanation: L, hint: L, scene?: InputStep["scene"]): InputStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "input",
    skill: SKILL,
    level,
    prompt,
    answers: [String(answer)],
    mode: "number",
    explanation,
    hint,
    ...(scene ? { scene } : {}),
  };
}

