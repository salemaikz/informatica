// и задания с расчётом. Шифртексты и числа в тексте считает код (enc/dec), а не набраны руками.
// Тексты после чисел — без падежных окончаний (в казахском окончание зависит от числа).

const SKILL = "net.crypto";
const T = (ru: string, kk: string): L => ({ ru, kk });

// ---------- шифр Цезаря (латиница, 26 букв, A = 0) ----------
const ABC = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const shift = (w: string, k: number) =>
  w
    .split("")
    .map((c) => ABC[(((ABC.indexOf(c) + k) % 26) + 26) % 26])
    .join("");
const enc = (w: string, k: number) => shift(w, k);
const dec = (w: string, k: number) => shift(w, -k);

type Opt = [ru: string, kk: string];
type WrongOpt = [ru: string, kk: string, whyRu: string, whyKk: string];

/** choice: верный вариант + неверные с разбором. Порядок перемешает poolBank. */
function ch(id: string, level: Level, prompt: Opt, right: Opt, wrongs: WrongOpt[], hint: Opt, expl: Opt): ChoiceStep {
  return {
    type: "choice",
    skill: SKILL,
    id: `p:${SKILL}:${id}`,
    level,
    prompt: T(...prompt),
    options: [T(...right), ...wrongs.map((w) => T(w[0], w[1]))],
    correct: 0,
    whyWrong: [null, ...wrongs.map((w) => T(w[2], w[3]))],
    hint: T(...hint),
    explanation: T(...expl),
  };
}

/** multi: несколько верных + неверные с разбором. */
function mu(id: string, level: Level, prompt: Opt, rights: Opt[], wrongs: WrongOpt[], hint: Opt, expl: Opt): MultiStep {
  return {
    type: "multi",
    skill: SKILL,
    id: `p:${SKILL}:${id}`,
    level,
    prompt: T(...prompt),
    options: [...rights.map((r) => T(...r)), ...wrongs.map((w) => T(w[0], w[1]))],
    correct: rights.map((_, i) => i),
    whyWrong: [...rights.map(() => null), ...wrongs.map((w) => T(w[2], w[3]))],
    hint: T(...hint),
    explanation: T(...expl),
  };
}

function inp(id: string, level: Level, prompt: Opt, answer: string, mode: "number" | "text", hint: Opt, expl: Opt): InputStep {
  return {
    type: "input",
    skill: SKILL,
    id: `p:${SKILL}:${id}`,
    level,
    prompt: T(...prompt),
    answers: mode === "text" ? [answer, answer.toLowerCase()] : [answer],
    mode,
    hint: T(...hint),
    explanation: T(...expl),
  };
}

function ord(id: string, level: Level, prompt: Opt, items: Opt[], hint: Opt, expl: Opt): OrderStep {
  return {
    type: "order",
    skill: SKILL,
    id: `p:${SKILL}:${id}`,
    level,
    prompt: T(...prompt),
    items: items.map((i) => T(...i)),
    hint: T(...hint),
    explanation: T(...expl),
  };
}

