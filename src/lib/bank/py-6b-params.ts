// ---------- Конструкторы заданий ----------

interface ChoiceArgs {
  id: string;
  level: Level;
  prompt?: L;
  scene?: Scene;
  options: Text[];
  correct: number;
  hint: L;
  explanation: L;
  whyWrong: (L | null)[];
}

const choice = (a: ChoiceArgs): ChoiceStep => ({
  id: `p:${SKILL}:${a.id}`,
  type: "choice",
  skill: SKILL,
  level: a.level,
  prompt: a.prompt ?? WHAT_PRINTS,
  scene: a.scene,
  options: a.options,
  correct: a.correct,
  hint: a.hint,
  explanation: a.explanation,
  whyWrong: a.whyWrong,
});

interface InputArgs {
  id: string;
  level: Level;
  prompt?: L;
  scene: Scene;
  answer: string;
  hint: L;
  explanation: L;
}

const input = (a: InputArgs): InputStep => ({
  id: `p:${SKILL}:${a.id}`,
  type: "input",
  skill: SKILL,
  level: a.level,
  prompt: a.prompt ?? WHAT_PRINTS,
  scene: a.scene,
  answers: [a.answer],
  mode: "number",
  hint: a.hint,
  explanation: a.explanation,
});

