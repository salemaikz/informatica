const SKILL = "net.protocols";
const w = (ru: string, kk: string): L => ({ ru, kk });

/** Неверный вариант: текст и объяснение, почему он неверен. */
type Wrong = [Text, L];

/** choice: верный вариант всегда первый — poolBank перемешает варианты по seed вместе с whyWrong. */
function ch(name: string, level: Level, prompt: L, correct: Text, wrongs: Wrong[], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${name}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** multi: whyWrong — по одному на каждый вариант (у верных null). */
function mu(name: string, level: Level, prompt: L, options: Text[], correct: number[], whyWrong: (L | null)[], explanation: L, hint: L): MultiStep {
  return { id: `p:${SKILL}:${name}`, type: "multi", skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint };
}

function num(name: string, level: Level, prompt: L, answer: string, explanation: L, hint: L): InputStep {
  return { id: `p:${SKILL}:${name}`, type: "input", skill: SKILL, level, prompt, answers: [answer], mode: "number", suffix: "байт", explanation, hint };
}

