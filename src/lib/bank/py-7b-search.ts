interface ChoiceArgs {
  name: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  options: Text[];
  correct: number;
  whyWrong: (L | null)[];
  explanation: L;
  hint: L;
}

const choice = (a: ChoiceArgs): ChoiceStep => ({
  id: `p:${SKILL}:${a.name}`,
  type: "choice",
  skill: SKILL,
  level: a.level,
  prompt: a.prompt,
  scene: a.scene,
  options: a.options,
  correct: a.correct,
  whyWrong: a.whyWrong,
  explanation: a.explanation,
  hint: a.hint,
});

interface InputArgs {
  name: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  answer: string;
  explanation: L;
  hint: L;
}

const input = (a: InputArgs): InputStep => ({
  id: `p:${SKILL}:${a.name}`,
  type: "input",
  skill: SKILL,
  level: a.level,
  prompt: a.prompt,
  scene: a.scene,
  answers: [a.answer],
  mode: "number",
  explanation: a.explanation,
  hint: a.hint,
});

const match = (name: string, level: Level, prompt: L, pairs: MatchStep["pairs"], explanation: L, hint: L): MatchStep => ({
  id: `p:${SKILL}:${name}`,
  type: "match",
  skill: SKILL,
  level,
  prompt,
  pairs,
  explanation,
  hint,
});

const order = (name: string, level: Level, prompt: L, items: OrderStep["items"], explanation: L, hint: L): OrderStep => ({
  id: `p:${SKILL}:${name}`,
  type: "order",
  skill: SKILL,
  level,
  prompt,
  items,
  explanation,
  hint,
});

