/** choice: первый вариант — верный (poolBank перемешает варианты вместе с whyWrong). */
function choice(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  right: Text,
  wrong: [Text, L][],
  hint: L,
  explanation: L,
  reveal?: Scene,
): ChoiceStep {
  return {
    type: "choice",
    id: qid(name),
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [right, ...wrong.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrong.map((w) => w[1])],
    hint,
    explanation,
    reveal,
  };
}

/** input: числовой ответ. */
function num(name: string, level: Level, prompt: L, scene: Scene | undefined, answer: number, hint: L, explanation: L, reveal?: Scene): InputStep {
  return { type: "input", id: qid(name), skill: SKILL, level, prompt, scene, answers: [String(answer)], mode: "number", hint, explanation, reveal };
}

/** multi: ok — верный вариант; why — разбор неверного. */
function multi(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  options: { t: Text; ok: boolean; why?: L }[],
  hint: L,
  explanation: L,
): MultiStep {
  return {
    type: "multi",
    id: qid(name),
    skill: SKILL,
    level,
    prompt,
    scene,
    options: options.map((o) => o.t),
    correct: options.flatMap((o, i) => (o.ok ? [i] : [])),
    whyWrong: options.map((o) => (o.ok ? null : (o.why as L))),
    hint,
    explanation,
  };
}

function match(name: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], hint: L, explanation: L): MatchStep {
  return { type: "match", id: qid(name), skill: SKILL, level, prompt, pairs, hint, explanation };
}

