interface Wrong {
  v: number;
  why: L;
}

interface Calc {
  /** Семейство с параметрами, без seed: g:net.hardware:<вид>:<параметры>. */
  id: string;
  level: Level;
  stem: L;
  ask: L;
  answer: number;
  wrongs: Wrong[];
  mode: "choice" | "input";
  hint: L;
  explanation: L;
}

type Gen = (rand: Rand) => Calc;

const ASK_SWITCHES = w("Какое наименьшее число коммутаторов нужно?", "Ең аз неше коммутатор керек?");

/** Условие про здание: n компьютеров, коммутаторы на p портов, один порт каждого занят кабелем к маршрутизатору. */
const buildingStem = (n: number, p: number): L =>
  w(
    `В здании ${n} компьютеров. Коммутаторы на ${p} портов, на каждом один порт занят кабелем к маршрутизатору.`,
    `Ғимаратта ${n} компьютер бар. Коммутаторлар ${p} портты, әрқайсысының бір портына маршрутизаторға баратын кабель қосылған.`,
  );

/** Параметры здания: коммутаторов нужно больше, чем при делении на p (ловушка), число компьютеров не кратно p − 1. */
function building(rand: Rand): { n: number; p: number; sw: number; naive: number } {
  for (let i = 0; i < 40; i++) {
    const p = pick(rand, [8, 16, 24, 48]);
    const n = int(rand, p + 2, 4 * p);
    const sw = Math.ceil(n / (p - 1));
    const naive = Math.ceil(n / p);
    if (sw !== naive && n % (p - 1) !== 0) return { n, p, sw, naive };
  }
  return { n: 48, p: 24, sw: 3, naive: 2 };
}

/** A: сколько портов свободно. */
const calcFree: Gen = (rand) => {
  const p = pick(rand, [8, 16, 24, 48]);
  const k = int(rand, 3, p - 3);
  const ans = p - k;
  return {
    id: `g:${SKILL}:free:p${p}k${k}`,
    level: 1,
    stem: w(`К коммутатору на ${p} портов подключено ${k} устройств.`, `${p} портты коммутаторға ${k} құрылғы қосылған.`),
    ask: w("Сколько портов свободно?", "Неше порт бос?"),
    answer: ans,
    wrongs: [
      { v: p + k, why: w("Подключённые устройства нужно вычитать из числа портов, а не прибавлять.", "Қосылған құрылғыларды порт санынан алу керек, қосуға болмайды.") },
      { v: k, why: w("Это число занятых портов, а спрашивают про свободные.", "Бұл — бос емес порттар саны, ал сұрақ бос порттар туралы.") },
      { v: ans - 1, why: w("Один порт лишний вычтен: свободных ровно столько, сколько осталось после подключения устройств.", "Бір порт артық шегерілген: бос порттар құрылғылар қосылғаннан кейін қалғанына тең.") },
      { v: ans + 1, why: w("Один порт лишний прибавлен: проверь вычитание.", "Бір порт артық қосылған: алуды тексер.") },
    ].filter((x) => x.v > 0 && x.v !== ans),
    mode: "choice",
    hint: w("Свободные порты — это все порты без тех, к которым уже что-то подключено.", "Бос порттар — барлық порттан бір нәрсе қосылған порттарды алып тастағанда қалғаны."),
    explanation: w(`Свободно ${p} − ${k} = ${ans} портов.`, `Бос порт: ${p} − ${k} = ${ans}.`),
  };
};

/** A: Мбит/с → МБ/с. */
