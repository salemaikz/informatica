/** C: сколько коммутаторов нужно. */
const calcSwitches: Gen = (rand) => {
  const { n, p, sw, naive } = building(rand);
  return {
    id: `g:${SKILL}:swcount:n${n}p${p}`,
    level: 3,
    stem: buildingStem(n, p),
    ask: ASK_SWITCHES,
    answer: sw,
    wrongs: [
      { v: naive, why: w("Забыт порт под кабель к маршрутизатору: делить нужно на число портов минус один.", "Маршрутизатор кабеліне арналған порт ұмытылған: порт санынан бірді алып бөлу керек.") },
      { v: sw + 1, why: w("Коммутаторов больше, чем нужно: проверь деление и округление вверх.", "Коммутатор қажеттіден көп: бөлу мен жоғары дөңгелектеуді тексер.") },
      { v: Math.floor(n / (p - 1)), why: w("Округлять нужно вверх: остаток компьютеров тоже надо подключить.", "Жоғары дөңгелектеу керек: қалған компьютерлерді де қосу керек.") },
    ].filter((x) => x.v > 0 && x.v !== sw),
    mode: "input",
    hint: w("Сначала найди, сколько компьютеров принимает один коммутатор, потом раздели и округли вверх.", "Алдымен бір коммутатор қанша компьютер қабылдайтынын тап, содан кейін бөліп, жоғары қарай дөңгелекте."),
    explanation: w(
      `На одном коммутаторе для компьютеров ${p} − 1 = ${p - 1} портов. ${n} : ${p - 1} ≈ ${num(n / (p - 1))}, округляем вверх: ${sw}. (Без учёта занятого порта вышло бы ${naive}: этого мало.)`,
      `Бір коммутаторда компьютерлерге ${p} − 1 = ${p - 1} порт бар. ${n} : ${p - 1} ≈ ${num(n / (p - 1))}, жоғары дөңгелектейміз: ${sw}. (Бос емес портты ескермесе, ${naive} шығар еді: бұл аз.)`,
    ),
  };
};

/** C: сколько всего кабелей. */
const calcCables: Gen = (rand) => {
  const { n, p, sw } = building(rand);
  const ans = n + sw;
  return {
    id: `g:${SKILL}:cables:n${n}p${p}`,
    level: 3,
    stem: buildingStem(n, p),
    ask: w(
      "Сколько всего кабелей в локальной сети, считая кабели от коммутаторов к маршрутизатору?",
      "Коммутаторлардан маршрутизаторға баратын кабельдерді қоса есептегенде, жергілікті желіде барлығы неше кабель бар?",
    ),
    answer: ans,
    wrongs: [{ v: n, why: w("Это только кабели к компьютерам.", "Бұл тек компьютерлерге баратын кабельдер.") }],
    mode: "input",
    hint: w("Сначала найди число коммутаторов. Потом сложи кабели к компьютерам и кабели к маршрутизатору.", "Алдымен коммутатор санын тап. Содан кейін компьютерлерге және маршрутизаторға баратын кабельдерді қос."),
    explanation: w(
      `Коммутаторов: ${n} : ${p - 1} ≈ ${num(n / (p - 1))}, округляем вверх до ${sw}. Кабелей: ${n} к компьютерам и ${sw} к маршрутизатору, всего ${n} + ${sw} = ${ans}.`,
      `Коммутатор: ${n} : ${p - 1} ≈ ${num(n / (p - 1))}, жоғары қарай ${sw}-ке дейін дөңгелектейміз. Кабель: компьютерлерге ${n} және маршрутизаторға ${sw}, барлығы ${n} + ${sw} = ${ans}.`,
    ),
  };
};

/** C: сколько портов останется свободно. */
const calcFreeTotal: Gen = (rand) => {
  const { n, p, sw } = building(rand);
  const ans = sw * p - (n + sw);
  return {
    id: `g:${SKILL}:freetotal:n${n}p${p}`,
    level: 3,
    stem: buildingStem(n, p),
    ask: w("Сколько портов на всех коммутаторах останется свободно?", "Барлық коммутаторларда неше порт бос қалады?"),
    answer: ans,
    wrongs: [],
    mode: "input",
    hint: w("Найди число коммутаторов и все порты. Занятых портов столько же, сколько кабелей.", "Коммутатор санын және барлық порттарды тап. Бос емес порттар саны кабель санына тең."),
    explanation: w(
      `Коммутаторов ${sw}, всего портов ${sw} · ${p} = ${sw * p}. Занято ${n} + ${sw} = ${n + sw} (по порту на кабель). Свободно ${sw * p} − ${n + sw} = ${ans}.`,
      `Коммутатор ${sw}, барлық порт ${sw} · ${p} = ${sw * p}. Бос емес порт ${n} + ${sw} = ${n + sw} (әр кабельге бір порттан). Бос порт ${sw * p} − ${n + sw} = ${ans}.`,
    ),
  };
};

/** C: канал делится между устройствами — время скачивания. */
const calcShared: Gen = (rand) => {
  let v = 100;
  let k = 5;
  let m = 50;
  for (let i = 0; i < 60; i++) {
    const tv = pick(rand, [60, 80, 100, 200]);
    const tk = pick(rand, [2, 4, 5, 10]);
    const tm = int(rand, 1, 20) * 5;
    if ((tm * 8 * tk) % tv === 0) {
      v = tv;
      k = tk;
      m = tm;
      break;
    }
  }
  const each = v / k;
  const t = (m * 8) / each;
  return {
    id: `g:${SKILL}:shared:v${v}k${k}m${m}`,
    level: 3,
    stem: w(
      `Тариф — ${v} Мбит/с, канал делится поровну между ${k} устройствами, которые скачивают файлы одновременно.`,
      `Тариф — ${v} Мбит/с, арна файл жүктеп жатқан ${k} құрылғының арасында тең бөлінеді.`,
    ),
    ask: w(`За сколько секунд одно устройство скачает файл ${m} МБ? (1 байт = 8 бит)`, `Бір құрылғы ${m} МБ файлды неше секундта жүктейді? (1 байт = 8 бит)`),
    answer: t,
    wrongs: [],
    mode: "input",
    hint: w("Сначала найди скорость одного устройства, потом объём в мегабитах, и только потом дели.", "Алдымен бір құрылғының жылдамдығын тап, содан кейін көлемді мегабитпен, ең соңында бөл."),
    explanation: w(
      `Скорость одного устройства: ${v} : ${k} = ${num(each)} Мбит/с. Объём: ${m} · 8 = ${m * 8} Мбит. Время: ${m * 8} : ${num(each)} = ${num(t)} с.`,
      `Бір құрылғының жылдамдығы: ${v} : ${k} = ${num(each)} Мбит/с. Көлем: ${m} · 8 = ${m * 8} Мбит. Уақыт: ${m * 8} : ${num(each)} = ${num(t)} с.`,
    ),
  };
};

const GENS: Record<Level, Gen[]> = {
  1: [calcFree, calcMbs],
  2: [calcPerSwitch, calcTime],
  3: [calcSwitches, calcCables, calcFreeTotal, calcShared],
};

/** Ответ-число в виде строки: целые без запятой, дробные с запятой. */
const answerText = (c: Calc) => (Number.isInteger(c.answer) ? String(c.answer) : num(c.answer));

function calcQuestion(level: Level, rand: Rand, seed: number): QuestionStep {
  const c = pick(rand, GENS[level])(rand);
  const base = { skill: SKILL, level: c.level, scene: undefined, hint: c.hint, explanation: c.explanation };
  const prompt = w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`);
  const id = `${c.id}:${seed % 100000}`;
  if (c.mode === "input") {
    const step: InputStep = { ...base, id, type: "input", prompt, answers: [answerText(c)], mode: Number.isInteger(c.answer) ? "number" : "text" };
    return step;
  }
  const uniq: Wrong[] = [];
  for (const x of c.wrongs) if (!uniq.some((u) => u.v === x.v)) uniq.push(x);
  const items = shuffle([{ v: c.answer, why: null as L | null }, ...uniq.slice(0, 3)], rand);
  const step: ChoiceStep = {
    ...base,
    id,
    type: "choice",
    prompt,
    options: items.map((x) => num(x.v)),
    correct: items.findIndex((x) => x.v === c.answer),
    whyWrong: items.map((x) => x.why),
  };
  return step;
}

/** Короткий ответ: только целые ответы (в режиме number запятая теряется). */
function calcShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x3c6ef372);
  let c = pick(rand, GENS[level])(rand);
  for (let i = 0; i < 20 && !Number.isInteger(c.answer); i++) c = pick(rand, GENS[level])(rand);
  return {
    id: `${c.id}:s${seed % 100000}`,
    skill: SKILL,
    level: c.level,
    prompt: w(`${c.stem.ru} ${c.ask.ru}`, `${c.stem.kk} ${c.ask.kk}`),
    answer: String(Math.round(c.answer)),
    mode: "number",
    explanation: c.explanation,
    hint: c.hint,
  };
}

// ---------- Статичный пул: знания ----------

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: верные идут первыми (их число — k), остальные — неверные с пояснением. */
function mu(id: string, level: Level, prompt: L, right: Text[], wrongs: [Text, L][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: [...right, ...wrongs.map((x) => x[0])],
    correct: right.map((_, i) => i),
    whyWrong: [...right.map(() => null), ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

