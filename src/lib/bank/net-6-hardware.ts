const pool = poolBank({ skill: SKILL, questions, statements, pairs, shorts });

const hardware: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed ^ 0x6a09e667);
    // Примерно треть заданий — расчёт, остальные — знания из пула.
    if (rand() < 0.35) return calcQuestion(level, rand, seed);
    return pool.question(level, seed);
  },
  statement: pool.statement,
  pair: pool.pair,
  short(level, seed) {
    const rand = seeded(seed ^ 0x2545f491);
    if (rand() < 0.4) return pool.short!(level, seed);
    return calcShort(level, seed);
  },
};

export const BANKS: SkillBank[] = [hardware];
