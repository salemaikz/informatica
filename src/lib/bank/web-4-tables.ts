/** Ячейка таблицы: t — текст, th — ячейка-заголовок, cs/rs — colspan/rowspan. */
export interface TCell {
  t: string;
  th?: boolean;
  cs?: number;
  rs?: number;
}

export const td = (t: string, cs = 1, rs = 1): TCell => ({ t, cs, rs });
export const th = (t: string, cs = 1, rs = 1): TCell => ({ t, th: true, cs, rs });

export interface TInfo {
  rows: number;
  cols: number;
  /** Все записанные ячейки (td + th). */
  cells: number;
  td: number;
  th: number;
}

/** Раскладывает ячейки по сетке (как браузер) и считает итоги. Бросает ошибку, если в сетке дырка или перекрытие. */
export function tableInfo(rows: TCell[][]): TInfo {
  const occ: boolean[][] = rows.map(() => []);
  let cols = 0;
  rows.forEach((row, r) => {
    let c = 0;
    for (const cell of row) {
      while (occ[r][c]) c++;
      const cs = cell.cs ?? 1;
      const rs = cell.rs ?? 1;
      for (let dr = 0; dr < rs; dr++) {
        for (let dc = 0; dc < cs; dc++) {
          if (r + dr >= rows.length) throw new Error(`rowspan выходит за таблицу (строка ${r + 1})`);
          if (occ[r + dr][c + dc]) throw new Error(`ячейки перекрываются (строка ${r + 1})`);
          occ[r + dr][c + dc] = true;
        }
      }
      c += cs;
      cols = Math.max(cols, c);
    }
  });
  rows.forEach((_, r) => {
    for (let c = 0; c < cols; c++) if (!occ[r][c]) throw new Error(`в таблице дырка: строка ${r + 1}, столбец ${c + 1}`);
  });
  const flat = rows.flat();
  const nTh = flat.filter((x) => x.th).length;
  return { rows: rows.length, cols, cells: flat.length, td: flat.length - nTh, th: nTh };
}

const cellTag = (c: TCell): string => {
  const name = c.th ? "th" : "td";
  const attrs = (c.rs && c.rs > 1 ? ` rowspan="${c.rs}"` : "") + (c.cs && c.cs > 1 ? ` colspan="${c.cs}"` : "");
  return `<${name}${attrs}>${c.t}</${name}>`;
};

/** Строка таблицы (tr) в виде строк кода: compact — одной строкой, если она не длиннее 60 символов. */
function rowLines(row: TCell[], compact: boolean): string[] {
  const one = `    <tr>${row.map(cellTag).join("")}</tr>`;
  if (compact && one.length <= 60) return [one];
  return ["    <tr>", ...row.map((c) => `        ${cellTag(c)}`), "    </tr>"];
}

/** Код таблицы: compact — вся строка таблицы в одной строке кода (если не длиннее 60 символов, иначе — по ячейкам). */
export function tableLines(rows: TCell[][], compact = false): string[] {
  tableInfo(rows);
  return ['<table border="1">', ...rows.flatMap((r) => rowLines(r, compact)), "</table>"];
}

/** Начало таблицы: первые shown строк, затем пустая строка «<tr> ... </tr>» (её нужно дописать в задании). Всю таблицу проверяет tableInfo. */
export function tablePartial(rows: TCell[][], shown: number, compact = false): string[] {
  tableInfo(rows);
  return ['<table border="1">', ...rows.slice(0, shown).flatMap((r) => rowLines(r, compact)), "    <tr>", "        ...", "    </tr>", "</table>"];
}

