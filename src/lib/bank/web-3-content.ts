const SKILL = "web.content";

const T = (ru: string, kk: string): L => ({ ru, kk });
const html = (lines: string[]): Scene => ({ kind: "code", lang: "html", lines });
const web = (lines: string[]): Scene => ({ kind: "web", html: lines.join("\n") });
const files = (tree: FileNode[], active: string): Scene => ({ kind: "files", tree, active });

/** Выбор из 4: whyWrong — по одному на вариант (у верного null). */
function ch(
  id: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number,
  whyWrong: (L | null)[],
  explanation: L,
  hint: L,
  scene?: Scene,
  reveal?: Scene,
): ChoiceStep {
  return { id: `g:${SKILL}:${id}`, type: "choice", skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint, scene, reveal };
}

/** Ввод числа: ответ — одно число. */
function inp(id: string, level: Level, prompt: L, answer: string, explanation: L, hint: L, scene?: Scene, reveal?: Scene): InputStep {
  return { id: `g:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, answers: [answer], mode: "number", explanation, hint, scene, reveal };
}

/** Несколько верных из 6. */
function mu(
  id: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number[],
  whyWrong: (L | null)[],
  explanation: L,
  hint: L,
  scene?: Scene,
  reveal?: Scene,
): MultiStep {
  return { id: `g:${SKILL}:${id}`, type: "multi", skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint, scene, reveal };
}

