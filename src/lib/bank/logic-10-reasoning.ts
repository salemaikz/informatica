/** Выбор: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrongs.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((w) => w[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: верные идут первыми. */
function mu(id: string, level: Level, prompt: L, rights: Text[], wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [...rights, ...wrongs.map((w) => w[0])],
    correct: rights.map((_, i) => i),
    whyWrong: [...rights.map(() => null), ...wrongs.map((w) => w[1])],
    explanation,
    hint,
  };
}

function inp(id: string, level: Level, prompt: L, answers: string[], explanation: L, hint: L, scene?: Scene): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, answers, mode: "number", explanation, hint };
}

function ord(id: string, level: Level, prompt: L, items: L[], explanation: L, hint: L): OrderStep {
  return { id: `p:${SKILL}:${id}`, type: "order", skill: SKILL, level, prompt, items, explanation, hint };
}

function mat(id: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], explanation: L, hint: L): MatchStep {
  return { id: `p:${SKILL}:${id}`, type: "match", skill: SKILL, level, prompt, pairs, explanation, hint };
}

