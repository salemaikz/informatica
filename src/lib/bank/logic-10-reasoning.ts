/** Условие задачи: сколько высказываний истинны (t) или ложны (f). */
type CondKey = "t1" | "t2" | "f1";
const COND: Record<CondKey, { truth: boolean; k: number; text: L }> = {
  t1: { truth: true, k: 1, text: T("ровно одно высказывание истинно", "пікірлердің дәл біреуі ақиқат") },
  t2: { truth: true, k: 2, text: T("ровно два высказывания истинны", "пікірлердің дәл екеуі ақиқат") },
  f1: { truth: false, k: 1, text: T("ровно одно высказывание ложно", "пікірлердің дәл біреуі жалған") },
};

/** Истинна ли фраза, если виновен culprit; speaker — тот, кто её произнёс. */
function holds(st: St, culprit: string, speaker: string): boolean {
  if (st.k === "it") return culprit === st.x;
  if (st.k === "not") return culprit !== st.x;
  if (st.k === "either") return culprit === st.x || culprit === st.y;
  return culprit !== speaker;
}

function randomSt(rand: Rand, names: string[], speaker: string): St {
  const others = names.filter((n) => n !== speaker);
  const r = rand();
  if (r < 0.32) return { k: "it", x: pick(rand, others) };
  if (r < 0.64) return { k: "not", x: pick(rand, others) };
  // «X или Y» из двух других при троих — то же, что «не я»: такой формой пользуемся только при четверых.
  if (names.length === 4 && r < 0.88) {
    const [x, y] = shuffle(others, rand);
    return { k: "either", x, y };
  }
  return { k: "me" };
}

const stKey = (s: St) => `${s.k}${s.x ?? ""}${s.y ?? ""}`;

interface Puzzle {
  names: string[];
  stm: St[];
  cond: CondKey;
  /** Сколько фраз истинны при каждой гипотезе (по порядку names). */
  counts: number[];
  bits: string[];
  answer: number;
}

function makePuzzle(level: Level, rand: Rand): Puzzle {
  const n = level === 1 ? 3 : level === 2 ? (rand() < 0.5 ? 3 : 4) : 4;
  const cond: CondKey = level === 1 ? "t1" : level === 2 ? (n === 3 ? "f1" : "t1") : rand() < 0.5 ? "f1" : "t2";
  const c = COND[cond];
  const need = c.truth ? c.k : n - c.k;
  for (let attempt = 0; attempt < 5000; attempt++) {
    const names = shuffle(NAMES, rand).slice(0, n);
    const stm = names.map((sp) => randomSt(rand, names, sp));
    if (new Set(stm.map(stKey)).size < n) continue;
    const bits = names.map((culprit) => stm.map((s, i) => (holds(s, culprit, names[i]) ? "1" : "0")).join(""));
    const counts = bits.map((b) => b.split("").filter((ch) => ch === "1").length);
    const fit = counts.map((cnt, i) => (cnt === need ? i : -1)).filter((i) => i >= 0);
    if (fit.length !== 1) continue;
    return { names, stm, cond, counts, bits, answer: fit[0] };
  }
  throw new Error("logic.reasoning: не удалось собрать задачу");
}

function stText(ctx: Ctx, s: St): L {
  if (s.k === "it") return ctx.it(s.x!);
  if (s.k === "not") return ctx.not(s.x!);
  if (s.k === "either") return ctx.either(s.x!, s.y!);
  return ctx.me;
}

/** «Кто виноват»: ровно один подозреваемый подходит под условие. */
function qWho(level: Level, seed: number): ChoiceStep {
  const rand = seeded(seed);
  const ctx = pick(rand, CTX);
  const pz = makePuzzle(level, rand);
  const n = pz.names.length;
  const c = COND[pz.cond];
  const need = c.truth ? c.k : n - c.k;
  const scene: Scene = {
    kind: "table",
    columns: [T("Кто говорит", "Кім айтады"), T("Что говорит", "Не айтады")],
    rows: pz.names.map((name, i) => [name, stText(ctx, pz.stm[i])]),
  };
  const rows = pz.names.map((name, i) => `${name}: ${pz.bits[i]} (${pz.counts[i]})`).join("; ");
  const answer = pz.names[pz.answer];
  return {
    id: `g:${SKILL}:who:${pz.cond}-${pz.stm.map(stKey).join("-")}:${seed}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt: {
      ru: `Известно: ${c.text.ru}. ${ctx.q.ru}`,
      kk: `Белгілі: ${c.text.kk}. ${ctx.q.kk}`,
    },
    scene,
    options: pz.names,
    correct: pz.answer,
    whyWrong: pz.names.map((name, i) =>
      i === pz.answer
        ? null
        : T(
            `Если виновен ${name}, истинны ${pz.counts[i]} из ${n} высказываний, а нужно ${need}.`,
            `Егер кінәлі ${name} болса, ${n} пікірдің ${pz.counts[i]}-і ақиқат, ал ${need} керек.`,
          ),
    ),
    hint: T(
      "Для каждого подозреваемого проверь все фразы: сколько из них были бы правдой, если виновен он? Нужна гипотеза, где число совпало с условием.",
      "Әр күдікті үшін барлық сөйлемді тексер: кінәлі сол болса, олардың нешеуі ақиқат болар еді? Саны шартқа сәйкес келетін болжам керек.",
    ),
    explanation: T(
      `Проверяем каждую гипотезу: 1 — фраза правдива, 0 — ложна, фразы идут в порядке таблицы; в скобках число правдивых. ${rows}. Условию («${c.text.ru}») удовлетворяет только ${answer}.`,
      `Әр болжамды тексереміз: 1 — сөйлем ақиқат, 0 — жалған, сөйлемдер кесте реті бойынша; жақшада ақиқаттар саны. ${rows}. Шартқа («${c.text.kk}») тек ${answer} сәйкес келеді.`,
    ),
  };
}

