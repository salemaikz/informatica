/** Шаг шифровки одной буквы: «C = 2: 2 + 3 = 5 → F», при выходе за Z — с вычитанием 26. */
function encTrace(w: string, k: number): string {
  return w
    .split("")
    .map((c) => {
      const n = idx(c);
      const s = n + k;
      return s > 25 ? `${c} = ${n}: ${n} + ${k} = ${s}, ${s} − 26 = ${s - 26} → ${ABC[s - 26]}` : `${c} = ${n}: ${n} + ${k} = ${s} → ${ABC[s]}`;
    })
    .join("; ");
}
function decTrace(w: string, k: number): string {
  return w
    .split("")
    .map((c) => {
      const n = idx(c);
      const d = n - k;
      return d < 0 ? `${c} = ${n}: ${n} − ${k} = ${d}, ${d} + 26 = ${d + 26} → ${ABC[d + 26]}` : `${c} = ${n}: ${n} − ${k} = ${d} → ${ABC[d]}`;
    })
    .join("; ");
}

