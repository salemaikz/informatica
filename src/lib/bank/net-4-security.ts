const ABC = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const idx = (c: string) => ABC.indexOf(c);
const shiftWord = (w: string, k: number) =>
  w
    .split("")
    .map((c) => ABC[(((idx(c) + k) % 26) + 26) % 26])
    .join("");
/** Ошибка «забыли, что в алфавите 26 букв»: при выходе за Z вычитают 25 вместо 26. */
const shiftWrong25 = (w: string, k: number) =>
  w
    .split("")
    .map((c) => {
      const s = idx(c) + k;
      return ABC[s > 25 ? s - 25 : s];
    })
    .join("");
const wraps = (w: string, k: number) => w.split("").some((c) => idx(c) + k > 25);

