function caesarStatement(level: Level, seed: number): Statement {
  const rand = seeded(seed);
  const word = pick(rand, level === 1 ? WORDS3.filter((w) => !wraps(w, 3)) : [...WORDS3, ...WORDS4]);
  const key = level === 1 ? int(rand, 1, 3) : int(rand, 2, 6);
  const value = rand() < 0.5;
  const right = shiftWord(word, key);
  const claim = value ? right : pick(rand, [shiftWord(word, -key), shiftWord(word, key + 1), shiftWord(word, key - 1), shiftWrong25(word, key)].filter((c) => c !== right && c !== word));
  return {
    id: `s:${SKILL}:caesar:${word}:${key}:${claim}`,
    skill: SKILL,
    level,
    text: T(`Шифр Цезаря с ключом ${key} превращает слово ${word} в ${claim}`, `${key} кілтімен Цезарь шифры ${word} сөзін ${claim} сөзіне айналдырады`),
    value: claim === right,
    explanation: T(`${encTrace(word, key)}. Результат: ${right}`, `${encTrace(word, key)}. Нәтиже: ${right}`),
    hint: HINT_ENC,
  };
}

function pwdStatement(level: Level, seed: number): Statement {
  const rand = seeded(seed);
  if (level < 3) {
    const len = int(rand, 3, 6);
    const total = 10 ** len;
    const value = rand() < 0.5;
    const claim = value ? total : pick(rand, [len * 10, 10 ** (len - 1), 10 ** (len + 1)]);
    return {
      id: `s:${SKILL}:pwd-digits:${len}:${claim}`,
      skill: SKILL,
      level,
      text: T(`У пароля из ${len} цифр ровно ${fmt(claim)} вариантов`, `${len} цифрдан тұратын құпиясөздің нұсқалар саны: ${fmt(claim)}`),
      value: claim === total,
      explanation: same(`Nᴸ = 10${sup(len)} = ${fmt(total)}`),
      hint: HINT_NL,
    };
  }
  for (let attempt = 0; attempt < 50; attempt++) {
    const a1 = pick(rand, ALPHAS);
    const a2 = pick(rand, ALPHAS);
    const l1 = int(rand, 4, Math.min(a1.maxLen, 9));
    const l2 = int(rand, 4, Math.min(a2.maxLen, 9));
    const v1 = a1.n ** l1;
    const v2 = a2.n ** l2;
    if (v1 === v2) continue;
    return {
      id: `s:${SKILL}:pwd-compare:${a1.n}:${l1}:${a2.n}:${l2}`,
      skill: SKILL,
      level,
      text: T(`Пароль «${a1.label(l1).ru}» надёжнее пароля «${a2.label(l2).ru}»`, `«${a1.label(l1).kk}» құпиясөзі «${a2.label(l2).kk}» құпиясөзінен берік`),
      value: v1 > v2,
      explanation: same(`${a1.n}${sup(l1)} = ${fmt(v1)}; ${a2.n}${sup(l2)} = ${fmt(v2)}`),
      hint: HINT_COMPARE,
    };
  }
  throw new Error("pwd statement: не удалось подобрать пару");
}

const bank: SkillBank = {
  skill: SKILL,
  question(level, seed) {
    const rand = seeded(seed);
    if (rand() < 0.5) return pool.question(level, seed + 99991);
    return pick(rand, GENS[level])(rand, level, seed);
  },
  statement(level, seed): Statement {
    const rand = seeded(seed);
    const r = rand();
    if (r < 0.5) return pool.statement!(level, seed + 99991);
    return r < 0.75 ? caesarStatement(level, seed) : pwdStatement(level, seed);
  },
  pair(level, seed): Pair {
    const rand = seeded(seed);
    if (level >= 2 && rand() < 0.25) {
      const key = int(rand, 2, 6);
      const word = pick(rand, [...WORDS3, ...WORDS4]);
      return { id: `p:${SKILL}:caesar:${word}:${key}`, skill: SKILL, level, left: `${word} +${key}`, right: shiftWord(word, key) };
    }
    return pool.pair!(level, seed + 99991);
  },
  short(level, seed): ShortQuestion {
    const rand = seeded(seed);
    const r = rand();
    if (r < 0.4) return pool.short!(level, seed + 99991);
    if (r < 0.7) {
      const key = int(rand, 1, 3);
      const word = pick(
        rand,
        WORDS3.filter((w) => !wraps(w, key)),
      );
      const cipher = shiftWord(word, key);
      return {
        id: `q:${SKILL}:caesar:${word}:${key}`,
        skill: SKILL,
        level,
        prompt: T(`Шифр Цезаря, ключ ${key}: зашифруй слово ${word} (латиница)`, `Цезарь шифры, кілт: ${key}. ${word} сөзін шифрла (латын әліпбиі)`),
        answer: cipher,
        mode: "text",
        explanation: T(`${encTrace(word, key)}. Результат: ${cipher}`, `${encTrace(word, key)}. Нәтиже: ${cipher}`),
        hint: HINT_ENC,
      };
    }
    const n = pick(rand, [2, 3, 4, 5, 10]);
    const len = int(rand, 2, n === 10 ? 4 : 3);
    return {
      id: `q:${SKILL}:pwd:${n}:${len}`,
      skill: SKILL,
      level,
      prompt: T(
        `Алфавит пароля — ${n} ${plural(n, "знак", "знака", "знаков")}, длина — ${len} ${plural(len, "символ", "символа", "символов")}. Сколько всего паролей?`,
        `Құпиясөз алфавиті — ${n} таңба, ұзындығы — ${len} символ. Барлығы неше құпиясөз?`,
      ),
      answer: String(n ** len),
      mode: "number",
      explanation: same(`Nᴸ = ${n}${sup(len)} = ${fmt(n ** len)}`),
      hint: HINT_NL,
    };
  },
};

