const w = (ru: string, kk: string): L => ({ ru, kk });

/** Выбор одного ответа: верный всегда первый — варианты перемешает poolBank по seed. */
function ch(id: string, level: Level, prompt: L, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Ввод числа. */
function inp(id: string, level: Level, prompt: L, answer: string, explanation: L, hint: L, scene?: Scene): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, answers: [answer], mode: "number", explanation, hint };
}

/** Несколько верных: [вариант, верен ли, почему неверен]. */
function mu(id: string, level: Level, prompt: L, opts: [Text, boolean, L?][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : (o[2] as L))),
    explanation,
    hint,
  };
}

/** Соответствие: справа без повторов. */
function ma(id: string, level: Level, prompt: L, pairs: [Text, Text][], explanation: L, hint: L): MatchStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "match",
    skill: SKILL,
    level,
    prompt,
    pairs: pairs.map(([left, right]) => ({ left, right })),
    explanation,
    hint,
  };
}

/** Порядок: элементы в правильной последовательности (на экране перемешаются). */
function or(id: string, level: Level, prompt: L, items: L[], explanation: L, hint: L): OrderStep {
  return { id: `p:${SKILL}:${id}`, type: "order", skill: SKILL, level, prompt, items, explanation, hint };
}

