const KK_NAMES: Record<string, string> = {
  СТРОЧН: "LOWER",
  ПРОПИСН: "UPPER",
  ДЛСТР: "LEN",
  СЦЕПИТЬ: "CONCATENATE",
  ЛЕВСИМВ: "LEFT",
  ПРАВСИМВ: "RIGHT",
  ПСТР: "MID",
  ЗАМЕНИТЬ: "REPLACE",
  ПОДСТАВИТЬ: "SUBSTITUTE",
  ЕСЛИ: "IF",
};
const KK_RE = new RegExp(`(${Object.keys(KK_NAMES).join("|")})(?=\\()`, "g");
/** Формула для казахской версии: русские имена функций → английские. */
const toKk = (f: string): string => f.replace(KK_RE, (m) => KK_NAMES[m]);
/** Формула как локализованная строка (варианты ответа, пары). */
const fm = (f: string): L => lk(f, toKk(f));
const R = (f: string): string => "`" + f + "`";
const K = (f: string): string => "`" + toKk(f) + "`";
/** Имя функции: ru и английское. */
const fn = (ru: string): L => lk(ru, KK_NAMES[ru] ?? ru);

// ---------- Мини-вычислитель формул ----------

type V = string | number | boolean;
type Cells = Record<string, string>;
type Node =
  | { t: "lit"; v: V }
  | { t: "ref"; a: string }
  | { t: "call"; name: string; args: Node[] }
  | { t: "bin"; op: string; l: Node; r: Node }
  | { t: "neg"; x: Node };

const TOKEN = /\s*(?:("(?:[^"]|"")*")|(\d+(?:\.\d+)?)|(\$?[A-Z]{1,2}\$?\d+)|([A-Za-zА-Яа-яЁё]+)\(|(<>|>=|<=|[-+*/&=<>(),;]))/y;

function tokenize(src: string): { k: string; v: string }[] {
  const out: { k: string; v: string }[] = [];
  TOKEN.lastIndex = 0;
  while (TOKEN.lastIndex < src.length) {
    const m = TOKEN.exec(src);
    if (!m) throw new Error(`формула «${src}»: неожиданный символ на «${src.slice(TOKEN.lastIndex)}»`);
    const kinds = ["str", "num", "ref", "fn", "op"];
    const idx = kinds.findIndex((_, g) => m[g + 1] !== undefined);
    out.push({ k: kinds[idx], v: m[idx + 1] });
  }
  return out;
}

function parse(src: string): Node {
  const t = tokenize(src);
  let i = 0;
  const peek = () => t[i];
  const isOp = (...ops: string[]) => peek()?.k === "op" && ops.includes(peek().v);
  const atom = (): Node => {
    const tok = t[i++];
    if (!tok) throw new Error(`формула «${src}»: оборвана`);
    if (tok.k === "str") return { t: "lit", v: tok.v.slice(1, -1).replace(/""/g, '"') };
    if (tok.k === "num") return { t: "lit", v: Number(tok.v) };
    if (tok.k === "ref") return { t: "ref", a: tok.v.replace(/\$/g, "") };
    if (tok.k === "op" && tok.v === "(") {
      const e = cmp();
      i++; // «)»
      return e;
    }
    if (tok.k === "fn") {
      const args: Node[] = [];
      if (isOp(")")) i++;
      else
        for (;;) {
          args.push(cmp());
          const sep = t[i++];
          if (sep.v === ")") break;
        }
      return { t: "call", name: tok.v.toUpperCase(), args };
    }
    throw new Error(`формула «${src}»: лишний токен ${tok.v}`);
  };
  const unary = (): Node => (isOp("-") ? (i++, { t: "neg", x: unary() }) : atom());
  const mul = (): Node => {
    let l = unary();
    while (isOp("*", "/")) {
      const op = t[i++].v;
      l = { t: "bin", op, l, r: unary() };
    }
    return l;
  };
  const add = (): Node => {
    let l = mul();
    while (isOp("+", "-")) {
      const op = t[i++].v;
      l = { t: "bin", op, l, r: mul() };
    }
    return l;
  };
  const cat = (): Node => {
    let l = add();
    while (isOp("&")) {
      i++;
      l = { t: "bin", op: "&", l, r: add() };
    }
    return l;
  };
  const cmp = (): Node => {
    let l = cat();
    while (isOp("=", "<>", "<", ">", "<=", ">=")) {
      const op = t[i++].v;
      l = { t: "bin", op, l, r: cat() };
    }
    return l;
  };
  const root = cmp();
  if (i !== t.length) throw new Error(`формула «${src}»: лишнее в конце`);
  return root;
}

const txt = (v: V): string => (typeof v === "boolean" ? (v ? "ИСТИНА" : "ЛОЖЬ") : String(v));
const num = (v: V): number => {
  const n = typeof v === "number" ? v : v === "" ? 0 : Number(v);
  if (Number.isNaN(n)) throw new Error(`«${String(v)}» — не число`);
  return n;
};
const shown = (v: V): string => (typeof v === "string" ? `"${v}"` : txt(v));

interface Run {
  value: V;
  /** Вызовы функций в порядке вычисления (сначала внутренние). */
  trace: { call: string; result: string }[];
}

function run(formula: string, cells: Cells = {}): Run {
  if (!formula.startsWith("=")) throw new Error(`формула «${formula}» должна начинаться с =`);
  const trace: Run["trace"] = [];
  const ev = (n: Node): V => {
    switch (n.t) {
      case "lit":
        return n.v;
      case "ref":
        return cells[n.a] ?? "";
      case "neg":
        return -num(ev(n.x));
      case "bin": {
        if (n.op === "&") return txt(ev(n.l)) + txt(ev(n.r));
        const l = ev(n.l);
        const r = ev(n.r);
        switch (n.op) {
          case "+": return num(l) + num(r);
          case "-": return num(l) - num(r);
          case "*": return num(l) * num(r);
          case "/": return num(l) / num(r);
          default: {
            const a = typeof l === "string" || typeof r === "string" ? [txt(l).toLowerCase(), txt(r).toLowerCase()] : [num(l), num(r)];
            const [x, y] = a as [string | number, string | number];
            return n.op === "=" ? x === y : n.op === "<>" ? x !== y : n.op === "<" ? x < y : n.op === ">" ? x > y : n.op === "<=" ? x <= y : x >= y;
          }
        }
      }
      case "call": {
        if (n.name === "ЕСЛИ") {
          const c = ev(n.args[0]);
          return ev(c ? n.args[1] : n.args[2]);
        }
        const a = n.args.map(ev);
        const s = a[0] === undefined ? "" : txt(a[0]);
        let out: V;
        switch (n.name) {
          case "СТРОЧН": out = s.toLowerCase(); break;
          case "ПРОПИСН": out = s.toUpperCase(); break;
          case "ДЛСТР": out = s.length; break;
          case "СЦЕПИТЬ": out = a.map(txt).join(""); break;
          case "ЛЕВСИМВ": out = s.slice(0, a.length > 1 ? Math.max(0, num(a[1])) : 1); break;
          case "ПРАВСИМВ": {
            const k = a.length > 1 ? Math.max(0, num(a[1])) : 1;
            out = s.slice(Math.max(0, s.length - k));
            break;
          }
          case "ПСТР": {
            const from = num(a[1]);
            if (from < 1) throw new Error("ПСТР: позиция меньше 1");
            out = s.slice(from - 1, from - 1 + num(a[2]));
            break;
          }
          case "ЗАМЕНИТЬ": {
            const from = num(a[1]);
            if (from < 1) throw new Error("ЗАМЕНИТЬ: позиция меньше 1");
            out = s.slice(0, from - 1) + txt(a[3]) + s.slice(from - 1 + num(a[2]));
            break;
          }
          case "ПОДСТАВИТЬ": {
            const old = txt(a[1]);
            const neu = txt(a[2]);
            if (a.length > 3) {
              let idx = -1;
              for (let k = 0; k < num(a[3]); k++) {
                idx = s.indexOf(old, idx + 1);
                if (idx < 0) break;
              }
              out = idx < 0 ? s : s.slice(0, idx) + neu + s.slice(idx + old.length);
            } else out = s.split(old).join(neu);
            break;
          }
          default:
            throw new Error(`неизвестная функция ${n.name}`);
        }
        trace.push({ call: `${n.name}(${a.map(shown).join(";")})`, result: txt(out) });
        return out;
      }
    }
  };
  return { value: ev(parse(formula.slice(1))), trace };
}

const calc = (formula: string, cells: Cells = {}): V => run(formula, cells).value;

// ---------- Подписи условий и разборов ----------

const cellsRu = (cells: Cells) => "Дано: " + Object.entries(cells).map(([a, v]) => `${a} = «${v}»`).join(", ") + ". ";
const cellsKk = (cells: Cells) => "Берілген: " + Object.entries(cells).map(([a, v]) => `${a} = «${v}»`).join(", ") + ". ";

/** Условие «что вернёт формула?» с описанием ячеек. */
const whatReturns = (f: string, cells: Cells): L =>
  lk(`${Object.keys(cells).length ? cellsRu(cells) : ""}Что вернёт формула ${R(f)}?`, `${Object.keys(cells).length ? cellsKk(cells) : ""}${K(f)} формуласы не қайтарады?`);

/** Пошаговый разбор по трассе вычисления (внутренние функции — первыми). */
function explainRun(f: string, cells: Cells, extra?: L): L {
  const { value, trace } = run(f, cells);
  const steps = trace.map((s) => `${s.call} = «${s.result}»`).join("; ");
  const ru = trace.length ? `Считаем по шагам: ${steps}. Результат: «${txt(value)}».` : `Результат формулы: «${txt(value)}».`;
  const kk = trace.length ? `Қадам бойынша есептейміз: ${toKk(steps)}. Нәтиже: «${txt(value)}».` : `Формуланың нәтижесі: «${txt(value)}».`;
  return extra ? lk(`${ru} ${extra.ru}`, `${kk} ${extra.kk}`) : lk(ru, kk);
}

const res = (v: V): string => txt(v);

// ---------- Конструкторы заданий ----------

interface Distractor {
  /** Формула с типичной ошибкой — в вариант попадёт её значение. */
  f?: string;
  /** Либо готовый текст варианта. */
  text?: string;
  why: L;
}

/** choice: «что вернёт формула?» — верный вариант и неверные считает код. */
function evalChoice(name: string, level: Level, f: string, cells: Cells, wrong: Distractor[], hint: L, extra?: L): ChoiceStep {
  const correctText = res(calc(f, cells));
  const options: Text[] = [correctText, ...wrong.map((w) => (w.f ? res(calc(w.f, cells)) : (w.text ?? "")))];
  if (new Set(options).size !== options.length) throw new Error(`${name}: варианты повторяются (${options.join(" | ")})`);
  return {
    id: pid(name),
    type: "choice",
    skill: SKILL,
    level,
    prompt: whatReturns(f, cells),
    options,
    correct: 0,
    explanation: explainRun(f, cells, extra),
    hint,
    whyWrong: [null, ...wrong.map((w) => w.why)],
  };
}

/** input: ответ считает код (число — режим number, текст — режим text). */
function evalInput(name: string, level: Level, f: string, cells: Cells, hint: L, extra?: L): InputStep {
  const v = calc(f, cells);
  return {
    id: pid(name),
    type: "input",
    skill: SKILL,
    level,
    prompt: whatReturns(f, cells),
    answers: [res(v)],
    mode: typeof v === "number" ? "number" : "text",
    explanation: explainRun(f, cells, extra),
    hint,
  };
}

/** multi: «какие формулы вернут target» — верные находит код (6 вариантов, 2–3 верных). */
function evalMulti(name: string, level: Level, target: string, cells: Cells, formulas: string[], hint: L): MultiStep {
  const values = formulas.map((f) => res(calc(f, cells)));
  const correct = values.flatMap((v, i) => (v === target ? [i] : []));
  if (formulas.length !== 6 || correct.length < 2 || correct.length > 3) throw new Error(`${name}: нужно 6 вариантов и 2–3 верных (сейчас ${correct.length})`);
  const lines = formulas.map((f, i) => `${f} = «${values[i]}»`);
  return {
    id: pid(name),
    type: "multi",
    skill: SKILL,
    level,
    prompt: lk(`${cellsRu(cells)}Выбери формулы, которые вернут «${target}».`, `${cellsKk(cells)}«${target}» мәнін қайтаратын формулаларды таңда.`),
    options: formulas.map(fm),
    correct,
    explanation: lk(`Значения формул: ${lines.join("; ")}. Подходят те, где получается «${target}».`, `Формулалардың мәндері: ${lines.map(toKk).join("; ")}. «${target}» шығатындары жарайды.`),
    hint,
    whyWrong: formulas.map((_, i) =>
      correct.includes(i) ? null : lk(`Эта формула возвращает «${values[i]}», а нужно «${target}».`, `Бұл формула «${values[i]}» қайтарады, ал «${target}» керек.`),
    ),
  };
}

/** match: формула ↔ значение (3–6 пар, значения без повторов). */
function evalMatch(name: string, level: Level, cells: Cells, formulas: string[], hint: L): MatchStep {
  const values = formulas.map((f) => res(calc(f, cells)));
  if (new Set(values).size !== values.length) throw new Error(`${name}: значения пар повторяются`);
  const lines = formulas.map((f, i) => `${f} = «${values[i]}»`);
  return {
    id: pid(name),
    type: "match",
    skill: SKILL,
    level,
    prompt: lk(`${cellsRu(cells)}Соедини формулу и её значение.`, `${cellsKk(cells)}Формула мен оның мәнін сәйкестендір.`),
    pairs: formulas.map((f, i) => ({ left: fm(f), right: values[i] })),
    explanation: lk(`Считаем каждую формулу изнутри наружу: ${lines.join("; ")}.`, `Әр формуланы ішінен сыртына қарай есептейміз: ${lines.map(toKk).join("; ")}.`),
    hint,
  };
}

/** match «функция ↔ действие» (без вычислений). */
function termMatch(name: string, level: Level, prompt: L, pairs: { left: Text; right: Text }[], explanation: L, hint: L): MatchStep {
  return { id: pid(name), type: "match", skill: SKILL, level, prompt, pairs, explanation, hint };
}

