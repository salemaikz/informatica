/** Генератор коротких вопросов: ответ считает код (числа в казахских текстах без окончаний). */
function genShort(level: Level, seed: number): ShortQuestion {
  const rand = seeded(seed ^ 0x51ed270b);
  if (level === 1) {
    const a = int(rand, 2, 9);
    const d = int(rand, 1, 9);
    return {
      id: `sh:${SKILL}:g-int-${a}-${d}`,
      skill: SKILL,
      level,
      prompt: w(`Что выведет print(int(${a}.${d}))?`, `print(int(${a}.${d})) не шығарады?`),
      answer: String(a),
      mode: "number",
      explanation: w(`int отбрасывает дробную часть: int(${a}.${d}) = ${a}.`, `int бөлшек бөлігін алып тастайды: int(${a}.${d}) = ${a}.`),
      hint: w("int не округляет. Что остаётся, если убрать дробную часть?", "int дөңгелектемейді. Бөлшек бөлігін алып тастасаң, не қалады?"),
    };
  }
  if (level === 2) {
    const a = int(rand, 11, 99);
    const b = int(rand, 11, 99);
    const digits = String(a * b).length;
    return {
      id: `sh:${SKILL}:g-len-${a}-${b}`,
      skill: SKILL,
      level,
      prompt: w(`Что выведет print(len(str(${a} * ${b})))?`, `print(len(str(${a} * ${b}))) не шығарады?`),
      answer: String(digits),
      mode: "number",
      explanation: w(`${a} * ${b} = ${a * b}: в записи ${digits} цифры, их и считает len.`, `${a} * ${b} = ${a * b}: жазбада ${digits} цифр бар, оларды len санайды.`),
      hint: w("Сначала вычисли произведение, потом посчитай цифры результата.", "Алдымен көбейтіндіні есепте, содан кейін нәтиженің цифрларын сана."),
    };
  }
  const a = int(rand, 2, 9);
  const d = pick(rand, [1, 2, 3, 4, 6, 7, 8, 9]);
  const answer = a + (d > 5 ? a + 1 : a);
  return {
    id: `sh:${SKILL}:g-round-${a}-${d}`,
    skill: SKILL,
    level,
    prompt: w(`x = ${a}.${d}. Что выведет print(int(x) + round(x))?`, `x = ${a}.${d}. print(int(x) + round(x)) не шығарады?`),
    answer: String(answer),
    mode: "number",
    explanation: w(
      `int(${a}.${d}) = ${a} (дробная часть отброшена), round(${a}.${d}) = ${d > 5 ? a + 1 : a} (ближайшее целое). Сумма: ${answer}.`,
      `int(${a}.${d}) = ${a} (бөлшек бөлігі алынып тасталды), round(${a}.${d}) = ${d > 5 ? a + 1 : a} (ең жақын бүтін сан). Қосынды: ${answer}.`,
    ),
    hint: w("Найди int(x) и round(x) по отдельности: одна команда отбрасывает, другая округляет.", "int(x) және round(x) мәндерін бөлек тап: бірі алып тастайды, екіншісі дөңгелектейді."),
  };
}

const pool = poolBank({ skill: SKILL, questions, statements, pairs, shorts });

const bank: SkillBank = {
  ...pool,
  short(level, seed) {
    // Половина коротких вопросов — генератор, половина — статичные.
    const rand = seeded(seed ^ 0x2545f491);
    return rand() < 0.5 ? genShort(level, seed) : pool.short!(level, seed);
  },
};

