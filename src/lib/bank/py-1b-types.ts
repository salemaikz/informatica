/** Выбор одного ответа: верный первым — варианты перемешает poolBank по seed (вместе с whyWrong). */
function ch(id: string, level: Level, prompt: L, scene: Scene | undefined, correct: Text, wrongs: [Text, L][], explanation: L, hint: L, reveal?: Scene): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    scene,
    reveal,
    options: [correct, ...wrongs.map((x) => x[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((x) => x[1])],
    explanation,
    hint,
  };
}

/** Несколько верных: [вариант, верен ли, почему неверен (для неверных)]. */
function mu(id: string, level: Level, prompt: L, scene: Scene | undefined, opts: [Text, boolean, L | null][], explanation: L, hint: L): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    scene,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    whyWrong: opts.map((o) => (o[1] ? null : o[2])),
    explanation,
    hint,
  };
}

function inp(id: string, level: Level, prompt: L, scene: Scene, answers: string[], mode: "number" | "text", explanation: L, hint: L, reveal?: Scene): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, scene, reveal, answers, mode, explanation, hint };
}

