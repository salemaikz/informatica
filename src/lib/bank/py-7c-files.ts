interface ChoiceArgs {
  id: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  reveal?: Scene;
  options: Text[];
  correct: number;
  whyWrong: (L | null)[];
  explanation: L;
  hint: L;
  ent?: boolean;
}

const choice = (a: ChoiceArgs): ChoiceStep => ({ type: "choice", skill: SKILL, ...a, id: `p:${SKILL}:${a.id}` });

interface MultiArgs extends Omit<ChoiceArgs, "correct"> {
  correct: number[];
}

const multi = (a: MultiArgs): MultiStep => ({ type: "multi", skill: SKILL, ...a, id: `p:${SKILL}:${a.id}` });

interface InputArgs {
  id: string;
  level: Level;
  prompt: L;
  scene?: Scene;
  answers: string[];
  mode: "number" | "binary" | "text";
  explanation: L;
  hint: L;
}

const input = (a: InputArgs): InputStep => ({ type: "input", skill: SKILL, ...a, id: `p:${SKILL}:${a.id}` });

const match = (
  id: string,
  level: Level,
  prompt: L,
  pairs: { left: Text; right: Text }[],
  explanation: L,
  hint: L,
): MatchStep => ({ type: "match", skill: SKILL, id: `p:${SKILL}:${id}`, level, prompt, pairs, explanation, hint });

