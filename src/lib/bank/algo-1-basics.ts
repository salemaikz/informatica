/** Короткий вопрос-трассировка с условием в тексте (без схемы): подходит для игр, где нет сцены. */
function genShort(rand: Rand, level: Level, seed: number): ShortQuestion {
  if (level === 1) {
    const x = int(rand, 2, 9);
    const a = int(rand, 2, 5);
    const b = int(rand, 1, 9);
    const z = x * a + b;
    return {
      id: `gs:${SKILL}:lin:${x}-${a}-${b}:${seed}`,
      skill: SKILL,
      level,
      prompt: T(`Ввод x = ${x}. Блоки: y = x · ${a}, затем z = y + ${b}. Что выведет «Вывод z»?`, `Енгізу x = ${x}. Блоктар: y = x · ${a}, содан кейін z = y + ${b}. «z шығару» не шығарады?`),
      answer: String(z),
      mode: "number",
      explanation: T(`y = ${x} · ${a} = ${x * a}, z = ${x * a} + ${b} = ${z}.`, `y = ${x} · ${a} = ${x * a}, z = ${x * a} + ${b} = ${z}.`),
      hint: T("Выполни блоки по порядку.", "Блоктарды ретімен орында."),
    };
  }
  if (level === 2) {
    const s0 = int(rand, 0, 5);
    const d = int(rand, 2, 5);
    const N = s0 + int(rand, 3, 6) * d + int(rand, 0, d - 1);
    let k = s0;
    let n = 0;
    while (k < N) {
      k += d;
      n++;
    }
    return {
      id: `gs:${SKILL}:loop:${s0}-${d}-${N}:${seed}`,
      skill: SKILL,
      level,
      prompt: T(`k = ${s0}. Пока k < ${N}: k = k + ${d}. Сколько раз выполнится блок «k = k + ${d}»?`, `k = ${s0}. k < ${N} болғанша: k = k + ${d}. «k = k + ${d}» блогы неше рет орындалады?`),
      answer: String(n),
      mode: "number",
      explanation: T(`Выписываем k: ${s0}, ${s0 + d}, … Условие k < ${N} верно ${n} раз, потом k = ${k} и цикл заканчивается.`, `k мәндерін жазамыз: ${s0}, ${s0 + d}, … k < ${N} шарты ${n} рет ақиқат, содан кейін k = ${k} және цикл аяқталады.`),
      hint: T("Считай проходы тела цикла, а не проверки условия.", "Цикл денесінің өтулерін сана, шартты тексерулерді емес."),
    };
  }
  const [p, q] = pick(rand, COPRIME);
  const g = int(rand, 2, 6);
  let a = p * g;
  let b = q * g;
  const A = a;
  const B = b;
  while (b !== 0) {
    const r = a % b;
    a = b;
    b = r;
  }
  return {
    id: `gs:${SKILL}:euclid:${A}-${B}:${seed}`,
    skill: SKILL,
    level,
    prompt: T(
      `a = ${A}, b = ${B}. Пока b ≠ 0: r = a mod b, a = b, b = r. Чему равно a в конце? (mod — остаток от деления.)`,
      `a = ${A}, b = ${B}. b ≠ 0 болғанша: r = a mod b, a = b, b = r. Соңында a неге тең? (mod — бөлгендегі қалдық.)`,
    ),
    answer: String(a),
    mode: "number",
    explanation: T(`Это алгоритм Евклида: в конце a = наибольший общий делитель чисел ${A} и ${B}, то есть ${a}.`, `Бұл Евклид алгоритмі: соңында a = ${A} және ${B} сандарының ең үлкен ортақ бөлгіші, яғни ${a}.`),
    hint: T("Веди таблицу значений a, b и r по проходам.", "Өтулер бойынша a, b және r мәндерінің кестесін жүргіз."),
  };
}

