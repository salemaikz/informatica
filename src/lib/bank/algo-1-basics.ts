/** Задание-choice с верным ответом первым (poolBank перемешает варианты вместе с whyWrong). */
function pq(id: string, level: Level, prompt: L, right: Text, wrongs: [Text, L][], explanation: L, hint: L, scene?: Scene): ChoiceStep {
  return {
    type: "choice",
    skill: SKILL,
    id: `p:${SKILL}:${id}`,
    level,
    prompt,
    scene,
    options: [right, ...wrongs.map((w) => w[0])],
    correct: 0,
    hint,
    explanation,
    whyWrong: [null, ...wrongs.map((w) => w[1])],
  };
}

