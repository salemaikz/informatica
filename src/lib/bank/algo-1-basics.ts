// --- алгоритм Евклида ---

const COPRIME: [number, number][] = [
  [5, 2], [7, 2], [7, 3], [8, 3], [5, 3], [7, 4], [9, 4], [11, 4], [8, 5], [7, 5], [9, 5], [11, 3],
];

function genEuclid(rand: Rand, level: Level, seed: number): InputStep {
  const [p, q] = pick(rand, COPRIME);
  const g = int(rand, 2, 7);
  const A = p * g;
  const B = q * g;
  let a = A;
  let b = B;
  const pairs: string[] = [`(${a}, ${b})`];
  const rs: number[] = [];
  while (b !== 0) {
    const r = a % b;
    rs.push(r);
    a = b;
    b = r;
    pairs.push(`(${a}, ${b})`);
  }
  const passes = rs.length;
  const askPasses = rand() < 0.4;
  const modNote = T("(mod — остаток от деления.)", "(mod — бөлгендегі қалдық.)");
  const trace = {
    ru: `Трассировка (a, b в начале проверки): ${pairs.join(" → ")}; остатки r: ${rs.join(", ")}.`,
    kk: `Трассировка (тексеру басындағы a, b): ${pairs.join(" → ")}; r қалдықтары: ${rs.join(", ")}.`,
  };
  const scene = flow(
    [
      { id: "s", shape: "start", label: START, x: 2, y: 0 },
      { id: "in", shape: "io", label: IN("a, b"), x: 2, y: 1 },
      { id: "q", shape: "if", label: "b ≠ 0?", x: 2, y: 2 },
      { id: "r", shape: "action", label: "r = a mod b", x: 2, y: 3 },
      { id: "sw", shape: "action", label: "a = b, b = r", x: 2, y: 4 },
      { id: "out", shape: "io", label: OUT("a"), x: 1, y: 3 },
      { id: "e", shape: "end", label: END, x: 1, y: 4 },
    ],
    [
      { from: "s", to: "in" },
      { from: "in", to: "q" },
      { from: "q", to: "r", label: YES },
      { from: "q", to: "out", label: NO },
      { from: "r", to: "sw" },
      { from: "sw", to: "q" },
      { from: "out", to: "e" },
    ],
  );
  return numberInput(
    {
      id: `g:${SKILL}:euclid:${A}-${B}-${askPasses ? "n" : "g"}:${seed}`,
      level,
      prompt: askPasses
        ? {
            ru: `Сколько раз выполнится блок «r = a mod b» при a = ${A} и b = ${B}? ${modNote.ru}`,
            kk: `a = ${A} және b = ${B} болғанда «r = a mod b» блогы неше рет орындалады? ${modNote.kk}`,
          }
        : {
            ru: `Что будет выведено при a = ${A} и b = ${B}? ${modNote.ru}`,
            kk: `a = ${A} және b = ${B} болғанда не шығады? ${modNote.kk}`,
          },
      scene,
      hint: {
        ru: "Веди таблицу значений a, b и r по проходам. Цикл остановится, когда b станет равным 0.",
        kk: "Өтулер бойынша a, b және r мәндерінің кестесін жүргіз. Цикл b 0-ге тең болғанда тоқтайды.",
      },
      explanation: {
        ru: `${trace.ru} Когда b = 0, цикл заканчивается: проходов ${passes}, выводится a = ${a}.${askPasses ? ` Ответ: ${passes}.` : ""}`,
        kk: `${trace.kk} b = 0 болғанда цикл аяқталады: өту саны ${passes}, a = ${a} шығады.${askPasses ? ` Жауабы: ${passes}.` : ""}`,
      },
    },
    askPasses ? passes : a,
  );
}

// --- вычитаем шаг, пока условие верно ---

function genDec(rand: Rand, level: Level, seed: number): InputStep {
  const T0 = int(rand, 5, 30);
  const D = int(rand, 7, 19);
  const m = int(rand, 4, 9);
  const r = int(rand, 0, D - 1);
  const a0 = T0 + m * D + r;
  const strict = rand() < 0.5;
  let a = a0;
  let k = 0;
  const vals = [a];
  while (strict ? a > T0 : a >= T0) {
    a -= D;
    k++;
    vals.push(a);
  }
  const sign = strict ? ">" : "≥";
  return numberInput(
    {
      id: `g:${SKILL}:dec:${a0}-${D}-${T0}-${strict ? "gt" : "ge"}:${seed}`,
      level,
      prompt: T("Что будет выведено в результате выполнения блок-схемы?", "Блок-сызба орындалғаннан кейін не шығады?"),
      scene: loopFlow(`a = ${a0}, k = 0`, `a ${sign} ${T0}?`, [`a = a − ${D}`, "k = k + 1"], "k"),
      hint: {
        ru: "Выпиши значения a после каждого прохода. Остановись, когда условие станет неверным, и посмотри, чему равно k. Обрати внимание на знак в ромбе.",
        kk: "Әр өтуден кейінгі a мәндерін жаз. Шарт жалған болғанда тоқтап, k неге тең екенін қара. Ромбтағы таңбаға назар аудар.",
      },
      explanation: {
        ru: `Значения a: ${trail(vals, 9)}. Условие «a ${sign} ${T0}» верно ${k} раз, затем при a = ${a} оно неверно и цикл заканчивается. Выводится k = ${k}.`,
        kk: `a мәндері: ${trail(vals, 9)}. «a ${sign} ${T0}» шарты ${k} рет ақиқат, содан кейін a = ${a} болғанда ол жалған және цикл аяқталады. k = ${k} шығады.`,
      },
    },
    k,
  );
}

// --- обратная задача: при каком a выведется K ---

function genInverse(rand: Rand, level: Level, seed: number): ChoiceStep {
  const d = int(rand, 3, 6);
  const K = int(rand, 3, 7);
  const kOf = (a: number) => Math.ceil(a / d);
  const inRange = (k: number) => (k - 1) * d + int(rand, 1, d);
  const right = inRange(K);
  const others = [K - 1, K + 1, K + 2].filter((k) => k >= 1 && k !== K).map((k) => inRange(k));
  const walk = (a: number) => {
    const vals: number[] = [];
    for (let v = a; v > 0; v -= d) vals.push(v);
    return vals;
  };
  const why = (a: number): L => {
    const k = kOf(a);
    return T(
      `При a = ${a} значения a: ${trail([...walk(a), walk(a).slice(-1)[0] - d], 7)} — ${k} проходов, выводится ${k}, а нужно ${K}.`,
      `a = ${a} болғанда a мәндері: ${trail([...walk(a), walk(a).slice(-1)[0] - d], 7)} — ${k} өту, ${k} шығады, ал ${K} керек.`,
    );
  };
  const lo = (K - 1) * d + 1;
  const hi = K * d;
  return choice(
    rand,
    {
      id: `g:${SKILL}:inverse:${d}-${K}-${right}:${seed}`,
      level,
      prompt: T(`При каком начальном значении a блок-схема выведет ${K}?`, `a-ның қандай бастапқы мәнінде блок-сызба ${K} шығарады?`),
      scene: loopFlow("k = 0", "a > 0?", [`a = a − ${d}`, "k = k + 1"], "k", "a"),
      hint: {
        ru: `Каждый проход вычитает ${d}, цикл идёт, пока a больше 0. Подставь варианты и посчитай проходы — или найди, при каких a их ровно ${K}.`,
        kk: `Әр өту ${d} санын азайтады, цикл a 0-ден үлкен болғанша жүреді. Нұсқаларды қойып, өтулерді сана — немесе олардың дәл ${K} болатын a мәндерін тап.`,
      },
      explanation: {
        ru: `Цикл идёт, пока a > 0, и каждый проход вычитает ${d}. При a = ${right} значения a: ${trail([...walk(right), walk(right).slice(-1)[0] - d], 7)} — ровно ${K} проходов. Вообще k = ${K} при a от ${lo} до ${hi}.`,
        kk: `Цикл a > 0 болғанша жүреді, әр өту ${d} санын азайтады. a = ${right} болғанда a мәндері: ${trail([...walk(right), walk(right).slice(-1)[0] - d], 7)} — дәл ${K} өту. Жалпы, a ${lo} мен ${hi} аралығында болғанда k = ${K}.`,
      },
    },
    String(right),
    others.map((a) => ({ text: String(a), why: why(a) })),
    // Запасной вариант — только вне диапазона верных a ((K − 1)·d + 1 … K·d).
    () => String(pick(rand, [int(rand, 1, lo - 1), int(rand, hi + 1, hi + 2 * d)])),
  );
}

