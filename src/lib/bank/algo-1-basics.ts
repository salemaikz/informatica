interface Wrong {
  text: Text;
  why: L;
}

const GENERIC_WHY = T(
  "Такой ответ не получается при пошаговой трассировке: выпиши значения переменных по проходам и сверь с каждым блоком.",
  "Мұндай жауап қадамдап трассировка кезінде шықпайды: өту бойынша айнымалылар мәндерін жазып, әр блокпен салыстыр.",
);

/** choice: правильный вариант + три неверных (с разбором ошибки), варианты перемешаны, whyWrong выровнен. */
function choice(rand: Rand, base: Base, right: Text, wrong: Wrong[], spare: () => Text): ChoiceStep {
  const seen = new Set<string>([JSON.stringify(right)]);
  const uniq: Wrong[] = [];
  for (const w of shuffle(wrong, rand)) {
    const key = JSON.stringify(w.text);
    if (seen.has(key)) continue;
    seen.add(key);
    uniq.push(w);
    if (uniq.length === 3) break;
  }
  for (let guard = 0; uniq.length < 3 && guard < 80; guard++) {
    const t = spare();
    const key = JSON.stringify(t);
    if (seen.has(key)) continue;
    seen.add(key);
    uniq.push({ text: t, why: GENERIC_WHY });
  }
  const all: { text: Text; why: L | null }[] = shuffle([{ text: right, why: null }, ...uniq], rand);
  return {
    type: "choice",
    skill: SKILL,
    ...base,
    options: all.map((o) => o.text),
    correct: all.findIndex((o) => o.why === null),
    whyWrong: all.map((o) => o.why),
  };
}

function numberInput(base: Base, answer: number): InputStep {
  return { type: "input", skill: SKILL, ...base, answers: [String(answer)], mode: "number" };
}

/** Список значений для разбора: короткий — целиком, длинный — начало, многоточие и конец. */
function trail(values: number[], max = 8): string {
  const f = (v: number) => (v < 0 ? `−${-v}` : String(v));
  const vs = values.map(f);
  if (vs.length <= max) return vs.join(" → ");
  return `${vs.slice(0, 3).join(" → ")} → … → ${vs.slice(-2).join(" → ")}`;
}

