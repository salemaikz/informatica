const SKILL = "algo.basics";

const int = (rand: Rand, min: number, max: number) => min + Math.floor(rand() * (max - min + 1));
const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const T = (ru: string, kk: string): L => ({ ru, kk });

// ---------- блок-схемы ----------

type Flow = Extract<Scene, { kind: "flow" }>;
const flow = (nodes: Flow["nodes"], edges: Flow["edges"], caption?: Text): Scene => ({ kind: "flow", nodes, edges, caption });

const START = T("Начало", "Басы");
const END = T("Конец", "Соңы");
const YES = T("Да", "Иә");
const NO = T("Нет", "Жоқ");
const IN = (v: string): L => T(`Ввод ${v}`, `${v} енгізу`);
const OUT = (v: string): L => T(`Вывод ${v}`, `${v} шығару`);

/** Цикл с предусловием: начальный блок init, ромб cond, тело из одного или двух блоков, выход — вывод (или сразу конец). */
function loopFlow(init: string, cond: string, body: string[], outVar?: string, inVar?: string): Scene {
  const nodes: Flow["nodes"] = [{ id: "s", shape: "start", label: START, x: 2, y: 0 }];
  const edges: Flow["edges"] = [];
  let y = 1;
  let prev = "s";
  const link = (id: string, label?: Text) => {
    edges.push({ from: prev, to: id, label });
    prev = id;
  };
  if (inVar) {
    nodes.push({ id: "in", shape: "io", label: IN(inVar), x: 2, y: y++ });
    link("in");
  }
  nodes.push({ id: "init", shape: "action", label: init, x: 2, y: y++ });
  link("init");
  const qy = y++;
  nodes.push({ id: "q", shape: "if", label: cond, x: 2, y: qy });
  link("q");
  body.forEach((b, i) => {
    nodes.push({ id: `b${i}`, shape: "action", label: b, x: 2, y: y++ });
    link(`b${i}`, i === 0 ? YES : undefined);
  });
  edges.push({ from: prev, to: "q" });
  if (outVar) {
    nodes.push({ id: "out", shape: "io", label: OUT(outVar), x: 1, y: qy + 1 });
    nodes.push({ id: "e", shape: "end", label: END, x: 1, y: qy + 2 });
    edges.push({ from: "q", to: "out", label: NO }, { from: "out", to: "e" });
  } else {
    nodes.push({ id: "e", shape: "end", label: END, x: 1, y: qy + 1 });
    edges.push({ from: "q", to: "e", label: NO });
  }
  return flow(nodes, edges);
}

/** Линейная блок-схема: ввод, действия подряд, вывод. */
function linearFlow(inVar: string, actions: string[], outVar: string): Scene {
  const nodes: Flow["nodes"] = [
    { id: "s", shape: "start", label: START, x: 2, y: 0 },
    { id: "in", shape: "io", label: IN(inVar), x: 2, y: 1 },
  ];
  const edges: Flow["edges"] = [{ from: "s", to: "in" }];
  let prev = "in";
  actions.forEach((a, i) => {
    nodes.push({ id: `a${i}`, shape: "action", label: a, x: 2, y: 2 + i });
    edges.push({ from: prev, to: `a${i}` });
    prev = `a${i}`;
  });
  nodes.push({ id: "out", shape: "io", label: OUT(outVar), x: 2, y: 2 + actions.length });
  nodes.push({ id: "e", shape: "end", label: END, x: 2, y: 3 + actions.length });
  edges.push({ from: prev, to: "out" }, { from: "out", to: "e" });
  return flow(nodes, edges);
}

/** Ветвление: ввод, ромб, два действия, вывод. */
function branchFlow(cond: Text, yes: string, no: string, xVar = "x"): Scene {
  return flow(
    [
      { id: "s", shape: "start", label: START, x: 2, y: 0 },
      { id: "in", shape: "io", label: IN(xVar), x: 2, y: 1 },
      { id: "q", shape: "if", label: cond, x: 2, y: 2 },
      { id: "a", shape: "action", label: yes, x: 1, y: 3 },
      { id: "b", shape: "action", label: no, x: 3, y: 3 },
      { id: "out", shape: "io", label: OUT("y"), x: 2, y: 4 },
      { id: "e", shape: "end", label: END, x: 2, y: 5 },
    ],
    [
      { from: "s", to: "in" },
      { from: "in", to: "q" },
      { from: "q", to: "a", label: YES },
      { from: "q", to: "b", label: NO },
      { from: "a", to: "out" },
      { from: "b", to: "out" },
      { from: "out", to: "e" },
    ],
  );
}

