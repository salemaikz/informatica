/** choice: верный вариант первым, перемешивает poolBank (вместе с whyWrong). */
function choice(id: string, level: Level, prompt: L, hint: L, explanation: L, right: Text, wrongs: [Text, L][]): ChoiceStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "choice",
    skill: SKILL,
    level,
    prompt,
    hint,
    options: [right, ...wrongs.map((w) => w[0])],
    correct: 0,
    whyWrong: [null, ...wrongs.map((w) => w[1])],
    explanation,
  };
}

/** multi: options — пары [вариант, почему неверен (null у верных)]. */
function multi(id: string, level: Level, prompt: L, hint: L, explanation: L, options: [Text, L | null][]): MultiStep {
  return {
    id: `p:${SKILL}:${id}`,
    type: "multi",
    skill: SKILL,
    level,
    prompt,
    hint,
    options: options.map((o) => o[0]),
    correct: options.flatMap((o, i) => (o[1] === null ? [i] : [])),
    whyWrong: options.map((o) => o[1]),
    explanation,
  };
}

function input(id: string, level: Level, prompt: L, hint: L, explanation: L, answer: string, suffix?: string): InputStep {
  return { id: `p:${SKILL}:${id}`, type: "input", skill: SKILL, level, prompt, hint, answers: [answer], mode: "number", suffix, explanation };
}

function match(id: string, level: Level, prompt: L, hint: L, explanation: L, pairs: { left: Text; right: Text }[]): MatchStep {
  return { id: `p:${SKILL}:${id}`, type: "match", skill: SKILL, level, prompt, hint, pairs, explanation };
}

