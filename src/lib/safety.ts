const ABUSE_SUBJECT = String.raw`(?:меня|мне)`;
// Спорт, игра, шахматы: «меня бьют в футболе», «побили в шахматы» — не насилие.
const NOT_SPORT = String.raw`(?!\s+(?:током|озноб\w*|дрож\w*|лихорадк\w*|кашл\w*|по\s+рукам\s+линейкой|(?:в|на)\s+(?:игр\w*|футбол\w*|хоккей\w*|баскетбол\w*|волейбол\w*|регби|спорт\w*|секци\w*|бокс\w*|борьб\w*|каратэ|шахмат\w*|шашк\w*|тренировк\w*|ринг\w*|ковр\w*|матч\w*|соревновани\w*)))`;
