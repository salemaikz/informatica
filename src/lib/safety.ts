// Кризисные темы в чате с наставником: модель не вызываем, отвечаем фиксированным заботливым текстом.
// Чистая логика без зависимостей от сервера: проверяет и маршрут /api/ai/tutor, и клиент (useTutor — не тратить лимит).
// Регулярные выражения ориентированы на «я»-высказывания, чтобы не ловить учебное
// («убить процесс», kill -9, «смерть персонажа», «умереть со скуки»).

export type Crisis = "self_harm" | "abuse";

/** Нижний регистр, ё → е, ң/қ и т.п. не трогаем; схлопываем пробелы и повторы знаков. */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[’'`´]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}


// \b в JS не работает с кириллицей — своя граница слова (u-флаг, буквы и цифры).
function rx(src: string): RegExp {
  const out = src.replace(/\\b/g, (_m, off: number) => {
    const prev = src.slice(0, off);
    return /(^|\(|\?:|\||:)$/.test(prev) ? "(?<![\\p{L}\\d])" : "(?![\\p{L}\\d])";
  });
  return new RegExp(out.replace(/\\w/g, "\\p{L}"), "u");
}

// Окончание слова-исключения: «умереть со скуки», «от смеха» — шутка, не кризис.
const NOT_JOKE = String.raw`(?!\s+(?:со\s+скуки|от\s+(?:скуки|смеха|стыда|усталости|страха|голода)|ради|за\s+|скуктан|күлкіден))`;

// Прыжок «в игре / в фильме» — сюжет, не кризис.
const NOT_GAME = String.raw`(?!\s+(?:в|на)\s+(?:игр\w*|фильм\w*|кино|мульт\w*|анимаци\w*|сцен\w*))`;
const JUMP_PLACE = String.raw`(?:с|из)\s+(?:моста|балкона|крыши|окна|высотки|многоэтажки|этажа)`;

