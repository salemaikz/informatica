/** Кризисная тема в тексте ученика или null. Учебное («убить процесс», kill -9) не срабатывает. */
export function detectCrisis(text: string): Crisis | null {
  if (!text) return null;
  const s = normalize(text.slice(0, 2000));
  if (SELF_HARM.some((re) => re.test(s))) return "self_harm";
  if (ABUSE.some((re) => re.test(s))) return "abuse";
  return null;
}

const KK_LETTERS = /[әіңғүұқөһ]/i;

/** Язык ответа: профиль ученика, но если он пишет явно по-казахски (специфические буквы) — по-казахски. */
export function crisisLang(text: string, profileLang: Lang): Lang {
  return KK_LETTERS.test(text) ? "kk" : profileLang;
}

const CRISIS_KEY = { self_harm: "ai.crisis.selfHarm", abuse: "ai.crisis.abuse" } as const;

/** Фиксированный ответ вместо вызова модели. */
export function crisisReply(kind: Crisis, lang: Lang): string {
  return aiDict[CRISIS_KEY[kind]][lang];
}

const CRISIS_TEXTS = new Set((["self_harm", "abuse"] as const).flatMap((k) => (["ru", "kk"] as const).map((l) => crisisReply(k, l))));

/** Это сохранённый кризисный ответ? Под ним не показываем «Сообщить об ошибке». */
export function isCrisisReply(text: string): boolean {
  return CRISIS_TEXTS.has(text.trim());
}
