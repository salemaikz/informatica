// lessonIds — уроки курса (content/course.ts), которые покрывают тему; пусто — урока пока нет («скоро»).
// Урок указан, только если он действительно закрывает тему; частичные совпадения помечены в docs/SCHOOL.md.

export type SchoolGrade = Exclude<Grade, "other">;

export interface SchoolTopic {
  id: string;
  title: L;
  /** Существующие уроки курса, закрывающие тему. Пусто — «скоро». */
  lessonIds: string[];
}

export interface SchoolSection {
  id: string;
  title: L;
  topics: SchoolTopic[];
}

export interface SchoolGradePlan {
  grade: SchoolGrade;
  sections: SchoolSection[];
}

const l = (ru: string, kk: string): L => ({ ru, kk });
const topic = (id: string, ru: string, kk: string, lessonIds: string[] = []): SchoolTopic => ({ id, title: l(ru, kk), lessonIds });
const section = (id: string, ru: string, kk: string, topics: SchoolTopic[]): SchoolSection => ({ id, title: l(ru, kk), topics });

