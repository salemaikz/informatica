import type { Grade, L, SchoolDirection } from "@/lib/types";

// Школьная программа по информатике РК, 5–11 классы: класс → разделы → темы → готовые уроки курса.
// Источник — ОФИЦИАЛЬНЫЙ текст: приказ Министра просвещения РК от 16.09.2022 № 399 (рег. в Минюсте № 29767), действующая редакция,
// «Долгосрочные планы» (четверть → раздел → темы, по строкам плана):
//   5–9 классы — приложение 55 (1 ч/нед, 34 ч/год);
//   10–11 ЕМН (естественно-математическое направление) — приложение 108 (2 ч/нед, 68 ч/год);
//   10–11 ОГН (общественно-гуманитарное направление) — приложение 109 (1 ч/нед, 34 ч/год).
// Тема = строка долгосрочного плана; раздел = раздел плана с номером четверти (`quarter`). Названия ru — по плану, с исправленными
// опечатками приказа и без транскрипций в скобках; kk — по казахскому тексту приказа, исправленному по глоссарию НЦТ (docs/ENT.md §4).
// id: `g5-1-1` (класс-раздел-тема); у ОГН — `g10o-1-1`, `g11o-1-1`; уникальны во всей программе.
// lessonIds — уроки курса (content/course.ts), которые объясняют тему; пусто — урока пока нет («скоро»).
// Урок указан, только если он действительно закрывает тему; частичные совпадения помечены в docs/SCHOOL.md,
// там же — расхождения ru и kk в самом приказе и открытые вопросы.

export type SchoolGrade = Exclude<Grade, "other">;

export interface SchoolTopic {
  id: string;
  title: L;
  /** Существующие уроки курса, закрывающие тему. Пусто — «скоро». */
  lessonIds: string[];
}

export interface SchoolSection {
  id: string;
  title: L;
  /** Четверть долгосрочного плана (1–4). */
  quarter?: 1 | 2 | 3 | 4;
  topics: SchoolTopic[];
}

export interface SchoolGradePlan {
  grade: SchoolGrade;
  /** Только 10–11 классы: ЕМН (прил. 108) или ОГН (прил. 109). У 5–9 — нет. */
  direction?: SchoolDirection;
  sections: SchoolSection[];
}

const l = (ru: string, kk: string): L => ({ ru, kk });
const topic = (id: string, ru: string, kk: string, lessonIds: string[] = []): SchoolTopic => ({ id, title: l(ru, kk), lessonIds });
const section = (id: string, quarter: 1 | 2 | 3 | 4, ru: string, kk: string, topics: SchoolTopic[]): SchoolSection => ({ id, title: l(ru, kk), quarter, topics });

