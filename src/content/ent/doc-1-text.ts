import type { EntItem, EntMatch, EntMulti, EntSingle, L, Level, Scene, Text } from "@/lib/types";

// Задания в формате ЕНТ к уроку doc-1-text («Текстовые документы», тема t12, навык docs.text).
// Состав: 12 single, 4 multi, 4 match; уровни A 10 / B 6 / C 4. Сочетания клавиш — Word, Google Документы, LibreOffice Writer.
// Числовые задачи (объём TXT, число страниц) пересчитаны python3. Тексты web-сцены — латинский lorem ipsum.

const T = (ru: string, kk: string): L => ({ ru, kk });
const SKILL = "docs.text";
const TOPIC = "t12" as const;

/** Абзац в узкой рамке с заданным выравниванием. */
const alignScene = (mode: "left" | "center" | "right" | "justify"): Scene => ({
  kind: "web",
  html: [
    `<div style="background:#fff;border:1px solid #cbd5e1;border-radius:4px;padding:8px 12px;width:220px;font:13px/1.4 Georgia,serif;text-align:${mode}">`,
    "Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore et dolore.",
    `</div>`,
  ].join("\n"),
});

/** Один верный из 4: каждый вариант — [текст, почему неверен (у верного null)]. */
function single(id: string, level: Level, prompt: L, opts: [Text, L | null][], explanation: L, hint: L, scene?: Scene): EntSingle {
  const correct = opts.findIndex((o) => o[1] === null);
  return {
    id: `doc-1-text:${id}`,
    kind: "single",
    topic: TOPIC,
    skill: SKILL,
    level,
    prompt,
    ...(scene ? { scene } : {}),
    options: opts.map((o) => o[0]),
    correct,
    whyWrong: opts.map((o) => o[1]),
    explanation,
    hint,
  };
}

/** Несколько верных из 6: [текст, верен ли]. */
function multi(id: string, level: Level, prompt: L, opts: [Text, boolean][], explanation: L, hint: L): EntMulti {
  return {
    id: `doc-1-text:${id}`,
    kind: "multi",
    topic: TOPIC,
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    explanation,
    hint,
  };
}

/** Соответствие: два пункта, четыре описания; answer[i] — индекс описания пункта i. */
function match(id: string, level: Level, prompt: L, items: Text[], choices: Text[], answer: number[], explanation: L, hint: L): EntMatch {
  return { id: `doc-1-text:${id}`, kind: "match", topic: TOPIC, skill: SKILL, level, prompt, items, choices, answer, explanation, hint };
}

