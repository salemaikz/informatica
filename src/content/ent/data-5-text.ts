// Задания в формате ЕНТ к уроку data-5-text (тема t12, навык sheets.text).
// Состав: 14 single (A 8 / B 4 / C 2), 4 multi (A, B, B, C), 4 match (A, A, B, C). Уровни: A 11, B 7, C 4.
// Каждая формула и её значение пересчитаны мини-вычислителем на python3 (семантика Excel, регистр различается в ПОДСТАВИТЬ).
// Названия функций: по-русски ЛЕВСИМВ, ПРАВСИМВ, ПСТР, ДЛСТР, СТРОЧН, ПРОПИСН, ЗАМЕНИТЬ, ПОДСТАВИТЬ, СЦЕПИТЬ;
// по-казахски в формулах — LEFT, RIGHT, MID, LEN, LOWER, UPPER, REPLACE, SUBSTITUTE, CONCATENATE (toKk делает перевод сам).
// Формулы в markdown (prompt, explanation, whyWrong) обёрнуты в обратные кавычки, чтобы символы & и * не ломали разметку.

const TOPIC = "t12" as const;
const SKILL = "sheets.text";

const lk = (ru: string, kk: string): L => ({ ru, kk });

const KK_NAMES: Record<string, string> = {
  СТРОЧН: "LOWER",
  ПРОПИСН: "UPPER",
  ДЛСТР: "LEN",
  СЦЕПИТЬ: "CONCATENATE",
  ЛЕВСИМВ: "LEFT",
  ПРАВСИМВ: "RIGHT",
  ПСТР: "MID",
  ЗАМЕНИТЬ: "REPLACE",
  ПОДСТАВИТЬ: "SUBSTITUTE",
  ЕСЛИ: "IF",
  СУММ: "SUM",
  СЧЁТ: "COUNT",
};
const KK_RE = new RegExp(`(${Object.keys(KK_NAMES).join("|")})(?=\\()`, "g");
/** Формула для казахской версии: русские имена функций → английские. */
const toKk = (f: string): string => f.replace(KK_RE, (m) => KK_NAMES[m]);
/** Формула как локализованная строка (варианты ответа, ячейки сцен). */
const fm = (f: string): L => lk(f, toKk(f));
/** Формула в markdown: ru и kk-версия в обратных кавычках. */
const R = (f: string): string => "`" + f + "`";
const K = (f: string): string => "`" + toKk(f) + "`";
/** Имя функции: ru и английское. */
const fn = (ru: string): L => lk(ru, KK_NAMES[ru] ?? ru);

const sheet = (rows: (string | L)[][], highlightCells?: [number, number][]): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
});

