const T = "t11" as const;
const SKILL = "it.ai";

const l = (ru: string, kk: string): L => ({ ru, kk });

interface Wrong {
  t: Text;
  why: L;
}

/** single: верный вариант вставляется на позицию `at`, остальные — неверные по порядку. */
function single(id: string, level: Level, at: number, prompt: L, right: Text, wrongs: Wrong[], explanation: L, hint: L, scene?: Scene): EntSingle {
  const options: Text[] = wrongs.map((w) => w.t);
  options.splice(at, 0, right);
  const whyWrong: (L | null)[] = wrongs.map((w) => w.why);
  whyWrong.splice(at, 0, null);
  return { id: `it-4-ai:${id}`, kind: "single", topic: T, skill: SKILL, level, prompt, scene, options, correct: at, whyWrong, explanation, hint };
}

