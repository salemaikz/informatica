/** single: верный вариант задаётся индексом, whyWrong — только для неверных (в порядке options). */
function single(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  options: Text[],
  correct: number,
  why: Record<number, L>,
  hint: L,
  explanation: L,
): EntSingle {
  return {
    id: `py-3b-for:${name}`,
    kind: "single",
    topic: T,
    skill: SKILL,
    level,
    prompt,
    scene,
    options,
    correct,
    whyWrong: options.map((_, i) => (i === correct ? null : why[i])),
    explanation,
    hint,
  };
}

function multi(
  name: string,
  level: Level,
  prompt: L,
  options: Text[],
  correct: number[],
  hint: L,
  explanation: L,
  scene?: Scene,
): EntMulti {
  return { id: `py-3b-for:${name}`, kind: "multi", topic: T, skill: SKILL, level, prompt, scene, options, correct, explanation, hint };
}

function match(
  name: string,
  level: Level,
  prompt: L,
  items: Text[],
  choices: Text[],
  answer: number[],
  hint: L,
  explanation: L,
  scene?: Scene,
): EntMatch {
  return { id: `py-3b-for:${name}`, kind: "match", topic: T, skill: SKILL, level, prompt, scene, items, choices, answer, explanation, hint };
}

