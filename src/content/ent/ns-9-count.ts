// Задания в формате ЕНТ к уроку ns-9-count (сколько единиц, нулей и цифр в двоичной записи), тема t04.
// Числа в условиях и вариантах не набраны руками: выражение описано данными (P/M — слагаемые), а единицы,
// нули и цифры считает код (BigInt → toString(2)); эти же расчёты перепроверены python3 (bin(...).count).
// Тексты после чисел — без падежных окончаний (в казахском окончание зависит от числа).

const SKILL = "ns.count";
const T = (ru: string, kk: string): L => ({ ru, kk });

type Wrong = [number, L];

/** single: вопрос про единицы/нули/цифры выражения; верный ответ считает код, верный вариант стоит на месте pos. */
function single(id: string, level: Level, terms: Term[], ask: Ask, pos: number, wrongs: Wrong[], how: L, hint: L): EntItem {
  const f = facts(terms);
  const correct = answerOf(f, ask);
  const picked: Wrong[] = [];
  const seen = new Set([correct]);
  for (const w of wrongs) {
    if (w[0] > 0 && !seen.has(w[0])) {
      seen.add(w[0]);
      picked.push(w);
    }
  }
  if (picked.length !== 3) throw new Error(`${id}: нужно ровно 3 разных неверных варианта, получено ${picked.length}`);
  const options: Text[] = picked.map((w) => String(w[0]));
  const whyWrong: (L | null)[] = picked.map((w) => w[1]);
  options.splice(pos, 0, String(correct));
  whyWrong.splice(pos, 0, null);
  return {
    id: `ns-9-count:${id}`,
    kind: "single",
    topic: "t04",
    skill: SKILL,
    level,
    prompt: askPrompt(ask, expr(terms)),
    options,
    correct: pos,
    whyWrong,
    explanation: L2(how, closing(f)),
    hint,
  };
}

/** Описание выражения «единиц X, нулей Y, цифр Z» для разбора multi (считает код). */
function brief(terms: Term[]): L {
  const f = facts(terms);
  const d = describe(f);
  return T(`${expr(terms)} — ${d.ru}, цифр ${f.digits}`, `${expr(terms)} — ${d.kk}, цифр ${f.digits}`);
}

/** multi по условию на факты: варианты — выражения, верные находит код. */
function multiBy(id: string, level: Level, prompt: L, items: Term[][], pred: (f: Facts) => boolean, intro: L, outro: L, hint: L): EntItem {
  const correct = items.map((t, i) => (pred(facts(t)) ? i : -1)).filter((i) => i >= 0);
  const list = items.map((t) => brief(t));
  const picks = correct.map((i) => expr(items[i])).join("; ");
  return {
    id: `ns-9-count:${id}`,
    kind: "multi",
    topic: "t04",
    skill: SKILL,
    level,
    prompt,
    options: items.map((t) => expr(t)),
    correct,
    explanation: T(
      `${intro.ru} ${list.map((l) => l.ru).join("; ")}. Подходят: ${picks}. ${outro.ru}`,
      `${intro.kk} ${list.map((l) => l.kk).join("; ")}. Сәйкес келетіндер: ${picks}. ${outro.kk}`,
    ),
    hint,
  };
}

/** Утверждение о выражении для multi с готовым текстом: верность считает код. */
function claimOption(terms: Term[], ask: Ask, claimed: number): { text: L; ok: boolean; why: L } {
  const f = facts(terms);
  const noun = ask === "ones" ? nOnes(claimed) : ask === "zeros" ? nZeros(claimed) : nDigits(claimed);
  const e = expr(terms);
  const real = answerOf(f, ask);
  const realNoun = ask === "ones" ? nOnes(real) : ask === "zeros" ? nZeros(real) : nDigits(real);
  return {
    text: T(`В двоичной записи числа ${e} ровно ${noun.ru}`, `${e} санының екілік жазбасында дәл ${noun.kk} бар`),
    ok: real === claimed,
    why: T(`${e}: на самом деле ${realNoun.ru}.`, `${e}: шын мәнінде ${realNoun.kk}.`),
  };
}

/** multi из готовых утверждений (текст, верность). */
function multiClaims(id: string, level: Level, prompt: L, claims: { text: L; ok: boolean; why: L }[], outro: L, hint: L): EntItem {
  const correct = claims.map((c, i) => (c.ok ? i : -1)).filter((i) => i >= 0);
  const wrong = claims.filter((c) => !c.ok);
  return {
    id: `ns-9-count:${id}`,
    kind: "multi",
    topic: "t04",
    skill: SKILL,
    level,
    prompt,
    options: claims.map((c) => c.text),
    correct,
    explanation: T(
      `Верны: ${claims.filter((c) => c.ok).map((c) => c.text.ru).join("; ")}. Неверны — ${wrong.map((c) => c.why.ru).join(" ")} ${outro.ru}`,
      `Дұрыс: ${claims.filter((c) => c.ok).map((c) => c.text.kk).join("; ")}. Қате — ${wrong.map((c) => c.why.kk).join(" ")} ${outro.kk}`,
    ),
    hint,
  };
}

