/** Кольцо из шести компьютеров (сетка 3×2), кабели в обе стороны; cut — оборванные кабели вида «1-2». */
const RING_POS = [
  [0, 0],
  [1, 0],
  [2, 0],
  [2, 1],
  [1, 1],
  [0, 1],
] as const;

const ringCut = (cut: string[], caption: L): Scene => ({
  kind: "flow",
  nodes: RING_POS.map(([x, y], i) => ({ id: `p${i + 1}`, shape: "device" as const, label: String(i + 1), icon: "laptop" as const, x, y })),
  edges: RING_POS.flatMap((_, i) => {
    const a = i + 1;
    const b = ((i + 1) % 6) + 1;
    if (cut.includes(`${a}-${b}`)) return [];
    return [
      { from: `p${a}`, to: `p${b}` },
      { from: `p${b}`, to: `p${a}` },
    ];
  }),
  caption,
});

