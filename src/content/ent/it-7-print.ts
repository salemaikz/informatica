/** Single: верный вариант вставляется на позицию pos (0–3), неверные — по порядку. */
function single(
  id: string,
  level: Level,
  pos: number,
  prompt: L,
  correct: Text,
  wrongs: [Text, L][],
  explanation: L,
  hint: L,
  scene?: Scene,
): EntSingle {
  const options: Text[] = wrongs.map((w) => w[0]);
  options.splice(pos, 0, correct);
  const whyWrong: (L | null)[] = wrongs.map((w) => w[1]);
  whyWrong.splice(pos, 0, null);
  return { id: `${T}:${id}`, kind: "single", topic: "t11", skill: SKILL, level, prompt, scene, options, correct: pos, whyWrong, explanation, hint };
}

function multi(id: string, level: Level, prompt: L, options: Text[], correct: number[], explanation: L, hint: L): EntMulti {
  return { id: `${T}:${id}`, kind: "multi", topic: "t11", skill: SKILL, level, prompt, options, correct, explanation, hint };
}

function match(id: string, level: Level, prompt: L, items: Text[], choices: Text[], answer: number[], explanation: L, hint: L): EntMatch {
  return { id: `${T}:${id}`, kind: "match", topic: "t11", skill: SKILL, level, prompt, items, choices, answer, explanation, hint };
}

