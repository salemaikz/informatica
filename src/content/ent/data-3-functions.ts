const EN: Record<string, string> = { СЧЁТЗ: "COUNTA", СЧЁТ: "COUNT", СУММ: "SUM", СРЗНАЧ: "AVERAGE", МАКС: "MAX", МИН: "MIN" };
/** Русские имена функций → английские (и в формулах, и в тексте): так пишут в казахских уроках курса. */
const en = (s: string) =>
  s.replace(/(?<![А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІіA-Za-z])(СЧЁТЗ|СЧЁТ|СУММ|СРЗНАЧ|МАКС|МИН)(?![А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІіA-Za-z])/g, (_, n: string) => EN[n]);
const lk = (ru: string, kk: string): L => ({ ru, kk: en(kk) });
const fx = (f: string): L => ({ ru: f, kk: en(f) });
/** Текст, где в kk нужны русские имена функций (сопоставление с английскими): без замены. */
const ru = (r: string, k: string): L => ({ ru: r, kk: k });
/** Имя функции без скобок. */
const nm = (n: string): L => ({ ru: n, kk: EN[n] });

