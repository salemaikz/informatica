/** single: неверные варианты с разбором; верный вставляется на позицию pos (0–3), чтобы ответы не были всегда первыми. */
function single(
  name: string,
  level: Level,
  prompt: L,
  scene: Scene | undefined,
  correct: Text,
  wrong: [Text, L][],
  pos: number,
  hint: L,
  explanation: L,
): EntSingle {
  const options: Text[] = wrong.map((x) => x[0]);
  const whyWrong: (L | null)[] = wrong.map((x) => x[1]);
  options.splice(pos, 0, correct);
  whyWrong.splice(pos, 0, null);
  return { id: `py-1c-ops:${name}`, kind: "single", topic: TOPIC, skill: SKILL, level, prompt, scene, options, correct: pos, whyWrong, explanation, hint };
}

function multi(name: string, level: Level, prompt: L, scene: Scene | undefined, options: Text[], correct: number[], hint: L, explanation: L): EntMulti {
  return { id: `py-1c-ops:${name}`, kind: "multi", topic: TOPIC, skill: SKILL, level, prompt, scene, options, correct, explanation, hint };
}

function match(name: string, level: Level, prompt: L, items: Text[], choices: Text[], answer: number[], hint: L, explanation: L): EntMatch {
  return { id: `py-1c-ops:${name}`, kind: "match", topic: TOPIC, skill: SKILL, level, prompt, items, choices, answer, explanation, hint };
}

