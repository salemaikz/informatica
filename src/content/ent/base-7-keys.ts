import type { EntItem, EntMatch, EntMulti, EntSingle, L, Level, Text } from "@/lib/types";

// Задания в формате ЕНТ к уроку base-7-keys («Клавиатура и горячие клавиши»), тема t08. Сочетания — для Windows 10/11.
// Соответствие русских и английских букв на клавишах («рука» → herf) сверено скриптом.

const T = (ru: string, kk: string): L => ({ ru, kk });
const SKILL = "base.keys";
const TOPIC = "t08" as const;

/** Один верный из 4: каждый вариант — [текст, почему неверен (у верного null)]. */
function single(id: string, level: Level, prompt: L, opts: [Text, L | null][], explanation: L, hint: L): EntSingle {
  const correct = opts.findIndex((o) => o[1] === null);
  return {
    id: `base-7-keys:${id}`,
    kind: "single",
    topic: TOPIC,
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct,
    whyWrong: opts.map((o) => o[1]),
    explanation,
    hint,
  };
}

/** Несколько верных из 6: [текст, верен ли]. */
function multi(id: string, level: Level, prompt: L, opts: [Text, boolean][], explanation: L, hint: L): EntMulti {
  return {
    id: `base-7-keys:${id}`,
    kind: "multi",
    topic: TOPIC,
    skill: SKILL,
    level,
    prompt,
    options: opts.map((o) => o[0]),
    correct: opts.flatMap((o, i) => (o[1] ? [i] : [])),
    explanation,
    hint,
  };
}

/** Соответствие: два пункта, четыре описания; answer[i] — индекс описания пункта i. */
function match(id: string, level: Level, prompt: L, items: Text[], choices: Text[], answer: number[], explanation: L, hint: L): EntMatch {
  return { id: `base-7-keys:${id}`, kind: "match", topic: TOPIC, skill: SKILL, level, prompt, items, choices, answer, explanation, hint };
}

