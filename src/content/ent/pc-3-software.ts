function reorder(item: EntItem): EntItem {
  const order = ORDER[item.id];
  if (!order) return item;
  const at = <T,>(arr: T[]) => order.map((i) => arr[i]);
  switch (item.kind) {
    case "single":
      return { ...item, options: at(item.options), whyWrong: item.whyWrong && at(item.whyWrong), correct: order.indexOf(item.correct) };
    case "multi":
      return { ...item, options: at(item.options), correct: item.correct.map((c) => order.indexOf(c)).sort((a, b) => a - b) };
    case "match":
      return { ...item, choices: at(item.choices), answer: item.answer.map((a) => order.indexOf(a)) };
    default:
      return item;
  }
}

