// Новое по сравнению с «Таблицами истинности»: 4 переменные (16 строк), подсчёт единиц без полной таблицы,
// «по таблице — выражение» (ключи строк, нули), фрагмент с неизвестным порядком столбцов.
// Наборы всегда идут двоичным счётом. Все ответы пересчитаны независимым разборщиком в python3.

type Bit = 0 | 1;

const sets = (n: number): Bit[][] =>
  Array.from({ length: 2 ** n }, (_, i) => Array.from({ length: n }, (_, k) => ((i >> (n - 1 - k)) & 1) as Bit));

const NOT = (a: Bit): Bit => (a === 1 ? 0 : 1);

/** Полная таблица выражения: столбцы переменных и итог F (значения считает код). */
const grid = (names: string[], f: (v: Bit[]) => Bit): Scene => ({
  kind: "table",
  columns: [...names, "F"],
  rows: sets(names.length).map((v) => [...v.map(String), String(f(v))]),
  mono: true,
});

