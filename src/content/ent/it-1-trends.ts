const SKILL = "it.trends";

const l = (ru: string, kk: string): L => ({ ru, kk });

interface Wrong {
  t: Text;
  why: L;
}

/** single: верный вариант вставляется на позицию `at`, остальные — неверные по порядку. */
function single(id: string, level: Level, at: number, prompt: L, right: Text, wrongs: Wrong[], explanation: L): EntSingle {
  const options: Text[] = wrongs.map((w) => w.t);
  options.splice(at, 0, right);
  const whyWrong: (L | null)[] = wrongs.map((w) => w.why);
  whyWrong.splice(at, 0, null);
  return { id: `it-1-trends:${id}`, kind: "single", topic: T, skill: SKILL, level, prompt, options, correct: at, whyWrong, explanation };
}

