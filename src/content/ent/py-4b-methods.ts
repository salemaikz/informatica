/** Задание «один верный из четырёх» (1 балл). */
function single(
  name: string,
  level: Level,
  scene: Scene,
  options: Text[],
  correct: number,
  explanation: L,
  hint: L,
  whyWrong: (L | null)[],
  prompt: L = OUT,
): EntSingle {
  return { id: `${T}:${name}`, kind: "single", topic: TOPIC, skill: SKILL, level, prompt, scene, options, correct, explanation, hint, whyWrong };
}

