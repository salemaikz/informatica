const w = (ru: string, kk: string): L => ({ ru, kk });

/** Один верный из четырёх; whyWrong по порядку вариантов (у верного null). */
function single(id: string, level: Level, prompt: L, options: Text[], correct: number, whyWrong: (L | null)[], explanation: L, hint: L): EntSingle {
  return { id: `info-5-alphabet:${id}`, kind: "single", topic: TOPIC, skill: SKILL, level, prompt, options, correct, whyWrong, explanation, hint };
}

function multi(id: string, level: Level, prompt: L, options: [L, boolean][], explanation: L, hint: L): EntMulti {
  return {
    id: `info-5-alphabet:${id}`,
    kind: "multi",
    topic: TOPIC,
    skill: SKILL,
    level,
    prompt,
    options: options.map((o) => o[0]),
    correct: options.flatMap((o, i) => (o[1] ? [i] : [])),
    explanation,
    hint,
  };
}

function match(id: string, level: Level, prompt: L, items: Text[], choices: Text[], answer: number[], explanation: L, hint: L): EntMatch {
  return { id: `info-5-alphabet:${id}`, kind: "match", topic: TOPIC, skill: SKILL, level, prompt, items, choices, answer, explanation, hint };
}

