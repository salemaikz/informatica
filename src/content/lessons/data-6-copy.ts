// Урок «Копирование формул: задачи ЕНТ» (раздел 7, тема ЕНТ t12). Навык sheets.copy.
// Опирается на «Ссылки и функции» (сдвиг, $) и «Функции СУММ, СРЗНАЧ…» (диапазон при копировании).
// Ход: сюжет (склад) → «копирование в уме»: три шага → диапазон = две ссылки → разборы A (влево и вверх,
// #ССЫЛКА!) → B (окно и растущий итог) → C (доля от итога, смешанная ссылка) → ловушка «вырезать ≠ копировать» →
// решаем вместе → сам → ЕНТ-боссы (multi и обратная задача) → сюжет.
// Все формулы после копирования и значения пересчитаны скриптом (сдвиг ссылок + вычисление), см. отчёт автора.
// Названия функций: по-русски — СУММ; по-казахски в формулах — английское SUM.

const ruKk = (ru: string, kk: string): L => ({ ru, kk });

/** Формула как L: в ru — русское имя функции, в kk — английское. */
const fx = (f: string): L => ({ ru: f.replace(/\bSUM\(/g, "СУММ("), kk: f });

/** Электронная таблица: sheet-режим, моноширинный шрифт. Индексы подсветки — с 0. */
const sheet = (rows: (string | L)[][], highlightCells?: [number, number][], caption?: string | L): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
  caption,
});

// ---------- Таблица «Склад» ----------

const stock = (d3: string, d4: string, hi?: [number, number][], caption?: string | L): Scene =>
  sheet(
    [
      [ruKk("Товар", "Тауар"), ruKk("Кол-во", "Саны"), ruKk("Цена, ₸", "Бағасы, ₸"), ruKk("Сумма, ₸", "Сомасы, ₸")],
      [ruKk("Тетрадь", "Дәптер"), "10", "150", "=B2*C2"],
      [ruKk("Ручка", "Қалам"), "25", "80", d3],
      [ruKk("Линейка", "Сызғыш"), "8", "60", d4],
    ],
    hi,
    caption,
  );

// ---------- Пустая сетка A1:E5 (для разбора «влево и вверх») ----------

const grid5 = (cells: Record<string, string | L>, hi: [number, number][], caption?: string | L): Scene => {
  const rows: (string | L)[][] = Array.from({ length: 5 }, () => Array.from({ length: 5 }, () => ""));
  for (const [name, text] of Object.entries(cells)) {
    const c = name.charCodeAt(0) - 65;
    const r = Number(name.slice(1)) - 1;
    rows[r][c] = text;
  }
  return sheet(rows, hi, caption);
};

