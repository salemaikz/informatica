// Ход: сюжет (журнал: «зачёт» руками) → ЕСЛИ как развилка → условия и кавычки → разбор «зачёт / незачёт» →
// вложенные ЕСЛИ (оценка) → ловушка порядка условий → СЧЁТЕСЛИ / СУММЕСЛИ → И / ИЛИ → разбор «премии»
