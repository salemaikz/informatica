// Названия функций: по-русски — ЕСЛИ, СЧЁТЕСЛИ, СУММЕСЛИ, И, ИЛИ, СУММ; по-казахски в формулах — IF, COUNTIF, SUMIF, AND, OR, SUM.
// Код-сцены не используем: имена функций в них не переводятся, поэтому формулы — в таблицах (ячейки ru/kk).

const lk = (ru: string, kk: string): L => ({ ru, kk });

/** Электронная таблица: sheet-режим, моноширинный шрифт. Индексы подсветки — с 0. */
const sheet = (rows: (string | L)[][], highlightCells?: [number, number][], caption?: string | L, highlightCols?: number[]): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
  highlightCols,
  caption,
});

