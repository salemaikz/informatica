import type { Lesson, Scene } from "@/lib/types";

// Урок 2.3 «Логические схемы» (раздел u2, тема ЕНТ t05). Расчётная тема.
// Ход: ситуация → два объяснения (элементы) → закрепление → разбор «формула по схеме» (схема собирается по шагам)
// → разбор «считаем выход» → решаем вместе → сам → разбор «обратная задача» → задания ЕНТ → полусумматор.
// Все значения в таблицах и ответы проверены расчётом в python3 (scripts/out/logic-3-circuits).

type Circuit = Extract<Scene, { kind: "circuit" }>;
type Gate = Circuit["gates"][number];
type Bit = 0 | 1;

const circuit = (inputs: string[], gates: Gate[], output: string, values?: Record<string, Bit>): Scene => ({
  kind: "circuit",
  inputs,
  gates,
  output,
  ...(values ? { values } : {}),
});

// F = ¬(A ∧ B) ∨ C — схема из разборов. Частичные сборки нужны, чтобы схема «росла» по шагам.
const C1_AND: Gate = { id: "g1", op: "and", in: ["A", "B"] };
const C1_NOT: Gate = { id: "g2", op: "not", in: ["g1"] };
const C1_OR: Gate = { id: "g3", op: "or", in: ["g2", "C"] };
const c1Part = (n: 1 | 2, values?: Record<string, Bit>): Scene => circuit(["A", "B"], n === 1 ? [C1_AND] : [C1_AND, C1_NOT], n === 1 ? "g1" : "g2", values);
const c1Full = (values?: Record<string, Bit>): Scene => circuit(["A", "B", "C"], [C1_AND, C1_NOT, C1_OR], "g3", values);

// F = (A ∨ B) ∧ ¬C
const c2 = (values?: Record<string, Bit>): Scene =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "or", in: ["A", "B"] },
      { id: "g2", op: "not", in: ["C"] },
      { id: "g3", op: "and", in: ["g1", "g2"] },
    ],
    "g3",
    values,
  );

// F = ¬(A ⊕ B)
const cXor = (values?: Record<string, Bit>): Scene =>
  circuit(
    ["A", "B"],
    [
      { id: "g1", op: "xor", in: ["A", "B"] },
      { id: "g2", op: "not", in: ["g1"] },
    ],
    "g2",
    values,
  );

// F = (¬A ∧ B) ∨ C
const cEnt = (): Scene =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "not", in: ["A"] },
      { id: "g2", op: "and", in: ["g1", "B"] },
      { id: "g3", op: "or", in: ["g2", "C"] },
    ],
    "g3",
  );

// F = (A ⊕ B) ∨ ¬C
const cCount = (): Scene =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "xor", in: ["A", "B"] },
      { id: "g2", op: "not", in: ["C"] },
      { id: "g3", op: "or", in: ["g1", "g2"] },
    ],
    "g3",
  );

// F = ¬(A ∨ B) ∨ (B ∧ C)
const cBoss = (): Scene =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "nor", in: ["A", "B"] },
      { id: "g2", op: "and", in: ["B", "C"] },
      { id: "g3", op: "or", in: ["g1", "g2"] },
    ],
    "g3",
  );

