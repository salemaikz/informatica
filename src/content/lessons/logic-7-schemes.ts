// Опирается на «Логические схемы» (logic-3-circuits), «Импликация и эквиваленция» (A → B = ¬A ∨ B),
// «Таблицы истинности». Ход: сюжет (5 вентилей ради лампы) → схема → формула → формула → схема → сопоставление
// → разбор «формула по схеме» (A) → решаем вместе → разбор «при каких входах 1» (B) → разбор «совпадают ли схемы» (C)
// → ловушка «двух наборов мало» → задания ЕНТ → сюжет.
// Все таблицы, формулы и ответы посчитаны python3 (scripts/out/logic-7-schemes/*.py: разбор формул и перебор наборов).

type Circuit = Extract<Scene, { kind: "circuit" }>;
type Gate = Circuit["gates"][number];
type Bit = 0 | 1;

const circuit = (inputs: string[], gates: Gate[], output: string, values?: Record<string, Bit>): Circuit => ({
  kind: "circuit",
  inputs,
  gates,
  output,
  ...(values ? { values } : {}),
});

// Сюжет и разбор 3: (A ∧ ¬B) ∨ (¬A ∧ B) — «лампа с двумя выключателями» из пяти вентилей
const x5 = (): Circuit =>
  circuit(
    ["A", "B"],
    [
      { id: "g1", op: "not", in: ["A"] },
      { id: "g2", op: "not", in: ["B"] },
      { id: "g3", op: "and", in: ["A", "g2"] },
      { id: "g4", op: "and", in: ["g1", "B"] },
      { id: "g5", op: "or", in: ["g3", "g4"] },
    ],
    "g5",
  );

// A ⊕ B — один вентиль
const xOne = (): Circuit => circuit(["A", "B"], [{ id: "g1", op: "xor", in: ["A", "B"] }], "g1");

// Теория 1: переключатель F = (A ∧ B) ∨ (¬B ∧ C)
const sel = (): Circuit =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "and", in: ["A", "B"] },
      { id: "g2", op: "not", in: ["B"] },
      { id: "g3", op: "and", in: ["g2", "C"] },
      { id: "g4", op: "or", in: ["g1", "g3"] },
    ],
    "g4",
  );

// Теория 2: (A → B) ∧ C = (¬A ∨ B) ∧ C
const impl = (): Circuit =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "not", in: ["A"] },
      { id: "g2", op: "or", in: ["g1", "B"] },
      { id: "g3", op: "and", in: ["g2", "C"] },
    ],
    "g3",
  );

// Разбор 1: F = (A ∨ B) ∧ ¬(B ∧ C). Частичные сборки — схема «растёт» по шагам.
const R1: Gate = { id: "g1", op: "or", in: ["A", "B"] };
const R2: Gate = { id: "g2", op: "and", in: ["B", "C"] };
const R3: Gate = { id: "g3", op: "not", in: ["g2"] };
const R4: Gate = { id: "g4", op: "and", in: ["g1", "g3"] };
const w1 = (n: 1 | 2 | 3 | 4): Circuit => {
  const all = [R1, R2, R3, R4];
  return circuit(n === 1 ? ["A", "B"] : ["A", "B", "C"], all.slice(0, n), `g${n}`);
};

// Решаем вместе: F = (A ⊕ C) ∨ ¬(B ∨ C)
const cl = (values?: Record<string, Bit>): Circuit =>
  circuit(
    ["A", "B", "C"],
    [
      { id: "g1", op: "xor", in: ["A", "C"] },
      { id: "g2", op: "nor", in: ["B", "C"] },
      { id: "g3", op: "or", in: ["g1", "g2"] },
    ],
    "g3",
    values,
  );

// Разбор 2: F = ¬(A ∨ B) ∧ (C ⊕ D)
