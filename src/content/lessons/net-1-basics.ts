const l = (ru: string, kk: string): L => ({ ru, kk });

// ---------- Сцены ----------

const node = (id: string, label: L, icon: IconName, x: number, y: number) => ({ id, shape: "device" as const, label, icon, x, y });
const cable = (id: string, x: number, y: number) => ({ id, shape: "box" as const, label: l("Кабель", "Кабель"), x, y });
/** Связь без направления: стрелки с двух концов. */
const link = (a: string, b: string) => [
  { from: a, to: b },
  { from: b, to: a },
];
const pc = (id: string, n: number | string, x: number, y: number) => node(id, l(`Компьютер ${n}`, `Компьютер ${n}`), "laptop", x, y);

/** Звезда: коммутатор в центре, четыре компьютера. off — компьютер с оборванным кабелем, down — центр сломан (связей нет). */
function star(opts: { off?: string; down?: boolean; active?: string; caption?: L } = {}): Scene {
  const ids = [
    ["a", 1, 1, 0],
    ["b", 2, 0, 1],
    ["c", 3, 2, 1],
    ["d", 4, 1, 2],
  ] as const;
  return {
    kind: "flow",
    nodes: [node("sw", l("Коммутатор", "Коммутатор"), "network", 1, 1), ...ids.map(([id, n, x, y]) => pc(id, n, x, y))],
    edges: opts.down ? [] : ids.filter(([id]) => id !== opts.off).flatMap(([id]) => link(id, "sw")),
    active: opts.active,
    caption: opts.caption,
  };
}

/** Шина: три компьютера на одном общем кабеле. cut — кабель оборван между вторым и третьим компьютером. */
function bus(opts: { cut?: boolean; caption?: L } = {}): Scene {
  return {
    kind: "flow",
    nodes: [pc("a", 1, 0, 0), pc("b", 2, 1, 0), pc("c", 3, 2, 0), cable("k1", 0, 1), cable("k2", 1, 1), cable("k3", 2, 1)],
    edges: [...link("a", "k1"), ...link("b", "k2"), ...link("c", "k3"), ...link("k1", "k2"), ...(opts.cut ? [] : link("k2", "k3"))],
    caption: opts.caption,
  };
}

/** Кольцо из четырёх компьютеров. */
function ring(labels: "numbers" | "letters" = "numbers", caption?: L): Scene {
  const name = (i: number) => (labels === "numbers" ? String(i + 1) : "ABCD"[i]);
  return {
    kind: "flow",
    nodes: [pc("a", name(0), 0, 0), pc("b", name(1), 1, 0), pc("c", name(2), 1, 1), pc("d", name(3), 0, 1)],
    edges: [...link("a", "b"), ...link("b", "c"), ...link("c", "d"), ...link("d", "a")],
    caption,
  };
}

/** Путь в интернет: stage 1 — только класс, 2 — добавлен маршрутизатор, 3 — добавлен интернет. */
function path(stage: 1 | 2 | 3, active: string): Scene {
  const nodes = [
    node("pc", l("Компьютер", "Компьютер"), "laptop", 0, 0),
    node("sw", l("Коммутатор", "Коммутатор"), "network", 1, 0),
    node("pr", l("Принтер", "Принтер"), "printer", 2, 0),
  ];
  const edges = [...link("pc", "sw"), ...link("sw", "pr")];
  if (stage >= 2) {
    nodes.push(node("rt", l("Маршрутизатор", "Маршрутизатор"), "router", 1, 1));
    edges.push(...link("sw", "rt"));
  }
  if (stage >= 3) {
    nodes.push(node("net", l("Интернет", "Интернет"), "globe", 1, 2));
    edges.push(...link("rt", "net"));
  }
  return { kind: "flow", nodes, edges, active };
}

