/** Путь запроса: браузер → DNS → сервер. stage 1..4 — как идёт разбор. */
function dnsScene(stage: 1 | 2 | 3 | 4): Scene {
  const browserLabel = stage === 4 ? l("Браузер: страница открыта", "Браузер: бет ашылды") : l("Браузер", "Браузер");
  const dnsLabel = stage >= 2 ? l("DNS: edu.gov.kz = 203.0.113.5", "DNS: edu.gov.kz = 203.0.113.5") : l("DNS-сервер", "DNS-сервер");
  const nodes: Extract<Scene, { kind: "flow" }>["nodes"] = [
    { id: "b", shape: "device", label: browserLabel, icon: "laptop", x: 1, y: 0 },
    { id: "d", shape: "device", label: dnsLabel, icon: "database", x: 0, y: 1 },
  ];
  const edges: Extract<Scene, { kind: "flow" }>["edges"] = [{ from: "b", to: "d", label: l("IP?", "IP?") }];
  if (stage >= 3) {
    nodes.push({ id: "s", shape: "device", label: l("Сервер сайта", "Сайт сервері"), icon: "server", x: 2, y: 1 });
    edges.push({ from: "b", to: "s", label: "203.0.113.5" });
  }
  const active = stage === 1 ? "b" : stage === 2 ? "d" : stage === 3 ? "s" : "b";
  return { kind: "flow", nodes, edges, active };
}

