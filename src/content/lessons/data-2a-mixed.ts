for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) PRODUCTS[`${"BCDE"[c]}${r + 2}`] = String((r + 1) * (c + 1));

const mult = (cells: Record<string, string>, hi: string[], caption?: string | L): Scene => grid(5, 5, { ...FACTORS, ...cells }, hi, caption);

