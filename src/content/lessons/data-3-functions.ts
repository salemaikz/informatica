// Ход: сюжет (журнал оценок) → устройство функции (имя, скобки, аргументы, «;») → шесть функций →
// разбор A «пять значений по таблице» → разбор B-ловушка «пусто, ноль, текст» → разбор C «много аргументов,
// функция в функции, пересекающиеся диапазоны» → функции при копировании → решаем вместе → сам → ЕНТ-боссы → сюжет.
// Опирается на уроки «Электронные таблицы и формулы» (data-1-sheets) и «Ссылки и функции» (data-2-refs).
// Все значения формул пересчитаны независимым Python-движком (scratchpad/xl.py), см. отчёт автора.
// Названия функций: по-русски СУММ, СРЗНАЧ, МАКС, МИН, СЧЁТ, СЧЁТЗ; по-казахски в формулах — SUM, AVERAGE, MAX, MIN, COUNT, COUNTA
// (так же, как в уроке data-2-refs). Разделитель аргументов — «;».

/** Английские имена функций: в казахских строках русское имя перед «(» заменяется автоматически. */
const EN: Record<string, string> = { СЧЁТЗ: "COUNTA", СЧЁТ: "COUNT", СУММ: "SUM", СРЗНАЧ: "AVERAGE", МАКС: "MAX", МИН: "MIN" };
const en = (s: string) => s.replace(/(СЧЁТЗ|СЧЁТ|СУММ|СРЗНАЧ|МАКС|МИН)\(/g, (_, n: string) => `${EN[n]}(`);
const lk = (ru: string, kk: string): L => ({ ru, kk: en(kk) });
/** Формула: ru — как есть, kk — с английскими именами функций. */
const fx = (f: string): L => ({ ru: f, kk: en(f) });

type Cell = string | L;

/** Электронная таблица: sheet-режим, моноширинный шрифт. Индексы подсветки — [строка, столбец] с 0. */
const sheet = (rows: Cell[][], highlightCells?: [number, number][], caption?: string | L): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
  caption,
});

/** Прямоугольник подсветки: столбцы c1..c2, строки r1..r2 (индексы с 0). */
const rect = (c1: number, r1: number, c2: number, r2: number): [number, number][] => {
  const out: [number, number][] = [];
  for (let r = r1; r <= r2; r++) for (let c = c1; c <= c2; c++) out.push([r, c]);
  return out;
};

