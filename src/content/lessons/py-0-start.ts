/** Сцена «код»: active — текущая строка, vars — коробки, output — уже напечатанное. */
function code(lines: string[], opt: { active?: number; marks?: number[]; vars?: [string, string][]; output?: string[]; caption?: L } = {}): Scene {
  return {
    kind: "code",
    lang: "python",
    lines,
    active: opt.active,
    marks: opt.marks,
    vars: opt.vars?.map(([name, value]) => ({ name, value })),
    output: opt.output,
    caption: opt.caption,
  };
}

