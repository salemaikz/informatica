interface SheetOpts {
  cells?: [number, number][];
  rows?: number[];
  cols?: number[];
  caption?: Text;
}

/** Электронная таблица «олимпиада»: заголовки в строке 1, данные — со строки 2 (индексы подсветки — с 0, заголовок — строка 0). */
const olymp = (data: Row[], o: SheetOpts = {}): Scene => ({
  kind: "table",
  sheet: true,
  rows: [HEAD, ...data],
  highlightCells: o.cells,
  highlightRows: o.rows,
  highlightCols: o.cols,
  caption: o.caption,
});

/** Вид таблицы после фильтра: видны только отобранные строки, номера строк листа идут с пропусками. */
const filtered = (rows: [string, ...Row][], o: { cols?: number[]; caption?: Text } = {}): Scene => ({
  kind: "table",
  columns: [lk("№ строки", "Жол №"), ...HEAD],
  rows,
  highlightCols: o.cols,
  caption: o.caption,
});

/** Подсветка прямоугольника [строка, столбец] (индексы с 0). */
const rect = (c1: number, r1: number, c2: number, r2: number): [number, number][] => {
  const out: [number, number][] = [];
  for (let r = r1; r <= r2; r++) for (let c = c1; c <= c2; c++) out.push([r, c]);
  return out;
};

