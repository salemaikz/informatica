type Edge = [string, string];

/** Матрица смежности по списку рёбер (directed — только в одну сторону). */
function adjacency(labels: string[], edges: Edge[], directed = false): number[][] {
  const m = labels.map(() => labels.map(() => 0));
  for (const [a, b] of edges) {
    m[labels.indexOf(a)][labels.indexOf(b)] = 1;
    if (!directed) m[labels.indexOf(b)][labels.indexOf(a)] = 1;
  }
  return m;
}

interface MatrixOpts {
  /** Подсветка: строки и столбцы вершин, ячейки — в координатах матрицы (без заголовков). */
  rows?: number[];
  cols?: number[];
  cells?: [number, number][];
  /** "row" — столбец сумм строк Σ; "both" — ещё и строка сумм столбцов. */
  sums?: "row" | "both";
  caption?: Extract<Scene, { kind: "table" }>["caption"];
}

/** Матрица смежности как таблица: слева и сверху — имена вершин. */
function matrixScene(labels: string[], m: number[][], o: MatrixOpts = {}): Scene {
  const colSums = labels.map((_, j) => m.reduce((a, r) => a + r[j], 0));
  const rows = m.map((r, i) => [labels[i], ...r.map(String), ...(o.sums ? [String(r.reduce((a, b) => a + b, 0))] : [])]);
  if (o.sums === "both") rows.push(["Σ", ...colSums.map(String), String(colSums.reduce((a, b) => a + b, 0))]);
  return {
    kind: "table",
    columns: ["", ...labels, ...(o.sums ? ["Σ"] : [])],
    rows,
    mono: true,
    highlightRows: o.rows,
    highlightCols: o.cols?.map((c) => c + 1),
    highlightCells: o.cells?.map(([r, c]) => [r, c + 1] as [number, number]),
    caption: o.caption,
  };
}

/** Ячейки-единицы над главной диагональю: каждое ребро ровно один раз. */
const upperOnes = (m: number[][]): [number, number][] => {
  const out: [number, number][] = [];
  m.forEach((r, i) => r.forEach((x, j) => x === 1 && j > i && out.push([i, j])));
  return out;
};

