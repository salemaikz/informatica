import type { L, Lesson, Scene } from "@/lib/types";

// Урок «Текстовые функции» (раздел 7, тема ЕНТ t12). Навык sheets.text.
// Ход: сюжет (список класса) → регистр и длина (повтор из «Электронных таблиц») → склейка & и СЦЕПИТЬ →
// разбор «имя + фамилия» → ЛЕВСИМВ / ПРАВСИМВ / ПСТР → разбор «логин» (функции внутри функций) →
// ЗАМЕНИТЬ / ПОДСТАВИТЬ → разбор «имя файла без расширения» (ДЛСТР в аргументе) → ловушки ЕНТ →
// решаем вместе → сам → ЕНТ-боссы → сюжет.
// Каждая формула и её значение пересчитаны мини-вычислителем на python3 (семантика Excel).
// Названия функций: по-русски СТРОЧН, ПРОПИСН, ДЛСТР, СЦЕПИТЬ, ЛЕВСИМВ, ПРАВСИМВ, ПСТР, ЗАМЕНИТЬ, ПОДСТАВИТЬ, ЕСЛИ;
// по-казахски в формулах — английские LOWER, UPPER, LEN, CONCATENATE, LEFT, RIGHT, MID, REPLACE, SUBSTITUTE, IF.
// Формулы пишем один раз по-русски: toKk() сам переводит имена функций для казахской версии.

const ruKk = (ru: string, kk: string): L => ({ ru, kk });

const KK_NAMES: Record<string, string> = {
  СТРОЧН: "LOWER",
  ПРОПИСН: "UPPER",
  ДЛСТР: "LEN",
  СЦЕПИТЬ: "CONCATENATE",
  ЛЕВСИМВ: "LEFT",
  ПРАВСИМВ: "RIGHT",
  ПСТР: "MID",
  ЗАМЕНИТЬ: "REPLACE",
  ПОДСТАВИТЬ: "SUBSTITUTE",
  ЕСЛИ: "IF",
};
const KK_RE = new RegExp(`(${Object.keys(KK_NAMES).join("|")})(?=\\()`, "g");
/** Формула для казахской версии: русские имена функций → английские. */
const toKk = (f: string): string => f.replace(KK_RE, (m) => KK_NAMES[m]);
/** Формула как локализованная строка (для ячеек сцен). */
const fm = (f: string): L => ruKk(f, toKk(f));
/** Формула в markdown: ru и kk-версия в обратных кавычках. */
const R = (f: string): string => "`" + f + "`";
const K = (f: string): string => "`" + toKk(f) + "`";

/** Электронная таблица: sheet-режим, моноширинный шрифт. Индексы подсветки — с 0. */
const sheet = (rows: (string | L)[][], highlightCells?: [number, number][], caption?: string | L): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
  caption,
});

// ---------- Таблица «Список класса» ----------

const hdrName = ruKk("Имя", "Аты");
const hdrSurname = ruKk("Фамилия", "Тегі");
const hdrFull = ruKk("Полное имя", "Толық аты");
const hdrLogin = ruKk("Логин", "Логин");

/** Имена в A2:B4; столбец C — по сценарию (полное имя или логин). */
const classTable = (hdrC: L, c: [string, string, string], hi?: [number, number][], caption?: string | L): Scene =>
  sheet(
    [
      [hdrName, hdrSurname, hdrC],
      ["Алия", "Сеитова", c[0]],
      ["Данияр", "Жумабаев", c[1]],
      ["Мадина", "Ким", c[2]],
    ],
    hi,
    caption,
  );

/** Формула → результат (таблица из двух столбцов). */
const formulaTable = (rows: [string, string][], caption?: string | L): Scene => ({
  kind: "table",
  columns: [ruKk("Формула", "Формула"), ruKk("Результат", "Нәтиже")],
  rows: rows.map(([f, res]) => [fm(f), res]),
  mono: true,
  caption,
});

