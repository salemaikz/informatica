type TableScene = Extract<Scene, { kind: "table" }>;
type Cond = [label: string, f: (x: number) => boolean];

const gt = (n: number): Cond => [`X > ${n}`, (x) => x > n];
const lt = (n: number): Cond => [`X < ${n}`, (x) => x < n];
const ge = (n: number): Cond => [`X ≥ ${n}`, (x) => x >= n];
const le = (n: number): Cond => [`X ≤ ${n}`, (x) => x <= n];
const notGt = (n: number): Cond => [`¬(X > ${n})`, (x) => !(x > n)];
const range = (a: number, b: number): number[] => Array.from({ length: b - a + 1 }, (_, i) => a + i);

interface TtOpts extends Partial<Omit<TableScene, "kind" | "columns" | "rows">> {
  /** Заголовки столбцов (по умолчанию «X» и подписи условий). */
  cols?: TableScene["columns"];
  /** Какие значения X подсветить строкой. */
  hiRows?: (x: number) => boolean;
}

/** Таблица «значение X → 0/1 для каждого условия»: числа считает код, а не автор. */
function tt(xs: number[], conds: Cond[], opts: TtOpts = {}): Scene {
  const { cols, hiRows, ...rest } = opts;
  return {
    kind: "table",
    columns: cols ?? ["X", ...conds.map((c) => c[0])],
    rows: xs.map((x) => [String(x), ...conds.map((c) => (c[1](x) ? "1" : "0"))]),
    mono: true,
    ...(hiRows ? { highlightRows: xs.flatMap((x, i) => (hiRows(x) ? [i] : [])) } : {}),
    ...rest,
  };
}

const and = (a: Cond, b: Cond, label = "∧"): Cond => [label, (x) => a[1](x) && b[1](x)];
const or = (a: Cond, b: Cond, label = "∨"): Cond => [label, (x) => a[1](x) || b[1](x)];

