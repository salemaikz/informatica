interface DocOpts {
  serif: boolean;
  size: number;
  titleSize: number;
  bold: boolean;
  center: boolean;
  justify: boolean;
  indent: boolean;
  lh: number;
}

/** Страница «доклада»: заголовок и два абзаца с настраиваемым оформлением. */
function doc(o: DocOpts, caption?: L): Scene {
  const font = o.serif ? "Georgia,'Times New Roman',serif" : "Arial,sans-serif";
  const p = (text: string) =>
    `<p style="margin:0 0 4px;text-align:${o.justify ? "justify" : "left"};text-indent:${o.indent ? 24 : 0}px">${text}</p>`;
  const html = [
    `<div style="${PAGE}font-family:${font};font-size:${o.size}px;line-height:${o.lh}">`,
    `<div style="font-size:${o.titleSize}px;font-weight:${o.bold ? 700 : 400};text-align:${o.center ? "center" : "left"};margin-bottom:4px">Lorem ipsum</div>`,
    p(LOREM1),
    p(LOREM2),
    `</div>`,
  ].join("\n");
  return { kind: "web", html, caption };
}

