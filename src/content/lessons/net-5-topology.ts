// Договорённость об обрыве: классическое кольцо — данные идут в ОДНУ сторону (обрыв останавливает передачу);
// в задачах с «двусторонними кабелями» одиночный обрыв кольцо переживает, два обрыва делят его на две группы.

const l = (ru: string, kk: string): L => ({ ru, kk });

// ---------- Сцены ----------

const node = (id: string, label: L | string, icon: IconName, x: number, y: number) => ({ id, shape: "device" as const, label, icon, x, y });
/** Связь в обе стороны: стрелки с двух концов. */
const link = (a: string, b: string) => [
  { from: a, to: b },
  { from: b, to: a },
];

/** Кольцо из шести компьютеров по сетке 3×2. cut — оборванные кабели вида «2-3»; oneWay — данные идут в одну сторону. */
const RING_POS = [
  [0, 0],
  [1, 0],
  [2, 0],
  [2, 1],
  [1, 1],
  [0, 1],
] as const;

function ring6(opts: { cut?: string[]; oneWay?: boolean; caption?: L } = {}): Scene {
  const cut = opts.cut ?? [];
  const edges = RING_POS.flatMap((_, i) => {
    const a = i + 1;
    const b = (i + 1) % 6 + 1;
    if (cut.includes(`${a}-${b}`)) return [];
    return opts.oneWay ? [{ from: `p${a}`, to: `p${b}` }] : link(`p${a}`, `p${b}`);
  });
  return {
    kind: "flow",
    nodes: RING_POS.map(([x, y], i) => node(`p${i + 1}`, String(i + 1), "laptop", x, y)),
    edges,
    caption: opts.caption,
  };
}

/** Школа-дерево: главный коммутатор, три коммутатора этажей, под каждым — группа компьютеров. down — вышедшее из строя устройство, cut — оборван кабель между главным коммутатором и этим этажным. */
function tree(opts: { per?: number; down?: "core" | "s1" | "s2" | "s3"; cut?: "s1" | "s2" | "s3"; caption?: L } = {}): Scene {
  const per = opts.per ?? 10;
  const floors = [
    ["s1", "1", 0],
    ["s2", "2", 1],
    ["s3", "3", 2],
  ] as const;
  const edges = [...floors.flatMap(([id]) => link("core", id)), ...floors.flatMap(([id, n]) => link(id, `g${n}`))].filter(
    (e) => !opts.down || (e.from !== opts.down && e.to !== opts.down),
  ).filter((e) => !opts.cut || !(e.from === "core" && e.to === opts.cut) && !(e.from === opts.cut && e.to === "core"));
  return {
    kind: "flow",
    nodes: [
      node("core", l("Главный коммутатор", "Басты коммутатор"), "network", 1, 0),
      ...floors.map(([id, n, x]) => node(id, l(`Коммутатор ${n}`, `Коммутатор ${n}`), "network", x, 1)),
      ...floors.map(([, n, x]) => node(`g${n}`, l(`${per} компьютеров`, `${per} компьютер`), "laptop", x, 2)),
    ],
    edges,
    active: opts.down,
    caption: opts.caption,
  };
}

