/** Схема «ввод → обработка → хранение → вывод». active — подсвеченный блок; подписи можно уточнить под пример. */
const sys = (
  active: string | undefined,
  labels: { in: L; cpu: L; mem: L; out: L },
  icons: { in: "keyboard" | "camera"; out: "monitor" | "phone" },
  caption?: L,
): Scene => ({
  kind: "flow",
  nodes: [
    { id: "in", shape: "device", label: labels.in, icon: icons.in, x: 0, y: 0 },
    { id: "cpu", shape: "device", label: labels.cpu, icon: "cpu", x: 0, y: 1 },
    { id: "out", shape: "device", label: labels.out, icon: icons.out, x: 0, y: 2 },
    { id: "mem", shape: "device", label: labels.mem, icon: "hard-drive", x: 1, y: 1 },
  ],
  edges: [
    { from: "in", to: "cpu" },
    { from: "cpu", to: "out" },
    { from: "cpu", to: "mem" },
  ],
  active,
  caption,
});

/** Общая схема четырёх действий. */
const general = (active?: string): Scene =>
  sys(
    active,
    { in: w("Ввод", "Енгізу"), cpu: w("Обработка", "Өңдеу"), mem: w("Хранение", "Сақтау"), out: w("Вывод", "Шығару") },
    { in: "keyboard", out: "monitor" },
    w("Путь информации в любом компьютере", "Кез келген компьютердегі ақпарат жолы"),
  );

/** Калькулятор: примеры в подписях. */
const calc = (active?: string): Scene =>
  sys(
    active,
    { in: w("Ввод: 2 + 3 =", "Енгізу: 2 + 3 ="), cpu: w("Обработка", "Өңдеу"), mem: w("Хранение: 5", "Сақтау: 5"), out: w("Вывод: 5", "Шығару: 5") },
    { in: "keyboard", out: "monitor" },
  );

