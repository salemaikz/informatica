type TreeKind = "before" | "moved" | "copied";

type FlowNode = Extract<Scene, { kind: "flow" }>["nodes"][number];
const dir = (id: string, label: string, x: number, y: number): FlowNode => ({ id, shape: "box", label, x, y });
const file = (id: string, label: string, x: number, y: number): FlowNode => ({ id, shape: "action", label, x, y });

function tree(kind: TreeKind, active?: string): Scene {
  // Две колонки: блоки получаются широкими, и имя report.docx помещается в одну строку на телефоне.
  const nodes = [
    dir("root", ROOT, 0, 0),
    dir("users", "Users", 0, 1),
    dir("games", "Games", 1, 1),
    dir("ali", "Ali", 0, 2),
    dir("docs", "Docs", 0, 3),
    dir("music", "Music", 1, 3),
  ];
  const edges = [
    { from: "root", to: "users" },
    { from: "root", to: "games" },
    { from: "users", to: "ali" },
    { from: "ali", to: "docs" },
    { from: "ali", to: "music" },
  ];
  if (kind === "before") {
    nodes.push(file("rep", "report.docx", 0, 4));
    edges.push({ from: "docs", to: "rep" });
  } else if (kind === "moved") {
    nodes.push(file("rep", "report.docx", 1, 4));
    edges.push({ from: "music", to: "rep" });
  } else {
    nodes.push(file("rep1", "report.docx", 0, 4), file("rep2", "report.docx", 1, 4));
    edges.push({ from: "docs", to: "rep1" }, { from: "music", to: "rep2" });
  }
  return {
    kind: "flow",
    nodes,
    edges,
    active,
    caption: l("Скруглённые блоки — папки, прямоугольные — файлы", "Дөңгеленген блоктар — бумалар, төртбұрыштылар — файлдар"),
  };
}

