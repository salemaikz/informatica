// ---- Шкафчик: F = (A ∨ B) ∧ (C → D)
const OR_AB: Col = { head: "A ∨ B", f: (v) => (v[0] | v[1]) as Bit };
const IMP_CD: Col = { head: "C → D", f: (v) => IMP(v[2], v[3]) };
const F_LOCK: Col = { head: "F", f: (v) => (OR_AB.f(v) & IMP_CD.f(v)) as Bit };
const LOCK = [OR_AB, IMP_CD, F_LOCK];

// ---- Цепочка: F = (A → B) ∧ (B → C) ∧ (C → D)
const I_AB: Col = { head: "A → B", f: (v) => IMP(v[0], v[1]) };
const I_BC: Col = { head: "B → C", f: (v) => IMP(v[1], v[2]) };
const I_CD: Col = { head: "C → D", f: (v) => IMP(v[2], v[3]) };
const F_CHAIN: Col = { head: "F", f: (v) => (I_AB.f(v) & I_BC.f(v) & I_CD.f(v)) as Bit };
const CHAIN = [I_AB, I_BC, I_CD, F_CHAIN];

// ---- Обратная задача: F = 1 только в строках 011 и 101
const KEY_011: Col = { head: "¬A ∧ B ∧ C", f: (v) => (NOT(v[0]) & v[1] & v[2]) as Bit };
const KEY_101: Col = { head: "A ∧ ¬B ∧ C", f: (v) => (v[0] & NOT(v[1]) & v[2]) as Bit };
const F_GIVEN: Col = { head: "F", f: (v) => (KEY_011.f(v) | KEY_101.f(v)) as Bit };
const CAND: Col = { head: "(A ∨ B) ∧ C", f: (v) => ((v[0] | v[1]) & v[2]) as Bit };

// ---- По нулям: F = 0 только в строке 110
const F_ZERO: Col = { head: "F", f: (v) => IMP((v[0] & v[1]) as Bit, v[2]) };
const NA: Col = { head: "¬A", f: (v) => NOT(v[0]) };
const NB: Col = { head: "¬B", f: (v) => NOT(v[1]) };
const F_OR3: Col = { head: "¬A ∨ ¬B ∨ C", f: (v) => (NOT(v[0]) | NOT(v[1]) | v[2]) as Bit };

// ---- Задание «Решаем вместе» и разбор по строкам
const AND_NB: Col = { head: "A ∧ ¬B", f: (v) => (v[0] & NOT(v[1])) as Bit };
const EQ_CD: Col = { head: "C ↔ D", f: (v) => (v[2] === v[3] ? 1 : 0) };
const F_Q4: Col = { head: "F", f: (v) => (AND_NB.f(v) | EQ_CD.f(v)) as Bit };
const F_RING: Col = {
  head: "F",
  f: (v) => (IMP(v[0], v[1]) & IMP(v[1], v[2]) & IMP(v[2], v[3]) & IMP(v[3], v[0])) as Bit,
};

// ---- ЕНТ-задание «по таблице — выражение»: F = A ∧ ¬B ∨ ¬A ∧ C
const F_ENT: Col = { head: "F", f: (v) => ((v[0] & NOT(v[1])) | (NOT(v[0]) & v[2])) as Bit };

