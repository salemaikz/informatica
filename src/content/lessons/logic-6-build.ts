type Bit = 0 | 1;
type Row = Bit[];
type TableScene = Extract<Scene, { kind: "table" }>;

/** Все наборы значений n переменных двоичным счётом: 000, 001, …, 111. */
const sets = (n: number): Row[] =>
  Array.from({ length: 2 ** n }, (_, i) => Array.from({ length: n }, (_, k) => ((i >> (n - 1 - k)) & 1) as Bit));

const NOT = (a: Bit): Bit => (a === 1 ? 0 : 1);
const IMP = (a: Bit, b: Bit): Bit => (a === 1 && b === 0 ? 0 : 1);

interface Col {
  head: string;
  f: (v: Row) => Bit;
}

/** Строки, где столбец равен value (индексы для highlightRows). */
const rowsWhere = (c: Col, n: number, value: Bit): number[] => sets(n).flatMap((v, i) => (c.f(v) === value ? [i] : []));

/** Таблица: столбцы переменных и столбцы-помощники; посчитано первых `shown` помощников, остальные — «?». */
function truth(
  names: string[],
  cols: Col[],
  shown: number,
  extra: { highlightRows?: number[]; highlightCols?: number[]; caption?: Text } = {},
): TableScene {
  return {
    kind: "table",
    columns: [...names, ...cols.map((c) => c.head)],
    rows: sets(names.length).map((v) => [...v.map(String), ...cols.map((c, i) => (i < shown ? String(c.f(v)) : "?"))]),
    mono: true,
    ...extra,
  };
}

