const ruKk = (ru: string, kk: string): L => ({ ru, kk });

/** Электронная таблица: sheet-режим, формулы моноширинным шрифтом. Индексы подсветки — с 0. */
const sheet = (rows: (string | L)[][], highlightCells?: [number, number][], caption?: string | L): Scene => ({
  kind: "table",
  sheet: true,
  mono: true,
  rows,
  highlightCells,
  caption,
});

/** Подсветка по адресам ячеек: «C1» → [строка 0, столбец 2]. */
const at = (...cells: string[]): [number, number][] => cells.map((a) => [Number(a.slice(1)) - 1, a.charCodeAt(0) - 65]);

/** Таблица nRows × nCols; содержимое ячеек задано адресами: { A1: "4", C1: "=A1+B1" }. */
const grid = (nRows: number, nCols: number, cells: Record<string, string | L>, hi: string[] = [], caption?: string | L): Scene => {
  const rows: (string | L)[][] = Array.from({ length: nRows }, () => Array.from({ length: nCols }, () => ""));
  for (const [name, text] of Object.entries(cells)) rows[Number(name.slice(1)) - 1][name.charCodeAt(0) - 65] = text;
  return sheet(rows, at(...hi), caption);
};

/** Допустимые записи адреса в пропуске: латиница и кириллица-двойники (А, В, С, Е). */
const CYR: Record<string, string> = { A: "А", B: "В", C: "С", E: "Е" };
const ref = (s: string): string[] => [s, s.replace(/[ABCE]/g, (c) => CYR[c])];

