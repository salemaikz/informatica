const dev = (id: string, label: L, icon: IconName, x: number, y: number) => ({ id, shape: "device" as const, label, icon, x, y });
const link = (a: string, b: string) => [
  { from: a, to: b },
  { from: b, to: a },
];

/**
 * Путь запроса из дома в интернет. stage 1 — телефон, ноутбук и роутер; 2 — то же (подсветка меняется);
 * 3 — добавлен модем; 4 — провайдер; 5 — сервер сайта; back — стрелки идут и обратно (ответ сайта).
 */
function homePath(stage: 1 | 2 | 3 | 4 | 5, active: string, back = false, caption?: L): Scene {
  const nodes = [
    dev("phone", l("Телефон", "Телефон"), "phone", 0, 0),
    dev("laptop", l("Ноутбук", "Ноутбук"), "laptop", 2, 0),
    dev("rt", l("Домашний роутер", "Үй роутері"), "router", 1, 1),
  ];
  const edges: { from: string; to: string; label?: L }[] = [
    { from: "phone", to: "rt", label: l("Wi-Fi", "Wi-Fi") },
    { from: "laptop", to: "rt", label: l("кабель", "кабель") },
  ];
  if (stage >= 3) {
    nodes.push(dev("mod", l("Модем", "Модем"), "repeat", 1, 2));
    edges.push({ from: "rt", to: "mod" });
  }
  if (stage >= 4) {
    nodes.push(dev("isp", l("Провайдер", "Провайдер"), "network", 1, 3));
    edges.push({ from: "mod", to: "isp" });
  }
  if (stage >= 5) {
    nodes.push(dev("web", l("Сервер сайта", "Сайт сервері"), "server", 1, 4));
    edges.push({ from: "isp", to: "web" });
  }
  if (back) {
    const reverse = edges.filter((e) => e.from !== "phone" && e.from !== "laptop").map((e) => ({ from: e.to, to: e.from }));
    edges.push(...reverse, { from: "rt", to: "phone" });
  }
  return { kind: "flow", nodes, edges, active, caption };
}

