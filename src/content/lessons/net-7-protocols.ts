/** Состояние пяти пакетов файла на разных этапах разбора. */
function packetsScene(state: "sent" | "lost" | "done"): Scene {
  const rows: [string, L][] =
    state === "sent"
      ? [1, 2, 3, 4, 5].map((n) => [String(n), l("отправлен", "жіберілді")] as [string, L])
      : [1, 2, 3, 4, 5].map((n) => {
          if (state === "lost" && n === 4) return [String(n), l("не пришёл → запрошен снова", "келмеді → қайта сұралды")] as [string, L];
          return [String(n), l("получен", "алынды")] as [string, L];
        });
  return {
    kind: "table",
    columns: statusColumns,
    rows,
    highlightRows: state === "lost" ? [3] : undefined,
    mono: false,
  };
}

